"use client";

/* Вердикт о сборе — ОДИН индикатор на все экраны, где человек смотрит цифры
 * (#140).
 *
 * ЗАЧЕМ ОБЩИЙ, А НЕ ПО ШТУКЕ НА ЛИСТ. Опасность иссуса не в том, что нет
 * экрана состояния, а в том, что мёртвый сбор ВЫГЛЯДИТ ЖИВЫМ там, где на цифры
 * смотрят. Значит вопрос не «есть ли где-то индикатор», а «есть ли он на КАЖДОМ
 * таком листе». Ночь на 15.08 он был бы на нуле листов; после первой половины
 * работы — на одном из двух, и лист кабинетов с его спендом, балансом и итогом
 * молчал бы ровно так же, как молчало всё в ту ночь.
 *
 * Второй индикатор, написанный отдельно, разошёлся бы с первым в словах на
 * первой же правке — поэтому он здесь один, а слова у него приезжают из
 * `@/lib/collector-health`, единственного места, где вердикт превращается в
 * текст.
 *
 * ДВА ПРАВИЛА КОНТРАКТА, и оба живут не здесь, а рядом — этот файл их только
 * соблюдает:
 *
 *   1. ЦВЕТ БЕРЁТСЯ ИЗ «тревога», А НЕ ИЗ ИМЕНИ СОСТОЯНИЯ (`healthTone`).
 *      `заперт` — не авария: Мета не пускает, причина названа, и рука человека
 *      там ничего не исправит. Красный на нём тратит доверие ко всем остальным
 *      красным, а потратив — возвращает нас в ту же ночь.
 *   2. ПОРОГОВ ЗДЕСЬ НЕТ НИ ОДНОГО. Что считать аварией, решает
 *      `core/collector.здоровье`; панель выбирает рамку и печатает присланное.
 *
 * ПОЧЕМУ «notice» ВСЁ-ТАКИ ПОКАЗЫВАЕТСЯ, А НЕ МОЛЧИТ. «Заперт» значит, что
 * цифры не обновляются — просто чинить это не нам. Промолчать о нём на листе,
 * где на эти цифры смотрят, значит сделать ровно то, против чего иссус. Он
 * говорит спокойным тоном и не зовёт никуда идти. Лист, у которого про
 * блокировку есть своя, более подробная плашка, гасит этот тон явно
 * (`showNotice={false}`) — иначе два сообщения об одном учат не читать оба.
 */

import * as React from "react";
import { useQuery } from "@tanstack/react-query";
import { api, type CollectorState } from "@/lib/analytics";
import {
  healthMeaning,
  healthRestartLine,
  healthTitle,
  healthTone,
  healthWriteLine,
  readHealth,
} from "@/lib/collector-health";
import { cn } from "@/lib/utils";
import { readOrphanAds, смыслСирот, строкаСирот } from "@/lib/orphan-ads";

/** Как часто перечитывать состояние, когда компонент тянет его сам.
 *
 *  Это НЕ порог аварии и не может им стать: здесь решается только, как быстро
 *  экран узнает о смене вердикта. Реже, чем на листе аналитики (там 30с): туда
 *  человек приходит следить за цифрами, а сюда — работать со списком, и лишний
 *  запрос в минуту на каждую открытую вкладку не бесплатен. */
const ОПРОС_МС = 60_000;

/** Состояние сбора для тех листов, у которых своего запроса нет.
 *
 *  Ошибку глотаем намеренно: недоступный демон — это не повод показать красную
 *  плашку про сбор. Про недоступность демона лист говорит своими средствами, а
 *  выдумывать из неё вердикт значит соврать в ту же сторону, что и молчание.
 *
 *  Запрос уехал в TanStack Query: `refetchInterval` заменил setInterval, а
 *  `enabled: false` — ранний return из useEffect. Старая семантика «null при
 *  ошибке» сохранена: query.error → null в return, чтобы вердикт не показал
 *  старый тон. */
function useCollector(включено: boolean): CollectorState | null {
  const query = useQuery({
    queryKey: ["analytics", "collector"] as const,
    queryFn: () => api.collector(),
    refetchInterval: ОПРОС_МС,
    /* Лист, который опрашивает `/collector` сам, второй раз опрашивать не надо:
       это был бы лишний запрос в минуту на каждую открытую вкладку и вдобавок
       второй ответ про то же самое, который может разойтись с первым. */
    enabled: включено,
    retry: false,
  });
  return query.error ? null : query.data ?? null;
}

export interface CollectorVerdictProps {
  /** Готовое состояние, когда лист уже ходит за ним сам. Не передан — компонент
   *  сходит сам; `null` — состояния нет, и тогда он молчит. */
  st?: CollectorState | null;
  /** Показывать ли спокойный тон (сегодня это `заперт`). Гасят его там, где про
   *  то же самое уже есть своя плашка. */
  showNotice?: boolean;
  className?: string;
}

export function CollectorVerdict({ st, showNotice = true, className }: CollectorVerdictProps) {
  const сам = st === undefined;
  const свой = useCollector(сам);
  const состояние = сам ? свой : st;

  /* СИРОТЫ СЧИТАЮТСЯ ДО ВЕРДИКТА О ЗДОРОВЬЕ И ПОКАЗЫВАЮТСЯ ОТДЕЛЬНО ОТ НЕГО
     (#164). Это не диагностика сбора: сбор при 422 сиротах идёт исправно и
     красит себя зелёным — ровно поэтому дыру и не замечали месяц. Спрячь мы
     строку под условие «сбор нездоров», индикатор молчал бы в том
     единственном случае, ради которого написан. */
  const сироты = readOrphanAds(состояние);
  const строка = строкаСирот(сироты);

  const в = readHealth(состояние?.здоровье);
  /* `null` значит «демон старше контракта», а не «сбор здоров»: на маке он
     обновляется рестартом Claude Desktop. Молчим — но молчим ровно так же, как
     молчали до вердикта, и лист продолжает жить по-старому. */
  const тон = в ? healthTone(в) : "calm";
  const молчитПроСбор = !в || тон === "calm" || (тон === "notice" && !showNotice);
  if (молчитПроСбор) {
    /* Сбору сказать нечего, а сиротам есть. Своя плашка спокойного тона: она
       про качество ДАННЫХ, а не про аварию, и красить её тревогой значило бы
       обесценить настоящую тревогу — тот же довод, что у `notice` выше. */
    return строка ? <ПлашкаСирот строка={строка} смысл={смыслСирот(сироты)} className={className} /> : null;
  }

  const цифры = [healthRestartLine(в), healthWriteLine(в)].filter(Boolean).join(" · ");
  const тревога = тон === "alarm";

  return (
    <div
      role="status"
      /* Тон отдельным атрибутом, а не только цветом. Так его видно и в тесте, и
         в инспекторе: «покрасили по имени состояния» иначе ловится только
         глазами и только в момент аварии. */
      data-tone={тон}
      className={cn(
        "flex-none rounded-xl border px-3 py-2",
        тревога
          ? "border-destructive/40 bg-destructive-soft"
          : "border-warning/30 bg-warning-soft",
        className,
      )}
    >
      <p className={cn("text-[12.5px] font-medium", тревога ? "text-destructive" : "text-warning")}>
        {healthTitle(в)}
      </p>
      <p
        className={cn(
          "mt-0.5 text-[11.5px] leading-relaxed",
          тревога ? "text-destructive/85" : "text-muted-foreground",
        )}
      >
        {healthMeaning(в)}
        {цифры ? ` ${цифры}.` : ""}
        {/* Причина — СЛОВАМИ ДЕМОНА: только он знает, сколько было подъёмов и
            что именно ответила Мета. Пересказ своими словами однажды окажется
            неверным пересказом, и заметить это будет некому. */}
        {в.почему ? ` Collector says: ${в.почему}` : ""}
      </p>
      {/* Сироты живут в той же плашке, но ОТДЕЛЬНОЙ строкой: это другая
          новость, и слитая с вердиктом о сборе она прочиталась бы как его
          подробность. */}
      {строка && (
        <p className="mt-1 text-[11.5px] leading-relaxed text-muted-foreground" title={смыслСирот(сироты)}>
          {строка}
        </p>
      )}
    </div>
  );
}

/** Плашка про сирот, когда со сбором всё хорошо. Спокойный тон намеренно: это
 *  про качество данных, а не про аварию. */
function ПлашкаСирот({ строка, смысл, className }: {
  строка: string; смысл: string; className?: string;
}) {
  return (
    <div
      role="status"
      data-tone="notice"
      data-orphan-ads="1"
      className={cn("flex-none rounded-xl border border-border bg-card px-3 py-2", className)}
      title={смысл}
    >
      <p className="text-[11.5px] leading-relaxed text-muted-foreground">{строка}</p>
    </div>
  );
}
