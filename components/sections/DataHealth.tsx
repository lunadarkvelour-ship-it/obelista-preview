"use client";

/* Состояние данных листа — ОДНА строка вместо стопки плашек.
 *
 * ЧТО БЫЛО. Над таблицей могли встать одновременно шесть блоков во всю ширину,
 * каждый с абзацем: «sync failed» по соцам, ошибка коллектора, «nothing can be
 * picked», две разные плашки режима снапшота и вердикт сбора. На живом проде
 * владелец видел жёлтый прямоугольник, начинающийся с
 * `2fcc2d23-ecd8-4122-ac84-a72dfc77d002` — то есть первое, что сообщал экран,
 * был идентификатор, который человеку не говорит ничего.
 *
 * Стопка предупреждений — это не «много информации», это ноль информации:
 * блок, который стоит там всегда, перестают читать целиком, вместе с той
 * строкой, ради которой всё написано.
 *
 * ЧТО СТАЛО. Одна строка: тон, короткая суть, число фактов. Раскрывается —
 * внутри все факты по одному, и там же ссылка туда, где это чинится.
 *
 * ПОЧЕМУ СЧЁТ, А НЕ ПЕРВЫЙ СОВПАВШИЙ. Факты бывают верны ОДНОВРЕМЕННО, и
 * свежая учётка ловит сразу три: снапшота нет, подключённых соцев нет, адрес
 * коллектора не отвечает. Строка, показывающая только первый, прячет два
 * других — то есть делает ровно то, против чего собрана. Поэтому суть говорит
 * о худшем факте, а число говорит, сколько их всего.
 *
 * ВЕРДИКТ СБОРА ЖИВЁТ ВНУТРИ, А НЕ ЗАМЕНЁН. `CollectorVerdict` — общий на
 * продукт индикатор (#140), и его присутствие на каждом листе с деньгами
 * держит сторож, который выводит список листов ИЗ КОДА
 * (`__tests__/collector-verdict-screens`). Написать здесь «свой, покороче»
 * значило бы завести второй словарь про одну аварию и обойти сторож, оставив
 * его зелёным. Поэтому он вкладывается как есть: сам решает, молчать ему или
 * говорить, и сам приносит свои `data-tone` и `data-orphan-ads`.
 *
 * ЖИВАЯ ОБЛАСТЬ ОДНА. `role="status"` объявлен здесь ровно один раз. Раньше
 * его объявляли и плашка устаревания, и вердикт сбора — две живые области на
 * одном экране заставляют читалку экрана зачитывать их наперебой.
 */

import * as React from "react";
import { ChevronRight } from "lucide-react";
import Link from "next/link";
import { CollectorVerdict } from "@/components/sections/CollectorVerdict";
import { cn } from "@/lib/utils";

/** Насколько всё плохо. Порядок значим: `сила` ниже сравнивает по нему. */
export type Тон = "внимание" | "тревога";

export interface Факт {
  /** Ключ для React и для тестов. */
  id: string;
  тон: Тон;
  /** Суть, одной строкой. До ~10 слов: это заголовок факта, а не объяснение. */
  что: string;
  /** Подробность — только если она добавляет действие или число. Абзацы,
   *  объясняющие читателю замысел, сюда не кладут: их никто не дочитывает. */
  детали?: string;
  /** Куда идти чинить. Только когда чинится рукой человека: ссылка «почини
   *  то, что чинится не тобой» хуже её отсутствия. */
  куда?: { href: string; текст: string };
}

const СИЛА: Record<Тон, number> = { "внимание": 1, "тревога": 2 };

const РАМКА: Record<Тон, string> = {
  "внимание": "border-warning/40 bg-warning-soft",
  "тревога": "border-destructive/30 bg-destructive-soft",
};

const ТОЧКА: Record<Тон, string> = {
  "внимание": "bg-warning",
  "тревога": "bg-destructive",
};

export interface DataHealthProps {
  факты: Факт[];
  /** Подпись режима источника данных. Стоит здесь, а не отдельной плашкой:
   *  «почему список короче вчерашнего» — вопрос про данные, и ответ на него
   *  обязан лежать там же, где остальные ответы про данные.
   *
   *  ЭТО МЕТКА, А НЕ ПЕРЕКЛЮЧАТЕЛЬ. Сам выбор режима уехал в «Интеграции»
   *  (решение владельца 17.08): он меняет весь продукт, значит это настройка,
   *  а не вид листа. Но молчать о нём здесь нельзя — тогда укоротившийся
   *  список остаётся без объяснения. */
  режим?: string;
  className?: string;
}

export function DataHealth({ факты, режим, className }: DataHealthProps) {
  const [раскрыт, setРаскрыт] = React.useState(false);

  /* Худший факт решает тон и текст свёрнутой строки: если что-то сломано
     всерьёз, человек обязан увидеть именно это, а не первое по порядку. */
  const главный = факты.slice().sort((a, b) => СИЛА[b.тон] - СИЛА[a.тон])[0];

  /* Сказать нечего — не рисуем ничего, кроме вердикта сбора: он сам решает,
     молчать ему или нет, и своей рамки при молчании не оставляет.
     Метка режима при этом всё равно нужна, если режим не обычный. */
  if (!главный) {
    return (
      <div className={className}>
        <CollectorVerdict />
        {режим && <РежимОдин режим={режим} />}
      </div>
    );
  }

  const ещё = факты.length - 1;

  return (
    <div className={className} role="status">
      <div className={cn("rounded-lg border", РАМКА[главный.тон])}>
        <button
          type="button"
          onClick={() => setРаскрыт((v) => !v)}
          aria-expanded={раскрыт}
          /* Вся строка — одна кнопка. Раскрывающая стрелка размером с иконку
             промахивается мышью на каждом втором нажатии, а строка шириной в
             экран не промахивается никогда. */
          className={cn(
            "focus-ring flex w-full items-center gap-2 rounded-lg px-3 py-2 text-left",
            "transition-colors duration-150 hover:bg-foreground/[0.03]",
          )}
        >
          <span
            className={cn("size-1.5 flex-none rounded-full", ТОЧКА[главный.тон])}
            aria-hidden
          />
          <span className="min-w-0 flex-1 truncate text-xs font-medium">{главный.что}</span>
          {ещё > 0 && (
            <span className="tnum flex-none text-2xs text-muted-foreground">
              +{ещё} more
            </span>
          )}
          <ChevronRight
            aria-hidden
            className={cn(
              "size-3.5 flex-none text-muted-foreground transition-transform duration-150",
              раскрыт && "rotate-90",
            )}
          />
        </button>

        {раскрыт && (
          <ul className="flex flex-col gap-2 border-t border-border/60 px-3 py-2">
            {факты.map((ф) => (
              <li key={ф.id} className="flex items-start gap-2">
                <span
                  className={cn("mt-1.5 size-1.5 flex-none rounded-full", ТОЧКА[ф.тон])}
                  aria-hidden
                />
                <div className="min-w-0">
                  <p className="text-xs">{ф.что}</p>
                  {/* Подробность БЕЗ обрезки: сюда попадает дословный ответ
                      демона, и по нему отличают неверный адрес сборщика от
                      отсутствующей ручки. Обрежь его — и различать станет
                      нечем. Ломаем по словам, чтобы длинный URL не растянул
                      строку за край. */}
                  {ф.детали && (
                    <p className="mt-0.5 break-words text-2xs text-muted-foreground">
                      {ф.детали}
                    </p>
                  )}
                  {ф.куда && (
                    <Link
                      href={ф.куда.href}
                      className="focus-ring mt-1 inline-block rounded text-2xs font-medium
                                 text-primary-ink underline underline-offset-2"
                    >
                      {ф.куда.текст}
                    </Link>
                  )}
                </div>
              </li>
            ))}
          </ul>
        )}
      </div>

      {/* Вердикт сбора — своей строкой под свёрткой, а не внутри неё: он про то,
          живы ли ЦИФРЫ вообще, и это вопрос раньше любого из фактов выше.
          Прятать его под «раскрыть» значило бы вернуть ровно ту ночь, ради
          которой он написан. */}
      <CollectorVerdict className="mt-2" />
      {режим && <РежимОдин режим={режим} />}
    </div>
  );
}

/** Метка режима источника. Отдельной строкой и спокойным тоном: это не
 *  проблема, это факт про то, откуда взят список. */
function РежимОдин({ режим }: { режим: string }) {
  return (
    <p className="mt-2 text-2xs text-muted-foreground">
      Source: <span className="text-foreground">{режим}</span> ·{" "}
      <Link
        href="/integrations"
        className="focus-ring rounded underline underline-offset-2 hover:text-foreground"
      >
        change in Integrations
      </Link>
    </p>
  );
}
