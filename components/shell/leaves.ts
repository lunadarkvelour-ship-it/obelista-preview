/** Листы панели.
 *
 *  Правило не «их ровно N», а какое МЕСТО достойно ссылки в навигации: сюда
 *  попадают самостоятельные места, куда можно войти с чистого экрана и сразу
 *  понять, что перед тобой. Аплоад и превью такими не стали и не станут: это
 *  шаги ОДНОГО пути, а не места, — связка настраивается на группу, а группа
 *  собирается в «Кабинетах». Дать на них ссылку в навигации значит разрешить
 *  войти в середину процесса, где ещё нечего настраивать. Путь один:
 *  кабинеты → аплоад → превью, и в LEAVES он не разбит по шагам.
 *
 *  «Rules» (автоправила, 14.08.2026) — место той же породы: с чистого
 *  экрана в него входят сами по себе, не как продолжение другого листа.
 *  Серверного движка под ним ещё нет (#25) — правило не про готовность
 *  функции, а про то, самостоятельное ли это место в навигации.
 *
 *  «Users» (иссус #18, блок Е плана переезда) — тоже такое место, и это лист
 *  ТОЛЬКО для админа. Пункт меню при этом виден всем: Sidebar про роли не
 *  знает и здесь этому не учится — это отдельная задача вне границ иссуса
 *  #18. Кто зайдёт без роли, увидит короткое «доступно только админам», и ни
 *  одна ручка списка учёток при этом не позовётся — гейт стоит внутри самого
 *  листа (`app/users/UsersView.tsx`), а не в навигации.
 *
 *  Конструктор `/launch` уехал отсюда же: он умел одну связку на один соц, а
 *  «Кабинеты» умеют сразу все. Адрес остался и уводит на новый путь.
 *
 *  «Agencies» (срез кабинетов по Business Manager) снесён 14.08.2026 по
 *  прямому требованию владельца — вместе с пунктом меню удалён и сам адрес
 *  `/agencies` (каталога `app/agencies/` больше нет). Здесь это записано
 *  потому, что в Next пункт меню и маршрут живут врозь: убрать строку из
 *  LEAVES мало, лист остаётся достижимым по прямой ссылке. Обратно — только
 *  новым решением владельца, а не копипастой соседней строки.
 *
 *  «Integrations» (иссус #126, 15.08.2026) — место той же породы, что Rules:
 *  входят в него сами по себе, а не из середины другого листа. Подключать
 *  сегодня физически нечего (ручек нет), но правило про навигацию — не про
 *  готовность механизма, а про самостоятельность места.
 *
 *  «Campaigns» (иссус #125, 15.08.2026) — управление тем, что уже льётся:
 *  кампании, адсеты и объявления с паузой и включением. Место самостоятельное
 *  по тому же признаку: входят в него с вопросом «что сейчас крутится», а не
 *  из середины залива. Ручек демона под него ещё нет — лист говорит об этом
 *  сам и не притворяется пустым кабинетом. */
