/* Единая горизонтальная сетка листов.
 *
 * Раньше каждый лист сам решал ширину, и все трое сидели в max-w-3xl (768px):
 * на 1600–2600px канваса форма занимала треть экрана, а остальное пустовало —
 * на 67% масштаба это выглядело особенно глупо. Теперь ширина одна на все
 * листы и растёт вместе с экраном, а плотность даёт раскладка в колонки.
 */

/** До xl колонка одна — держим её в 768px, иначе строка «подпись — поле»
 *  разъезжается на всю ширину и глазу тяжело связать её концы. С xl секции
 *  раскладываются в колонки, и общая ширина растёт до 2100px. */
export const PAGE_WIDTH = "mx-auto w-full max-w-3xl xl:max-w-[2100px]";

/** Ширина для листов, которые читают, а не заполняют: превью и импорт. Там
 *  колонок всего две, и на 2100px они разъезжаются в пустоту. */
export const READ_WIDTH = "mx-auto w-full max-w-3xl xl:max-w-[1600px]";

/** Поля страницы. Совпадают у контейнера и у липкой полоски-итога. */
export const PAGE_PAD = "px-4 lg:px-6 xl:px-8";

/** Отрицательные поля — для блоков, которые должны выходить на всю ширину
 *  канваса изнутри контейнера (полоска-итог). */
export const PAGE_PAD_NEG = "-mx-4 lg:-mx-6 xl:-mx-8";
