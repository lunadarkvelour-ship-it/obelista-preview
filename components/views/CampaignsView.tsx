/** Второй уровень: поиск и множественный выбор кабинетов.
 *
 *  Три вещи, которые владелец просил дословно («выбор аккаунтов нескольких +
 *  поиск аккаунтов + выбор просмотра по соцу»), живут ровно здесь и здесь же
 *  складываются: соц выбран уровнем выше, поиск сужает список, галочки
 *  собирают набор, который откроется одним деревом.
 *
 *  Экспортируется ради смотрелки. */
export function AccountLevel({
  кабинеты, всего, отмечено, поиск, onПоиск, onОтметить, onОтметитьМного, onОткрыть,
}: {
  кабинеты: UnifiedAccount[];
  всего: number;
  отмечено: string[];
  поиск: string;
  onПоиск: (v: string) => void;
  onОтметить: (act_id: string) => void;
  /** Отметить набор целиком, не перебирая по одному. Отдельным обработчиком, а
   *  не циклом по `onОтметить`: цикл по переключателю снял бы отметку с тех,
   *  что уже отмечены, — «выбрать всё активное» после второго нажатия
   *  превращалось бы в «снять всё активное». */
  onОтметитьМного: (ids: string[]) => void;
  onОткрыть: (ids: string[]) => void;
}) {
  const набор = new Set(отмечено);
  const видимыеId = кабинеты.map((a) => a.act_id);
  /* Активные считаются ПО ПОКАЗАННЫМ: поиск сузил список — сузился и набор,
     иначе кнопка молча возьмёт то, чего человек сейчас не видит. */
  const активныеId = активные(кабинеты).map((a) => a.act_id);

  return (
    <div className="flex min-h-0 flex-1 flex-col gap-2">
      <div className="flex flex-none flex-wrap items-center gap-2">
        <div className="relative min-w-[220px] flex-1">
          <Search
            className="pointer-events-none absolute left-2.5 top-1/2 size-4 -translate-y-1/2 text-muted-foreground"
            strokeWidth={1.5}
            aria-hidden
          />
          <input
            value={поиск}
            onChange={(e) => onПоиск(e.target.value)}
            placeholder="Ad account name, id or BM"
            aria-label="Search ad accounts"
            className={cn(CTRL, CTRL_IDLE, "w-full pl-8")}
          />
        </div>
        {/* «Всё активное» стоит ПЕРЕД «всё показанное» и работает одним
            нажатием: у владельца из 72 кабинетов профиля активных шесть, а
            забаненных 63 — «открыть все» дало бы дерево, где девять веток из
            десяти мертвы. Кнопка гаснет, когда активных нет: предлагать
            действие, которое ничего не откроет, хуже, чем не предлагать. */}
        <Button
          onClick={() => onОткрыть(активныеId)}
          disabled={!активныеId.length}
          className={cn(CTRL, CTRL_IDLE, "disabled:opacity-60")}
          /* Подсказка на обёртке не нужна: кнопка выключается только когда
             активных ноль, и это же написано числом на ней самой. */
        >
          Open all active ({активныеId.length})
        </Button>
        <Button
          onClick={() => onОтметитьМного(активныеId)}
          disabled={!активныеId.length}
          className={cn(CTRL, CTRL_IDLE, "disabled:opacity-60")}
        >
          Select all active
        </Button>
        <Button
          onClick={() => onОткрыть(видимыеId)}
          disabled={!видимыеId.length}
          className={cn(CTRL, CTRL_IDLE, "disabled:opacity-60")}
        >
          Open all shown ({видимыеId.length})
        </Button>
        <Button
          onClick={() => onОткрыть(отмечено)}
          disabled={!отмечено.length}
          className={cn(CTRL, CTRL_MUTED, "disabled:opacity-60")}
        >
          Open selected ({отмечено.length})
        </Button>
      </div>

      <p className="flex-none text-[11.5px] text-faint">
        {кабинеты.length} of {всего} ad accounts
        {отмечено.length ? ` · ${отмечено.length} selected` : ""}
      </p>

      <div className="min-h-0 flex-1 overflow-auto rounded-xl border border-border">
        {кабинеты.length ? (
          кабинеты.map((a) => {
            const отмечен = набор.has(a.act_id);
            return (
              <div
                key={a.act_id}
                className="flex items-center gap-2 border-b border-border px-3 py-1.5 last:border-0"
              >
                <input
                  type="checkbox"
                  checked={отмечен}
                  onChange={() => onОтметить(a.act_id)}
                  aria-label={`Select ${a.name || a.act_id}`}
                  className="size-3.5 flex-none accent-primary"
                />
                <span className="min-w-0 flex-1 truncate text-[12.5px] text-foreground"
                      title={a.name || a.act_id}>
                  {a.name || a.act_id}
                </span>
                <span className="hidden flex-none truncate font-mono text-[10.5px] text-faint sm:block">
                  {a.act_id}
                </span>
                {/* Состояние кабинета словом Меты, а не кружком: «DISABLED»
                    объясняет, почему в нём ничего не крутится, раньше, чем
                    человек откроет дерево. Пусто — «не снимали», и это тоже
                    сказано словом. */}
                <span className="w-24 flex-none text-right text-[11.5px] text-muted-foreground"
                      title={a.status ? "status from the collector" : "status has never been collected"}>
                  {a.status ? a.status.toLowerCase() : "not collected"}
                </span>
                <Button
                  onClick={() => onОткрыть([a.act_id])}
                  className={cn(CTRL, CTRL_IDLE, "h-[26px] px-2")}
                >
                  open
                  <ChevronRight className="size-3 flex-none" />
                </Button>
              </div>
            );
          })
        ) : (
          <p className="px-4 py-8 text-center text-[12.5px] text-muted-foreground">
            {всего
              ? "Nothing matches this search."
              : "This profile has no ad accounts we know of yet."}
          </p>
        )}
      </div>
    </div>
  );
}
