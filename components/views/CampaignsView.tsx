/** Число, а не «не считали». Отдельной функцией, потому что ноль — законное
 *  значение, и `!группа.доставляется` превратил бы его в прочерк. */
function типЧисла(v: number | null | undefined): v is number {
  return typeof v === "number" && Number.isFinite(v);
}

