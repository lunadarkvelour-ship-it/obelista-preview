/* ── крошки: где я и как вернуться ────────────────────────────────────────── */

/** Путь заходом в глубину. Не украшение: без него уровень «кабинеты» выглядит
 *  как новый лист, а не как место внутри соца, и возвращаться человеку некуда.
 *
 *  Каждая крошка — кнопка вверх. Текущий уровень кнопкой НЕ делаем: кнопка,
 *  которая никуда не ведёт, учит не нажимать соседние. */
function Крошки({ место, соцы, onСоцам, onКабинетам }: {
  место: Место;
  соцы: СоцСтрока[];
  onСоцам: () => void;
  onКабинетам: (соц: string | null) => void;
}) {
  if (место.шаг === "соцы") return null;
  const имя = место.соц
    ? соцы.find((s) => s.profile === место.соц)?.label || место.соц
    : "all connected profiles";
  const крошка = (текст: string, onPress?: () => void) =>
    onPress ? (
      <Button
        onClick={onPress}
        className="focus-ring rounded px-1 text-[11.5px] text-muted-foreground hover:text-foreground"
      >
        {текст}
      </Button>
    ) : (
      <span className="px-1 text-[11.5px] font-medium text-foreground">{текст}</span>
    );

  return (
    <nav aria-label="Where you are" className="flex flex-none flex-wrap items-center gap-0.5">
      <ChevronLeft className="size-3.5 flex-none text-faint" aria-hidden />
      {крошка("profiles", onСоцам)}
      <ChevronRight className="size-3 flex-none text-faint" aria-hidden />
      {крошка(имя, место.шаг === "дерево" ? () => onКабинетам(место.соц) : undefined)}
      {место.шаг === "дерево" ? (
        <>
          <ChevronRight className="size-3 flex-none text-faint" aria-hidden />
          {крошка(
            место.кабы.length === 1 ? "1 ad account" : `${место.кабы.length} ad accounts`,
          )}
        </>
      ) : null}
    </nav>
  );
}

