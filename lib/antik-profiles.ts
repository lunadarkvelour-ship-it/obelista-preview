/* Список профилей для билдера залива: откуда он берётся и почему не из дырки.
 *
 * ЧТО БЫЛО. Список складывался как `rows.filter(r => r.in_antik)` — то есть из
 * ответа ЛОКАЛЬНОГО API антидетекта, который слушает `127.0.0.1` на машине
 * оператора. В облаке такого API нет по устройству, серверу до него не
 * дотянуться в принципе, и признак там ложен у всех строк. Значит после
 * зачистки прода билдер в облаке показал бы пустой список и стал бы
 * неработающим инструментом — молча, без единого слова о причине.
 *
 * ПОЧЕМУ НЕЛЬЗЯ ПРОСТО СНЯТЬ ФИЛЬТР. Он появился не от лишней осторожности:
 * 06.08 в выпадающем списке жили восемь мёртвых профилей из четырнадцати, и
 * один стоял дефолтом в пресете. Предлагать залить с того, чего нет, — хуже
 * пустого списка, потому что человек выбирает и узнаёт правду в конце.
 *
 * РЕШЕНИЕ: брать ЛУЧШИЙ ДОСТУПНЫЙ признак, а не единственный.
 * Если локальный антидетект отвечает — верим ему и показываем только живые:
 * лучшее знание есть, игнорировать его незачем. Если он молчит — показываем
 * всё, что знает Обелиста, и ПОМЕЧАЕМ непроверенное.
 *
 * Пометка тут главная. «Панель говорит „профилей нет“ там, где просто закрыт
 * лаунчер» — самый дорогой класс ошибки в продукте: человек верит панели и идёт
 * чинить не то. Молчаливый полный список — та же ошибка с другой стороны.
 * Поэтому неподтверждённое показывается, но названо неподтверждённым.
 *
 * Ошибка в эту сторону дешевле и по последствиям: спека с мёртвым профилем
 * падает на заливе, который идёт на машине оператора через локальный антидетект
 * — то есть там, где правда известна, громко и сразу. Пустой список не падает
 * никогда, он просто не даёт работать.
 */

export interface РядСоца {
  profile_id: string;
  profile_name: string;
  connected: boolean;
  in_antik: boolean;
}

export interface ПрофильБилдера {
  id: string;
  name: string;
  /** Соц подключён к приложению — значит по нему поедут спенд и статусы. */
  connected: boolean;
  /** Профиль подтверждён живым источником прямо сейчас.
   *  `false` — Обелиста про него знает, но подтвердить некому. */
  подтверждён: boolean;
}

export interface ВыборПрофилей {
  профили: ПрофильБилдера[];
  /** Отвечает ли источник, который может подтвердить существование профиля.
   *  Считается по факту — есть ли хоть одна подтверждённая строка, — а не по
   *  флагу «я в облаке»: флаг забудут выставить, и панель соврёт ровно там, где
   *  её лечат. */
  подтверждениеЕсть: boolean;
}

export function профилиДляБилдера(rows: РядСоца[]): ВыборПрофилей {
  const подтверждениеЕсть = rows.some((r) => r.in_antik);
  const взять = подтверждениеЕсть ? rows.filter((r) => r.in_antik) : rows;
  return {
    подтверждениеЕсть,
    профили: взять.map((r) => ({
      id: r.profile_id,
      name: r.profile_name || r.profile_id,
      connected: r.connected,
      подтверждён: r.in_antik,
    })),
  };
}
