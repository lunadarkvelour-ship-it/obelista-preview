/**
 * Гео-срез: корзина для денег, у которых гео спросить не у кого (#150).
 *
 * ЧТО БЫЛО. Вкладки среза — `all · BD · DZ · EG` — собираются из данных, и это
 * уже честно. Нечестным было другое: строка спенда, у которой гео неизвестно,
 * проходила в «all» и НЕ ПРОХОДИЛА НИ ПОД ОДНО гео. Деньги исчезали из всех
 * срезов разом и молча — каждая вкладка честно показывала свою сумму, и только
 * сложение вкладок выдавало недостачу.
 *
 * ЗАМЕР НА ЖИВОЙ БАЗЕ 15.08, 09.08-15.08: EG 3628.15, DZ 3472.17, BD 3160.09 —
 * сумма вкладок 10260.41 против 10287.07 в «all». Пропало 26.66 на шести
 * объявлениях.
 *
 * ПОЧЕМУ ПОДПИСЬ ИМЕННО ПРО КАМПАНИЮ, А НЕ «ГЕО НЕИЗВЕСТНО». Иссус
 * предполагал сломанный разбор гео из имён кампаний. Проверка по классам
 * показала обратное: «кампания есть, гео из имени не разобралось» — НОЛЬ
 * случаев за неделю. Всё до копейки — объявления, про кампанию которых мы
 * ничего не знаем: у 422 `campaign_id` пуст вовсе, у 42 он есть, а строки
 * кампании нет. Гео живёт в имени кампании, поэтому «нет кампании» = «нет
 * гео».
 *
 * Разница между двумя подписями практическая, а не стилистическая: прочитав
 * «гео неизвестно», человек идёт править имена кампаний — то есть делать
 * работу, которой не существует. Прочитав «данные о кампании ещё не собраны»,
 * он знает, что корзина сожмётся сама, когда сбор доберётся до кампаний.
 *
 * ЗНАЧЕНИЕ ЗДЕСЬ — ЭТО СТЫК С СЕРВЕРОМ, а не украшение экрана: оно уходит в
 * `?geo=` и им же сервер отбирает строки (`core/leaderboard.ГЕО_НЕИЗВЕСТНО`).
 * Разъехаться этим двум нельзя, поэтому их сводит тест, читающий НАСТОЯЩИЙ
 * питоновский файл, а не свою копию строки (`__tests__/analytics-geo.test.ts`).
 */

/** Значение среза «гео не у кого спросить». Двухбуквенным кодом страны быть не
 *  может, поэтому с настоящим гео не столкнётся никогда. */
export const GEO_UNKNOWN = "none";

/** Подпись вкладки. `null` — весь срез. */
export function geoLabel(geo: string | null | undefined): string {
  if (!geo) return "all";
  return geo === GEO_UNKNOWN ? "no campaign data" : geo;
}

/** То же, но для колонки «Geo» в строке крео: она 84 пикселя шириной, и
 *  полная подпись в неё не влезает. Отдельная функция, а не обрезка на месте:
 *  сокращение — это тоже подпись, и придумывать её в разметке значит завести
 *  второй источник правды на тот же смысл. */
export function geoShort(geo: string | null | undefined): string {
  if (!geo) return "";
  return geo === GEO_UNKNOWN ? "n/a" : geo;
}

/** Почему эта вкладка вообще есть — текст для подсказки под курсором.
 *  Пустая строка у обычного гео: подсказка «DZ значит DZ» только мешает. */
export function geoHint(geo: string | null | undefined): string {
  return geo === GEO_UNKNOWN
    ? "Spend we can't place: these ads have no campaign collected yet, and geo comes from the campaign name. It isn't a country with zero spend — it's spend we can't attribute. The bucket shrinks as campaigns get collected."
    : "";
}

/** Список вкладок в том порядке, в каком их читают: страны по алфавиту, а
 *  корзина последней.
 *
 *  Последней не из вежливости: она не страна, и вставать между `DZ` и `EG` ей
 *  незачем. Сортировка обычная строковая поставила бы `none` ровно туда, и
 *  вкладка читалась бы как ещё одно гео. */
export function geoTabs(seen: Iterable<string>): string[] {
  const все = [...new Set([...seen])].filter(Boolean);
  const страны = все.filter((g) => g !== GEO_UNKNOWN).sort();
  return все.includes(GEO_UNKNOWN) ? [...страны, GEO_UNKNOWN] : страны;
}
