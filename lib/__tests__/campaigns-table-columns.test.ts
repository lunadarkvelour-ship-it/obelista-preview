/* ШАПКА, СТРОКИ И ФУТЕР ЛИСТА — ОДНА ТАБЛИЦА, И ЭТО ДЕРЖИТСЯ МЕХАНИЗМОМ.
 *
 * Шапки у листа не было вовсе, и владелец 15.08 сказал ровно это: непонятно,
 * какая цифра к какой метрике. Шапка появилась — и вместе с ней договорённость
 * между ЧЕТЫРЬМЯ местами: заголовок, строка кабинета, строка объекта, футер.
 * Написанная словами («не забудь поправить все четыре»), она живёт до первой
 * правки: цифра под чужой подписью — это не «немного съехало», это чужие деньги
 * под чужим именем.
 *
 * НА ЭТОЙ ТАБЛИЦЕ СХОДЯТСЯ ТРИ ЧУЖИХ КОНТРАКТА, и потому сверка тут не
 * формальность:
 *   • РАМКА (`РАМКА_ЛИСТА` в `lib/campaigns-tree`) — имя, статус, возраст,
 *     кнопка. Выключить их нельзя никогда: это не метрики, а условия доверия к
 *     строке;
 *   • МЕТРИКИ (`CAMP_COLUMNS` в `lib/campaigns-columns`, #159) — выключаемые,
 *     их набор выбирает человек;
 *   • ВОРОНКА (`колонкиВоронки` в `lib/campaigns-funnel`) — список ИЗ ОТВЕТА
 *     источника, наш файл его не знает заранее.
 *
 * Тест читает НАСТОЯЩИЙ ОТРИСОВАННЫЙ ВЫВОД всех четырёх мест, а не свою копию
 * списка: фикстура, переписанная руками, подтверждала бы представление автора
 * вместо вывода компонентов.
 *
 * ПРОВЕРЕНО НА КРАСНОМ, А НЕ ОБЕЩАНО. Три подлома прогнаны руками, вот что
 * вышло — и что это значит:
 *
 *   1. убрать `data-col` у клетки метрики → краснеют ЧЕТЫРЕ проверки, включая
 *      сам отрицательный контроль;
 *   2. написать ширину рамки в шапке РУКАМИ мимо контракта → краснеет проверка
 *      ширины и называет колонку по имени;
 *   3. поменять ширину В САМОМ контракте → зелено, и это ВЕРНО: шапка, строки
 *      и футер берут её оттуда же и едут вместе. Механизм стережёт РАСХОЖДЕНИЕ
 *      мест, а не значение ширины, и обещать здесь большее было бы той самой
 *      неправдой рядом с честной проверкой.
 */
import { describe, expect, it } from "vitest";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import {
  МИН_ИМЯ, РАМКА_ЛИСТА, картаБюджетов, колонка, плоскийЛист, поКабинетам,
  строкиФутера, ширинаТаблицы,
} from "@/lib/campaigns-tree";
import {
  CAMP_COLUMNS, итоги, колонки as видимыеКолонки,
} from "@/lib/campaigns-columns";
import { подготовить } from "@/lib/campaigns-funnel";
import {
  FUNNEL_BY_ID, FUNNEL_DERIVED_BY_ID, FUNNEL_METRICS, LEADERBOARD_FUNNEL_IDS,
  type FunnelMetricId,
} from "@/lib/funnel-metrics";
import type { CampaignRow, Level } from "@/lib/campaigns";
import {
  AccountFloor, CampRow, ФутерТотал, БезРодителяРяд, ШапкаКолонок,
} from "@/components/views/CampaignsView";

const NOW = Date.parse("2026-08-15T12:00:00Z");

const R = (p: Partial<CampaignRow> & { fb_id: string; level: Level }): CampaignRow =>
  ({ parent_id: null, act_id: "act_1", name: p.fb_id, status: "ACTIVE", ...p } as CampaignRow);

/** Метки колонок в порядке отрисовки. Читается из HTML, а не из пропсов:
 *  проверять надо то, что увидит человек. */
const колонкиИз = (html: string) =>
  [...html.matchAll(/data-col="([^"]+)"/g)].map((m) => m[1]);

/* ВСЕ колонки каталога, а не состав по умолчанию: проверять надо ту таблицу,
   которую человек может себе собрать, включая ступени воронки. */
const МЕТРИКИ = видимыеКолонки(CAMP_COLUMNS.map((c) => c.key));
/* Связка воронки: строки есть, чтобы ячейки ступеней рисовали числа, а не
   только «не загружено». */
const ОТВЕТ_ВОРОНКИ = {
  ok: true, metrics: ["sub", "ftd"], lead_metric: "sub",
  rows: { c1: { sub: 12, ftd: 3 } },
  unmatched: { ambiguous: [] },
} as never;
const КОЛОНКИ = { метрики: МЕТРИКИ, ctx: подготовить(ОТВЕТ_ВОРОНКИ) };

/** Ожидаемая последовательность меток: имя → метрики → рамка справа.
 *  Собирается ИЗ ТЕХ ЖЕ источников, что и разметка, а не переписывается. */
const ОЖИДАЕМО = [
  "name",
  ...МЕТРИКИ.map((c) => c.key),
  "status", "age", "action",
];

const НАБОР: CampaignRow[] = [
  R({ fb_id: "c1", level: "campaign", spend: 1234, daily_budget: 7000,
      currency: "USD", active_ads: 2, impressions: 5000, clicks: 100,
      checked_at: "2026-08-15T11:40:00Z" }),
  R({ fb_id: "s1", level: "adset", parent_id: "c1" }),
  R({ fb_id: "a9", level: "ad", parent_id: "нет-такого" }),
];
const ЭТАЖИ = поКабинетам(НАБОР);
const СТРОКИ = плоскийЛист(ЭТАЖИ, {
  иначе: new Set<string>(), подФильтром: true, одинКабинет: true,
});

function нарисовать(вид: "кабинет" | "объект" | "без родителя" | "футер"): string {
  if (вид === "футер") {
    return renderToStaticMarkup(createElement(ФутерТотал, {
      итог: итоги(строкиФутера(ЭТАЖИ), { воронка: подготовить(ОТВЕТ_ВОРОНКИ) }),
      счёт: { campaign: 1, adset: 1, ad: 1 },
      кабинетов: ЭТАЖИ.length, колонки: КОЛОНКИ,
    }));
  }
  const с = СТРОКИ.find((x) => x.вид === вид);
  if (!с) throw new Error(`в наборе нет строки вида «${вид}» — тест проверял бы пустоту`);
  if (с.вид === "кабинет") {
    return renderToStaticMarkup(createElement(AccountFloor, {
      группа: с.группа, имя: "Hiuhiu_MediaBuyer_3.8_2", now: NOW,
      open: с.open, hasKids: с.hasKids, onToggle: () => {}, колонки: КОЛОНКИ,
    }));
  }
  if (с.вид === "без родителя") {
    return renderToStaticMarkup(createElement(БезРодителяРяд, {
      сколько: с.сколько, depth: с.depth, open: с.open, onToggle: () => {},
      колонки: КОЛОНКИ,
    }));
  }
  return renderToStaticMarkup(createElement(CampRow, {
    item: с.item, now: NOW, pending: {},
    бюджет: картаБюджетов(НАБОР).get(с.item.node.row.fb_id),
    колонки: КОЛОНКИ,
    onToggle: () => {}, onSwitch: () => {},
  }));
}

const ВИДЫ = ["кабинет", "объект", "без родителя", "футер"] as const;

describe("колонки шапки, строк и футера — один и тот же список", () => {
  it("список не пустой и без повторов", () => {
    /* Сверка пустого с пустым зелена ровно так же, как сверка полного с
       полным, и не проверяет ничего. */
    expect(ОЖИДАЕМО.length).toBeGreaterThanOrEqual(5);
    expect(new Set(ОЖИДАЕМО).size).toBe(ОЖИДАЕМО.length);
    expect(МЕТРИКИ.length).toBeGreaterThan(0);
    /* Ступени воронки — тоже колонки каталога (#159 забрал их группой), и они
       обязаны быть в этой таблице: иначе тест проверяет половину экрана. */
    expect(МЕТРИКИ.map((c) => c.key)).toContain("sub");
    /* КОЛОНКА БЕЗ ШИРИНЫ СХЛОПЫВАЕТСЯ В НОЛЬ — и это не «немного съехало», а
       пустой экран: на живом проде колонка имени была шириной 0, и развёрнутое
       дерево показывало голые «camp», «adset», «ad» без единого имени. Поэтому
       ширина обязана быть ЧИСЛОМ у всех, кроме имени, которое тянется само и
       имеет свой минимум. */
    for (const c of РАМКА_ЛИСТА) {
      if (c.ключ === "name") expect(c.ширина, c.ключ).toBeNull();
      else expect(c.ширина ?? 0, c.ключ).toBeGreaterThan(0);
    }
    expect(МИН_ИМЯ).toBeGreaterThan(0);
  });

  it("шапка печатает ровно этот список и подписи рамки", () => {
    const h = renderToStaticMarkup(createElement(ШапкаКолонок, { колонки: КОЛОНКИ }));
    expect(колонкиИз(h)).toEqual(ОЖИДАЕМО);
    for (const c of РАМКА_ЛИСТА) {
      if (c.подпись) expect(h, c.ключ).toContain(`>${c.подпись}<`);
    }
    /* Подписи метрик — из каталога, а не набранные во вьюхе. */
    for (const c of МЕТРИКИ) expect(h, c.key).toContain(c.title);
  });

  for (const вид of ВИДЫ) {
    it(`«${вид}» несёт те же колонки в том же порядке`, () => {
      expect(колонкиИз(нарисовать(вид))).toEqual(ОЖИДАЕМО);
    });
  }

  it("ширина рамки — ОДНО ЧИСЛО на шапку, строку и футер", () => {
    /* Ширина классом Tailwind тут отработала своё: класс существует только
       после сборки и его нельзя сложить, а таблице нужна СУММА, чтобы
       прокручиваться вместо сжатия. */
    const места = [
      renderToStaticMarkup(createElement(ШапкаКолонок, { колонки: КОЛОНКИ })),
      ...ВИДЫ.map(нарисовать),
    ];
    for (const html of места) {
      for (const c of РАМКА_ЛИСТА) {
        const кл = new RegExp(`data-col="${c.ключ}"[^>]*style="([^"]*)"`).exec(html);
        expect(кл, `нет стиля у колонки ${c.ключ}`).not.toBeNull();
        if (c.ширина == null) {
          expect(кл![1], c.ключ).toContain(`min-width:${МИН_ИМЯ}px`);
        } else {
          expect(кл![1], c.ключ).toContain(`width:${c.ширина}px`);
        }
      }
    }
  });

  it("таблица знает свою полную ширину — иначе ей нечем прокручиваться", () => {
    /* Сумма обязана расти вместе с колонками: иначе она однажды окажется меньше
       содержимого, и сжатие вернётся тем же способом, что и в первый раз. */
    const узкая = ширинаТаблицы(видимыеКолонки(["spend"]));
    const широкая = ширинаТаблицы(МЕТРИКИ);
    expect(узкая).toBeGreaterThan(МИН_ИМЯ);
    expect(широкая).toBeGreaterThan(узкая);
    /* И она НЕ меньше того, что реально занимают колонки. */
    const сумма = МЕТРИКИ.reduce((n, c) => n + c.width, 0)
      + РАМКА_ЛИСТА.reduce((n, c) => n + (c.ширина ?? МИН_ИМЯ), 0);
    expect(широкая).toBeGreaterThanOrEqual(сумма);
  });

  it("ширина метрики — ЧИСЛОМ из каталога, одна на шапку и строку", () => {
    /* Число, а не класс, — правило каталога: три места, пишущие `w-24` по
       памяти, дают три разные ширины через месяц. */
    const шапка = renderToStaticMarkup(createElement(ШапкаКолонок, { колонки: КОЛОНКИ }));
    const строка = нарисовать("объект");
    for (const c of МЕТРИКИ) {
      expect(шапка, `шапка ${c.key}`).toContain(`width:${c.width}px`);
      expect(строка, `строка ${c.key}`).toContain(`width:${c.width}px`);
    }
  });

  it("сверка правда ловит расхождение — проверено на КРАСНОМ", () => {
    /* Отрицательный контроль данными: убери из настоящей разметки одну клетку
       — сверка обязана покраснеть. Без этого шага зелёные строки выше не
       значат ничего: проверка, не проверенная на красном, — украшение вывода. */
    const строка = нарисовать("объект");
    expect(колонкиИз(строка)).toEqual(ОЖИДАЕМО);
    expect(колонкиИз(строка.replace('data-col="spend"', 'data-было="spend"')))
      .not.toEqual(ОЖИДАЕМО);
    /* И порядок тоже: перестановка меток обязана быть замечена. */
    expect(колонкиИз('<span data-col="spend"></span><span data-col="name"></span>'))
      .not.toEqual(["name", "spend"]);
    /* И ступень воронки — такая же колонка: пропала — сверка краснеет. */
    expect(колонкиИз(строка.replace('data-col="sub"', 'data-было="sub"')))
      .not.toEqual(ОЖИДАЕМО);
  });

  it("колонки, которой нет в рамке, не бывает молча", () => {
    /* Пустая ширина вместо ошибки дала бы схлопнутую колонку и вид «слегка
       съехало» вместо поломки. */
    expect(() => колонка("no-such" as never)).toThrow(/РАМКА_ЛИСТА/);
  });
});

/* ── ОКНО ДОЕЗЖАЕТ ДО КЛЕТКИ, А НЕ ТЕРЯЕТСЯ ПО ДОРОГЕ ────────────────────────
 *
 * Каталог объясняет пустой охват по-разному, и точный ответ у него есть только
 * тогда, когда он знает ОКНО: «за семь дней точного охвата не бывает» чинится
 * выбором одного дня, а «за этот день не собрано» — сбором. Без окна он честно
 * отказывается выбирать между ними («without knowing the window we will not
 * claim either»), и это не поломка, а вежливое незнание — которое человеку
 * ничего не говорит.
 *
 * Проверяется не текст каталога (он его хозяин), а МОЯ ПРОВОДКА: доехало ли
 * окно до клетки. Оговорка про то, ЧТО ИМЕННО ловит эта проверка, стоит здесь
 * не случайно — первая её версия сверялась с фразой, которой в коде уже нет
 * (её убрал 3ce1d9e4), и отрицательный контроль это и показал. Проверять надо
 * то, что код делает сегодня, а не то, что о нём рассказали. */
describe("период доезжает до ячейки охвата", () => {
  const СТРОКА = R({
    fb_id: "a1", level: "ad", parent_id: null, spend: 187_312, currency: "USD",
    impressions: 412_004, clicks: 3128,
  });
  const ОКНО = {
    since: "2026-08-09", until: "2026-08-15", tz: "UTC+3", days: 7,
    today: "2026-08-15",
  } as never;
  const рисуем = (период?: unknown) => {
    const этажи = поКабинетам([СТРОКА]);
    const [строка] = плоскийЛист(этажи, {
      иначе: new Set<string>(), подФильтром: true, одинКабинет: true,
    }).filter((x) => x.вид === "объект");
    if (!строка || строка.вид !== "объект") throw new Error("строки объекта нет");
    return renderToStaticMarkup(createElement(CampRow, {
      item: строка.item, now: NOW, pending: {},
      колонки: { метрики: видимыеКолонки(["spend", "reach"]), период: период as never },
      onToggle: () => {}, onSwitch: () => {},
    }));
  };

  it("с окном ячейка называет НАСТОЯЩУЮ причину, а не выдуманную", () => {
    const h = рисуем(ОКНО);
    expect(h).toMatch(/exact for a single day only/i);
    /* И главное: не утверждает того, что опровергает спенд в этой же строке. */
    expect(h).not.toMatch(/No spend rows for this ad/i);
  });

  it("без окна точной причины НЕ появляется — значит проверка живая", () => {
    /* Отрицательный контроль ДАННЫМИ: убери окно из проводки — и точный ответ
       пропадает, остаётся отказ выбирать. Если это когда-нибудь совпадёт с
       веткой «с окном», проверка выше перестанет что-либо значить. */
    const h = рисуем(undefined);
    expect(h).not.toMatch(/exact for a single day only\. Over/i);
    expect(h).toMatch(/without knowing the window/i);
  });

  it("спенд в этой же строке правда есть — иначе спорить было бы не с чем", () => {
    expect(рисуем(ОКНО)).toMatch(/data-col="spend"[^>]*>\$1873</);
  });
});

/* ── воронка «Кампаний» — тот же каталог, что на «Аналитике» ──────────────
 *
 * Требование владельца дословно: метрики воронки «должны быть ОДИНАКОВЫЕ с
 * листом creative analytics». Проверяем не «похоже», а ДОСЛОВНО: ключ, подпись
 * и расшифровка колонки этого листа берутся из общего каталога
 * (`lib/funnel-metrics`), и разойтись им теперь негде — а если кто-то заведёт
 * здесь второй список, покраснеет эта проверка и назовёт ступень по имени. */
describe("группы ВОРОНКА и ЦЕНЫ собраны из общего каталога", () => {
  const группа = (g: string) => CAMP_COLUMNS.filter((c) => c.group === g);

  it("состав группы «воронка» — ступени каталога, и ни одной чужой", () => {
    const ключи = группа("воронка").map((c) => c.key as string);
    for (const k of ключи) {
      expect(FUNNEL_BY_ID[k as FunnelMetricId], `ступень ${k} не из каталога`).toBeTruthy();
    }
    // Каждая ступень, доехавшая до лидерборда «Аналитики», обязана быть и тут.
    for (const id of LEADERBOARD_FUNNEL_IDS) expect(ключи).toContain(id);
  });

  it("подписи ступеней ДОСЛОВНО каталожные", () => {
    for (const c of группа("воронка")) {
      const m = FUNNEL_BY_ID[c.key as unknown as FunnelMetricId];
      expect(c.title, c.key).toBe(m.title);
      expect(c.hint, c.key).toBe(m.hint);
      // Складывать ступени можно и нужно: это события, а не уникальные люди.
      expect(c.total, c.key).toBe("sum");
    }
  });

  it("цены ступеней стоят ровно там, где каталог их объявил", () => {
    const цены = группа("эффективность").map((c) => c.key as string);
    for (const m of FUNNEL_METRICS) {
      if (!m.cost) continue;
      if (!LEADERBOARD_FUNNEL_IDS.includes(m.id as never)) continue;
      expect(цены, `нет цены ${m.cost} для ${m.id}`).toContain(m.cost);
      const c = CAMP_COLUMNS.find((x) => (x.key as string) === m.cost)!;
      expect(c.title).toBe(FUNNEL_DERIVED_BY_ID[m.cost].title);
      expect(c.hint).toBe(FUNNEL_DERIVED_BY_ID[m.cost].hint);
      // Из СУММ, а не среднее по строкам: кампания с тысячей подписчиков и
      // кампания с двумя не имеют равного веса.
      expect(c.total, m.cost).toBe("derived");
    }
  });

  it("ВЫРУЧКИ В КОЛОНКАХ ЛИСТА НЕТ — её приносит только ответ источника", () => {
    /* Колонки собираются из `ступениАналитики()`, то есть из лидерборда. Стой
       тут Revenue статически, весь парк видел бы прочерк под словом «Revenue»,
       что читается как «заработали ноль». */
    expect(CAMP_COLUMNS.map((c) => c.key as string)).not.toContain("revenue");
  });
});
