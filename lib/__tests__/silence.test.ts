/* Тишина в цифрах видна как тишина, а не как ноль — панельная половина #122.
 *
 * ПРОВЕРЯЕМ НЕ «читается ли поле», а способы соврать, каждый из которых тише
 * самого дефекта:
 *
 *  1. Ноль вместо незнания. Строка, у которой воронка не приезжала ни разу,
 *     обязана показывать пробел, а не «0 депов»: это два разных вывода и два
 *     разных действия, а по этим цифрам ещё и тушат автоправила.
 *  2. Метка «не собрано» на СОБРАННОМ. Она дороже пропуска: отменяет доверие ко
 *     всем остальным меткам, и тогда байер снова читает нули как нули. Значит
 *     ни старый демон, ни частично собранная группа метку получать не должны.
 *  3. Рукописный список мест, где цифра может оказаться несобранной. Он не
 *     знает про источник и колонку, которых ещё нет, — и молча пропустит их
 *     ровно тогда, когда они появятся.
 */
import { describe, expect, it } from "vitest";
import {
  readSilence,
  shortDay,
  silenceNote,
  ячейкаНеСобрана,
  колонкаЧитаетВоронку,
  ВОРОНОЧНЫЕ_ПОЛЯ,
} from "@/lib/silence";
import { COLUMNS, type ColKey } from "@/lib/analytics-columns";
import { buildTree, derive, type Node } from "@/lib/analytics-tree";
import type { AdRow } from "@/lib/analytics";

/** Ответ демона: полный блок «тишина» за неделю с двумя дырами. */
const ТИШИНА = {
  дней: 7,
  spend: {
    собрано_дней: 5,
    молчат: ["2026-08-13", "2026-08-14"],
    последний_сбор: "2026-08-15T04:11:02+00:00",
  },
  funnel: { собрано_дней: 7, молчат: [], последний_сбор: "2026-08-15T04:12:00+00:00" },
  кабинетов_молчит: 3,
  кабинеты_молчат: ["act_1", "act_2", "act_3"],
  молчит: true,
};

const объявление = (p: Partial<AdRow> & { fb_id: string }): AdRow => ({
  ad_name: p.fb_id, creative: "cr", act_id: "act_1", act_name: null, agency: null,
  campaign_id: null, campaign: null, adset_id: null, adset: null, geo: null,
  attrib_method: null, attrib_confidence: null, effective_status: null,
  socials: [], owner_profile: null,
  spend: 10, clicks: 100, sub: 0, contact: 0, checkout: 0, ftd: 0, rd: 0,
  ...p,
});

describe("разбор блока: половинчатый ответ не становится «всё собрано»", () => {
  it("поля нет вовсе — null, а не спокойствие", () => {
    /* `null` значит «демон старше контракта». Сказать на этом «данные полные» —
       ровно то враньё, против которого весь иссус. */
    expect(readSilence(undefined)).toBeNull();
    expect(readSilence({})).toBeNull();
    expect(readSilence({ дней: 7 })).toBeNull();
    expect(readSilence("тишина")).toBeNull();
  });

  it("сводный признак берётся у демона и здесь НЕ пересчитывается", () => {
    /* Правило «что считать тишиной» живёт в одном месте (`core/silence`). Две
       копии на двух языках разъедутся молча, а по этим цифрам тушат кампании.
       Ловушка: демон говорит «молчит: false» при непустых списках — панель
       обязана послушаться его, а не свой вывод из списков. */
    const s = readSilence({ ...ТИШИНА, молчит: false })!;
    expect(s.молчит).toBe(false);
    expect(silenceNote(s)).toBeNull();
  });
});

describe("источники не перечислены руками", () => {
  it("третий источник, о котором панель не знает, всё равно виден", () => {
    /* Демон заведёт второй трекер или свой сборщик кликов — пара полей
       `spend`/`funnel` его молча не заметит, и экран скажет «всё собрано», не
       спросив про него. Источники вычитываются ПО ФОРМЕ. */
    const s = readSilence({
      ...ТИШИНА,
      clicks2: { собрано_дней: 4, молчат: ["2026-08-10"], последний_сбор: null },
    })!;
    expect(s.источники.map((и) => и.key).sort()).toEqual(["clicks2", "funnel", "spend"]);
    expect(silenceNote(s)!.detail).toContain("clicks2");
  });

  it("посторонние поля источниками не притворяются", () => {
    const s = readSilence(ТИШИНА)!;
    expect(s.источники.map((и) => и.key).sort()).toEqual(["funnel", "spend"]);
  });
});

describe("слова: что именно не собрано и чем это НЕ является", () => {
  const note = silenceNote(readSilence(ТИШИНА))!;

  it("названы дни, а не только их число", () => {
    expect(note.detail).toContain("2 of 7 days have no spend collected at all");
    expect(note.detail).toContain("Aug 13, Aug 14");
  });

  it("собранный источник в тексте не упоминается вовсе", () => {
    /* Воронка в этом окне собрана целиком. Написать про неё «0 дней молчат»
       значит утопить настоящую дыру в списке того, что в порядке. */
    expect(note.detail).not.toContain("funnel");
  });

  it("кабинеты, к которым не ходили НИ РАЗУ, названы отдельно", () => {
    /* Самый опасный случай: каб в списке есть, спенд ноль, читается как «не
       тратил», а мы к нему просто не ходили. */
    expect(note.detail).toContain("3 ad accounts were not polled once");
  });

  it("сказано, что ноль тут не ноль И что это не «протухший спенд»", () => {
    /* #149 про другое: там спросили слишком рано и число занижено; здесь не
       спрашивали вовсе. Общая фраза «цифрам не верь» на оба случая приводит к
       тому, что не верят ничему и не чинят ничего. */
    expect(note.detail).toContain('means "not collected"');
    expect(note.detail).toContain("arrived too early in the day");
  });

  it("день печатается разбором строки, а не через Date", () => {
    /* `new Date("2026-08-14")` — полночь UTC, и в минусовом поясе печатается
       ВЧЕРАШНИМ днём. Подпись «не собрано 13-го» на дыре за 14-е хуже, чем
       отсутствие подписи. */
    expect(shortDay("2026-08-14")).toBe("Aug 14");
    expect(shortDay("2026-01-01")).toBe("Jan 1");
    expect(shortDay("мусор")).toBe("мусор");
  });
});

describe("колонки воронки не перечислены руками", () => {
  it("список полей взят из каталога колонок, а не переписан", () => {
    /* Каталог и есть место, где объявлено, что такое воронка. Копия здесь
       отстала бы от него на первой же новой ступени. */
    expect([...ВОРОНОЧНЫЕ_ПОЛЯ].sort())
      .toEqual(COLUMNS.filter((c) => c.group === "воронка").map((c) => c.key).sort());
    expect(ВОРОНОЧНЫЕ_ПОЛЯ.length).toBeGreaterThanOrEqual(5);
  });

  it("производные колонки попадают в проверку САМИ, без упоминания в коде", () => {
    /* Главное место этого файла. Зависимость определяется опытом: стираем на
       пробной строке цифры воронки и смотрим, изменилось ли значение. Поэтому
       CPFTD, Sub→FTD и Clicks/FTD покрыты, хотя нигде не перечислены, — и
       завтрашняя производная будет покрыта так же. */
    for (const key of ["ftd", "rd", "sub", "cpftd", "sub_to_ftd", "clicks_per_ftd"] as ColKey[]) {
      expect(колонкаЧитаетВоронку(key), `${key} читает воронку`).toBe(true);
    }
    /* А спенд и клики — не читают, и метка на них была бы враньём: их собирает
       другой источник, и молчание трекера про них ничего не говорит. */
    for (const key of ["spend", "clicks", "geos"] as ColKey[]) {
      expect(колонкаЧитаетВоронку(key), `${key} воронку не читает`).toBe(false);
    }
  });

  it("«with FTD» проба НЕ ловит, и потому он честен у себя дома", () => {
    /* Граница метода, названная вслух. Проба отвечает на вопрос «читает ли
       воронку `derive`», а `ads_with_ftd` считается раньше — при сборке узла из
       строки ответа. Значит его честность обязана жить там же: у объявления,
       чья воронка не приезжала, это поле пустое, а не ноль.
       Метод не «почти работает» — у него есть край, и край проверен. */
    expect(колонкаЧитаетВоронку("ads_with_ftd")).toBe(false);
    const [каб] = buildTree([{ ...объявление({ fb_id: "1", ftd: 0 }), funnel_at: null }]);
    const n = каб.children![0].children![0].children![0];
    expect(n.ads_with_ftd).toBeNull();
    expect(каб.ads_with_ftd).toBeNull();
  });

  it("вопрос задан КОЛОНКЕ, а не паре «колонка и строка»", () => {
    /* На строке с нулевыми подписками `Sub→FTD` отдаёт прочерк по делению на
       ноль — и по значению неотличим от колонки, воронку не читающей вовсе.
       Свойство колонки от попавшейся строки зависеть не должно, иначе метка
       появлялась бы через раз и выглядела бы случайной. */
    expect(колонкаЧитаетВоронку("sub_to_ftd")).toBe(true);
  });

  it("ни одна колонка каталога не осталась без ответа", () => {
    /* Обход, который ничего не проверил, зелёный ровно так же. Здесь важно, что
       вопрос ЗАДАН каждой колонке — включая ту, которую заведут завтра. */
    for (const c of COLUMNS) expect(typeof колонкаЧитаетВоронку(c.key)).toBe("boolean");
  });
});

describe("ячейка: ноль, которого не было, показан пробелом", () => {
  /** Кладём `funnel_at` ровно так, как это делает JSON: ключа нет вовсе либо
   *  он есть со значением. Через объект, а не через `?? null`, потому что вся
   *  проверка именно про разницу этих двух случаев. */
  function objectWith(r: AdRow, funnel_at: string | null | undefined): AdRow {
    return funnel_at === undefined ? r : { ...r, funnel_at };
  }

  /** Узел объявления: каб → кампания → адсет → объявление. */
  const объява = (funnel_at: string | null | undefined): Node => {
    const [каб] = buildTree([objectWith(объявление({ fb_id: "1", ftd: 0, sub: 0 }), funnel_at)]);
    return каб.children![0].children![0].children![0];
  };

  it("демон сказал «не приезжало ни разу» — вместо нулей пробел", () => {
    const n = объява(null);
    expect(n.funnel_at).toBeNull();
    expect(ячейкаНеСобрана(n, "ftd")).toBe(true);
    expect(ячейкаНеСобрана(n, "sub_to_ftd")).toBe(true);
    /* Спенд собран другим источником и остаётся числом: пометить его значило бы
       соврать в другую сторону. */
    expect(ячейкаНеСобрана(n, "spend")).toBe(false);
  });

  it("демон постарше поля не прислал — НИ ОДНОЙ метки", () => {
    /* Пометить весь лист «не собрано» на старом демоне значит отменить доверие
       ко всем меткам разом первым же обновлением. */
    const n = объява(undefined);
    expect(n.funnel_at).toBeUndefined();
    expect(ячейкаНеСобрана(n, "ftd")).toBe(false);
  });

  it("воронка приезжала — ноль остаётся нулём", () => {
    const n = объява("2026-08-15T04:00:00+00:00");
    expect(ячейкаНеСобрана(n, "ftd")).toBe(false);
    expect(derive(n, "ftd")).toBe(0);
  });
});

describe("группа: метка не ставится на частично собранное", () => {
  /** Каб с двумя объявлениями — та самая группа, у которой цифры суммой. */
  const два = (a: string | null, b: string | null): Node[] =>
    buildTree([
      { ...объявление({ fb_id: "1", ftd: 3 }), funnel_at: a },
      { ...объявление({ fb_id: "2", ftd: 0 }), funnel_at: b },
    ]);

  it("приехало хоть у одного — сумма частично настоящая, метки нет", () => {
    /* Здесь правило ПРОТИВОПОЛОЖНО возрасту спенда, где решает слабое звено.
       Там вопрос «насколько стара сумма», тут — «есть ли в ней собранное».
       Метка на собранном дороже пропуска. */
    const [каб] = два("2026-08-15T04:00:00+00:00", null);
    expect(каб.funnel_at).toBe("2026-08-15T04:00:00+00:00");
    expect(ячейкаНеСобрана(каб, "ftd")).toBe(false);
  });

  it("не приехало ни у кого — метка на всей группе", () => {
    const [каб] = два(null, null);
    expect(каб.funnel_at).toBeNull();
    expect(ячейкаНеСобрана(каб, "ftd")).toBe(true);
  });

  it("самая свежая отметка среди детей, а не самая старая", () => {
    const [каб] = два("2026-08-10T00:00:00+00:00", "2026-08-15T00:00:00+00:00");
    expect(каб.funnel_at).toBe("2026-08-15T00:00:00+00:00");
  });
});
