/* Какая дверь показывается на первом экране продукта.
 *
 * ПАРОЛЕЙ В ЭТОМ ФАЙЛЕ НЕТ И НЕ БУДЕТ — ни настоящих, ни выдуманных. Пароль
 * владельца не существует ни для одной линии: он вводит его сам в форме.
 * Поэтому здесь проверяется решение и вёрстка, а не отправка формы: чтобы
 * проверить отправку, пришлось бы написать пароль, а тест, ради которого в
 * репозиторий кладут пароль, вреднее отсутствующего.
 *
 * Почему решение вынесено из страницы: ответ `/auth/me` приезжает эффектом, а
 * `renderToStaticMarkup` эффектов не выполняет — до состояния «сервер ответил»
 * из вёрстки не добраться. То же место, на котором сегодня уже дважды ловили
 * ложное зелёное.
 */
import { describe, it, expect, vi } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { дверь, дверьДоОтвета } from "@/lib/auth-screen";
import { authErrorText } from "@/lib/auth-copy";
/* Подменяется ТОЛЬКО навигация: страница — клиентский компонент Next и без
   контекста роутера не рисуется вовсе («invariant expected app router to be
   mounted»). Тексты, разметка и решение остаются настоящими — мок, который
   подставляет свои строки вместо продуктовых, перестаёт быть глазами и
   становится зеркалом. Сегодня это уже пряталo ровно тот дефект, ради которого
   смотрелку и заводили. */
vi.mock("next/navigation", () => ({
  useRouter: () => ({ replace: () => {}, push: () => {} }),
  useSearchParams: () => new URLSearchParams(),
}));

import LoginPage from "@/app/login/page";

describe("дверь выбирается по ответу сервера", () => {
  it("свежая установка: отказ, но учёток нет — заводим первую", () => {
    /* Главный случай. Сервер отвечает 401, потому что войти ещё некем, и
       признак приходит ИМЕННО в отказе. Живи он только в успехе, панель узнала
       бы про свежую установку ровно никогда. */
    expect(дверь({ отвечено: true, вошёл: false, свежаяУстановка: true })).toBe("регистрация");
  });

  it("установка занята — обычный вход", () => {
    expect(дверь({ отвечено: true, вошёл: false, свежаяУстановка: false })).toBe("вход");
  });

  it("сессия жива — человека тут не держим", () => {
    expect(дверь({ отвечено: true, вошёл: true, свежаяУстановка: false })).toBe("внутрь");
  });

  it("сервер про установку не сказал — считаем занятой, а не «неизвестно»", () => {
    /* Старый сервер поля не присылает. Показать на этом форму первой
       регистрации значило бы предложить завести админа установке, где учётки
       давно есть. Ошибка в эту сторону дешевле: человек увидит вход, которым
       и так умеет пользоваться. */
    expect(дверь({ отвечено: true, вошёл: false })).toBe("вход");
  });

  it("ответа ещё нет — это отдельное состояние, а не «вход»", () => {
    expect(дверь({ отвечено: false, вошёл: false, свежаяУстановка: true })).toBe("ждём");
  });

  it("до ответа рисуем форму входа, а не пустоту", () => {
    // Человек, пришедший по 401, начинает печатать сразу; запертые на время
    // проверки поля съедают первые нажатия.
    expect(дверьДоОтвета()).toBe("вход");
  });
});

describe("дверь читает «свежая ли установка», а НЕ «открыта ли регистрация»", () => {
  /* Иссус #143, и охраняется он чтением ИСХОДНИКА страницы, а не поведения
     функции. Причина именно в этом: `дверь()` берёт то, что ей дали, и на любом
     значении ведёт себя правильно. Ошибка была этажом выше — страница положила
     в аргумент не то поле, потому что до 15.08 «установка свободна» и «можно
     зарегистрироваться» были одним вопросом с одним именем. Тест на функцию
     такого не ловит вовсе: он зелёный при обеих проводках.

     Что сломается, если проводку вернут: `registration_open` сегодня всегда
     `true`, значит СВЕЖЕЙ покажется каждая установка, и продукт начнёт
     предлагать завести первую учётку тем, у кого она давно есть. Молча и
     выглядя исправным. */
  const страница = readFileSync(
    path.resolve(__dirname, "..", "..", "app", "login", "page.tsx"), "utf8");

  it("в дверь передаётся признак свежей установки", () => {
    expect(страница).toMatch(/дверь\(\{[^}]*свежаяУстановка:/);
  });

  it("`registrationOpen` из ответа страница не читает вовсе", () => {
    /* Не «читает иначе», а не читает: это разные вопросы, и смешать их — ровно
       тот способ, каким иссус завёлся. Ищем именно ЧТЕНИЕ поля, а не слово:
       упоминание в комментарии рядом и объясняет, почему поле здесь не берут. */
    expect(страница).not.toContain("r.registrationOpen");
    expect(страница.match(/дверь\(\{[^}]*\}/)?.[0] || "").not.toContain("registration");
  });

  it("признак берётся из ответа как `firstTenant`", () => {
    expect(страница).toContain("r.firstTenant");
  });

  it("и поле с таким именем сервер правда кладёт в ответ", () => {
    /* Сверка с настоящим источником, а не с фикстурой. Переименуют поле на
       бэкенде — панель не упадёт: `data.first_tenant` станет `undefined`, дверь
       прочтёт это как «установка занята» и покажет вход. Свежая установка
       перестанет предлагать первую регистрацию, а узнать об этом будет негде:
       ровно тот класс, из-за которого иссус #143 и завёлся. */
    const сервер = readFileSync(
      path.resolve(__dirname, "..", "..", "..", "core", "authweb.py"), "utf8");
    expect(сервер).toContain('"first_tenant"');
  });
});

describe("текст про закрытое окно не предлагает невозможного", () => {
  it("называет приглашение, а не «попробуйте позже»", () => {
    /* Окно закрывается НАВСЕГДА первой учёткой. «Попробуйте позже» отправило бы
       человека ждать события, которого не будет. */
    const t = authErrorText("registration_closed");
    expect(t).toContain("invite");
    expect(t.toLowerCase()).not.toContain("later");
    expect(t.toLowerCase()).not.toContain("try again");
  });
});

describe("экран регистрации говорит человеку, что он делает", () => {
  /* Рендерим саму страницу. Эффекты не выполняются, поэтому она стоит в
     состоянии «ответа ещё нет» — и это ровно то, что надо проверить с другой
     стороны: до ответа продукт НЕ предлагает завести админа. */
  const doОтвета = () => renderToStaticMarkup(createElement(LoginPage));

  it("до ответа сервера регистрация не предлагается", () => {
    const html = doОтвета();
    expect(html).not.toContain("Set up Obelista");
    expect(html).toContain("Sign in");
  });

  it("обещание про пароль стоит на экране, где его вводят", () => {
    // Та же формулировка, что в /privacy. Расхождение документа и экрана
    // ревьюер Меты замечает, и это частая причина отказа.
    expect(doОтвета()).toContain("cannot be turned back");
  });
});

describe("переключатель двери: выбор человека сильнее признака сервера", () => {
  /* Владелец 15.08 открыл регистрацию всем и попросил ссылку «нет аккаунта?
     Sign up» в обе стороны. До этого дверь решал ОДИН сервер: окно первой
     регистрации открыто — показываем регистрацию, закрыто — вход. Человек
     переключить её не мог никак.

     Здесь охраняется главное свойство новой двери: нажатая ссылка обязана
     сменить форму. Кнопка, которая не работает, потому что «сервер считает
     иначе», — худший вид неработающего: она выглядит рабочей. */

  it("выбрал регистрацию — показываем регистрацию, даже когда установка занята", () => {
    expect(дверь({ отвечено: true, вошёл: false, свежаяУстановка: false,
                   выбор: "регистрация" })).toBe("регистрация");
  });

  it("выбрал вход — показываем вход, даже на свежей установке", () => {
    expect(дверь({ отвечено: true, вошёл: false, свежаяУстановка: true,
                   выбор: "вход" })).toBe("вход");
  });

  it("не выбирал — прежнее поведение сохраняется", () => {
    /* Отрицательный контроль: чиня переключатель, нельзя было сломать то, ради
       чего этот модуль вообще заведён — первому человеку показать регистрацию
       сразу, потому что входить ему нечем. */
    expect(дверь({ отвечено: true, вошёл: false, свежаяУстановка: true })).toBe("регистрация");
    expect(дверь({ отвечено: true, вошёл: false, свежаяУстановка: false })).toBe("вход");
  });

  it("живая сессия сильнее любого выбора", () => {
    /* Выбор — про то, какую ФОРМУ показать. Вошедшему форма не нужна вовсе, и
       уводить его внутрь важнее, чем уважить нажатую минуту назад ссылку. */
    expect(дверь({ отвечено: true, вошёл: true, выбор: "регистрация" })).toBe("внутрь");
  });
});
