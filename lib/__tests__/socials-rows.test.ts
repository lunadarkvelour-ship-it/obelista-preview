/* Деление строк листа «Профили» и его вёрстка.
 *
 * Один символ в условии этого деления стоил владельцу рабочего дня: 14.08 он
 * нажал Disconnect, строка исчезла с экрана НАВСЕГДА, и подключить аккаунт
 * обратно из панели стало нечем. Демон всё это время отдавал строку со ссылкой
 * согласия — не рисовала панель. Невидимых строк в тот вечер было четыре.
 *
 * Поэтому здесь два уровня. Деление проверяется как чистая функция: внутри
 * компонента оно недостижимо тестом — строки приезжают эффектом, а тестовый
 * рендер эффектов не выполняет. Вёрстка проверяется рендером того, что на
 * первом проходе уже видно: шапки с кнопкой.
 *
 * ЧТО ПРОВЕРЕНО ПО ИСХОДНИКУ, А НЕ РЕНДЕРОМ, — говорю вслух, потому что
 * умолчание об этом и есть вид покрытия. Текст пустого состояния и текст
 * строки живут в состояниях, куда статический рендер не доходит: для них нужен
 * ответ демона. Их проверяет последний блок — чтением файла.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { splitSocials } from "@/lib/socials-rows";
import { SocialsView } from "@/components/views/SocialsView";

describe("на экране оказываются ВСЕ строки, а не только видимые в антидетекте", () => {
  it("неподключённый попадает в список, даже когда его нет в антидетекте", () => {
    /* Ровно случай владельца: он нажал Disconnect, профиль в антидетекте при
       этом никуда не делся или делся — неважно, строка обязана остаться. */
    const { rest } = splitSocials([{ connected: false, in_antik: false }]);
    expect(rest).toHaveLength(1);
  });

  it("подключённый остаётся подключённым, даже когда его нет в антидетекте", () => {
    // У него живой токен и с него идёт сбор: спрятать такую строку значило бы
    // потерять соц, который работает.
    const { linked } = splitSocials([{ connected: true, in_antik: false }]);
    expect(linked).toHaveLength(1);
  });

  it("ни одна строка не теряется по дороге", () => {
    const rows = [
      { connected: true, in_antik: true },
      { connected: true, in_antik: false },
      { connected: false, in_antik: true },
      { connected: false, in_antik: false },
    ];
    const { linked, rest } = splitSocials(rows);
    expect(linked.length + rest.length).toBe(rows.length);
  });

  it("в облаке, где антидетекта нет вовсе, список не пуст", () => {
    // Локального API антидетекта серверу не видно в принципе, значит `in_antik`
    // там ложен У ВСЕХ. Прежнее условие давало на этом пустой экран человеку,
    // которому надо начать работу.
    const облако = [
      { connected: false, in_antik: false },
      { connected: false, in_antik: false },
      { connected: true, in_antik: false },
    ];
    const { linked, rest } = splitSocials(облако);
    expect(rest).toHaveLength(2);
    expect(linked).toHaveLength(1);
  });

  it("пустой вход не выдумывает строк", () => {
    expect(splitSocials([])).toEqual({ linked: [], rest: [] });
  });
});

describe("кнопка подключения есть на экране с первого кадра", () => {
  const html = renderToStaticMarkup(createElement(SocialsView));

  it("«Add account» — это КНОПКА, а не слова в инструкции", () => {
    /* Проверяем элемент, а не наличие строки на странице. Первая редакция
       искала подстроку — и не покраснела, когда я переименовала кнопку в
       «Connect»: те же слова стоят в свёрнутой инструкции ниже, и тест
       радостно нашёл их там. Совпадение текста где-то на экране не значит, что
       нажимать есть на что. */
    const кнопка = html.match(/<button[^>]*>(?:(?!<\/button>)[\s\S])*Add account[\s\S]*?<\/button>/);
    expect(кнопка).not.toBeNull();
  });

  it("инструкции разработчика на листе нет", () => {
    expect(html).not.toContain("venv/bin");
    expect(html).not.toContain("analytics_daemon.py");
    expect(html).not.toContain("127.0.0.1");
  });

  it("парк с машины заводится прямо отсюда — ОБОИМИ вендорами", () => {
    /* ЗДЕСЬ РАНЬШЕ СТОЯЛ ОБРАТНЫЙ СТОРОЖ: «про антидетект на экране не сказано
       ни слова», с доводом «в облаке человек его в глаза не видел, а на маке
       это не его забота». Довод был верен для ПРЕЖНЕГО продукта, где панель
       только показывала цифры.

       14.08 владелец потребовал обратного: состав профилей приходит с ЕГО
       машины, и завести их он должен из панели. Мост к этому моменту был
       достроен с обеих сторон — демон выдавал код (`/link_code`), MCP-тул
       `link_profiles` его принимал, — и не сходился ровно посередине: взять
       код человеку было НЕГДЕ. Профили не приехали ни разу, а лист показывал
       наследство старой базы и выглядел рабочим.

       Поэтому сторож развёрнут, а не снят: он охраняет наличие двери вместо
       её отсутствия. Проверяем КНОПКУ, а не слова: тем же доводом, что и у
       «Add account» выше — совпадение текста где-то на экране не значит, что
       нажимать есть на что.

       Проверки на ВЕНДОРА здесь по-прежнему нет намеренно: соседний сторож
       сканирует на него всю панель, и упоминание его словом в этом файле
       уронило бы его на нашем же тесте. Заодно его свойство: ищет он без учёта
       регистра, а запретное слово входит в его собственное имя файла, —
       поэтому сослаться на него по имени в комментарии тоже нельзя. */
    const кнопка = html.match(
      /<button[^>]*>(?:(?!<\/button>)[\s\S])*Scan ShardX Profiles[\s\S]*?<\/button>/);
    expect(кнопка).not.toBeNull();
    /* И ВТОРОЙ — РАВНОПРАВНО. С XR-44 вендора два; лист, знающий про одного,
       заставляет парк второго не существовать. */
    expect(html).toMatch(
      /<button[^>]*>(?:(?!<\/button>)[\s\S])*Scan AdsPower Profiles[\s\S]*?<\/button>/);
  });

  it("сканирование парка стоит раньше Facebook account flow", () => {
    const импорт = html.indexOf("Scan ShardX Profiles");
    const фейсбук = html.indexOf("Add account");
    expect(импорт).toBeGreaterThanOrEqual(0);
    expect(фейсбук).toBeGreaterThanOrEqual(0);
    expect(импорт).toBeLessThan(фейсбук);
    /* «Primary path · local connector» и абзац про то, какие поля едут,
       ушли вместе с блоком: у двух равноправных вендоров главного пути нет, а
       объяснение транспорта не помогает нажать кнопку.

       ГАРАНТИЯ, РАДИ КОТОРОЙ ЭТА СТРОКА СТОЯЛА, ОСТАЛАСЬ: сканирование парка и
       подключение аккаунта Меты — РАЗНЫЕ действия, и лист не должен читаться
       так, будто кнопка скана заодно подключит Facebook. Проверяем это по
       порядку и раздельности блоков, а не по абзацу, который мы же и сняли. */
    expect(html).toContain("Add account");
    expect(html).not.toMatch(/Primary path/);
  });

  it("код привязки не выдаётся сам собой, до нажатия", () => {
    /* Каждая выдача МИНТИТ новый код и обесценивает предыдущий
       (`core/profiles_bridge.py:issue_code`). Экран, который дёргает эту ручку
       на отрисовке, ломал бы код, названный минуту назад, — и человек видел бы
       «просрочен» на том, что только что взял.

       Отрицательный контроль: если однажды кто-то повесит выдачу на эффект
       загрузки, тест покраснеет. Шестнадцать шестнадцатеричных знаков подряд
       на первом кадре взяться неоткуда. */
    expect(html).not.toMatch(/>[0-9a-f]{16}</);
    /* Кнопки только ОТКРЫВАЮТ модалку; запрос уходит из её эффекта. Значит на
       статическом рендере листа ключа быть не может вовсе — ни просроченного,
       ни свежего. */
    expect(html).toContain("Scan ShardX Profiles");
    expect(html).not.toMatch(/expires in/i);
  });
});

describe("текст состояний, недостижимых статическим рендером — проверка по исходнику", () => {
  /* Эти строки живут за ответом демона: пустое состояние требует `loaded` и
     нулевого списка, текст строки — самой строки. Рендер туда не доходит, и
     зелёный тест на них означал бы «не дошли», а не «дефекта нет». Поэтому
     проверяем текст файла и говорим об этом вслух. */
  const исходник = readFileSync("components/views/SocialsView.tsx", "utf-8");
  const литералы = () => исходник.match(/"[^"\n]*"|'[^'\n]*'/g) ?? [];

  it("пустое состояние зовёт нажать кнопку, а не чинить антидетект", () => {
    expect(исходник).toContain("No accounts yet");
    expect(исходник).toContain("Add account");
  });

  it("строка различает «отключил сам» и «ещё не подключал»", () => {
    // Раньше здесь стояло «profile not in antidetect» — свойство файла со
    // снимком локальной машины, в облаке ложное у всех.
    expect(исходник).toContain("disconnected — collecting stopped");
    expect(исходник).toContain("not connected yet");
    /* Только литералы: в комментарии старая формулировка стоит как рассказ о
       том, ЧТО убрали и почему. Запретив её там, я запретила бы объяснять
       причину — а причина здесь дороже самой правки. */
    const литералыФайла = литералы();
    expect(литералыФайла.filter((s) => s.includes("not in antidetect"))).toEqual([]);
  });

  it("ни в одной строке кода не осталось команды для разработчика", () => {
    const виновные = литералы().filter(
      (s) => s.includes("venv/bin") || s.includes("analytics_daemon.py"),
    );
    expect(виновные).toEqual([]);
  });
});
