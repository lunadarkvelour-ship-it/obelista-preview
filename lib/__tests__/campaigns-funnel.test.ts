describe("НИ ОДНОГО НУЛЯ, пока воронка не приезжала", () => {
  const пусто = подготовить({ ok: true, tracker: null, ever_at: null });

  it("в ячейке стоит прочерк, а не цифра", () => {
    for (const m of ["sub", "contact", "checkout", "ftd", "rd", "revenue"]) {
      const cell = ячейкаВоронки(пусто, { fb_id: "1", level: "campaign", name: "A" }, m);
      const html = renderToStaticMarkup(createElement(FunnelValueCell, { cell }));
      /* Ищем цифры в ОТРИСОВАННОМ тексте, а не в модели: ноль может приехать
         из форматирования (`num(null)` вернул бы «0», если кто-то поправит
         фолбэк), и модель об этом не узнает. */
      const текст = html.replace(/<[^>]+>/g, "").replace(/&[a-z#0-9]+;/g, "");
      expect(текст, m).not.toMatch(/\d/);
    }
  });

  it("над таблицей стоит плашка с причиной, а не пустое место", () => {
    const html = renderToStaticMarkup(createElement(FunnelNotice, { ctx: пусто }));
    expect(html).toMatch(/No funnel has ever arrived/);
    expect(html).toMatch(/not because nobody subscribed/i);
  });

  it("положительный контроль: настоящее число рисуется числом", () => {
    /* Без него сторож выше позеленел бы и в тот день, когда с экрана пропали бы
       ВСЕ цифры — то есть когда сломалось бы то, ради чего колонки сделаны. */
    const ctx = подготовить(ОТВЕТ);
    const cell = ячейкаВоронки(ctx, { fb_id: "120001", level: "campaign", name: "Смена A" }, "sub");
    const html = renderToStaticMarkup(createElement(FunnelValueCell, { cell }));
    expect(html).toContain("1,200");
  });

  it("счётчик спрятанного виден и когда глаз ОТКРЫТ", () => {
    /* Самый вероятный способ потерять этот сигнал — нарисовать счётчик внутри
       кнопки и показывать только в закрытом положении. Тогда дефект видит
       только тот, кто его уже спрятал. */
    for (const глаз of ["all", "with_spend"] as const) {
      const html = renderToStaticMarkup(createElement(FunnelEyeToggle, {
        eye: глаз, скрыто: 2, скрытоЛида: 5520, leadTitle: "subs", onChange: () => {},
      }));
      const текст = html.replace(/<[^>]+>/g, " ");
      expect(текст, глаз).toContain("2 without spend");
      expect(текст, глаз).toContain("5,520");
    }
  });

  it("строка воронки без объекта рисуется числами, а спенд у неё прочерк", () => {
    const сирота = сиротыВоронки(ОТВЕТ)[0];
    const html = renderToStaticMarkup(createElement(FunnelOrphanTreeRow, {
      row: сирота, columns: колонкиВоронки(ОТВЕТ),
    }));
    expect(html).toContain("4,000");                  // подписчики видны
    expect(html).toContain("no object");              // и сказано, почему они ничьи
    expect(html).not.toMatch(/\$\s*0/);               // спенда нет — и он не ноль
  });

  it("тёзки на экране отличимы от пустоты", () => {
    const ctx = подготовить(ОТВЕТ);
    const cell = ячейкаВоронки(ctx, { fb_id: "777", level: "campaign", name: "Аноним" }, "sub");
    const html = renderToStaticMarkup(createElement(FunnelValueCell, { cell }));
    expect(html).toContain("text-warning");
    expect(html).not.toMatch(/>\s*300\s*</);      // цифру тёзки не приписываем
  });
});

/* ── подписи после сноса второго списка ──────────────────────────────────
 *
 * До 17.08 рядом с `подписьШага` лежала карта `ПОДПИСЬ_ВНЕ_КАТАЛОГА` — «запасной
 * ответ для ступеней, которых в каталоге „Аналитики“ нет». В ней была одна
 * запись, выручка, и жила она там ровно потому, что тот каталог знал только те
 * ступени, под которые на ЕГО листе завели колонку. То есть подпись ступени
 * зависела от того, показывает ли её другой лист, и в день, когда выручку
 * завели бы там, две подписи начали бы спорить — молча, как всегда.
 *
 * Теперь канон один (`lib/funnel-metrics`) и знает все шесть ступеней
 * независимо от того, кто их рисует. Проверки ниже стерегут, чтобы второй
 * список не завёлся заново.
 */
describe("подпись ступени приходит из общего каталога, и только оттуда", () => {
  it("выручка подписана, хотя колонки под неё на лидерборде нет", () => {
    expect(подписьШага("revenue")).toEqual({
      title: "Revenue",
      hint: "money the CRM reports for these people",
    });
    expect(COLUMNS.map((c) => c.key)).not.toContain("revenue");
  });

  it("подпись КАЖДОЙ ступени канона — дословно каталожная", () => {
    for (const m of FUNNEL_METRICS) {
      expect(подписьШага(m.id), m.id).toEqual({ title: m.title, hint: m.hint });
    }
  });

  it("в файле «Кампаний» не осталось второго списка подписей", () => {
    /* Проверка по ИСТОЧНИКУ, а не по поведению: вернуть карту обратно и
       заполнить её теми же значениями — это зелёное поведение и разъехавшаяся
       договорённость. Ловится только чтением самого файла. */
    const src = readFileSync(
      path.join(КОРЕНЬ, "panel/lib/campaigns-funnel.ts"), "utf8",
    );
    expect(src).not.toMatch(/ПОДПИСЬ_ВНЕ_КАТАЛОГА/);
    expect(src).toMatch(/from "@\/lib\/funnel-metrics"/);
  });

  it("незнакомая движку ступень называется ключом, а не пропадает", () => {
    expect(подписьШага("mystery_step")).toEqual({
      title: "mystery_step",
      hint: "funnel step «mystery_step» reported by the source",
    });
  });
});
