/* ── что говорит движок ─────────────────────────────────────────────────── */

describe("канон воронки читается у движка, а не переписан в панель", () => {
  it("у каждого шага CANON движка есть человеческая подпись", () => {
    /* `core/sources/base.CANON` — единственный список шагов. Появится седьмой —
       он получит подпись из каталога «Аналитики», а не исчезнет с экрана. */
    const src = читатьДвижок("core/sources/base.py");
    const m = src.match(/^CANON\s*=\s*\(([^)]*)\)/m);
    expect(m, "в core/sources/base.py не нашёлся CANON").toBeTruthy();
    const канон = [...m![1].matchAll(/"([a-z_]+)"/g)].map((x) => x[1]);
    expect(канон.length).toBeGreaterThanOrEqual(5);
    for (const шаг of канон) {
      // Подпись, равная ключу, — это «подписи нет»: человеку показали бы `ftd`
      // вместо «FTD», и никто бы не заметил.
      expect(подписьШага(шаг).title, `нет подписи для шага ${шаг}`).not.toBe(шаг);
    }
  });

  it("лид этой вертикали — подписчик, и так же он назван в движке", () => {
    /* Слова владельца: «лид это лид… это вообще подписчик». Спутать лид с
       регистрацией или депом значит показать 84 вместо 16974, причём цифра
       будет выглядеть настоящей. */
    const src = читатьДвижок("core/funnel_join.py");
    expect(src).toMatch(/^ЛИД\s*=\s*"sub"$/m);
    expect(колонкиВоронки(ОТВЕТ).find((c) => c.lead)?.metric).toBe("sub");
  });

  it("колонка CRM называется Subs и НИКОГДА не Leads", () => {
    /* Решение диспетчера 15.08, и оно про столкновение двух правд: «результат»
       Меты — это лид ПИКСЕЛЯ (живой замер: 9 на кампанию), а лид владельца —
       подписчик CRM (16974 на той же кампании). Обе цифры настоящие, разница
       почти в две тысячи раз. Поэтому слово `Leads` не принадлежит никому:
       половина Меты зовётся Results, половина CRM — Subs. */
    expect(подписьШага("sub").title).toBe("Subs");
    for (const c of колонкиВоронки(ОТВЕТ)) {
      expect(c.title.toLowerCase(), c.metric).not.toContain("lead");
    }
  });

  it("СОСТАВ, ПОРЯДОК И ПОДПИСИ — те же, что на Creative Analytics", () => {
    /* Требование владельца: метрики воронки «должны быть ОДИНАКОВЫЕ с листом
       Creative Analytics». Сверяем с ЖИВЫМ каталогом того листа — тем самым, из
       которого берут его таблица, выбор колонок, сортировка и CSV, — а не с
       переписанным сюда списком: переписанный знает только то, что кто-то
       вспомнил в день написания. */
    const воронкаАналитики = DEFAULT_VISIBLE.filter((k) => BY_KEY[k]?.group === "воронка");
    const каталог = BY_KEY as Record<string, { title: string; group: string } | undefined>;
    const мои = колонкиВоронки(ОТВЕТ).filter((c) => каталог[c.metric]);
    expect(мои.map((c) => c.metric)).toEqual(воронкаАналитики);
    for (const c of мои) {
      expect(c.title, c.metric).toBe(каталог[c.metric]!.title);
    }
  });

  it("ступень, заведённая на «Аналитике», приезжает сюда САМА", () => {
    /* Доказательство, что совпадение держится механизмом, а не вниманием: в
       каталоге воронки нет ни одной ступени, о которой этот лист не знал бы. */
    const воронкаКаталога = COLUMNS.filter((c) => c.group === "воронка").map((c) => c.key);
    const знаем = колонкиВоронки({ ...ОТВЕТ, metrics: воронкаКаталога }).map((c) => c.metric);
    expect([...знаем].sort()).toEqual([...воронкаКаталога].sort());
  });
});

