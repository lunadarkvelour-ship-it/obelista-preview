describe("воронка без объекта показывается своими строками", () => {
  it("обе беды попадают в список, самая большая потеря — сверху", () => {
    /* ИМЕНА В ФИКСТУРЕ ПОДОБРАНЫ ТАК, ЧТО АЛФАВИТ ДАЁТ ОБРАТНЫЙ ПОРЯДОК: «Аноним»
       с тремя сотнями подписчиков против «Я переименована» с четырьмя тысячами.
       Первая редакция этого сторожа была ФАЛЬШИВОЙ — подделка «сортируем по
       имени» проходила её насквозь, потому что в тех именах оба порядка
       совпадали. Проверка, зелёная лицом к поломке, не проверяет ничего. */
    const сироты = сиротыВоронки(ОТВЕТ);
    expect(сироты.map((r) => r.kind)).toEqual(["no_object", "ambiguous"]);
    expect(сироты[0].metrics.sub).toBe(4000);
    expect(сироты[0].name).toBe("Я переименована");
    // И прямо: по алфавиту первым был бы другой.
    const поАлфавиту = [...сироты].sort((a, b) => a.name.localeCompare(b.name));
    expect(поАлфавиту[0].name).not.toBe(сироты[0].name);
  });

  it("у каждой сказано, почему спенда к ней нет и что делать", () => {
    const сироты = сиротыВоронки(ОТВЕТ);
    expect(сироты.find((r) => r.kind === "ambiguous")!.reason).toMatch(/Rename/i);
    expect(сироты.find((r) => r.kind === "no_object")!.reason).toMatch(/renamed in Ads Manager/i);
  });

  it("метрики едут числами, а неизмеренное не превращается в ноль", () => {
    const сирота = сиротыВоронки(ОТВЕТ)[0];
    expect(сирота.metrics.sub).toBe(4000);
    expect(сирота.metrics.revenue).toBeUndefined();     // `null` в ответе — не ноль
  });

  it("воронки без объекта нет — список пуст, и рисовать нечего", () => {
    expect(сиротыВоронки({ ...ОТВЕТ, unmatched: { ambiguous: [], no_object: [] } })).toEqual([]);
  });
});

