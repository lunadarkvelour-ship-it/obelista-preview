describe("почему колонки пусты — пять разных ответов, а не один", () => {
  it("ручки нет на этом деплое", () => {
    expect(состояниеВоронки(null, { ручкиНет: true })).toBe("no_handle");
  });

  it("воронка не приезжала НИ РАЗУ — это не ноль подписчиков", () => {
    /* Сегодняшнее состояние прода: приём отбивался 403 и не работал ни разу. */
    expect(состояниеВоронки({ ok: true, tracker: null, ever_at: null })).toBe("never");
    expect(объяснениеСостояния("never")).toMatch(/not because nobody subscribed/i);
    // И сказано, где чинить: иначе честная плашка оставляет человека ни с чем.
    expect(объяснениеСостояния("never")).toMatch(/Integrations/);
  });

  it("демон не сказал, приезжала ли она вообще — это тоже не ноль", () => {
    /* Поля нет = демон старше контракта. Ровно та же троичность, что у
       `funnel_at` на «Аналитике»: смешать «не приезжало» с «не знаем» значит
       вернуть болезнь, ради которой поле и заведено. */
    expect(состояниеВоронки({ ok: true, tracker: null })).toBe("unknown_ever");
    expect(объяснениеСостояния("unknown_ever")).toMatch(/do not know/i);
  });

  it("приезжала, но не в это окно — и дата последнего приезда названа", () => {
    const s = { ok: true, tracker: null, ever_at: "2026-08-01T10:00:00Z" };
    expect(состояниеВоронки(s)).toBe("empty_window");
    expect(объяснениеСостояния("empty_window", s)).toContain("2026-08-01T10:00:00Z");
  });

  it("цифры за окно есть — они перевешивают молчание про «когда-нибудь»", () => {
    // Иначе старый демон без `ever_at` погасил бы колонки, полные настоящих цифр.
    expect(состояниеВоронки({ ...ОТВЕТ, ever_at: undefined })).toBe("ok");
    expect(объяснениеСостояния("ok")).toBe("");
  });
});

