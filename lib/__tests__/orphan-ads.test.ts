/* Сироты на экране: число, движение, и молчание там, где сказать нечего (#164).
 *
 * Проверяется не «есть ли строка», а ЧТО ИМЕННО она утверждает. Индикатор
 * пишется ради случая, когда всё выглядит здоровым: сбор идёт, экран зелёный,
 * а 422 объявления месяц лежат без кампании. Значит и проверять надо тот
 * случай — плашку при спокойном сборе, — а не только красный.
 */
import { describe, expect, it } from "vitest";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import {
  readOrphanAds, показыватьСирот, смыслСирот, строкаСирот,
} from "@/lib/orphan-ads";
import { CollectorVerdict } from "@/components/sections/CollectorVerdict";

const здоровье = (тревога: boolean) => ({
  состояние: тревога ? "встал" : "идёт",
  почему: тревога ? "коллектор не пишет" : "",
  тревога,
  подъёмов: 1,
  уронов: 0,
  окно_с: 3600,
  последняя_запись_с: 30,
});

describe("чтение ответа демона", () => {
  it("три числа доезжают как есть", () => {
    expect(readOrphanAds({
      ads_no_campaign: 422, ads_no_campaign_prev: 500,
      ads_no_campaign_since_s: 86400,
    })).toEqual({ сейчас: 422, было: 500, стоит_с: 86400 });
  });

  it("демон старше индикатора — это «не знаем», а не «сирот нет»", () => {
    /* Ноль здесь означал бы хорошую новость, полученную без единой проверки. */
    expect(readOrphanAds({}).сейчас).toBeNull();
    expect(readOrphanAds(null).сейчас).toBeNull();
  });

  it("посчитанный ноль остаётся нулём", () => {
    expect(readOrphanAds({ ads_no_campaign: 0 }).сейчас).toBe(0);
  });
});

describe("когда молчим", () => {
  it("сирот нет — строки нет: ноль не должен занимать место на экране", () => {
    expect(показыватьСирот({ сейчас: 0, было: null, стоит_с: null })).toBe(false);
    expect(строкаСирот({ сейчас: 0, было: null, стоит_с: null })).toBe("");
  });

  it("не считали — тоже молчим, но это другое молчание", () => {
    /* Сказать «сирот нет», ничего не посчитав, — соврать ровно тем способом,
       из-за которого дыру не замечали месяц. */
    expect(показыватьСирот({ сейчас: null, было: null, стоит_с: null })).toBe(false);
    expect(смыслСирот({ сейчас: null, было: null, стоит_с: null })).toBe("");
  });
});

describe("строка говорит о ДВИЖЕНИИ, а не только о числе", () => {
  it("«было столько, стало столько» — когда есть с чем сравнить", () => {
    const s = строкаСирот({ сейчас: 422, было: 500, стоит_с: 3600 });
    expect(s).toContain("422");
    expect(s).toContain("down from 500");
  });

  it("рост назван ростом, а не «изменением»", () => {
    expect(строкаСирот({ сейчас: 500, было: 422, стоит_с: 3600 })).toContain("up from 422");
  });

  it("сравнивать не с чем — сказано, сколько число стоит на месте", () => {
    /* Это и есть симптом: не цифра, а её неподвижность. */
    expect(строкаСирот({ сейчас: 422, было: null, стоит_с: 30 * 86400 }))
      .toContain("unchanged for 30d");
  });

  it("возраст числа не выдумывается, когда его не прислали", () => {
    const s = строкаСирот({ сейчас: 422, было: null, стоит_с: null });
    expect(s).toBe("422 ads have no campaign");
    expect(s).not.toMatch(/unchanged|for \d/);
  });

  it("объяснение называет цену вопроса, а не только факт", () => {
    const m = смыслСирот({ сейчас: 422, было: null, стоит_с: 30 * 86400 });
    expect(m).toMatch(/breakdown by campaign/i);
    expect(m).toMatch(/month/i);
    expect(m).toMatch(/overwritten/i);
  });
});

describe("плашка на экране", () => {
  const html = (st: unknown) =>
    renderToStaticMarkup(createElement(CollectorVerdict, { st: st as never }));

  it("при ЗДОРОВОМ сборе сироты всё равно видны", () => {
    /* Главный случай файла. Спрячь строку под условие «сбор нездоров» —
       индикатор промолчит ровно тогда, когда он нужен: при 422 сиротах сбор
       идёт исправно и красит себя зелёным. */
    const вид = html({ здоровье: здоровье(false), ads_no_campaign: 422,
                       ads_no_campaign_prev: 500, ads_no_campaign_since_s: 86400 });
    expect(вид).toContain("422 ads have no campaign");
    expect(вид).toContain("down from 500");
  });

  it("плашка сирот спокойного тона — это качество данных, а не авария", () => {
    /* Покрасить тревогой значит обесценить настоящую тревогу: тот же довод,
       по которому `заперт` не красный. */
    const вид = html({ здоровье: здоровье(false), ads_no_campaign: 422 });
    expect(вид).toContain('data-tone="notice"');
    expect(вид).not.toContain('data-tone="alarm"');
  });

  it("при аварии сбора сироты стоят отдельной строкой, а не сливаются с ней", () => {
    const вид = html({ здоровье: здоровье(true), ads_no_campaign: 422 });
    expect(вид).toContain('data-tone="alarm"');
    expect(вид).toContain("422 ads have no campaign");
  });

  it("сирот нет и сбор здоров — на экране ничего", () => {
    expect(html({ здоровье: здоровье(false), ads_no_campaign: 0 })).toBe("");
    expect(html({ здоровье: здоровье(false) })).toBe("");
  });

  it("вердикт о сборе не сломался: авария по-прежнему видна без сирот", () => {
    /* Отрицательный контроль к правке чужого компонента: добавляя строку, я
       обязан не отнять старое поведение. */
    expect(html({ здоровье: здоровье(true) })).toContain('data-tone="alarm"');
  });
});
