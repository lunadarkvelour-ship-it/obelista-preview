/* Период как КОНТЕКСТ РАЗДЕЛА (#154, пункт 5) — и как он доезжает до ручки.
 *
 * ЧТО ЗДЕСЬ САМОЕ ВАЖНОЕ. Не разбор адреса сам по себе, а два свойства, каждое
 * из которых ломается молча:
 *
 *   • период уходит В ЗАПРОС, а не фильтрует ответ. Отфильтруй панель ответ у
 *     себя — на экране была бы сумма, которую никто не считал за это окно, и
 *     выглядела бы она нормально;
 *   • панель НЕ СЧИТАЕТ ДАТЫ САМА. «Какое сегодня число» знает один
 *     `core/period.py` в поясе продукта; браузер живёт в поясе своего человека,
 *     и второй счётчик разошёлся бы с первым на границе суток — без ошибки, без
 *     красного, просто на день не туда.
 *
 * Второе проверяется прицельно: в файле не должно быть арифметики дат вовсе.
 */
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";
import {
  ПРЕСЕТЫ, TZ_ПО_УМОЛЧАНИЮ, НАЧАЛЬНЫЙ, вURL, изURL, нуженЗапрос, периодВЗапрос,
  тотЖе, type PeriodQuery,
} from "@/lib/period";

const ROOT = path.resolve(__dirname, "..", "..");

describe("период уходит в запрос", () => {
  it("пресет едет именем, а не парой дат", () => {
    expect(периодВЗапрос({ preset: "last_7d" })).toEqual({ period: "last_7d", tz: null });
  });

  it("свой диапазон едет парой дат, без пресета", () => {
    expect(периодВЗапрос({ since: "2026-08-01", until: "2026-08-03" })).toEqual({
      since: "2026-08-01", until: "2026-08-03", tz: null,
    });
  });

  it("пресет побеждает залежавшиеся даты, а не досылается вместе с ними", () => {
    /* Демон принимает ЛИБО одно, ЛИБО другое и на оба сразу отвечает отказом
       (`core/period.окно`). Человек при этом сделал понятное движение — нажал
       кнопку, — и получить за это ошибку он не должен. */
    const q = периодВЗапрос({ preset: "today", since: "2026-08-01", until: "2026-08-03" });
    expect(q.period).toBe("today");
    expect(q.since).toBeUndefined();
    expect(q.until).toBeUndefined();
  });

  it("пустой период не досылает ничего — иначе демон примет пустое за заданное", () => {
    expect(периодВЗапрос(null)).toEqual({});
  });
});

describe("период переживает переход между разделами", () => {
  it("адрес → период → адрес возвращает то же самое", () => {
    for (const адрес of ["period=last_7d", "since=2026-08-01&until=2026-08-03"]) {
      expect(new URLSearchParams(вURL(изURL(адрес))).toString()).toBe(адрес);
    }
  });

  it("пустой адрес даёт умолчание, а не пустоту", () => {
    /* Пустой период на листе означал бы «покажи что-нибудь»: демон подставит
       своё умолчание, панель нарисует свои кнопки, и они разойдутся. */
    expect(изURL("")).toEqual(НАЧАЛЬНЫЙ);
    expect(НАЧАЛЬНЫЙ.preset).toBe("today");
  });

  it("одна дата в адресе — это один день", () => {
    expect(изURL("since=2026-08-01")).toEqual({ since: "2026-08-01", until: "2026-08-01" });
  });

  it("чужой мусор в адресе не роняет лист", () => {
    /* Адрес приходит снаружи: ссылка от коллеги, старая закладка. Проверять
       значения будет демон — он один знает, какие пресеты есть сегодня. */
    expect(() => изURL("period=позавчера&foo=bar")).not.toThrow();
    expect(изURL("period=позавчера").preset).toBe("позавчера");
  });

  it("одинаковые периоды узнаются одинаковыми — иначе лист перезапрашивает себя", () => {
    expect(тотЖе({ preset: "today" }, { preset: "today" })).toBe(true);
    expect(тотЖе({ preset: "today" }, { preset: "yesterday" })).toBe(false);
    expect(тотЖе({ since: "2026-08-01", until: "2026-08-01" }, { preset: "today" })).toBe(false);
  });
});

describe("панель не считает даты сама", () => {
  const текст = readFileSync(path.join(ROOT, "lib", "period.ts"), "utf8");
  const код = текст
    .split("\n")
    .filter((s) => !/^\s*(\*|\/\/|\/\*)/.test(s))
    .join("\n");

  it("в файле нет арифметики дат", () => {
    /* Соблазн велик и выглядит безобидно: «посчитаю последние 7 дней здесь,
       чтобы подсветить кнопку». В этот момент у продукта появляется второе
       «сегодня» — в поясе браузера. Даты приходят ОТВЕТОМ демона, и подсветка
       считается по имени пресета, которое он же вернул. */
    for (const примета of ["new Date", "Date.now", "setDate", "getFullYear", "toISOString"]) {
      expect(код).not.toContain(примета);
    }
  });

  it("пояс по умолчанию назван ровно один раз и совпадает с движком", () => {
    /* Вторая половина сверки — в `tests/test_period.py`: он читает ЭТОТ файл и
       требует совпадения с `core/period.ПОЯС_ПО_УМОЛЧАНИЮ`. Здесь проверяем
       только то, что копия одна: две разъедутся молча. */
    expect(TZ_ПО_УМОЛЧАНИЮ).toBe("UTC+3");
    expect(код.match(/"UTC\+3"/g)?.length).toBe(1);
  });
});

describe("кнопки периода", () => {
  it("имена не пустые и не повторяются", () => {
    const ids = ПРЕСЕТЫ.map((п) => п.id);
    expect(new Set(ids).size).toBe(ids.length);
    expect(ids.every(Boolean)).toBe(true);
  });

  it("подпись кнопки не обещает границ окна", () => {
    /* «Last 7 days including today» на кнопке начнёт врать в тот день, когда
       пресет поменяет смысл на бэкенде. Что именно посчитано, человек читает
       по датам из ответа — они стоят рядом с кнопками. */
    for (const п of ПРЕСЕТЫ) {
      expect(п.label).not.toMatch(/includ|excluding|20\d\d/i);
    }
  });
});

/* ── против шторма запросов (#167) ────────────────────────────────────────────
 *
 * ЧТО БЫЛО. Лист аналитики решал «надо ли перезапросить», сравнивая выбранный
 * период с периодом ИЗ ОТВЕТА. Просьба и ответ тут разные по устройству:
 * панель просит `{preset: "today"}` и пояс не называет, движок отвечает тем же
 * пресетом и УЖЕ РАЗРЕШЁННЫМ поясом. Строки не совпадали никогда, поэтому на
 * каждый ответ эффект просил снова.
 *
 * ЗАМЕР НА ЖИВОМ ПРОДЕ, не рассуждение: 99 запросов лидерборда за 60 секунд с
 * одной открытой вкладки. Побочно этим были выключены ВСЕ кнопки дат и
 * «обновить» — они гаснут на время загрузки, а загрузка не кончалась, и
 * владелец не мог сменить период вовсе.
 */
describe("нуженЗапрос: сравниваем просьбу с просьбой, а не с ответом", () => {
  /** Ответ движка ровно той формы, что приезжает с прода: пресет тот же,
   *  а пояс уже разрешён в имя. */
  const ОТВЕТ = {
    preset: "today", since: "2026-08-15", until: "2026-08-15",
    tz: "UTC+3", offset_minutes: 180,
  } as unknown as PeriodQuery;

  it("ВОСПРОИЗВЕДЕНИЕ ЦИКЛА: просьба и ответ не совпадают никогда", () => {
    /* Отрицательный полюс находки. Пока это так, любое сравнение с ответом
       обречено, и чинить надо не строку сравнения, а то, С ЧЕМ сравниваем. */
    expect(тотЖе(НАЧАЛЬНЫЙ, ОТВЕТ)).toBe(false);
  });

  it("сравнение с прошлой ПРОСЬБОЙ замыкаться не может", () => {
    const было = { период: НАЧАЛЬНЫЙ, geo: null };
    expect(нуженЗапрос(было, НАЧАЛЬНЫЙ, null)).toBe(false);
  });

  it("первый заход спрашивает всегда", () => {
    expect(нуженЗапрос(null, НАЧАЛЬНЫЙ, null)).toBe(true);
  });

  it("сменил период рукой — спрашиваем", () => {
    const было = { период: НАЧАЛЬНЫЙ, geo: null };
    expect(нуженЗапрос(было, { preset: "yesterday" }, null)).toBe(true);
    expect(нуженЗапрос(было, { since: "2026-08-01", until: "2026-08-02" }, null))
      .toBe(true);
  });

  it("сменил гео — спрашиваем; та же вкладка гео — нет", () => {
    const было = { период: НАЧАЛЬНЫЙ, geo: "DZ" };
    expect(нуженЗапрос(было, НАЧАЛЬНЫЙ, "EG")).toBe(true);
    expect(нуженЗапрос(было, НАЧАЛЬНЫЙ, "DZ")).toBe(false);
    /* `null` и `undefined` — одна и та же вкладка «все». Разведи их, и
       переключение туда-сюда снова начнёт долбить сервер. */
    expect(нуженЗапрос({ период: НАЧАЛЬНЫЙ, geo: null }, НАЧАЛЬНЫЙ, null)).toBe(false);
  });

  it("ОТВЕТ ДВИЖКА НА РЕШЕНИЕ НЕ ВЛИЯЕТ ВООБЩЕ", () => {
    /* Главная гарантия: что бы ни вернул движок, новый запрос из-за этого не
       родится. Именно это кольцо и раскручивалось. */
    const было = { период: НАЧАЛЬНЫЙ, geo: null };
    for (const чужое of [ОТВЕТ, { preset: "today", tz: "Europe/Moscow" },
                         { since: "2026-08-15", until: "2026-08-15" }]) {
      void чужое;
      expect(нуженЗапрос(было, НАЧАЛЬНЫЙ, null)).toBe(false);
    }
  });
});
