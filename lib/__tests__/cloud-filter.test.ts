/* Срез листа кабинетов.
 *
 * Лист на 261 строку без фильтра нечитаем — владелец сказал это прямо, увидев
 * его на своём парке. Поэтому здесь проверяется не «работает ли фильтр вообще»,
 * а те места, где он врёт незаметно: хоронит живое, прячет искомое, считает не
 * то, что показывает.
 *
 * С иссусом #121 лист стал один на оба источника, и фильтр вместе с ним: строка
 * теперь несёт и состояние из базы, и соцев из снапшота. Проверки ниже держат обе
 * половины — и то, что они не мешают друг другу.
 */
import { describe, it, expect } from "vitest";
import {
  СОСТОЯНИЯ, срез, подключён, профилиСписок, счётПоСостояниям, ПУСТОЙ_СРЕЗ,
} from "@/lib/cloud-filter";
import { можноЛить, отмечаемые } from "@/lib/cloud-accounts";
import type { UnifiedAccount } from "@/lib/cloud-accounts";
import type { AccountOwner } from "@/lib/account-rows";

const соц = (p: Partial<AccountOwner> & { profile: string }): AccountOwner => ({
  label: "", present: true, fresh: true, oauth: false, ...p,
});

const каб = (p: Partial<UnifiedAccount> & { act_id: string }): UnifiedAccount => ({
  name: null, bm_name: null, status: null, status_checked_at: null,
  funding_type: null, funding_display_string: null,
  owners: [], profile: null, profileLabel: "", pixels: [], personal: false,
  inSnapshot: false, inCloud: true, ...p,
});

const парк: UnifiedAccount[] = [
  каб({ act_id: "act_1", name: "MeDuA6aeP 17/7-8", bm_name: "BM NQ", status: "ACTIVE",
        status_checked_at: "2026-08-14T10:00:00Z", funding_type: "CREDIT_CARD",
        pixels: [{ id: "1575609560601059", name: "hiu—ogaff" }],
        profile: "k1a", profileLabel: "17/7 spx", inSnapshot: true,
        owners: [соц({ profile: "k1a", label: "17/7 spx", oauth: true }),
                 соц({ profile: "k1b", label: "10/8 hiu" })] }),
  каб({ act_id: "act_2", name: "Ko Swe", status: "DISABLED",
        status_checked_at: "2026-08-14T10:00:00Z",
        profile: "k1b", profileLabel: "10/8 hiu", inSnapshot: true,
        owners: [соц({ profile: "k1b", label: "10/8 hiu" })] }),
  каб({ act_id: "act_3", name: "Hiuhiu_MediaBuyer3_8.8_6", bm_name: "2020" }),
];

describe("поиск находит то, чем человек его кормит", () => {
  it("по имени", () => {
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, запрос: "Ko Swe" }).map((a) => a.act_id)).toEqual(["act_2"]);
  });

  it("по act_id — его приносят из Ads Manager и из чата", () => {
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, запрос: "act_3" }).map((a) => a.act_id)).toEqual(["act_3"]);
  });

  it("по имени БМ — «покажи всё из этого БМ» первый вопрос на большом парке", () => {
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, запрос: "BM NQ" }).map((a) => a.act_id)).toEqual(["act_1"]);
  });

  it("по соцу — и по ЛЮБОМУ из владельцев, а не только по главному", () => {
    /* Главный соц выбран годностью к заливу, а ищут кабинет по тому соцу, с
       которого его видели. Прятать общий каб от второго владельца значит
       потерять его на ровном месте. */
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, запрос: "k1b" }).map((a) => a.act_id))
      .toEqual(["act_1", "act_2"]);
  });

  it("регистр не важен: id набирают как придётся", () => {
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, запрос: "ko swe" })).toHaveLength(1);
  });

  it("пустой запрос ничего не режет", () => {
    expect(срез(парк, ПУСТОЙ_СРЕЗ)).toHaveLength(3);
  });

  it("вставленный список отбирает ТОЧНО, а не подстрокой", () => {
    /* Форма вставки разбирается в `acc-query` и здесь только используется —
       второго разбора рядом нет намеренно. Проверяем стык: список из имени и id
       находит ровно два кабинета и не тащит третий по случайному совпадению. */
    const s = срез(парк, { ...ПУСТОЙ_СРЕЗ, запрос: "Ko Swe\nMeDuA6aeP 17/7-8" });
    expect(s.map((a) => a.act_id).sort()).toEqual(["act_1", "act_2"]);
  });
});

describe("состояние: главное — не похоронить живое", () => {
  it("живые — только ACTIVE", () => {
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, состояние: "живые" }).map((a) => a.act_id)).toEqual(["act_1"]);
  });

  it("кабинет с НЕснятым статусом ни в одну корзину беды НЕ попадает", () => {
    /* Самая дорогая ошибка этого фильтра. «Не ACTIVE» и «неизвестно» — разные
       вещи: на чистом проде статус не снят вообще ни у кого, и наивное
       `status !== "ACTIVE"` объявило бы мёртвым весь парк.

       Общего ведра «мёртвые» больше нет: бан, неоплата и проверка Меты — три
       разные новости с тремя разными лечениями, и теперь у каждой свой пункт.
       Тем важнее, что неопрошенный не попадает НИ В ОДНУ из них. */
    for (const с of ["забаненные", "биллинг", "на проверке"] as const) {
      expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, состояние: с }).map((a) => a.act_id),
             `неопрошенный каб попал в «${с}»`)
        .not.toContain("act_3");
    }
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, состояние: "забаненные" }).map((a) => a.act_id))
      .toEqual(["act_2"]);
  });

  it("«не собрано» — отдельное состояние, а не подвид мёртвых", () => {
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, состояние: "не собрано" }).map((a) => a.act_id)).toEqual(["act_3"]);
  });

  it("без карты — только про тех, у кого состояние ВООБЩЕ снимали", () => {
    /* Раньше сюда попадал и неопрошенный `act_3`, и фильтр расходился с плиткой
       наверху: она такие кабинеты считает отдельной величиной («card unknown»),
       потому что «карты нет» и «не спрашивали» — разные утверждения. Человек
       нажимал «no card 6» и получал восемь строк. */
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, состояние: "без карты" }).map((a) => a.act_id))
      .toEqual(["act_2"]);
  });

  /* «БЕЗ ПИКСЕЛЯ», «ОБЩИЕ» И «СОЦ ПОДКЛЮЧЁН» БОЛЬШЕ НЕ ПУНКТЫ ФИЛЬТРА.
     Меню теперь ровно корзины статуса Меты, а эти три отвечали на «почему
     данные такие», а не «что мне делать» — владелец снял их вместе с рядом
     «more filters».

     Сами факты остались фактами, и продукт обязан их различать: `подключён`
     решает охват (на нём стоит лист «Кампании»), «виден больше чем с одного
     соца» рисует бейдж `shared` в строке, а пустой список пикселей — прочерк.
     Проверяются они там, где живут: `подключён` — в `accounts-scope`, `shared`
     и пиксели — в `cloud-owners` и `preview-cloud-accounts`.

     Здесь остаётся одно: убедиться, что снятые пункты правда сняты, а не
     превратились в фильтр, который молча ничего не делает. */
  it("снятые пункты не остались фильтром, который пропускает всё", () => {
    /* Состояние, выпавшее из типа, но оставшееся в `срез` веткой `default`,
       вернуло бы ВЕСЬ парк — то есть фильтр, который выглядит работающим и не
       фильтрует. Проверяем через набор: чего нет в списке, того нельзя и
       выбрать. */
    expect(СОСТОЯНИЯ).not.toContain("без пикселя");
    expect(СОСТОЯНИЯ).not.toContain("общие");
    expect(СОСТОЯНИЯ).not.toContain("соц подключён");
    expect(СОСТОЯНИЯ).not.toContain("можно лить");
    expect(СОСТОЯНИЯ).not.toContain("мёртвые");
  });

  it("«можно лить» — ровно то, что отмечается чекбоксом", () => {
    /* Определение одно на продукт и живёт в `cloud-accounts.можноЛить`: то же
       самое, по чему горит чекбокс строки. Второе вычисление того же правила
       разошлось бы с первым на первой же правке, а гит этого не показывает —
       файлы разные.

       СРАВНИВАЕМ С ПРЕДИКАТОМ, А НЕ С `a.profile`: с #166 годность включает и
       состояние самого кабинета. Прежняя запись сверяла фильтр с половиной
       правила и осталась бы зелёной ровно в том случае, из-за которого иссус и
       заведён, — «ready to upload 145» при 99 забаненных. */
    /* Пункта «можно лить» больше нет — чип снят по прямым словам владельца
       («чип только раздражает»). Правило от этого стало ВАЖНЕЕ: теперь оно
       единственное, что решает, гаснет ли чекбокс, и множество отмечаемых
       строится им же (`cloud-accounts.отмечаемые`). */
    const годные = отмечаемые(парк);
    expect(годные.map((a) => a.act_id)).toEqual(парк.filter(можноЛить).map((a) => a.act_id));
    expect(годные.every(можноЛить)).toBe(true);
  });

  it("МЁРТВЫЙ КАБИНЕТ не «можно лить», даже когда соц жив", () => {
    /* Жалоба владельца дословно: «заливаемых не может быть 145, если 99
       забанены». Соц у такого кабинета в порядке, окно на месте — а залить
       нельзя ничем, и спека его всё равно выбрасывает (`lib/groups.ts`). */
    const мёртвый = [каб({
      act_id: "act_dead", profile: "p1", profileLabel: "p1", status: "DISABLED",
      owners: [соц({ profile: "p1", oauth: true, present: true })],
    })];
    expect(отмечаемые(мёртвый)).toHaveLength(0);
    /* Отрицательный контроль: он при этом НЕ исчез с листа — история и спенд
       остаются. Фильтр «все» обязан его показывать. */
    expect(срез(мёртвый, ПУСТОЙ_СРЕЗ)).toHaveLength(1);
  });

  it("PENDING_CLOSURE тоже не заливается — список банов один на продукт", () => {
    /* Отклонённый когда-то PR завёл свой список из одного `DISABLED`, и
       `PENDING_CLOSURE` проходил как живой. Здесь это ловится числом. */
    const закрывается = [каб({
      act_id: "act_pc", profile: "p1", profileLabel: "p1", status: "PENDING_CLOSURE",
      owners: [соц({ profile: "p1", oauth: true, present: true })],
    })];
    expect(отмечаемые(закрывается)).toHaveLength(0);
  });

  it("НЕОПЛАЧЕННЫЙ кабинет заливается: это не бан, а счёт", () => {
    /* Отрицательный контроль ко всему блоку, и он важнее прочих: сторож,
       запрещающий больше, чем запрещает залив, прячет от человека кабинеты,
       в которые залить МОЖНО. `billing` спека пропускает — значит и мы. */
    const неоплачен = [каб({
      act_id: "act_bill", profile: "p1", profileLabel: "p1", status: "UNSETTLED",
      owners: [соц({ profile: "p1", oauth: true, present: true })],
    })];
    expect(отмечаемые(неоплачен)).toHaveLength(1);
    /* И он находится своим пунктом меню, а не тонет в общем ведре: неоплату
       лечат оплатой, и увидеть её списком человек должен отдельно от бана. */
    expect(срез(неоплачен, { ...ПУСТОЙ_СРЕЗ, состояние: "биллинг" })).toHaveLength(1);
    expect(срез(неоплачен, { ...ПУСТОЙ_СРЕЗ, состояние: "забаненные" })).toHaveLength(0);
  });

  it("ТОКЕН БЕЗ ЖИВОГО ОКНА попадает в «подключён», но НЕ в «можно лить»", () => {
    /* Живой парк владельца 15.08 выглядел ровно так: токены под мёртвыми
       ключами прежнего вендора антидетекта, живые окна без токенов. Одно
       состояние на оба вопроса дало бы отфильтрованный список, которому человек
       поверит, и каждая строка в нём была бы неверна. */
    const мёртвоеОкно = [каб({
      act_id: "act_9",
      owners: [соц({ profile: "k1fg9weq", oauth: true, present: false })],
    })];
    /* Спрашиваем ИСТОЧНИКИ, а не пункты меню: обоих пунктов больше нет, а оба
       правила живы и расходятся ровно на этой строке. */
    expect(мёртвоеОкно.filter(подключён)).toHaveLength(1);
    expect(отмечаемые(мёртвоеОкно)).toHaveLength(0);
    expect(мёртвоеОкно.filter(подключён).length - отмечаемые(мёртвоеОкно).length).toBe(1);
  });
});

describe("фильтр по соцу", () => {
  it("показывает каб с ЛЮБОГО его соца, а не только с главного", () => {
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, профиль: "k1b" }).map((a) => a.act_id))
      .toEqual(["act_1", "act_2"]);
  });

  it("кабинет, соца которого не знает никто, под фильтром по соцу НЕ показывается", () => {
    /* Соблазн показать его «на всякий случай» есть, и поддаться нельзя: фильтр
       по соцу отвечает на вопрос «что я залью с этого профиля», а с кабинета без
       соца залить нечем. Он виден без фильтра и в счётчике «всего». */
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, профиль: "k1a" }).map((a) => a.act_id)).toEqual(["act_1"]);
  });
});

describe("фильтры складываются, а не спорят", () => {
  it("состояние и поиск вместе", () => {
    /* Фильтра по БМ больше нет — измерение ушло с листа целиком. Имя БМ
       осталось находимым ПОИСКОМ, и складываться с состоянием обязано так же,
       как складывался фильтр. */
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, состояние: "живые", запрос: "BM NQ" })).toHaveLength(1);
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, состояние: "забаненные", запрос: "BM NQ" }))
      .toHaveLength(0);
  });

  it("соц и состояние вместе", () => {
    expect(срез(парк, { ...ПУСТОЙ_СРЕЗ, профиль: "k1b", состояние: "живые" }).map((a) => a.act_id))
      .toEqual(["act_1"]);
  });
});

describe("вспомогательное считается по тем же правилам, что и фильтрует", () => {
  /* Списка БМ больше нет: выпадашку сняли вместе со всем измерением. Проверять
     тут нечего, а держать тест на удалённую функцию — значит держать документ,
     который врёт. Поиск по имени БМ проверяется в `accounts-scope`. */

  it("список соцев — по ВЛАДЕЛЬЦАМ, но только по ПОДКЛЮЧЁННЫМ", () => {
    /* По владельцам, а не по главному соцу: иначе соц, который всюду проиграл
       выбор главного, пропал бы из фильтра вместе со своими кабинетами.
       Но только по тем, кем сегодня можно работать: `k1b` без токена — это
       история связей, а не выбор. Владелец про такие: «я их удалял,
       архивировал — нахуй не надо». */
    expect(профилиСписок(парк).map((p) => p.id)).toEqual(["k1a"]);
  });

  it("счётчики совпадают с тем, что покажет фильтр", () => {
    /* Если счётчик и фильтр считают по-разному, человек нажимает «12 мёртвых» и
       видит девять строк — и перестаёт верить обоим. */
    const счёт = счётПоСостояниям(парк);
    for (const с of СОСТОЯНИЯ) {
      expect(счёт[с]).toBe(срез(парк, { ...ПУСТОЙ_СРЕЗ, состояние: с }).length);
    }
    expect(счёт["все"]).toBe(парк.length);
  });
});
