/* ── хранение ──────────────────────────────────────────────────────────────
   Тесты гоняются в node, где `window` нет вовсе. Подставляем минимальное
   хранилище: проверяется наша логика разбора, а не браузер. */

const хранилище = () => {
  const данные = new Map<string, string>();
  return {
    getItem: (k: string) => (данные.has(k) ? данные.get(k)! : null),
    setItem: (k: string, v: string) => void данные.set(k, v),
  };
};
const подставить = (ls: ReturnType<typeof хранилище>) => {
  (globalThis as { window?: unknown }).window = { localStorage: ls };
};

afterEach(() => {
  delete (globalThis as { window?: unknown }).window;
});

describe("выбор переживает перезаход", () => {
  it("на сервере и без сохранённого — состав по умолчанию", () => {
    expect(загрузитьКолонки()).toEqual(CAMP_DEFAULT_VISIBLE);
    подставить(хранилище());
    expect(загрузитьКолонки()).toEqual(CAMP_DEFAULT_VISIBLE);
  });

  it("сохранённое возвращается как есть, вместе с порядком", () => {
    const ls = хранилище();
    подставить(ls);
    сохранитьКолонки(["clicks", "spend"]);
    expect(ls.getItem(CAMP_COLS_LS_KEY)).toBe('["clicks","spend"]');
    expect(загрузитьКолонки()).toEqual(["clicks", "spend"]);
  });

  it("ПУСТОЙ набор — это выбор, и он переживает перезаход", () => {
    /* «Выключил все метрики» и «ничего не сохранено» — разные вещи. Вернуть
       дефолт на следующем заходе значит не выполнить требование иссуса, а
       сделать вид, что выполнил. */
    const ls = хранилище();
    подставить(ls);
    сохранитьКолонки([]);
    expect(загрузитьКолонки()).toEqual([]);
  });

  it("набор из одних чужих ключей — это мусор прошлой версии, откат к дефолту", () => {
    const ls = хранилище();
    подставить(ls);
    /* Ключи с «Аналитики», которых в каталоге кампаний нет и не будет: там
       они про крео и раскладку. `cpftd` для этого больше не годится — цены
       ступеней теперь есть и здесь. */
    ls.setItem(CAMP_COLS_LS_KEY, '["geos","ads_with_ftd"]');
    expect(загрузитьКолонки()).toEqual(CAMP_DEFAULT_VISIBLE);
  });

  it("чужие ключи вперемешку со своими — свои остаются", () => {
    const ls = хранилище();
    подставить(ls);
    ls.setItem(CAMP_COLS_LS_KEY, '["geos","spend","clicks"]');
    expect(загрузитьКолонки()).toEqual(["spend", "clicks"]);
  });

  it("битое содержимое не роняет лист", () => {
    const ls = хранилище();
    подставить(ls);
    ls.setItem(CAMP_COLS_LS_KEY, "{не json");
    expect(загрузитьКолонки()).toEqual(CAMP_DEFAULT_VISIBLE);
    ls.setItem(CAMP_COLS_LS_KEY, '{"колонки":["spend"]}');
    expect(загрузитьКолонки()).toEqual(CAMP_DEFAULT_VISIBLE);
  });
});

/* ── сделано, но не показано: охват, частота и цены ступеней ────────────────
 *
 * Все три были готовы в модели и НЕ ИМЕЛИ КОЛОНОК: охват с частотой приехали с
 * #154 и замерены на живой Мете, ячейка цены ступени существовала с воронкой.
 * Механизм есть, экрана нет, знать о них неоткуда — ровно та порода, что
 * стоила дня на ключе приёма воронки.
 */

describe("охват и частота: показаны, но НЕ СЛОЖЕНЫ", () => {
  const дневная = строка({
    level: "ad", spend: 10_000, impressions: 11_054, clicks: 100, reach: 10_472,
  });

  it("у охвата и частоты есть колонки — иначе их не видит никто", () => {
    const ключи = CAMP_COLUMNS.map((c) => c.key);
    expect(ключи).toContain("reach");
    expect(ключи).toContain("frequency");
  });

  it("охват объявления за день печатается числом", () => {
    expect(ячейка("reach", дневная).текст).toBe("10,472");
  });

  it("частота считается той же формулой, что у Меты", () => {
    /* Сверено на живом кабинете 15.08: 11054/10472 = 1.0556, у Меты в
       `frequency` — 1.055577. Второй формулы здесь нет: считает `campaigns.ts`. */
    expect(ячейка("frequency", дневная).текст).toBe("1.06");
  });

  it("пустой охват объяснён РАЗНЫМИ фразами на разные причины", () => {
    /* Три причины — не тот уровень, длинное окно, не собрано — лечатся
       по-разному, а на экране все три прочерк. Свести их в одну фразу значит
       отправить человека чинить исправное. */
    const родитель = ячейка("reach", строка({ level: "campaign", spend: 100 }));
    const окно = ячейка("reach", строка({ level: "ad", spend: 100 }),
      { период: { since: "2026-08-08", until: "2026-08-14", tz: "UTC+3", days: 7, today: "2026-08-15" } });
    const несобрано = ячейка("reach", строка({ level: "ad" }));
    const тексты = [родитель, окно, несобрано].map((я) => я.подсказка);
    expect(new Set(тексты).size).toBe(3);
    for (const я of [родитель, окно, несобрано]) expect(я.текст).toBe(DASH);
  });

  it("окно не передали — не выдумываем причину и не спорим с соседней колонкой", () => {
    /* НАЙДЕНО ЧТЕНИЕМ ЖИВОГО ВЫЗОВА: дерево зовёт `ячейка()` без периода
       (`CampaignsView`), а `почемуНетОхвата` без него отвечает «строк расхода
       за это окно нет» — и это утверждение прямо противоречит спенду, стоящему
       в той же строке. Человек идёт чинить исправный сбор. Пока окно не
       передают, честный ответ один: причин две, и мы не знаем, которая. */
    const я = ячейка("reach", строка({ level: "ad", spend: 12_345, impressions: 100 }));
    expect(я.текст).toBe(DASH);
    expect(я.подсказка).not.toMatch(/no spend rows/i);
    expect(я.подсказка).toMatch(/single day/i);
    // А с окном — точная причина, без всяких «одно из двух».
    const сОкном = ячейка("reach", строка({ level: "ad", spend: 12_345 }),
      { период: { since: "2026-08-08", until: "2026-08-14", tz: "UTC+3", days: 7, today: "2026-08-15" } });
    expect(сОкном.подсказка).toMatch(/7 days/);
  });

  it("В ИТОГЕ охват и частота — прочерк с объяснением, а не сумма", () => {
    /* Сумма охватов считает одного человека дважды; среднее частот — это
       среднее дробей с разными знаменателями. Оба выглядели бы настоящими. */
    const т = итоги([дневная, строка({ level: "ad", spend: 20, impressions: 30, reach: 25 })]);
    expect(т.reach.текст).toBe(DASH);
    expect(т.reach.число).toBeNull();
    expect(т.reach.подсказка).toMatch(/unique people/i);
    expect(т.frequency.текст).toBe(DASH);
    expect(т.frequency.подсказка).toMatch(/averaging ratios|cannot be summed/i);
  });
});

describe("цена ступени воронки: колонка есть, и считается от сумм", () => {
  const воронка = подготовить({
    ok: true, tracker: "keine_media", lead_metric: "sub",
    ever_at: "2026-08-15T00:00:00Z", metrics: ["sub"],
    rows: {
      большая: { level: "campaign", days: 7, sub: 1000 },
      малая: { level: "campaign", days: 7, sub: 2 },
    },
  });
  const большая = строка({ fb_id: "большая", spend: 100_000, currency: "USD" });
  const малая = строка({ fb_id: "малая", spend: 100_000, currency: "USD" });

  it("у каждой ступени воронки есть колонка цены, названная словом «Аналитики»", () => {
    /* Связи «sub → cpsub» нет ни в одних данных: `contact` зовётся `cpcon`, а
       `checkout` — `cpcheck`, то есть шаблон «cp + имя» уже неверен. Карта
       объявлена руками ОДИН раз, и вот проверка, что она не протухла. */
    for (const шаг of ступениАналитики()) {
      const ключ = ЦЕНА_ШАГА[шаг];
      expect(ключ, `у ступени ${шаг} не объявлена цена`).toBeTruthy();
      expect(CAMP_COLUMNS.map((c) => c.key), ключ).toContain(ключ);
      const мой = (CAMP_BY_KEY as Record<string, { title: string } | undefined>)[ключ];
      const их = (АНАЛИТИКА as Record<string, { title: string } | undefined>)[ключ];
      expect(мой?.title, ключ).toBe(их?.title);
    }
  });

  it("в строке цена делит спенд на то, что дала воронка", () => {
    expect(ячейка("cpsub", большая, { воронка }).текст).toBe("$1.00");
  });

  it("ИТОГ — от сумм, а не среднее по строкам, и разница видна", () => {
    /* Среднее двух цен ($1 и $500) дало бы $250.50 — правдоподобное число,
       которого нет ни у кого. Верное: 200000 минорных на 1002 подписчика. */
    const т = итоги([большая, малая], { воронка });
    expect(т.cpsub.число).toBeCloseTo(200_000 / 1002, 6);
    expect(т.cpsub.текст).toBe("$2.00");
    expect(т.cpsub.текст).not.toBe("$250.50");
  });

  it("делить не на что — прочерк с причиной, а не «бесплатно»", () => {
    const пусто = ячейка("cpsub", строка({ fb_id: "нет", spend: 100 }), { воронка });
    expect(пусто.текст).toBe(DASH);
    expect(пусто.подсказка).toMatch(/no sub/i);
    const безСвязки = ячейка("cpsub", большая);
    expect(безСвязки.текст).toBe(DASH);
    expect(безСвязки.подсказка).toMatch(/not free|unknown/i);
  });
});

