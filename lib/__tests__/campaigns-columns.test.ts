/* Колонку рисуют ТРИ места — шапка, строка и футер (#153), — и все три берут
 * её отсюда. Поэтому здесь проверяется не «функция считает», а то, ради чего
 * модуль вообще один: что колонка, которую заведут завтра, не выпадет из
 * отрисовки молча, и что прочерк нигде не превратился в ноль. */

const строка = (p: Partial<CampaignRow> = {}): CampaignRow => ({
  fb_id: "c1", level: "campaign", parent_id: null, act_id: "act_1",
  name: "кампания", status: "ACTIVE", currency: "USD", ...p,
});

