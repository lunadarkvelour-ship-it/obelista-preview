describe("рисуется КАЖДАЯ колонка каталога, а не перечисленные руками", () => {
  /* Список берётся ИЗ КОДА. Тест, перебирающий выписанные ключи, не знает про
     колонку, которую заведут завтра, — а именно она и выпадет из отрисовки. */
  /* «Полная строка» — это строка, у которой собрано ВСЁ, включая охват. Он
     бывает только у объявления и только за одни сутки, поэтому уровень здесь
     `ad`: на кампании его отсутствие — свойство метрики, а не пробел в сборе,
     и тест на отрисовку не должен спорить с этим. */
  const полная = строка({
    level: "ad", active_ads: 3, spend: 12_345, daily_budget: 7_000,
    impressions: 100_000, clicks: 1_000, reach: 90_000,
  });

  /* «Полная строка» для воронки — это ещё и связка: её числа лежат не в
     `CampaignRow`, а в ответе `/funnel_join` по `fb_id`. Контекст собирается
     ИЗ КАТАЛОГА (`group === "воронка"`), а не из выписанных ключей: ступень,
     заведённую завтра, тест обязан наполнить сам, иначе он покраснеет на
     пустоте вместо того, чтобы проверить отрисовку. */
  const ступени = CAMP_COLUMNS.filter((c) => c.group === "воронка").map((c) => c.key);
  const воронка = подготовить({
    ok: true, tracker: "keine_media", lead_metric: "sub", ever_at: "2026-08-15T00:00:00Z",
    metrics: ступени,
    rows: {
      [полная.fb_id]: {
        level: "campaign", days: 7,
        ...Object.fromEntries(ступени.map((k, i) => [k, 100 - i])),
      },
    },
  });

  for (const c of CAMP_COLUMNS) {
    it(`«${c.key}» даёт текст и подсказку на полной строке`, () => {
      const я = ячейка(c.key, полная, { воронка });
      expect(я.текст, c.key).toBeTruthy();
      expect(я.текст, c.key).not.toBe(DASH);
      expect(я.подсказка.trim(), c.key).not.toBe("");
      expect(ТОН_КЛАСС[я.тон], c.key).toBeTruthy();
    });

    it(`«${c.key}» на пустой строке даёт ПРОЧЕРК с объяснением, а не ноль`, () => {
      /* Самая дорогая поломка этого листа (#122): ноль в колонке денег — это
         утверждение «не потрачено», которого мы не делали. У воронки та же
         беда своими словами: связку передаём, но про ЭТОТ объект она молчит —
         и ячейка обязана сказать «не приезжало», а не «ноль подписчиков». */
      const я = ячейка(c.key, строка({ fb_id: "нет-такого" }), { воронка });
      expect(я.текст, c.key).toBe(DASH);
      expect(я.подсказка.length, c.key).toBeGreaterThan(10);
    });
  }
});

