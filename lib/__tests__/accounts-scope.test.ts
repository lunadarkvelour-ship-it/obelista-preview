describe("меню статусов покрывает целое и не теряет корзин", () => {
  it("у КАЖДОЙ корзины статуса есть свой пункт", () => {
    /* Это и есть гарантия, которую держала плитка (#166: «145 · 40 active ·
       99 disabled» — шести нет, и узнать где негде). Плитки не стало, гарантия
       осталась: набор пунктов выводится из `Record<StatusLabel, …>`, то есть
       новая корзина не скомпилируется без пункта. Здесь проверяется, что
       вывод правда состоялся, а не что кто-то переписал список руками. */
    const корзины: StatusLabel[] = ["active", "disabled", "billing", "review", "unknown"];
    for (const к of корзины) {
      expect(СОСТОЯНИЕ_КОРЗИНЫ[к], `корзина ${к} без пункта меню`).toBeTruthy();
      expect(СОСТОЯНИЯ_МЕНЮ).toContain(СОСТОЯНИЕ_КОРЗИНЫ[к]);
    }
    /* Плюс «все» — и ничего сверх того: пункт, не являющийся корзиной, сломал
       бы сходимость суммы, ради которой всё это и собрано. */
    expect(СОСТОЯНИЯ_МЕНЮ).toHaveLength(корзины.length + 1);
    expect(СОСТОЯНИЯ_МЕНЮ[0]).toBe("все");
  });

  it("СУММА ПУНКТОВ РАВНА ЦЕЛОМУ — на любом парке", () => {
    /* Прямая жалоба владельца, перенесённая с плитки на меню: сорок плюс
       девяносто девять это не сто сорок пять, и шести нет. */
    const смесь = [
      каб({ act_id: "a1", status: "ACTIVE", status_checked_at: "2026-08-17" }),
      каб({ act_id: "d1", status: "DISABLED", status_checked_at: "2026-08-17" }),
      каб({ act_id: "u1", status: "UNSETTLED", status_checked_at: "2026-08-17" }),
      каб({ act_id: "r1", status: "PENDING_RISK_REVIEW", status_checked_at: "2026-08-17" }),
      каб({ act_id: "n1" }),
    ];
    const счёт = счётПоСостояниям(смесь);
    const сумма = СОСТОЯНИЯ_МЕНЮ
      .filter((с) => с !== "все")
      .reduce((n, с) => n + счёт[с], 0);
    expect(сумма).toBe(смесь.length);
    expect(счёт["все"]).toBe(смесь.length);
  });

  it("бан считается общим словарём, а не своим списком", () => {
    /* `PENDING_CLOSURE` — тоже бан: разбана у Меты не бывает. Свой список из
       одного `DISABLED` здесь однажды уже заводили, и закрывающийся кабинет
       проходил как живой. */
    const баны = [
      каб({ act_id: "d1", status: "DISABLED" }),
      каб({ act_id: "d2", status: "PENDING_CLOSURE" }),
      каб({ act_id: "u1", status: "UNSETTLED" }),
      каб({ act_id: "n1" }),
    ];
    expect(срез(баны, { ...ПУСТОЙ_СРЕЗ, состояние: "забаненные" }).map((a) => a.act_id))
      .toEqual(["d1", "d2"]);
    /* НЕОПЛАЧЕННЫЙ СЧЁТ — НЕ БАН, и теперь у него свой пункт, а не общее ведро
       «не активен». Он лечится оплатой, и звать его баном значит хоронить
       живое. */
    expect(срез(баны, { ...ПУСТОЙ_СРЕЗ, состояние: "биллинг" }).map((a) => a.act_id))
      .toEqual(["u1"]);
    /* Статус не снимали — «не собрано», а не «мёртвый». */
    expect(срез(баны, { ...ПУСТОЙ_СРЕЗ, состояние: "не собрано" }).map((a) => a.act_id))
      .toEqual(["n1"]);
  });

  it("«без карты» есть в срезе, но НЕ пунктом меню", () => {
    /* Оно пересекается и с активными, и с баном (73 из 109 на живом парке),
       поэтому корзиной быть не может — сумма пунктов перестала бы сходиться.
       Отбирать его надо постоянно, поэтому оно живёт нажимаемым числом в
       сводной строке. */
    expect(СОСТОЯНИЯ).toContain("без карты");
    expect(СОСТОЯНИЯ_МЕНЮ).not.toContain("без карты");
    const парк2 = [
      каб({ act_id: "c1", status: "ACTIVE", status_checked_at: "2026-08-17" }),
      каб({ act_id: "c2", status: "ACTIVE", status_checked_at: "2026-08-17",
            funding_display_string: "VISA *5446" }),
      каб({ act_id: "c3" }),
    ];
    expect(срез(парк2, { ...ПУСТОЙ_СРЕЗ, состояние: "без карты" }).map((a) => a.act_id))
      .toEqual(["c1"]);
  });
});

