/* Период в Creative Analytics: панельная половина сторожа (#161).
 *
 * Движковая половина живёт в `tests/test_analytics_period.py` и проверяет, что
 * два разных окна дают разные суммы. Здесь — то, чего она увидеть не может: ушёл
 * ли выбор человека В ЗАПРОС, и не завела ли панель собственный ответ на вопрос
 * «какое сегодня число».
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ПОЛОВИНА, А НЕ ПРИДИРКА. Движок можно починить целиком,
 * и лист всё равно останется сломанным: панель, считающая «последние 7 дней»
 * сама, отправит СВОИ даты, движок честно посчитает по ним, и оба будут правы.
 * Разойдутся они только у человека в другом поясе и только после полуночи —
 * то есть там, где никто не смотрит. Именно так это и жило: в листе стояли
 * `ymd(new Date())` и четыре пресета со своей арифметикой.
 *
 * СПОСОБЫ СОВРАТЬ, каждый тише предыдущего:
 *  1. принять период и не положить его в запрос — снаружи выглядит рабочим;
 *  2. положить в запрос И пресет, и пару дат — движок ответит отказом, а
 *     человек сделал понятное движение;
 *  3. посчитать даты в браузере — расходится только в чужом поясе;
 *  4. промолчать про границы суток парка — молчание читается как подтверждение.
 */
import { afterEach, describe, expect, it, vi } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";
import { api } from "@/lib/analytics";
import {
  НАЧАЛЬНЫЙ, оСуткахПарка, периодВЗапрос, type PeriodПарка,
} from "@/lib/period";

const ЛИСТ = readFileSync(
  path.resolve(__dirname, "..", "..", "components", "views", "AnalyticsView.tsx"), "utf8");

/** Исходник без комментариев. Запреты обязаны проверяться по КОДУ: объяснение,
 *  почему мы так больше не делаем, само роняло бы тест, и следующий читатель
 *  убрал бы объяснение вместо того, чтобы оставить проверку. */
const КОД = ЛИСТ.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

/** Перехват запроса: нас интересует АДРЕС, который ушёл, а не тело ответа. */
function перехват(): { адреса: string[] } {
  const адреса: string[] = [];
  vi.stubGlobal("fetch", (u: string) => {
    адреса.push(String(u));
    return Promise.resolve({
      ok: true, status: 200, json: () => Promise.resolve({ ok: true }),
    } as unknown as Response);
  });
  return { адреса };
}

afterEach(() => vi.unstubAllGlobals());

const парк = (п: Partial<PeriodПарка>): PeriodПарка => ({
  since: "2026-08-09", until: "2026-08-15", tz: "UTC+3", days: 7,
  today: "2026-08-15", ...п,
});

describe("выбор человека доезжает до запроса, а не остаётся на экране", () => {
  it("пресет уходит ИМЕНЕМ, а даты за него считает движок", () => {
    /* Имя, а не пара дат, — в этом вся правка. Посчитай панель «7 days» сама,
       у продукта стало бы два «сегодня», и разошлись бы они на границе суток. */
    expect(периодВЗапрос({ preset: "last_7d" }))
      .toEqual({ period: "last_7d", tz: null });
  });

  it("три ручки листа получают ОДИН И ТОТ ЖЕ период", async () => {
    /* Таблица, лес и дерево одного крео обязаны отвечать про одно окно. Уедь
       они врозь — раскрытая ветка не сойдётся с той строкой, из которой её
       раскрыли, и сойтись им будет негде: это разные запросы. */
    const { адреса } = перехват();
    await api.board({ preset: "yesterday" });
    await api.ads({ preset: "yesterday" });
    await api.creative("dz5", { preset: "yesterday" });
    expect(адреса).toHaveLength(3);
    for (const адрес of адреса) {
      expect(адрес, адрес).toContain("period=yesterday");
    }
    expect(адреса[0]).toContain("/leaderboard");
    expect(адреса[1]).toContain("/ads");
    expect(адреса[2]).toContain("/creative/dz5");
  });

  it("ДВА разных периода дают ДВА разных запроса", async () => {
    /* Панельный двойник главного утверждения движковой половины. Тест вида
       «в адресе есть period=» зелен и на коде, который кладёт туда одну и ту же
       строку всегда. */
    const { адреса } = перехват();
    await api.board({ preset: "today" });
    await api.board({ preset: "yesterday" });
    await api.board({ since: "2026-08-01", until: "2026-08-03" });
    expect(new Set(адреса).size).toBe(3);
    expect(адреса[2]).toContain("since=2026-08-01");
    expect(адреса[2]).toContain("until=2026-08-03");
    /* И пара дат НЕ досылается вместе с пресетом: движок на два ответа об
       одном вопросе отвечает отказом, а человек сделал понятное движение. */
    expect(адреса[2]).not.toContain("period=");
    expect(адреса[0]).not.toContain("since=");
  });

  it("гео едет тем же запросом и период не вытесняет", async () => {
    const { адреса } = перехват();
    await api.board({ preset: "last_7d" }, "DZ");
    expect(адреса[0]).toContain("period=last_7d");
    expect(адреса[0]).toContain("geo=DZ");
  });
});

describe("своей арифметики дат на листе не осталось", () => {
  it("период — одно значение, и начальное берётся из общего контура", () => {
    expect(КОД).toContain("React.useState<PeriodQuery>(НАЧАЛЬНЫЙ)");
    /* `НАЧАЛЬНЫЙ` — это ИМЯ пресета, а не дата: считает её движок. Проверяем и
       сам контур, иначе «today» могло бы стать датой в панели. */
    expect(НАЧАЛЬНЫЙ).toEqual({ preset: "today" });
  });

  it("лист не считает ни «сегодня», ни «N дней назад» сам", () => {
    for (const запрещено of [
      /ymd\(new Date\(\)\)/,
      /new Date\(\)\.get(FullYear|Month|Date)\(\)/,
      /setDate\(/,
      /toISOString/,
    ]) {
      expect(КОД, String(запрещено)).not.toMatch(запрещено);
    }
    /* И вырезание комментариев что-то оставило: пустая строка прошла бы все
       запреты разом и ничего бы не значила. */
    expect(КОД.length).toBeGreaterThan(5000);
  });

  it("кнопки периода — общий компонент, а не свой ряд в разметке", () => {
    /* Второй такой же контур и есть болезнь: он разойдётся с первым в первый
       же день. У листа кампаний тот же `PeriodPicker`. */
    expect(КОД).toContain("<PeriodPicker");
    expect(КОД).toMatch(/from\s+"@\/components\/views\/PeriodPicker"/);
    expect(КОД).toMatch(/from\s+"@\/lib\/period"/);
    /* Своего списка пресетов у листа больше нет. */
    expect(КОД).not.toMatch(/const PRESETS/);
  });

  it("«за всё» стало явным выбором с настоящими датами", () => {
    /* Раньше «весь диапазон» получался САМ, когда дат не прислали, — lifetime
       под видом среза. Теперь это нажатие, и границы берутся из ответа движка
       (`stored_from`, `today`), а не из часов браузера. */
    expect(КОД).toContain("stored_from");
    expect(КОД).toContain("period?.today");
  });

  it("период живёт в адресе страницы, а не только в компоненте", () => {
    /* Иначе переход на другой раздел начинает период заново, а человек уверен,
       что смотрит то же окно. Плюс ссылка коллеге открывает тот же экран. */
    expect(КОД).toContain("изURL(");
    expect(КОД).toContain("вURL(");
  });
});

describe("про границы суток парка лист не молчит", () => {
  /* Мы считаем сутки в UTC+3, Мета режет дневные строки по часам САМОГО
     кабинета, а лидерборд складывает деньги поперёк парка. Приведение поясов
     владелец отложил (#162) — значит расхождение существует, и назвать его
     обязан экран. */

  it("все кабинеты в нашем поясе — сказано, что границы совпали", () => {
    const т = оСуткахПарка(парк({ accounts: 12, accounts_same: 12,
                                  same_day_boundary: true }));
    expect(т).toContain("12");
    expect(т.toLowerCase()).toContain("match");
  });

  it("есть чужой пояс — названо, сколько их и чем это грозит сумме", () => {
    const т = оСуткахПарка(парк({ accounts: 80, accounts_same: 72,
                                  accounts_diff: 8, same_day_boundary: false }));
    expect(т).toContain("8 of 80");
    /* Главное, что человек обязан унести: сумма сложена из РАЗНЫХ суток. */
    expect(т.toLowerCase()).toContain("different moments");
    /* И что переложить их в наши границы нечем — это устройство Меты, а не
       наша недоделка, иначе фраза читается как обещание починить. */
    expect(т.toLowerCase()).toContain("no finer breakdown");
  });

  it("пояс неизвестен — это «не знаем», а НЕ «совпадает»", () => {
    /* На живом парке пояс пуст у 137 кабинетов из 268, то есть это обычное
       состояние. Превратить его в «совпадает» значит соврать большинству. */
    const т = оСуткахПарка(парк({ accounts: 80, accounts_same: 20,
                                  accounts_unknown: 60, same_day_boundary: null }));
    expect(т).toContain("60 of 80");
    expect(т.toLowerCase()).toContain("we do not know");
    expect(т.toLowerCase()).not.toContain("match:");
  });

  it("три состояния дают ТРИ РАЗНЫХ текста, а не один на все", () => {
    /* Отрицательный контроль на «сделал вид, что различает». Одинаковая фраза
       прошла бы каждую проверку выше по отдельности. */
    const тексты = [true, false, null].map((в) => оСуткахПарка(парк({
      accounts: 10, accounts_same: 5, accounts_diff: 3, accounts_unknown: 2,
      same_day_boundary: в as boolean | null,
    })));
    expect(new Set(тексты).size).toBe(3);
    for (const т of тексты) expect(т).not.toBe("");
  });

  it("денег в окне нет вовсе — молчим, и это не «совпадает»", () => {
    /* Единственный случай, когда сказать нечего: ни один кабинет в окно ничего
       не положил. Оговорка на пустом экране была бы шумом, а шум перестают
       читать вместе с настоящими оговорками. */
    expect(оСуткахПарка(парк({ accounts: 0, same_day_boundary: null }))).toBe("");
    expect(оСуткахПарка(null)).toBe("");
  });

  it("фраза доезжает до экрана, а не остаётся в модуле", () => {
    /* Ровно та болезнь, что была с вердиктом о сборе: компонент работал и
       стоял не везде. */
    expect(КОД).toContain("суткиТекст={оСуткахПарка(");
  });
});
