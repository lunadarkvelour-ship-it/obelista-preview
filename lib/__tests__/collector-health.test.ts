import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import {
  healthLevel,
  healthMeaning,
  healthRestartLine,
  healthTitle,
  healthTone,
  healthWriteLine,
  readHealth,
  type CollectorHealth,
} from "@/lib/collector-health";

/* Панельная половина #140. Два правила контракта, нарушить которые легко и
 * дорого, и оба держатся тестом, а не аккуратностью:
 *
 *  1. ЦВЕТ БЕРЁТСЯ ИЗ «тревога», А НЕ ИЗ «состояние». `заперт` — не тревога:
 *     Мета не пускает, причина названа, рука человека там ничего не исправит.
 *     Красное на нём = посланный чинить чужое владелец, который на третий раз
 *     перестанет верить индикатору.
 *  2. ПОРОГОВ В ПАНЕЛИ НЕТ. Что считать аварией, решает `core/collector.
 *     здоровье`. Две копии правила на двух языках разъезжаются молча, а по
 *     этим цифрам автоправила тушат кампании.
 */

/** Здоровый вердикт, из которого тесты меняют по одному полю. */
const ИДЁТ: CollectorHealth = {
  состояние: "идёт",
  почему: "",
  тревога: false,
  подъёмов: 1,
  уронов: 0,
  окно_с: 1800,
  последняя_запись_с: 40,
};

describe("цвет решает «тревога», а не имя состояния", () => {
  it("заперт без тревоги — не красное: чинится не у нас", () => {
    const h: CollectorHealth = { ...ИДЁТ, состояние: "заперт", тревога: false, почему: "Мета не пускает" };
    expect(healthTone(h)).toBe("notice");
    expect(healthLevel(h)).not.toBe("bad");
  });

  it("остыл с тревогой — красное", () => {
    const h: CollectorHealth = { ...ИДЁТ, состояние: "остыл", тревога: true };
    expect(healthTone(h)).toBe("alarm");
    expect(healthLevel(h)).toBe("bad");
  });

  it("если демон однажды скажет «заперт, но рука нужна» — панель покрасит красным, не споря", () => {
    /* Главный тест файла: он доказывает, что читается ПОЛЕ, а не имя. Собери
       мы цвет из списка состояний — этот случай остался бы жёлтым, и решение
       демона было бы молча отменено панелью. */
    const h: CollectorHealth = { ...ИДЁТ, состояние: "заперт", тревога: true };
    expect(healthTone(h)).toBe("alarm");
  });

  it("и наоборот: «мигает» без тревоги не красится красным самовольно", () => {
    const h: CollectorHealth = { ...ИДЁТ, состояние: "мигает", тревога: false, подъёмов: 47 };
    expect(healthTone(h)).toBe("notice");
  });

  it("«идёт» — спокойное, и это единственное спокойное состояние", () => {
    expect(healthTone(ИДЁТ)).toBe("calm");
    for (const s of ["остыл", "заперт", "встал", "мигает"]) {
      expect(healthTone({ ...ИДЁТ, состояние: s })).not.toBe("calm");
    }
  });

  it("незнакомое состояние от нового демона не роняет панель и красится по тревоге", () => {
    const тихое: CollectorHealth = { ...ИДЁТ, состояние: "дремлет", тревога: false };
    const злое: CollectorHealth = { ...ИДЁТ, состояние: "дремлет", тревога: true };
    expect(healthTone(тихое)).toBe("notice");
    expect(healthTone(злое)).toBe("alarm");
    // И называется своим именем, а не выдуманным «всё хорошо».
    expect(healthTitle(тихое)).toContain("дремлет");
  });
});

describe("слова — про цифры на экране, а не про сервис", () => {
  it("у каждого известного состояния свой заголовок и своё объяснение", () => {
    const states = ["идёт", "остыл", "заперт", "встал", "мигает"];
    const titles = states.map((s) => healthTitle({ ...ИДЁТ, состояние: s }));
    const means = states.map((s) => healthMeaning({ ...ИДЁТ, состояние: s }));
    expect(new Set(titles).size).toBe(states.length);
    expect(new Set(means).size).toBe(states.length);
    for (const m of means) expect(m.length).toBeGreaterThan(30);
  });

  it("«заперт» прямо говорит, что чинить нечего и обновление не поможет", () => {
    const m = healthMeaning({ ...ИДЁТ, состояние: "заперт" }).toLowerCase();
    expect(m).toMatch(/not broken on our side|refreshing does not help/);
  });

  it("«мигает» говорит про автоправила: они решают по этим же цифрам", () => {
    expect(healthMeaning({ ...ИДЁТ, состояние: "мигает" })).toMatch(/automation rules/i);
  });
});

describe("цифры показываем там, где они меняют смысл", () => {
  it("сорок семь подъёмов за полчаса — строкой с числом", () => {
    const h: CollectorHealth = { ...ИДЁТ, состояние: "мигает", тревога: true,
                                 подъёмов: 47, уронов: 47, окно_с: 1800 };
    expect(healthRestartLine(h)).toBe(
      "restarted 47 times in 30 min, 47 of them killed by the watchdog");
  });

  it("КТО КРУТИТ ЦИКЛ — сказано словами, а не вторым числом подряд", () => {
    /* Главный вопрос той аварии, и на него отвечает разница двух чисел: все
       подъёмы от сторожа — значит демон не отвечает на /health; ни одного —
       значит он падает сам. В ночь на 15.08 это выясняли руками, разбирая
       сотни одинаковых строк в логе.

       Словами, потому что «47 / 47» не читается и читается НЕВЕРНО — как доля
       или как диапазон. */
    const цикл = { ...ИДЁТ, состояние: "мигает", тревога: true, подъёмов: 47, окно_с: 1800 };
    expect(healthRestartLine({ ...цикл, уронов: 47 } as CollectorHealth))
      .toContain("47 of them killed by the watchdog");
    expect(healthRestartLine({ ...цикл, уронов: 12 } as CollectorHealth))
      .toContain("12 of them killed by the watchdog");
    expect(healthRestartLine({ ...цикл, уронов: 0 } as CollectorHealth))
      .toContain("none of them by the watchdog");
  });

  it("поля «уронов» нет вовсе — про сторожа молчим, а не оправдываем его", () => {
    /* `null` значит «демон старше контракта». Ноль значит «сторож ни при чём».
       Смешать их — объявить сторожа невиновным там, где мы про него не
       спрашивали; это тот же ноль-против-тишины, ради которого заведён #122. */
    const h: CollectorHealth = { ...ИДЁТ, состояние: "мигает", тревога: true,
                                 подъёмов: 47, уронов: null, окно_с: 1800 };
    expect(healthRestartLine(h)).toBe("restarted 47 times in 30 min");
    expect(healthRestartLine(h)).not.toContain("watchdog");
  });

  it("обычный старт строкой про перезапуски не хвастается", () => {
    expect(healthRestartLine(ИДЁТ)).toBeNull();
    expect(healthRestartLine({ ...ИДЁТ, состояние: "мигает", подъёмов: 0 })).toBeNull();
    expect(healthRestartLine({ ...ИДЁТ, состояние: "мигает", подъёмов: 5, окно_с: 0 })).toBeNull();
  });

  it("восемь подъёмов на «остыл» НЕ показываются: у выкатки их столько же", () => {
    /* Замерено в журнале деплоев ночи на 15.08: восемь подъёмов за пятнадцать
       минут — обычная работа. Число рядом с чужим диагнозом отправляет искать
       поломку там, где её нет; циклом это называет демон, а не панель. */
    const h: CollectorHealth = { ...ИДЁТ, состояние: "остыл", тревога: true, подъёмов: 8, окно_с: 900 };
    expect(healthRestartLine(h)).toBeNull();
  });

  it("возраст последней записи — только когда сбор НЕ идёт", () => {
    expect(healthWriteLine(ИДЁТ)).toBeNull();
    expect(healthWriteLine({ ...ИДЁТ, состояние: "остыл", последняя_запись_с: 2400 }))
      .toBe("last successful write 40 min ago");
  });

  it("«ни разу за подъём» — это не ноль минут назад", () => {
    const h: CollectorHealth = { ...ИДЁТ, состояние: "встал", последняя_запись_с: null };
    expect(healthWriteLine(h)).toMatch(/no successful write/i);
  });

  it("меньше минуты не превращается в «0 min ago» — это противоположный смысл", () => {
    expect(healthWriteLine({ ...ИДЁТ, состояние: "остыл", последняя_запись_с: 20 }))
      .toMatch(/less than a minute/);
  });

  it("часы читаются часами, а не сотнями минут", () => {
    expect(healthWriteLine({ ...ИДЁТ, состояние: "остыл", последняя_запись_с: 3 * 3600 + 300 }))
      .toBe("last successful write 3 h 5 min ago");
  });
});

describe("разбор ответа — отсутствие вердикта это не «здоров»", () => {
  it("старый демон без поля даёт null, а не бодрое зелёное", () => {
    expect(readHealth(undefined)).toBeNull();
    expect(readHealth(null)).toBeNull();
    expect(readHealth({})).toBeNull();
    expect(readHealth("идёт")).toBeNull();
  });

  it("половинчатый ответ тоже null: без «тревога» цвет выбирать нечем", () => {
    expect(readHealth({ состояние: "остыл" })).toBeNull();
    expect(readHealth({ тревога: true })).toBeNull();
  });

  it("полный ответ разбирается, числа приводятся, отсутствующая запись остаётся null", () => {
    const h = readHealth({
      состояние: "мигает",
      почему: "демон поднимался 47 раз за 30 мин",
      тревога: true,
      подъёмов: 47,
      уронов: 12,
      окно_с: 1800,
      последняя_запись_с: null,
    })!;
    expect(h.состояние).toBe("мигает");
    expect(h.тревога).toBe(true);
    expect(h.подъёмов).toBe(47);
    expect(h.уронов).toBe(12);
    expect(h.последняя_запись_с).toBeNull();
    expect(h.почему).toContain("47");
  });

  it("мусор в числах не превращается в NaN на экране", () => {
    const h = readHealth({
      состояние: "остыл", тревога: true,
      подъёмов: "много", окно_с: null, последняя_запись_с: "давно",
    })!;
    expect(h.подъёмов).toBe(0);
    expect(h.окно_с).toBe(0);
    expect(h.последняя_запись_с).toBeNull();
    /* А вот «уронов» в ноль НЕ схлопывается: ноль здесь — утверждение про
       сторожа, и мусор не имеет права им притвориться. */
    expect(h.уронов).toBeNull();
  });
});

/* --- Красная линия: порогов в панели нет --------------------------------- */

const src = readFileSync(join(process.cwd(), "lib", "collector-health.ts"), "utf-8");
const код = src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");

describe("панель не заводит своих порогов — их решает демон", () => {
  it("ни одно поле вердикта не сравнивается с числом", () => {
    /* Именно так дублируются пороги: `если последняя_запись_с > 1800 — красным`.
       Сравнение с числом здесь и есть вторая копия правила, которое живёт в
       `core/collector.здоровье`; расходиться им нельзя — по этим цифрам тушат
       кампании. Проверка допускает `подъёмов <= 1` (это не порог аварии, а
       «показывать ли строку про перезапуски вообще») — но её же и ловит на
       любом другом числе. */
    const поля = ["последняя_запись_с", "окно_с", "подъёмов"];
    for (const п of поля) {
      const сравнения = [...код.matchAll(new RegExp(`${п}\\s*(>=|<=|>|<|===|!==)\\s*(\\d+)`, "g"))];
      for (const m of сравнения) {
        expect(
          п === "подъёмов" && m[1] === "<=" && m[2] === "1",
          `${п} ${m[1]} ${m[2]} — это порог, а он живёт в core/collector.здоровье`,
        ).toBe(true);
      }
    }
  });

  it("в файле нет чисел, похожих на минуты и секунды порога", () => {
    // 1800, 30 * 60, 20 * 60 и прочее — признак переехавшего сюда порога.
    expect(код).not.toMatch(/\b\d+\s*\*\s*60\b/);
    expect(код).not.toMatch(/\b(?:1800|3600|900|1200)\b/);
  });
});
