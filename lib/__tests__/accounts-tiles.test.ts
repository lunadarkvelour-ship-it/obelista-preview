/* Шапка листа кабинетов: сумма частей обязана сходиться с целым (#166).
 *
 * Владелец на своём экране входа: «145 ad accounts · 40 active · 99 disabled» —
 * сорок плюс девяносто девять это 139, ШЕСТИ НЕТ, и узнать где негде. Шесть
 * нашлись в соседней плитке, но вопрос был задан правильный: набор плиток
 * обязан ПОКРЫВАТЬ целое, иначе человек ищет недостачу, которой нет, — или не
 * находит ту, которая есть.
 *
 * ГЛАВНОЕ ЗДЕСЬ — ПРОВЕРКА НЕ ПО СПИСКУ, А ПО ПОКРЫТИЮ. Список плиток,
 * написанный руками, не знает про корзину, которой сегодня пусто: `review` не
 * показывался нигде, и первый же кабинет на проверке Меты исчез бы с экрана
 * молча. Поэтому тест перебирает ВСЕ корзины из `StatusLabel` и требует, чтобы
 * сумма показанного равнялась сумме всего.
 */
import { describe, expect, it } from "vitest";
import type { StatusLabel } from "@/lib/account-status";
import { плиткиСостояний } from "@/lib/cloud-accounts";

const счёт = (p: Partial<Record<StatusLabel, number>> = {}): Record<StatusLabel, number> => ({
  active: 0, disabled: 0, billing: 0, review: 0, unknown: 0, ...p,
});

const сумма = (c: Record<StatusLabel, number>) =>
  Object.values(c).reduce((a, b) => a + b, 0);

const показано = (c: Record<StatusLabel, number>) =>
  плиткиСостояний(c).reduce((a, п) => a + п.value, 0);

describe("сумма частей сходится с целым", () => {
  it("на числах владельца с его экрана", () => {
    /* Ровно то, что он видел: 145 = 40 + 99 + 6 + 0. */
    const c = счёт({ active: 40, disabled: 99, billing: 6, unknown: 0 });
    expect(показано(c)).toBe(145);
    expect(показано(c)).toBe(сумма(c));
  });

  it("КАЖДАЯ корзина попадает на экран, если она непуста", () => {
    /* Перебор по одной: корзина, забытая в разметке, здесь становится
       расхождением числа, а не «мы её не заметили». */
    const корзины: StatusLabel[] = ["active", "disabled", "billing", "review", "unknown"];
    for (const k of корзины) {
      const c = счёт({ [k]: 7 } as Partial<Record<StatusLabel, number>>);
      expect(показано(c), `корзина ${k} не показана ни одной плиткой`).toBe(7);
    }
  });

  it("на смеси всех пяти корзин сразу", () => {
    const c = счёт({ active: 3, disabled: 11, billing: 2, review: 5, unknown: 9 });
    expect(показано(c)).toBe(сумма(c));
  });

  it("пустой парк — нули, а не пустая шапка", () => {
    /* «0 active» это ответ, а не отсутствие ответа: на свежей учётке он и есть
       вся правда, и молчание вместо него читается как поломка экрана. */
    expect(плиткиСостояний(счёт()).length).toBeGreaterThan(0);
    expect(показано(счёт())).toBe(0);
  });
});

describe("что именно показано", () => {
  it("состояние названо ОДНИМ словом — тем же, что в фильтрах", () => {
    /* В шапке было `disabled`, в фильтрах `banned`: одно число, два слова, и
       человек искал между ними разницу, которой нет. */
    const ключи = плиткиСостояний(счёт({ disabled: 99 })).map((п) => п.key);
    expect(ключи).toContain("banned");
    expect(ключи).not.toContain("disabled");
  });

  it("«under review» появляется, только когда есть кого показывать", () => {
    /* Отрицательный контроль к покрытию: лечение не должно разрастись в пятую
       плитку с нулём на каждом экране. Ноль в ней ничего не теряет — сумма
       остаётся равной целому. */
    expect(плиткиСостояний(счёт({ active: 5 })).map((п) => п.key))
      .not.toContain("under review");
    expect(плиткиСостояний(счёт({ active: 5, review: 1 })).map((п) => п.key))
      .toContain("under review");
  });

  it("нули остальных корзин остаются на экране", () => {
    /* «not collected 0» значит «состояние снято у всех» — это ответ. Спрятать
       его значит промолчать о том, что проверка была. */
    const ключи = плиткиСостояний(счёт({ active: 5 })).map((п) => п.key);
    expect(ключи).toEqual(["active", "banned", "billing", "not collected"]);
  });

  it("у каждой плитки есть объяснение, а не только цифра", () => {
    for (const п of плиткиСостояний(счёт({ active: 1, review: 1 }))) {
      expect(п.hint.length, `плитка ${п.key} без объяснения`).toBeGreaterThan(20);
    }
  });
});
