/* ИТОГ НАСЛЕДУЕТ НЕЗНАНИЕ СТРОК (#122, находка владельца 15.08).
 *
 * ЧТО ОН УВИДЕЛ. Восемь строк креативов честно показывали `n/c` в колонках
 * Subs, CPSub, Cont, CPCon, а строка Total под ними — «0» и прочерк. Человек
 * смотрит вниз, читает «0 подписок» и решает, что подписок нет. Их не ноль —
 * их НЕ ЗНАЕМ. Строки были починены, итог остался врать.
 *
 * ЧЕМ ЭТО ОПАСНЕЕ ОБЫЧНОЙ ОШИБКИ. Итог читают ПОСЛЕДНИМ и на нём
 * останавливаются: он выглядит выводом из всего, что выше. Ноль в выводе
 * отменяет всю честность строк над ним.
 *
 * СПИСОК МЕСТ С ИТОГАМИ ЗДЕСЬ НЕ РУКОПИСНЫЙ. Он выводится из кода: любое
 * сложение, которое гасит «не знаем» в ноль ещё до сложения, — это оно и есть,
 * и ищется оно по форме, а не по памяти автора.
 */
import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { totalsOf } from "@/lib/analytics-total";

const ROOT = path.resolve(__dirname, "..", "..");

const строка = (p: Record<string, unknown>) => ({
  spend: null, clicks: null, sub: null, contact: null, checkout: null,
  ftd: null, rd: null, ads: null, ads_with_ftd: null, geos: [], ...p,
}) as never;

describe("сумма, которой не из чего сложиться, — не ноль", () => {
  it("ни одна строка не дала числа — итога НЕТ", () => {
    const t = totalsOf([строка({}), строка({})]);
    expect(t.sub).toBeNull();
    expect(t.contact).toBeNull();
    /* И производные от него тоже: цена подписки из неизвестного числа
       подписок — не «бесплатно», а «не знаем». */
    expect(t.cpsub).toBeNull();
  });

  it("хоть одна дала — это число, а не «не знаем»", () => {
    /* Обратная ошибка так же дорога: спрятать посчитанное из осторожности
       значит сделать лист бесполезным там, где данные есть. */
    const t = totalsOf([строка({ sub: 4 }), строка({})]);
    expect(t.sub).toBe(4);
  });

  it("настоящий ноль остаётся нулём", () => {
    /* «Подписок не было» — факт, и его нельзя превращать в «не знаем»: это та
       же подмена, только в другую сторону. */
    expect(totalsOf([строка({ sub: 0 })]).sub).toBe(0);
  });

  it("пустая таблица не выдумывает ноль", () => {
    expect(totalsOf([]).spend).toBeNull();
  });
});

describe("места, где складывают, не гасят «не знаем» в ноль", () => {
  /* Оговорки — с причиной у каждой, и обе проверяются на существование ниже:
     список, переживший свой предмет, молча прощает то, чего уже нет. */
  const ОГОВОРКИ: Array<{ файл: string; почему: string }> = [
    {
      файл: "lib/analytics-tree.ts",
      почему: "node.ads — счётчик объявлений: у каждого узла он равен единице по "
        + "построению, и «не знаем» там не бывает вовсе",
    },
    {
      файл: "components/analytics/DataState.tsx",
      почему: "сумма протухшего спенда: строка рядом с ней и так говорит «настоящая "
        + "цифра выше», то есть неполнота названа словами, а не потеряна",
    },
    {
      файл: "lib/analytics-export.ts",
      почему: "сумма для payload `manage`: она про то, что мы ОТПРАВЛЯЕМ в Мету, "
        + "а не про то, что знаем — там ноль и есть ноль объектов",
    },
  ];

  function* исходники(dir: string): Generator<string> {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.isSymbolicLink()) continue;
      const p = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (!["node_modules", "__tests__", ".next"].includes(e.name)) yield* исходники(p);
      } else if (/\.tsx?$/.test(e.name)) yield p;
    }
  }

  it("ни одного сложения через `?? 0` вне объяснённых мест", () => {
    const найдено: string[] = [];
    let файлов = 0;
    for (const f of исходники(ROOT)) {
      файлов += 1;
      const где = path.relative(ROOT, f);
      if (ОГОВОРКИ.some((о) => о.файл === где)) continue;
      readFileSync(f, "utf8").split("\n").forEach((строка, i) => {
        /* Ищем форму, а не имя: сложение, в котором отсутствие подменяется
           нулём прямо на входе. Именно так итог и терял незнание строк. */
        if (/\+=?\s*\(?[^;]*\?\?\s*0\)?/.test(строка) && /reduce|\+=/.test(строка)) {
          найдено.push(`${где}:${i + 1}: ${строка.trim().slice(0, 100)}`);
        }
      });
    }
    /* Обход, который ничего не нашёл, зелёный ровно так же, как обход, которому
       нечего было находить. */
    expect(файлов).toBeGreaterThan(50);
    expect(найдено, `здесь «не знаем» становится нулём: ${найдено.join(" | ")}`).toEqual([]);
  });

  it("оговорка не переживает файл, к которому относится", () => {
    for (const о of ОГОВОРКИ) {
      expect(() => readFileSync(path.join(ROOT, о.файл), "utf8")).not.toThrow();
    }
  });
});
