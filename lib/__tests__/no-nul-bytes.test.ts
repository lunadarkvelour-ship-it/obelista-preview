import { describe, expect, it } from "vitest";
import { execFileSync } from "node:child_process";
import { readFileSync, statSync } from "node:fs";
import path from "node:path";

/** Корень репозитория: `panel/lib/__tests__` → вверх на три. */
const КОРЕНЬ = path.resolve(__dirname, "..", "..", "..");

/** Двоичные форматы, у которых нулевой байт — норма, а не порча. Каждое
 *  расширение здесь названо потому, что файл такого типа В РЕПОЗИТОРИИ ЕСТЬ. */
const ДВОИЧНЫЕ = new Set([
  ".png", ".jpg", ".jpeg", ".gif", ".webp", ".avif", ".ico",
  ".woff", ".woff2", ".ttf", ".otf", ".eot",
  ".zip", ".gz", ".tgz", ".pdf", ".db", ".sqlite", ".pyc", ".mp4", ".mov",
]);

function файлыДерева(): string[] {
  /* `-c` отслеживаемые, `-o` новые, `--exclude-standard` — без игнорируемых.
     Именно этот набор может уехать в коммит, а значит именно он и стережётся. */
  const вывод = execFileSync(
    "git", ["-C", КОРЕНЬ, "ls-files", "-co", "--exclude-standard", "-z"],
    { encoding: "buffer", maxBuffer: 64 * 1024 * 1024 },
  );
  return вывод.toString("utf8").split("\0").filter(Boolean);
}

describe("нулевых байтов в исходниках нет", () => {
  const файлы = файлыДерева().filter((f) => !ДВОИЧНЫЕ.has(path.extname(f).toLowerCase()));

  it("дерево вообще прочиталось — иначе сторож стерёг бы пустоту", () => {
    /* Положительный контроль на сам сторож: `git ls-files`, отдавший пустоту
       (не тот каталог, нет гита, сменился флаг), сделал бы проверку ниже
       вечнозелёной, ничего при этом не проверяя. */
    expect(файлы.length).toBeGreaterThan(100);
    expect(файлы).toContain("panel/lib/campaigns-funnel.ts");
    expect(файлы.some((f) => f.endsWith(".py"))).toBe(true);
  });

  it("ни в одном файле нет нулевого байта", () => {
    const порченые: string[] = [];
    for (const rel of файлы) {
      const полный = path.join(КОРЕНЬ, rel);
      let буфер: Buffer;
      try {
        if (!statSync(полный).isFile()) continue;
        буфер = readFileSync(полный);
      } catch {
        continue;                                  // файл исчез между листингом и чтением
      }
      const at = буфер.indexOf(0);
      if (at >= 0) {
        /* Место называем сразу: искать нулевой байт глазами нечем — редактор
           его не показывает, а grep по такому файлу молчит. */
        const строка = буфер.subarray(0, at).toString("utf8").split("\n").length;
        порченые.push(`${rel}:${строка}`);
      }
    }
    expect(порченые, "нулевой байт в исходнике — лечится escape-последовательностью \\u0000")
      .toEqual([]);
  });
});
