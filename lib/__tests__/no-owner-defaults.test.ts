/* В панели нет путей «только под владельца».
 *
 *  Правило владельца 14.08.2026, дословно: делать так, чтобы он пользовался
 *  системой «равноправно с остальными юзерами», и «не делать костыли, которые
 *  типо только под меня».
 *
 *  Это не стиль, а устройство. Захардкоженный id профиля в дефолте — путь,
 *  которого у второго человека нет и быть не может; у него панель просто
 *  начнёт с чужого несуществующего значения.
 *
 *  Плюс такой дефолт протухает молча. `k1epd0wv` стоял в `specToState` и выбыл
 *  из антидетекта 05.08: в снапшоте его нет, а `validate` ищет кабы в
 *  `snapshot.profiles[profile]` — для неизвестного профиля получает undefined и
 *  ПРОПУСКАЕТ все снапшотные проверки разом. Пустой список предупреждений
 *  человек читает как «залив чистый», хотя он значит «проверить было нечем».
 *
 *  Тесты ниже — ловушка на будущее: они падают, если конкретный id вернут.
 */
import { describe, expect, it } from "vitest";
import { specToState } from "@/lib/spec-to-state";
import { DEFAULT_FORM, DEF_BIND, DEF_TAGS, DEF_CATALOG, LICHKA, START_FORM } from "@/lib/seed";
import type { Spec } from "@/lib/types";

describe("дефолты панели ничьи", () => {
  it("профиль в стартовой форме пуст", () => {
    expect(DEFAULT_FORM.profile).toBe("");
  });

  it("теги, привязки, каталог и лички пусты — их заводит пользователь", () => {
    // Если сюда однажды впишут «hiu»/«spx» или чей-то кабинет, второй человек
    // получит чужие настройки на первом же открытии панели.
    expect(DEF_TAGS).toEqual({});
    expect(DEF_BIND).toEqual({});
    expect(DEF_CATALOG).toEqual({});
    expect(LICHKA).toEqual({});
  });

  it("состояние чистого открытия панели пусто — там же однажды жил личный пресет", () => {
    // START_FORM уже пуст сегодня (комментарий рядом с ним объясняет, что
    // раньше там лежали чужие гео, ссылка, спец-категория и выбывший профиль)
    // — но ничто не проверяло, что он останется пустым. Ровно это место уже
    // было инцидентом один раз: тест без ловушки на возврат не тест.
    expect(START_FORM).toEqual({});
  });
});

describe("импорт спеки не подставляет чужой профиль", () => {
  it("профиль из спеки берётся как есть", () => {
    expect(specToState({ profiles: ["любой-профиль"] } as Spec, {}).form.profile)
      .toBe("любой-профиль");
  });

  it("нет профиля в спеке — ПУСТО, а не подставленный id", () => {
    expect(specToState({} as Spec, {}).form.profile).toBe("");
    expect(specToState({ profiles: [] } as unknown as Spec, {}).form.profile).toBe("");
  });

  it("в дефолт не зашит идентификатор ни одного антидетекта", () => {
    // Ловушка на возврат. `k1xxxxxx` — формат прежнего антидетекта, UUID — ShardX.
    // Оба протухают молча: id профиля не переживает переезд между вендорами.
    const p = specToState({} as Spec, {}).form.profile;
    expect(p).not.toMatch(/^k1[a-z0-9]{6}$/);
    expect(p).not.toMatch(/^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i);
    expect(p).not.toMatch(/^[0-9a-f]{8}$/i);
  });
});
