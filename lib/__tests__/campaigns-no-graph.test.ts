/* Сторож главного условия #125: лист кампаний НЕ ХОДИТ В GRAPH.
 *
 * ПОЧЕМУ ЭТО СТОРОЖ, А НЕ СТРОЧКА В ДОКЕ. Устройство листа задано владельцем и
 * оно про бюджет вызовов: лимит Меты считается на ПРИЛОЖЕНИЕ, ~60 вызовов на
 * пятиминутку на всё сразу. Лист, который спрашивает Graph при открытии, ест
 * тот же бюджет, что фоновый сбор спенда, и душит его — а заметно это будет не
 * на панели, а через час, по недосчитанному спенду. Правило «читаем из своей
 * базы» без места исполнения живёт только в голове автора: следующая правка
 * делается копипастой соседнего листа, а в соседнем (`/accounts` в аналитике,
 * `/tree`) хождение в Graph — норма.
 *
 * Критерий иссуса звучит «фоновый сбор не проседает от открытого листа —
 * ПРОВЕРЕНО, а не предположено». Автоматически проверить можно ровно эту
 * половину: что панель физически не зовёт ручку, которая ходит в Мету. Вторая
 * половина — замер сбора при открытом листе на живой машине — на панели
 * непроверяема, и она честно вынесена в «что осталось непроверенным».
 */
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(__dirname, "..", "..");

/** Файлы листа. Списком, а не обходом каталога: сторож обязан падать, когда
 *  лист расползётся по новым файлам, — тогда автор придёт сюда и решит осознанно,
 *  а не унесёт хождение в Graph в файл, о котором сторож не знает. */
const ФАЙЛЫ = [
  "lib/campaigns.ts",
  "lib/campaigns-tree.ts",
  /* Навигация по пяти уровням (#125): она решает, ЧТО спрашивать, и потому
     первая, куда захочется дописать «а тут заодно спросим Мету напрямую». */
  "lib/campaigns-nav.ts",
  "components/views/CampaignsView.tsx",
  /* Период (#154). Именно сюда захочется дописать «за произвольную дату
     спросим Мету напрямую, у нас же всё равно нет этих дней в базе» — и это
     будет вызов в Graph на каждое нажатие кнопки, на каждый открытый кабинет
     сразу. Данные за период у нас есть: `spend_daily` пишется с
     `time_increment=1`, то есть по дням, и сумма по окну — те же самые цифры
     Меты, а не оценка. */
  "lib/period.ts",
  "components/views/PeriodPicker.tsx",
  /* КАТАЛОГ МЕТРИК И ВОРОНКА — лист расползся по ним (#159, #161), и сторож,
     не знающий про новые файлы, охраняет вчерашний лист. Соблазн здесь тот же
     и даже сильнее: в клетке видно, что цифры нет, и «доспросим у Меты ровно
     эту метрику» выглядит точечным — а на дереве это вызов на КАЖДУЮ клетку
     каждой строки, то есть бюджет приложения на одном открытии листа. */
  "lib/campaigns-columns.ts",
  "lib/campaigns-funnel.ts",
  "components/campaigns/CampaignColumns.tsx",
  "components/sections/campaigns/FunnelCells.tsx",
];

/** Ручки и адреса, которые означают поход в Мету.
 *
 *  `/tree` — существующая ручка демона: она делает `api.call(act, {fields:
 *  campaigns…})` на КАЖДЫЙ вызов (`scripts/analytics_daemon.py:1194`). Именно
 *  ею соблазнительно накормить этот лист: она уже есть и отдаёт ровно то дерево,
 *  которое нужно. Это и есть ошибка, ради которой сторож написан. */
const ЗАПРЕЩЕНО = [
  "graph.facebook.com",
  '"/tree"',
  "'/tree'",
  "/tree?",
];

describe("лист кампаний не ходит в Graph", () => {
  for (const f of ФАЙЛЫ) {
    it(`${f} читает только наши ручки`, () => {
      const текст = readFileSync(path.join(ROOT, f), "utf8");
      for (const запрет of ЗАПРЕЩЕНО) {
        /* Комментарии не в счёт: и в коде, и здесь про `/tree` написано
           словами — объяснение, почему ею НЕЛЬЗЯ пользоваться, само её
           называет. Сторож, запрещающий упоминание, запретил бы объяснение. */
        const код = текст
          .split("\n")
          .filter((s) => !/^\s*(\*|\/\/|\/\*)/.test(s))
          .join("\n");
        expect(код.includes(запрет), `${f}: ${запрет}`).toBe(false);
      }
    });
  }

  it("список файлов листа не устарел", () => {
    // Пустой или разъехавшийся список — сторож, который ничего не сторожит.
    for (const f of ФАЙЛЫ) {
      expect(readFileSync(path.join(ROOT, f), "utf8").length).toBeGreaterThan(100);
    }
  });
});

/* ── ВТОРОЙ СПОСОБ СЖЕЧЬ ТОТ ЖЕ БЮДЖЕТ: ПЕРЕЗАПРОС НА КАЖДЫЙ РЕНДЕР ──────────
 *
 * Сторож выше запрещает ходить в Graph. Но бюджет вызовов Меты общий на
 * ПРИЛОЖЕНИЕ, и лист умеет съесть его и через нашу ручку: период — объект, в
 * React он новый на каждый рендер, и положенный в зависимости эффекта как есть
 * он даёт бесконечный перезапрос всех открытых кабинетов. На экране это не
 * видно ВООБЩЕ: цифры те же, спиннер мигает, а фоновый сбор спенда задыхается
 * через час и в другом месте.
 *
 * Правило «сравнивать период общей функцией `тотЖе`» без места исполнения живёт
 * только в голове автора, а следующая правка делается копипастой соседнего
 * листа. Поэтому оно проверяется.
 *
 * ЧТО ИМЕННО ЛОВИТ ЭТОТ СТОРОЖ, А ЧТО НЕТ — сказано по факту, а не обещанием.
 * Ловит ИСЧЕЗНОВЕНИЕ двух вещей из вьюхи: общей функции сравнения и периода в
 * запросе. НЕ ловит неверный СПИСОК ЗАВИСИМОСТЕЙ эффекта: чтобы увидеть петлю
 * запросов, надо запустить React с эффектами, а тестовый рендер их не
 * выполняет. Написать здесь «петля не пройдёт» было бы обещанием механизма,
 * которого нет, — а это ровно тот класс лжи, когда сама проверка честная.
 */
describe("период не устраивает петлю запросов", () => {
  const вью = () => readFileSync(path.join(ROOT, "components/views/CampaignsView.tsx"), "utf8");

  it("сравнение периодов идёт общей функцией, а не своим правилом рядом", () => {
    /* Второе правило «что такое тот же период» разъедется с первым молча:
       `периодВЗапрос` меняется, а копия сравнения остаётся прежней. */
    expect(вью()).toMatch(/тотЖе\(/);
  });

  it("период уходит В ЗАПРОС, а не фильтрует ответ на клиенте", () => {
    /* Фильтрация по месту показывала бы сумму, которую никто не считал за это
       окно, — и выглядела бы точной цифрой. */
    expect(вью()).toMatch(/campaignsApi\.list\(\s*[^)]+,\s*[^)]+\)/);
  });

  it("сама проверка умеет краснеть", () => {
    /* Отрицательный контроль: на тексте без вызова с периодом обе проверки
       обязаны не совпасть. Иначе зелёные строки выше не значат ничего. */
    const плохой = "campaignsApi.list(id)";
    expect(плохой).not.toMatch(/campaignsApi\.list\(\s*[^)]+,\s*[^)]+\)/);
    expect(плохой).not.toMatch(/тотЖе\(/);
  });
});
