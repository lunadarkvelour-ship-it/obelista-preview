import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/* Токены темы — это код, который никто не типизирует и никто не вызывает.
 *
 * Дважды за один вечер правка комментария в `globals.css` съедала объявления
 * ниже: текст вставлялся ПОСЛЕ закрывающего `*​/`, парсер молча проглатывал
 * следующее правило, сборка при этом проходила зелёной, а на экране просто
 * пропадала тепловая подложка со всей таблицы. Ни tsc, ни vitest, ни `next
 * build` такого не видят — это валидный CSS, просто не тот.
 *
 * Здесь два дешёвых стража: комментарии сбалансированы, и токены, на которые
 * ссылается код, действительно объявлены. Второе важнее первого: `heat.ts`
 * подставляет имена переменных строками, и опечатка в имени даёт ровно то же
 * молчаливое исчезновение цвета.
 */

const CSS = readFileSync(join(process.cwd(), "app", "globals.css"), "utf-8");

/** Токены, без которых экран визуально ломается, а тесты остаются зелёными. */
const ОБЯЗАТЕЛЬНЫЕ = [
  // тепловая шкала — их подставляет lib/heat.ts
  "--heat-cold", "--heat-mid", "--heat-hot", "--heat-max", "--heat-floor",
  // спарклайн — их подставляет CreativeTable по шаблону `--spark-${trend}`
  "--spark-up", "--spark-down", "--spark-flat",
  "--spark-fill-up", "--spark-fill-down", "--spark-fill-flat", "--spark-base",
  // ступени контраста
  "--faint", "--ghost",
  // кружки состояния кабинета
  "--dot-live", "--dot-warn", "--dot-dead", "--dot-unknown",
  // выделение строки
  "--row-selected", "--row-selected-hover", "--row-selected-bar",
];

describe("globals.css — токены на месте", () => {
  it.each(ОБЯЗАТЕЛЬНЫЕ)("%s объявлен", (имя) => {
    // Не привязываемся к началу строки: часть токенов объявлена в одну строку
    // с селектором (`:root { --heat-max: 32%; }`), и это нормально.
    expect(CSS).toMatch(new RegExp(имя.replace(/-/g, "\\-") + "\\s*:"));
  });

  it("тепло объявлено для обеих тем, а не только для светлой", () => {
    /* Потолок обязан различаться: одна и та же доля над белым и над #171719
       даёт то пастель, то блок, перебивающий число. Пропустить тёмную ветку —
       это не «немного не так», это нечитаемая таблица у половины сессий. */
    expect(CSS).toMatch(/:root\[data-theme="dark"\][^}]*--heat-max/);
    expect(CSS).toMatch(/:root\[data-theme="dark"\][^}]*--heat-floor/);
  });

  it("каждый комментарий закрыт — иначе следующее правило будет съедено", () => {
    /* Считать вхождения нельзя: `/*` встречается и внутри текста комментариев,
       и счётчики честно расходятся там, где всё в порядке. Идём подряд от
       открытия к ближайшему закрытию — так же, как это делает парсер. */
    let i = 0;
    let оборванный = -1;
    while (i < CSS.length - 1) {
      if (CSS.slice(i, i + 2) === "/*") {
        const j = CSS.indexOf("*/", i + 2);
        if (j === -1) {
          оборванный = CSS.slice(0, i).split("\n").length;
          break;
        }
        i = j + 2;
      } else i++;
    }
    expect(оборванный).toBe(-1);
  });

  it("нет прозы, оставшейся снаружи комментария", () => {
    /* Ровно тот случай: после закрытия комментария дописан абзац, который
       заканчивается вторым закрытием. Скобки при этом сходятся, а правило под
       ними умирает. Ищем не «непохожее на CSS» — многострочные значения и
       списки селекторов тоже непохожи, — а именно русский текст вне
       комментария: в объявлениях его не бывает. */
    const строки = CSS.split("\n");
    let вКомментарии = false;
    const проза: string[] = [];
    for (const raw of строки) {
      const l = raw.trim();
      if (!вКомментарии && l.startsWith("/*")) {
        вКомментарии = !l.includes("*/");
        continue;
      }
      if (вКомментарии) {
        if (l.includes("*/")) вКомментарии = false;
        continue;
      }
      // Хвостовой комментарий на строке объявления — нормально, вырезаем его.
      const без = l.replace(/\/\*[^]*?\*\//g, "");
      const кириллица = (без.match(/[а-яё]/gi) || []).length;
      if (кириллица > 3) проза.push(l.slice(0, 70));
    }
    expect(проза).toEqual([]);
  });
});
