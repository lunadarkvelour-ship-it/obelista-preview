/* Ловушка на возврат мёртвого вендора и наших внутренних слов на экран.
 *
 *  ПОЧЕМУ такой тест вообще есть. Правило «в панели нет AdsPower» само по себе
 *  живёт только в голове того, кто его придумал. Панель фронтовую правят
 *  копипастой соседнего блока чаще, чем пишут с нуля, а копируется вместе с
 *  разметкой и текст. Правило без места исполнения — не правило: одного
 *  «Connect AdsPower», вернувшегося в форму, хватит, чтобы у арендатора на
 *  первом экране появилось поле ввода ключа, которого не существует.
 *
 *  ПОЧЕМУ именно этот вендор. Парк переехал на ShardX, адспауэровские id
 *  мертвы, а поля ввода ключа у ShardX нет и не будет: адрес и токен лаунчер
 *  пишет себе на диск сам (`core/shardx.py`), и спрашивать их у человека
 *  второй раз — тот самый ручной ввод, от которого код специально уходил.
 *  Порт 50325 — тот же факт с другой стороны: локальный API прежнего вендора.
 *
 *  ПОЧЕМУ не только вендор, но и «snapshot»/«daemon» в пустом состоянии
 *  кабинетов. Это НАШИ слова, а не слова человека, и на сервере они вдобавок
 *  зовут чинить то, чего у арендатора нет вовсе: данные с машины оператора
 *  туда не уезжают, локального сбора там не бывает. Ошибка такого текста не
 *  видна ни компилятору, ни глазами при беглом чтении диффа — видна только
 *  тому, кто открыл пустую панель первый раз.
 */
import { describe, expect, it } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

/** Корень панели: `panel/lib/__tests__` → `panel`. */
const ROOT = path.resolve(__dirname, "..", "..");

/** Чужое и сгенерированное: зависимости и сборка.
 *
 *  `__tests__` в этом списке — исправление, оплаченное простоем всей доставки.
 *
 *  Прежде исключением был ОДИН файл, этот самый: сторож не может искать слово,
 *  не написав его. Но это свойство не его личное, а любого сторожа: тест,
 *  запрещающий строку, обязан её назвать — иначе ему нечего запрещать. Через
 *  несколько часов в панель въехал второй такой тест, назвал вендора в своём
 *  списке запрещённого, и `main` покраснел. По отдельности оба PR были
 *  зелёными: первый не знал про файл, которого ещё не было, второй гонялся до
 *  того, как сторож попал в main. Гит конфликта не показывает — файлы разные.
 *  Цена: деплой ждёт зелёного CI, три прогона подряд `skipped`, и двенадцать
 *  влитых за день PR не доехали до машины ни байтом.
 *
 *  Правильная граница проходит не по имени файла, а по смыслу: **тест не
 *  является поверхностью продукта.** Человек его не открывает, в сборку он не
 *  попадает, и слово в нём никого ни к чему не приглашает. Продуктовый код при
 *  этом сканируется как сканировался — а именно он и был предметом правила. */
const МИМО_ПАПКИ = new Set([
  ".git", ".next", ".vercel", "node_modules", "out", "build", "coverage", "__tests__",
]);

/** Двоичное читать как текст бессмысленно — шрифты и картинки. */
const ДВОИЧНОЕ = /\.(png|jpe?g|gif|webp|avif|ico|woff2?|ttf|otf|eot|mp4|mov|pdf|zip)$/i;

/* Сгенерированное — не исходники, и слова в нём не наши.
 *
 * `tsconfig.tsbuildinfo` ронял этот тест ИМЕНЕМ ЭТОГО ЖЕ ФАЙЛА: кэш
 * компилятора хранит список путей, и `no-adspower.test.ts` в нём лежит
 * строкой. `package-lock.json` опасен иначе — хэши в нём случайны, и однажды
 * в каком-нибудь integrity встретится подстрока порта. Обе поломки были бы
 * ложной тревогой, а ложная тревога учит выключать сторожа. */
const СГЕНЕРИРОВАННОЕ = /(\.tsbuildinfo|package-lock\.json)$/;

function* исходники(dir: string): Generator<string> {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    /* Симлинки не обходим. В репозитории их нет ни одного, а в воркtree агента
       ими подсовывают `node_modules` с основного чекаута — по симлинку туда
       обход уходил бы в чужие зависимости и падал на первой же папке. */
    if (e.isSymbolicLink()) continue;
    if (e.isDirectory()) {
      if (!МИМО_ПАПКИ.has(e.name)) yield* исходники(p);
      continue;
    }
    if (!e.isFile() || ДВОИЧНОЕ.test(e.name) || СГЕНЕРИРОВАННОЕ.test(e.name)) continue;
    yield p;
  }
}

/* Единственное исключение, и оно не про экран.
 *
 * В ответе демона у связки «соц ↔ профиль» есть поле `antidetect`, и вендор
 * лежит там ЗНАЧЕНИЕМ: у старых связок в базе так и записано. Описание чужих
 * данных — не то же самое, что наш интерфейс: переписать эту строку значило бы
 * соврать про то, что реально приезжает с сервера. Исключение точечное: любая
 * другая строка в том же файле тест всё так же уронит. */
const РАЗРЕШЕНО: Array<{ файл: string; строка: RegExp }> = [
  { файл: "lib/analytics.ts", строка: /Каким вендором заведён/ },
];

/* ЗАПРЕТ НА ИМЯ ВЕНДОРА СНЯТ — И ЭТО НЕ ПОСЛАБЛЕНИЕ, А СМЕНА ФАКТА.
 *
 * Сторож писался, когда парк переехал на ShardX, адспауэровские id умерли, а
 * поля ввода ключа у нового вендора нет и не будет. Тогда «в панели нет
 * AdsPower» было правдой, и правило защищало от копипасты мёртвого блока.
 *
 * С XR-44 вендора ДВА и они равноправны: парк байера может лежать в любом, и
 * `/link_code` требует явного `?provider=shardx|adspower` без умолчания.
 * Оставить запрет — значит запретить продукту называть половину того, с чем он
 * работает, и следующий воркер снимал бы сторож молча, чтобы собрать сборку.
 *
 * ПОЭТОМУ ЗАПРЕТ ЗАМЕНЁН, А НЕ УДАЛЁН. Ниже — положительная гарантия: оба
 * вендора названы, названы РАВНО, и ни один не помечен «скоро». Пустой файл на
 * этом месте не заметил бы возвращения «AdsPower coming soon».
 *
 * `50325` под запретом ОСТАЛСЯ. Это локальный порт антидетекта, и ходит в него
 * скилл на машине байера, а не панель: адрес в облачном коде означал бы, что
 * кто-то снова попробовал дотянуться с сервера до `127.0.0.1` арендатора.
 */
describe("локальный порт антидетекта в панели не упоминается", () => {
  it("ни одного упоминания локального порта вендора", () => {
    const найдено: string[] = [];
    let файлов = 0;
    for (const f of исходники(ROOT)) {
      файлов += 1;
      const где = path.relative(ROOT, f);
      readFileSync(f, "utf8").split("\n").forEach((строка, i) => {
        if (!/50325/.test(строка)) return;
        if (РАЗРЕШЕНО.some((и) => и.файл === где && и.строка.test(строка))) return;
        найдено.push(`${где}:${i + 1}: ${строка.trim().slice(0, 120)}`);
      });
    }
    // Обход, который ничего не нашёл, зелёный ровно так же, как обход, которому
    // нечего было находить. Разделяем эти два случая явно.
    expect(файлов).toBeGreaterThan(100);
    expect(найдено).toEqual([]);
  });
});

describe("оба вендора антидетекта равноправны на «Профилях»", () => {
  const скан = readFileSync(
    path.join(ROOT, "components", "sections", "profiles", "ScanProfiles.tsx"), "utf8");

  it("обе кнопки названы точными подписями", () => {
    /* Подписи владельца, и их две. Одна кнопка на листе означала бы, что парк
       второго вендора внести в Обелисту нечем. */
    expect(скан).toContain("shardx: \"ShardX\"");
    expect(скан).toContain("adspower: \"AdsPower\"");
    expect(скан).toMatch(/Scan \{ВЕНДОР\[p\]\} Profiles/);
  });

  it("ни один вендор не помечен «скоро» и не выключен", () => {
    /* Прямые слова владельца: «no disabled/coming-soon AdsPower state». */
    expect(скан).not.toMatch(/coming soon/i);
    expect(скан).not.toMatch(/isDisabled=\{true\}/);
    expect(скан).not.toMatch(/adspower[^\n]*disabled/i);
  });

  it("вендор едет ЯВНО и в запрос, и в инструкцию скилла", () => {
    /* Символы ключа вендора не кодируют — у обоих он одинаков. Потеря
       контекста здесь означает сбор парка не из того приложения. */
    expect(readFileSync(path.join(ROOT, "lib", "analytics.ts"), "utf8"))
      .toContain('searchParams.set("provider", provider)');
    expect(скан).toContain("provider=${сост.вендор}");
  });

  it("после выдачи вендор не переключается", () => {
    /* Второго выбора внутри модалки нет: ключ уже выписан под одного, и
       переключатель рядом рассинхронизировал бы надпись с ключом. */
    const модалка = скан.slice(скан.indexOf("function КлючВендора"));
    expect(модалка).not.toMatch(/ПОРЯДОК\.map/);
    expect(модалка).not.toMatch(/setОткрыт/);
  });

  it("ключ читается ТОЛЬКО из успешного ответа", () => {
    /* При конфликте сервер кладёт в поле `code` строку `provider_conflict` —
       то же имя, что несёт ключ при успехе. Чтение без проверки `ok` показало
       бы человеку слово `provider_conflict` как его ключ. */
    const api = readFileSync(path.join(ROOT, "lib", "analytics.ts"), "utf8");
    expect(api).toContain("if (data?.ok === true) return data as LinkCode;");
    expect(api).toContain('if (data?.error === "provider_conflict")');
  });
});

describe("пустой лист кабинетов не зовёт чинить то, чего у человека нет", () => {
  const пустой = path.join(ROOT, "components", "views", "NoAccounts.tsx");

  it("в нём нет наших внутренних слов и локальных адресов", () => {
    const текст = readFileSync(пустой, "utf8");
    expect(текст).not.toMatch(/snapshot/i);
    expect(текст).not.toMatch(/daemon/i);
    expect(текст).not.toMatch(/127\.0\.0\.1/);
  });

  /* Листов кабинетов было два, и второй («Agencies») снесён 14.08.2026 по
     прямому требованию владельца — крутить цикл по паре здесь больше не по
     чему. Сам сторож не про количество листов, а про то, что лист берёт
     ОБЩЕЕ пустое состояние вместо своего близнеца с нашими словами: как раз
     близнец и был бы тем местом, куда «snapshot» и «daemon» вернулись бы мимо
     проверки выше. */
  it("лист кабинетов берёт общее пустое состояние, а не свой близнец", () => {
    const текст = readFileSync(path.join(ROOT, "components", "views", "AccountsView.tsx"), "utf8");
    expect(текст).toMatch(/<NoAccounts\s*\/>/);
    expect(текст).not.toMatch(/function NoSnapshot/);
  });
});
