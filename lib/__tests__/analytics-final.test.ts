/* Крупное число за незакрытый день не выдаёт себя за итог (#149).
 *
 * ЧТО ПРОВЕРЯЕМ, а что нет. Не «правильно ли посчитан спенд» — его считает
 * движок, и он же чинит занижение. Здесь проверяется ровно одно: понимает ли
 * человек, глядя на крупное число, окончательное оно или ещё набегает. До этой
 * правки лист честно писал в поповере «настоящая цифра выше» и крупно показывал
 * неверную — то есть признался и всё равно соврал.
 *
 * Способы соврать заново, каждый из которых тише самого дефекта:
 *  1. Промолчать про сегодня. Сегодняшний день не закрыт ПО ОПРЕДЕЛЕНИЮ, и
 *     число за него — «столько уже», а не «столько всего».
 *  2. Пометить верное число. Прошлый закрытый день занижен не бывает, и метка
 *     на нём отменяет доверие ко всем остальным меткам.
 *  3. Сравнить даты не в том часовом поясе. `toISOString` восточнее Гринвича
 *     превращает «сегодня» во «вчера», и метка пропала бы ровно там, где день
 *     и правда идёт.
 */
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";
import { неИтог, нижняяГраница, readOpenDays } from "@/lib/analytics-final";

const СЕГОДНЯ = "2026-08-15";

describe("окно, включающее сегодня, итогом не является", () => {
  it("окно кончается сегодня — число ещё набегает", () => {
    const n = неИтог({ until: СЕГОДНЯ, today: СЕГОДНЯ })!;
    expect(n.почему).toBe("today");
    expect(n.label).toBe("spend so far");
    expect(n.hint).toContain("not the day's total");
  });

  it("окно уходит в будущее — то же самое, а не «нет данных»", () => {
    /* Так бывает от пресета «7 days» на границе суток и от чужой таймзоны в
       поле ввода. Молчать здесь значило бы объявить итогом окно, которое ещё
       даже не наступило. */
    expect(неИтог({ until: "2026-08-20", today: СЕГОДНЯ })?.почему).toBe("today");
  });

  it("вчерашнее окно — ИТОГ, и метки на нём нет", () => {
    /* Отрицательный контроль, и он здесь главный. Метка на верном числе дороже
       пропуска: увидев её на закрытом дне дважды, человек перестанет читать её
       и там, где она про дело. */
    expect(неИтог({ until: "2026-08-14", today: СЕГОДНЯ })).toBeNull();
  });

  it("ответа ещё нет — молчим, а не помечаем пустой экран", () => {
    expect(неИтог({ until: "", today: СЕГОДНЯ })).toBeNull();
    expect(неИтог({ until: СЕГОДНЯ, today: "" })).toBeNull();
  });
});

describe("незакрытый ПРОШЛЫЙ день (#149, closed_at)", () => {
  /* Проверка владельца после выката звучит ровно так: «≥» на сегодня есть, на
     вчера — нет, если вчера закрыт. Обе половины ниже. */

  it("вчера ЗАКРЫТ — метки нет, это итог", () => {
    /* Главный отрицательный контроль всего файла. Движок теперь ставит
       `closed_at` только по чтению ПОСЛЕ конца суток кабинета, то есть отметка
       значит «можно верить». Метка на таком числе отменяет доверие ко всем
       остальным меткам. */
    expect(неИтог({ until: "2026-08-14", today: СЕГОДНЯ, openDays: false })).toBeNull();
  });

  it("вчера НЕ закрыт — число нижняя граница, и сказано почему", () => {
    const n = неИтог({ until: "2026-08-14", today: СЕГОДНЯ, openDays: true })!;
    expect(n.почему).toBe("not-closed");
    expect(n.hint).toContain("lower bound");
    /* Причина названа так, как она устроена: день кончается в таймзоне
       КАБИНЕТА, а не нашей. Без этого «не закрыт» читается как наша поломка. */
    expect(n.hint).toContain("own time zone");
  });

  it("признака нет вовсе — про прошлые дни НЕ ДОГАДЫВАЕМСЯ", () => {
    /* Ошибаться здесь можно только в сторону молчания: пометить верное число
       дороже, чем промолчать про занижённое. */
    expect(неИтог({ until: "2026-08-14", today: СЕГОДНЯ })).toBeNull();
    expect(неИтог({ until: "2026-08-14", today: СЕГОДНЯ, openDays: false })).toBeNull();
  });

  it("сегодня сильнее незакрытых дней: причина называется одна и самая близкая", () => {
    /* Обе верны, но человеку нужна та, что объясняет ЭТО число сейчас. Две
       причины подряд в одной плашке читаются как «всё сломано». */
    expect(неИтог({ until: СЕГОДНЯ, today: СЕГОДНЯ, openDays: true })?.почему).toBe("today");
  });

  it("одной датой на весь лист тоже можно, но это ЗАПАСНОЙ путь", () => {
    /* Оставлено ради полноты и помечено как нежелательное: кабинеты в разных
       гео, и одна дата на весь парк обязана соврать в одну из сторон — у UTC+3
       сутки кончились, у Лос-Анджелеса нет. */
    expect(неИтог({ until: "2026-08-14", today: СЕГОДНЯ, closedThrough: "2026-08-12" })?.почему)
      .toBe("not-closed");
    expect(неИтог({ until: "2026-08-14", today: СЕГОДНЯ, closedThrough: "2026-08-14" }))
      .toBeNull();
  });
});

describe("знак нижней границы", () => {
  it("стоит ПЕРЕД числом", () => {
    /* «$856.82+» читается как часть суммы и теряется в колонке цифр; «≥» ломает
       форму строки и потому замечается без чтения подписи. */
    expect(нижняяГраница("$856.82")).toBe("≥ $856.82");
  });

  it("не «примерно»: мы знаем ТОЧНО, что не больше показанного", () => {
    expect(нижняяГраница("$1")).not.toContain("~");
    expect(нижняяГраница("$1")).not.toContain("≈");
  });
});

describe("часовой пояс: «сегодня» местное, а не UTC", () => {
  it("сравнение идёт строками дат, без Date внутри", () => {
    /* Ловушка на возврат `toISOString()`: восточнее Гринвича он отдаёт вчерашний
       день, и метка «день ещё идёт» пропала бы ровно там, где день идёт.
       Проверяем ПОВЕДЕНИЕМ: функция обязана верить переданной дате и не
       спрашивать часы сама. */
    const было = неИтог({ until: "2026-08-15", today: "2026-08-15" });
    expect(было?.почему).toBe("today");
    const тоже = неИтог({ until: "2026-08-15", today: "2026-08-16" });
    expect(тоже).toBeNull();
  });
});

/* --- Правило доехало до экрана ------------------------------------------- */

/* Модель выше ничего не рисует, а ошибка живёт в стыке: правило посчитано, а
   крупное число по-прежнему выглядит итогом. Ровно так уже было с вердиктом о
   сборе — компонент работал и стоял не везде.
   Рисовать сам лист серверным рендером нельзя (он тянет данные эффектом,
   которых `renderToStaticMarkup` не выполняет), поэтому проверяем ПРОВОДКУ по
   исходнику: тот же приём, что в `auth-screen.test.ts`, и по той же причине —
   разъезжается здесь не значение, а то, что положили в аргумент. */
describe("крупное число на листе знает про незакрытый день", () => {
  const лист = readFileSync(
    path.resolve(__dirname, "..", "..", "components", "views", "AnalyticsView.tsx"), "utf8");

  it("правило берётся из `lib/analytics-final`, а не написано в разметке", () => {
    expect(лист).toMatch(/from\s+"@\/lib\/analytics-final"/);
    expect(лист).toContain("неИтог({");
  });

  it("«сегодня» приезжает ИЗ ОТВЕТА движка, а не считается в браузере", () => {
    /* Прежняя редакция требовала обратного — `today: ymd(new Date())`, местный
       календарь вместо `toISOString`. Она была права против той болезни:
       восточнее Гринвича `toISOString` отдаёт вчерашний день, и метка «день ещё
       идёт» пропадала там, где день идёт. Но лечила она симптом одним поясом
       ниже. Сутки продукта считает `core/period.py` (сейчас UTC+3), и часы
       БРАУЗЕРА — это второй ответ на вопрос «какое сегодня число»: у байера из
       Тбилиси он наступает на час раньше нашего, и метка снималась бы за час до
       срока. Ответ движка приезжает в том же поясе, что и границы окна, — то
       есть сравнивать `until` с `today` есть смысл только внутри одного ответа.

       Проверяем ОБЕ стороны: что берём из ответа и что своего расчёта не
       осталось. Одно без другого прошло бы и на коде, где рядом живут оба.

       Запреты проверяются по КОДУ БЕЗ КОММЕНТАРИЕВ. Иначе объяснение, почему
       мы так больше не делаем, само роняло бы тест — и следующий читатель
       убрал бы объяснение вместо того, чтобы оставить проверку. Тот же приём
       и по той же причине, что в `landing.test.ts`. */
    const код = лист.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
    expect(код).toContain("today: board?.period?.today");
    expect(код).not.toContain("toISOString");
    expect(код).not.toMatch(/ymd\(new Date\(\)\)/);
    expect(код).not.toMatch(/new Date\(\)\.get(FullYear|Month|Date)\(\)/);
    /* И само вырезание комментариев обязано что-то оставить: пустая строка
       прошла бы все запреты разом. */
    expect(код).toContain("неИтог({");
  });

  it("конец окна берётся из ОТВЕТА, а не из поля ввода", () => {
    /* В поле ввода лежит намерение, на экране — прежний срез: пока новый едет,
       метка обязана описывать то, что человек видит, а не то, что он набрал. */
    expect(лист).toContain("until: board?.until");
  });

  it("незакрытый день берётся из недобора, а не из своего порога", () => {
    /* Демон считает `stale_gap_s` ТОЛЬКО по дням с `closed_at IS NULL`, значит
       непустой недобор сам по себе доказывает, что день не закрыт. Свой порог
       «какой недобор считать недобором» лист не заводит — он один на продукт и
       живёт в `staleLevel`. */
    expect(лист).toContain("openDays: открытыеДни");
    expect(лист).toContain("staleLevel(n.stale_gap_s");
    const блок = лист.slice(лист.indexOf("const открытыеДни"), лист.indexOf("const неитог"));
    expect(блок).not.toMatch(/[><]=?\s*\d{3,}/);
  });

  it("знак нижней границы стоит у спенда И у цены депа", () => {
    /* Цена депа считается из спенда: если спенд занижен, настоящая цена ВЫШЕ
       показанной. Промолчать здесь значит дать закрыть связку по цифре, которая
       выглядит лучше правды. */
    const блок = лист.slice(лист.indexOf("const totals"), лист.indexOf("</DialogTrigger>"));
    expect((блок.match(/нижняяГраница\(/g) || []).length).toBeGreaterThanOrEqual(2);
  });
});

/* ── МЕТКА, КОТОРАЯ СТОИТ ВЕЗДЕ, НЕ ЗНАЧИТ НИЧЕГО (правка 15.08) ─────────────
 *
 * Владелец на живом листе: «в аналитике теперь ВЕЗДЕ пишет spend day not
 * closed, cost so far, везде вот это больше-равно, ДАЖЕ ЕСЛИ выбираешь
 * фильтрацию по 30 дням или за всё время». Причина: сегодня не закрыт по
 * определению, значит любое окно, кончающееся сегодня, помечалось целиком.
 *
 * Здесь сторожится РАЗДЕЛЕНИЕ двух ответов: слова про состав окна человек
 * видит всегда, а знак ≥ — утверждение о числе — делается редко и не панелью.
 */
describe("знак ≥ отделён от слов про состав окна", () => {
  const ДЕНЬ = "2026-08-15";

  it("тридцать дней с одним идущим днём: слова есть, знака НЕТ", () => {
    const n = неИтог({ since: "2026-07-17", until: ДЕНЬ, today: ДЕНЬ });
    expect(n?.дни).toBe("1 of 30 days");
    expect(n?.граница).toBe(false);
    /* И подпись под крупным числом остаётся обычной: «spend so far» — тоже
       утверждение о числе, и следовать оно обязано за знаком, а не за самим
       фактом идущего дня. */
    expect(n?.label).toBe("spend");
  });

  it("окно «сегодня»: знак есть, и это не порог, а тождество", () => {
    /* Незакрытое здесь и ЕСТЬ всё окно: доля равна единице, сравнивать не с
       чем. Ровно поэтому панель может решить это сама, без порога. */
    const n = неИтог({ since: ДЕНЬ, until: ДЕНЬ, today: ДЕНЬ });
    expect(n?.доля).toBe(1);
    expect(n?.граница).toBe(true);
    expect(n?.label).toBe("spend so far");
  });

  it("решение сборщика сильнее панельного: прислал «заметно» — знак есть", () => {
    /* Порог живёт в движке одной константой рядом с запросом. Панель читает
       решение: две константы в двух языках расходятся молча. */
    const n = неИтог({
      since: "2026-08-09", until: ДЕНЬ, today: ДЕНЬ, materialFromEngine: true,
    });
    expect(n?.граница).toBe(true);
  });

  it("прислал «незаметно» — знака нет, даже на однодневном окне", () => {
    const n = неИтог({
      since: ДЕНЬ, until: ДЕНЬ, today: ДЕНЬ, materialFromEngine: false,
    });
    expect(n?.граница).toBe(false);
    /* Слова при этом остаются: состав окна — не то же, что утверждение о
       числе, и человек имеет право его видеть. */
    expect(n).not.toBe(null);
  });

  it("счёт дней берётся у сборщика, а «как минимум» — только когда его нет", () => {
    /* Выдумывать счёт нельзя: на нём держится и подпись, и (у сборщика) знак. */
    expect(неИтог({ since: "2026-08-09", until: ДЕНЬ, today: ДЕНЬ, openDays: true,
                    openDaysCount: 3, windowDaysFromEngine: 7 })?.дни)
      .toBe("3 of 7 days");
    expect(неИтог({ since: "2026-08-09", until: ДЕНЬ, today: ДЕНЬ, openDays: true })?.дни)
      .toBe("at least 2 of 7 days");
  });

  it("сборщик говорит «открытых дней нет» — метки нет вовсе", () => {
    /* Замер автора сборщика на копии живой базы: за 30 дней window_days 7,
       open_days 0, незакрытых денег 0.00 — то есть метка не должна стоять
       нигде, а стояла везде. Это и был дефект, независимый от порога. */
    const n = неИтог({
      since: "2026-08-09", until: "2026-08-14", today: ДЕНЬ,
      openDaysCount: 0, windowDaysFromEngine: 7,
    });
    expect(n).toBe(null);
  });
});

describe("состав окна читается одной дверью и терпит отсутствие полей", () => {
  it("полей нет — это не ошибка, а «сборщик их ещё не отдаёт»", () => {
    expect(readOpenDays({ since: "x", until: "y" }))
      .toEqual({ openDays: null, windowDays: null, material: null, share: null });
    expect(readOpenDays(null))
      .toEqual({ openDays: null, windowDays: null, material: null, share: null });
  });

  it("имена привязаны к ОКНУ и не сталкиваются с /collector", () => {
    /* `open_days` в ответе `/collector` уже занято и значит другое: открытые
       прошедшие дни арендатора вообще, без всякого окна. Одно слово на два
       разных числа в двух ответах разъедется молча, как только третий читатель
       начнёт читать оба. Поэтому здесь читается только `window_open_days`. */
    expect(readOpenDays({ window_open_days: 0, window_days: 7, stale_material: false,
                          stale_share: 0 }))
      .toEqual({ openDays: 0, windowDays: 7, material: false, share: 0 });
    /* И чужое имя НЕ подхватывается: иначе панель начала бы считать окно по
       числу, которое про весь парк. */
    expect(readOpenDays({ open_days: 5, window_days: 7 }).openDays).toBe(null);
  });

  it("мусор в полях не превращается в число", () => {
    expect(readOpenDays({ window_open_days: "3", window_days: -1, stale_material: "да",
                          stale_share: 7 }))
      .toEqual({ openDays: null, windowDays: null, material: null, share: null });
  });
});
