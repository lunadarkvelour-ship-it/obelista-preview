/* Галка «выбрать всё» обязана СХОДИТЬСЯ. Живой дефект, найденный 17.08.
 *
 * ЧТО БЫЛО НА ПРОДЕ. Шапка таблицы считала отмечаемыми строки по одному
 * правилу (`Boolean(r.profile)` — «соц известен»), а выбор клал в набор строки
 * по другому (`можноЛить`). Правила расходятся ровно на забаненном кабинете с
 * известным профилем: `noUploadReason` проверяет бан ПЕРВЫМ, до профиля.
 *
 * Такая строка попадала в «сколько можно отметить» и не попадала в «что
 * отмечено» — значит «отмечено всё» не наступало никогда. На парке владельца
 * это 70 строк из 109. А так как обработчик передавал `!allVisibleSelected`, он
 * всегда передавал `true`: галка выделяла всё и НЕ УМЕЛА СНЯТЬ ВЫДЕЛЕНИЕ.
 *
 * ПОЧЕМУ ЭТОГО НЕ ПОЙМАЛИ. Сторож рядом (`data-source-mode`) назывался
 * «AccountsView фильтрует выбор общим правилом» и проверял... наличие в
 * исходнике строки `visible.filter(снапРежим ? можноЛить` — то есть текста
 * ВЫРАЖЕНИЯ, которое и содержало второе правило. Название утверждало гарантию,
 * проверка закрепляла её нарушение. Классика: проверка есть, зелёная, не
 * проверяет ничего.
 *
 * ПОЭТОМУ ЗДЕСЬ ПРОВЕРЯЕТСЯ ПОВЕДЕНИЕ, А НЕ ТЕКСТ. Правило вынесено в
 * `cloud-accounts.отмечаемые`, и тест зовёт его, а не читает файл.
 *
 * КОНТРОЛЬ, ЧТО ТЕСТ НЕ ПУСТОЙ: ниже прямо записано СТАРОЕ правило и проверено,
 * что на этой фикстуре оно даёт ДРУГОЙ ответ. Если однажды `noUploadReason`
 * изменится так, что расхождения не станет, это упадёт — и правильно: тогда
 * фикстура перестала описывать дефект, ради которого написана, и её надо
 * пересобрать, а не оставлять зелёной.
 */
import { describe, expect, it } from "vitest";
import { отмечаемые, можноЛить, noUploadReason } from "@/lib/cloud-accounts";
import type { UnifiedAccount } from "@/lib/cloud-accounts";
import type { AccountOwner } from "@/lib/account-rows";

const соц = (p: Partial<AccountOwner> & { profile: string }): AccountOwner => ({
  label: "", present: true, fresh: true, oauth: true, ...p,
});

const каб = (over: Partial<UnifiedAccount> & { act_id: string }): UnifiedAccount => ({
  currency: "USD",
  owners: [],
  pixels: [],
  profile: null,
  profileLabel: "",
  inSnapshot: true,
  ...over,
} as UnifiedAccount);

/** Живой кабинет с подключённым соцем: отмечается. */
const ЖИВОЙ = каб({
  act_id: "act_1",
  status: "ACTIVE",
  profile: "p1",
  owners: [соц({ profile: "p1", label: "1/8 MediaBuyer3 hiu" })],
});

/** ЗАБАНЕННЫЙ, НО С ИЗВЕСТНЫМ СОЦЕМ — вся суть дефекта.
 *  На парке владельца таких 70: строка «Hiuhiu_MediaBuyer_3.8_2 · disabled ·
 *  ad policy» с живым профилем в колонке. */
const БАН_С_СОЦЕМ = каб({
  act_id: "act_2",
  status: "DISABLED",
  profile: "p1",
  owners: [соц({ profile: "p1", label: "1/8 MediaBuyer3 hiu" })],
});

/** Соца не знаем вовсе — не отмечается по другой причине. */
const БЕЗ_СОЦА = каб({ act_id: "act_3", status: "ACTIVE" });

const ПАРК = [ЖИВОЙ, БАН_С_СОЦЕМ, БЕЗ_СОЦА];

describe("«выбрать всё» сходится с тем, что правда отмечается", () => {
  it("забаненный кабинет с известным соцем НЕ отмечаем", () => {
    /* Именно этот случай прежнее правило считало отмечаемым. */
    expect(noUploadReason(БАН_С_СОЦЕМ)).toBe("account-dead");
    expect(можноЛить(БАН_С_СОЦЕМ)).toBe(false);
    expect(отмечаемые(ПАРК).map((a) => a.act_id)).toEqual(["act_1"]);
  });

  it("множество отмечаемых и предикат отметки — одно и то же, строка в строку", () => {
    /* Свойство, а не пример: что бы ни лежало в парке, шапка и выбор обязаны
       отвечать одинаково. Разойдись они на один кабинет — галка перестанет
       сходиться, и снять выделение ею будет нельзя. */
    const набор = new Set(отмечаемые(ПАРК).map((a) => a.act_id));
    for (const a of ПАРК) {
      expect(набор.has(a.act_id), `${a.act_id}: множество и предикат разошлись`)
        .toBe(можноЛить(a));
    }
  });

  it("галка может сойтись: отметив всё отмечаемое, получаем «отмечено всё»", () => {
    /* Ровно то, чего на проде не наступало никогда. Считаем так же, как
       компонент: `allVisibleSelected = выбираемые.every(отмечено)`. */
    const выбираемые = отмечаемые(ПАРК);
    const отмечено = new Set(выбираемые.filter(можноЛить).map((a) => a.act_id));
    expect(выбираемые.length).toBeGreaterThan(0);
    expect(выбираемые.every((a) => отмечено.has(a.act_id))).toBe(true);
  });

  it("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: прежнее правило на этой же фикстуре даёт другой ответ", () => {
    /* Без этой проверки предыдущие три зелены и на сломанном коде тоже —
       они бы просто описывали правило, которого никто не нарушал. Здесь
       записано, ЧТО именно было не так, и что фикстура это ловит. */
    const прежнее = (a: UnifiedAccount) => Boolean(a.profile);
    const поПрежнему = ПАРК.filter(прежнее).map((a) => a.act_id);
    const поНынешнему = отмечаемые(ПАРК).map((a) => a.act_id);

    expect(поПрежнему).toEqual(["act_1", "act_2"]);
    expect(поНынешнему).toEqual(["act_1"]);
    expect(поПрежнему, "правила обязаны расходиться — иначе фикстура не про дефект")
      .not.toEqual(поНынешнему);
  });
});
