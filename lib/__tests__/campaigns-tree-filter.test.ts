/* Фильтр внутри дерева НЕ ЛОМАЕТ ДЕРЕВО.
 *
 * Владелец 15.08: «всё должно быть деревом, это базовая логика этого
 * интерфейса». Отсюда правило, которое проверяется здесь: строка, совпавшая с
 * поиском, приходит вместе со всеми своими предками — иначе объявление висит в
 * воздухе, и человек не видит, ЧЕМ оно выключено, а это и есть ответ, за
 * которым он пришёл на лист.
 *
 * Предки при этом НЕ СЧИТАЮТСЯ НАЙДЕННЫМИ (`совпало` их не содержит), и это
 * вторая половина правила: строка, показанная для контекста, не должна
 * читаться как результат поиска — иначе «нашлось 12» превращается в «нашлось
 * 4, а восемь мы дорисовали».
 *
 * Проверяется ЧЕРЕЗ ПОЛНЫЙ ПУТЬ ОТРИСОВКИ (`срезДерева` → `поКабинетам` →
 * `плоскийЛист`), а не только на первой функции: порядок и глубина — свойства
 * того, что увидит человек, и потеряться они могут в любом из трёх шагов.
 */
import { describe, expect, it } from "vitest";
import {
  ПУСТОЙ_СРЕЗ_ДЕРЕВА, плоскийЛист, поКабинетам, срезДерева,
  type СрезДерева,
} from "@/lib/campaigns-tree";
import type { CampaignRow } from "@/lib/campaigns";

const NOW = Date.parse("2026-08-16T12:00:00Z");
const назад = (s: number) => new Date(NOW - s * 1000).toISOString();

const r = (p: Partial<CampaignRow> & { fb_id: string; level: CampaignRow["level"] }):
  CampaignRow => ({
  parent_id: null, act_id: "act_1", name: p.fb_id, status: "ACTIVE",
  effective_status: "ACTIVE", checked_at: назад(60), owner: "00076f0a", ...p,
});

/* Два кабинета, в каждом своя ветка на четыре этажа. Имя, по которому ищем,
   стоит ТОЛЬКО у объявления в первом кабинете: так проверяется и подъём к
   предкам, и то, что соседняя ветка не увязалась следом. */
const ДЕРЕВО: CampaignRow[] = [
  r({ fb_id: "c1", level: "campaign", name: "кампания синяя", spend: 100 }),
  r({ fb_id: "s1", level: "adset", parent_id: "c1", name: "адсет синий", spend: 100 }),
  r({ fb_id: "a1", level: "ad", parent_id: "s1", name: "крео ЖЁЛТЫЙ баннер", spend: 60 }),
  r({ fb_id: "a2", level: "ad", parent_id: "s1", name: "крео зелёный баннер", spend: 40 }),
  r({ fb_id: "c2", level: "campaign", name: "кампания красная", spend: 5 }),
  r({ fb_id: "s2", level: "adset", parent_id: "c2", name: "адсет красный", spend: 5 }),
  r({ fb_id: "a3", level: "ad", parent_id: "s2", name: "крео красный баннер", spend: 5 }),
  r({ fb_id: "c3", level: "campaign", act_id: "act_2", name: "чужой кабинет", spend: 1 }),
];

const срез = (p: Partial<СрезДерева> = {}) =>
  срезДерева(ДЕРЕВО, { ...ПУСТОЙ_СРЕЗ_ДЕРЕВА, ...p });

const ids = (rows: CampaignRow[]) => rows.map((x) => x.fb_id);

describe("фильтр сохраняет предков совпавшей строки", () => {
  it("совпало объявление — остаются его адсет и его кампания", () => {
    const s = срез({ запрос: "жёлтый" });
    expect(ids(s.rows)).toEqual(["c1", "s1", "a1"]);
  });

  it("предки — КОНТЕКСТ, а не результат поиска", () => {
    const s = срез({ запрос: "жёлтый" });
    expect([...s.совпало]).toEqual(["a1"]);
    /* Ровно то, чем вьюха приглушает строку: она спрашивает `совпало`, а не
       «есть ли строка в ответе». */
    expect(s.rows.filter((x) => !s.совпало.has(x.fb_id)).map((x) => x.fb_id))
      .toEqual(["c1", "s1"]);
  });

  it("несовпавшие ветки уходят целиком — и своя, и чужого кабинета", () => {
    const s = срез({ запрос: "жёлтый" });
    for (const чужой of ["c2", "s2", "a3", "c3", "a2"]) {
      expect(ids(s.rows).includes(чужой), чужой).toBe(false);
    }
  });

  it("порядок строк — исходный, сверху вниз по дереву", () => {
    /* Порядок задаёт отрисовку: перевернувшись, дерево покажет объявление над
       его кампанией, и отступы станут врать про вложенность. */
    const s = срез({ запрос: "баннер" });
    expect(ids(s.rows)).toEqual(["c1", "s1", "a1", "a2", "c2", "s2", "a3"]);
  });

  it("пустой запрос отдаёт дерево целиком и всё считает найденным", () => {
    const s = срез();
    expect(ids(s.rows)).toEqual(ids(ДЕРЕВО));
    expect(s.совпало.size).toBe(ДЕРЕВО.length);
  });

  it("совпадение по id работает так же, как по имени", () => {
    /* На живом парке половина строк без человеческого имени, и ищут их по id. */
    const s = срез({ запрос: "a3" });
    expect(ids(s.rows)).toEqual(["c2", "s2", "a3"]);
    expect([...s.совпало]).toEqual(["a3"]);
  });

  it("совпала кампания — её дети НЕ подтягиваются", () => {
    /* Предки нужны для контекста, потомки — нет: они и есть то, от чего
       человек фильтровался. */
    const s = срез({ запрос: "кампания красная" });
    expect(ids(s.rows)).toEqual(["c2"]);
  });
});

describe("фильтр по состоянию — тот же закон о предках", () => {
  const СМЕШАННОЕ: CampaignRow[] = [
    r({ fb_id: "c1", level: "campaign", name: "жива", status: "ACTIVE" }),
    r({ fb_id: "s1", level: "adset", parent_id: "c1", name: "адсет", status: "ACTIVE" }),
    r({ fb_id: "a1", level: "ad", parent_id: "s1", name: "включено, а не идёт",
        status: "ACTIVE", effective_status: "CAMPAIGN_PAUSED" }),
    r({ fb_id: "a2", level: "ad", parent_id: "s1", name: "идёт", status: "ACTIVE" }),
  ];

  it("«не доставляется» оставляет предков, но найденным считает одно объявление", () => {
    const s = срезДерева(СМЕШАННОЕ, { ...ПУСТОЙ_СРЕЗ_ДЕРЕВА, состояние: "не доставляется" });
    expect(ids(s.rows)).toEqual(["c1", "s1", "a1"]);
    expect([...s.совпало]).toEqual(["a1"]);
  });
});

describe("глубина и этаж кабинета переживают фильтр", () => {
  const раскрыто = { иначе: new Set<string>(), подФильтром: true, одинКабинет: false };

  it("после среза строка стоит на своей глубине, а кабинет остаётся этажом", () => {
    /* Глубина считается ОТ КАБИНЕТА: кампания 1, адсет 2, объявление 3. Если
       фильтр её уронит, отфильтрованное дерево нарисуется плоским списком —
       ровно тем, на что жаловался владелец. */
    const s = срез({ запрос: "жёлтый" });
    const строки = плоскийЛист(поКабинетам(s.rows), раскрыто);
    expect(строки.map((x) => x.вид)).toEqual(["кабинет", "объект", "объект", "объект"]);
    const глубины = строки
      .filter((x): x is Extract<typeof x, { вид: "объект" }> => x.вид === "объект")
      .map((x) => [x.item.node.row.fb_id, x.item.depth]);
    expect(глубины).toEqual([["c1", 1], ["s1", 2], ["a1", 3]]);
  });

  it("кабинет, из которого не осталось ни строки, этажом не рисуется", () => {
    const s = срез({ запрос: "жёлтый" });
    expect(поКабинетам(s.rows).map((г) => г.act_id)).toEqual(["act_1"]);
  });

  it("объявление, потерявшее адсет по фильтру, НЕ встаёт рядом с кампанией", () => {
    /* Сирота — строка, чьего родителя в ответе нет — уезжает в свою ветку под
       кабинетом. Проверяем на срезе, где родитель отфильтрован: дерево обязано
       остаться деревом даже тогда, когда его порезали. */
    const кусок = [ДЕРЕВО[0], ДЕРЕВО[2]]; // c1 и a1 без адсета между ними
    const этажи = поКабинетам(кусок);
    expect(этажи[0].roots.map((n) => n.row.fb_id)).toEqual(["c1"]);
    expect(этажи[0].безРодителя.map((n) => n.row.fb_id)).toEqual(["a1"]);
  });
});

describe("счётчик спрятанного глазом считается всегда", () => {
  it("глаз выключен — число всё равно известно", () => {
    /* Иначе человек не узнает, что прятать есть что, пока не нажмёт: число —
       замер НАШЕЙ дырки в сборе спенда, а не удобство. */
    const безСпенда = [...ДЕРЕВО, r({ fb_id: "a7", level: "ad", parent_id: "s1",
                                      name: "спенд не найден", spend: null })];
    const выкл = срезДерева(безСпенда, ПУСТОЙ_СРЕЗ_ДЕРЕВА);
    const вкл = срезДерева(безСпенда, { ...ПУСТОЙ_СРЕЗ_ДЕРЕВА, безСпендаСкрыт: true });
    expect(выкл.скрытоБезСпенда).toBe(1);
    expect(вкл.скрытоБезСпенда).toBe(1);
    expect(ids(вкл.rows).includes("a7")).toBe(false);
  });

  it("ноль спенда глазом НЕ прячется: ноль — это факт, а не незнание", () => {
    const сНулём = [...ДЕРЕВО, r({ fb_id: "a8", level: "ad", parent_id: "s1",
                                   name: "крутилось и не потратило", spend: 0 })];
    const вкл = срезДерева(сНулём, { ...ПУСТОЙ_СРЕЗ_ДЕРЕВА, безСпендаСкрыт: true });
    expect(ids(вкл.rows).includes("a8")).toBe(true);
    expect(вкл.скрытоБезСпенда).toBe(0);
  });
});
