/* Корзина «данные о кампании ещё не собраны» — стык панели и движка (#150).
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ. Значение среза `none` — не строка на экране, а ДОГОВОРЁННОСТЬ
 * между двумя половинами: панель кладёт его в `?geo=`, а сервер по нему
 * отбирает строки без гео (`core/leaderboard.ГЕО_НЕИЗВЕСТНО`, он же
 * подставляется в предикат леса объявлений у демона). Переименуй кто-нибудь
 * одну сторону — вторая не упадёт: вкладка просто перестанет что-либо
 * находить, а выглядеть это будет как «в этой корзине пусто», то есть как
 * ХОРОШАЯ новость. Ровно та тихая порода, из-за которой деньги и терялись.
 *
 * Поэтому тест читает НАСТОЯЩИЙ питоновский файл, а не копию строки рядом с
 * собой: копия договорённости разъезжается с оригиналом так же молча.
 */
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";
import { GEO_UNKNOWN, geoHint, geoLabel, geoTabs } from "@/lib/analytics-geo";

const КОРЕНЬ = path.join(__dirname, "..", "..", "..");

function исходник(файл: string): string {
  return readFileSync(path.join(КОРЕНЬ, файл), "utf8");
}

describe("значение корзины совпадает с движком", () => {
  it("`GEO_UNKNOWN` — та же строка, что `ГЕО_НЕИЗВЕСТНО` в core/leaderboard.py", () => {
    const py = исходник("core/leaderboard.py");
    const m = /^ГЕО_НЕИЗВЕСТНО = "([^"]+)"/m.exec(py);
    expect(m, "в core/leaderboard.py не нашлось объявления ГЕО_НЕИЗВЕСТНО").toBeTruthy();
    expect(m![1]).toBe(GEO_UNKNOWN);
  });

  it("движок отбирает по этому значению именно строки БЕЗ гео", () => {
    /* Не «константа объявлена», а «она участвует в отборе». Объявить строку и
       забыть применить — отдельный способ сломать корзину, и он выглядит как
       рабочий код. */
    const py = исходник("core/leaderboard.py");
    expect(py).toMatch(/ГЕО_ПРЕДИКАТ/);
    expect(py).toMatch(/COALESCE\(ca\.geo_token, ''\) = ''/);
  });

  it("лес объявлений берёт предикат у лидерборда, а не пишет свой", () => {
    /* Вкладка и разворот под ней обязаны отвечать одинаково: разойдись они,
       клик по корзине откроет пустоту, и человек прочтёт это как «данных
       нет». Четвёртая копия предиката тут и жила. */
    const py = исходник("scripts/analytics_daemon.py");
    expect(py).toMatch(/leaderboard\.ГЕО_ПРЕДИКАТ/);
  });
});

describe("подписи", () => {
  it("корзина не притворяется страной", () => {
    expect(geoLabel(GEO_UNKNOWN)).toBe("no campaign data");
    expect(geoLabel("DZ")).toBe("DZ");
    expect(geoLabel(null)).toBe("all");
  });

  it("подсказка объясняет, что это НЕ страна с нулём", () => {
    /* «В этом гео ноль» и «гео не знаем» — разные ответы (та же порода, что
       #122). Текст обязан называть вторую вещь второй вещью. */
    expect(geoHint(GEO_UNKNOWN)).toMatch(/can't attribute|can't place/);
    expect(geoHint("DZ")).toBe("");
  });

  it("корзина стоит последней, а не между странами", () => {
    expect(geoTabs(["EG", GEO_UNKNOWN, "BD", "DZ"]))
      .toEqual(["BD", "DZ", "EG", GEO_UNKNOWN]);
    expect(geoTabs(["EG", "BD"])).toEqual(["BD", "EG"]);
  });

  it("пустых вкладок не бывает", () => {
    expect(geoTabs(["", "DZ"])).toEqual(["DZ"]);
  });
});
