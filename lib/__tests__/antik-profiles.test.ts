/* Откуда билдер залива берёт список профилей.
 *
 * Место дорогое дважды. Пустой список делает билдер неработающим инструментом —
 * а владелец пользуется им каждый день. Полный, но непроверенный список
 * предлагает залить с профиля, которого может уже не быть, и человек узнаёт об
 * этом в самом конце: 06.08 в выпадающем списке жили восемь мёртвых профилей из
 * четырнадцати, и один стоял дефолтом в пресете.
 *
 * Правило поэтому не «фильтровать» и не «не фильтровать», а брать ЛУЧШИЙ
 * ДОСТУПНЫЙ признак и честно называть, когда его нет.
 */
import { describe, it, expect } from "vitest";
import { профилиДляБилдера, type РядСоца } from "@/lib/antik-profiles";

const ряд = (id: string, in_antik: boolean, connected = true): РядСоца => ({
  profile_id: id,
  profile_name: `имя-${id}`,
  connected,
  in_antik,
});

describe("локальный антидетект отвечает — верим ему", () => {
  const rows = [ряд("живой", true), ряд("мёртвый", false)];

  it("мёртвые в билдер не попадают", () => {
    // Лучшее знание есть — игнорировать его незачем. Ровно тот дефект, ради
    // которого фильтр когда-то и завели.
    const { профили } = профилиДляБилдера(rows);
    expect(профили.map((p) => p.id)).toEqual(["живой"]);
  });

  it("подтверждение засчитано", () => {
    expect(профилиДляБилдера(rows).подтверждениеЕсть).toBe(true);
  });

  it("живой профиль помечен подтверждённым", () => {
    expect(профилиДляБилдера(rows).профили[0].подтверждён).toBe(true);
  });
});

describe("подтвердить некому — показываем всё, что знает Обелиста", () => {
  /* Главный случай после зачистки: в облаке локального API нет по устройству,
     признак ложен у всех строк. Пустой список тут — не осторожность, а молчание
     на месте ответа. */
  const облако = [ряд("a", false), ряд("b", false), ряд("c", false, false)];

  it("список НЕ пуст", () => {
    expect(профилиДляБилдера(облако).профили).toHaveLength(3);
  });

  it("сказано, что подтверждения нет", () => {
    expect(профилиДляБилдера(облако).подтверждениеЕсть).toBe(false);
  });

  it("каждая строка помечена непроверенной", () => {
    // Молча выдать непроверенное за проверенное — та же ложь, что и пустой
    // список, только в другую сторону.
    expect(профилиДляБилдера(облако).профили.every((p) => !p.подтверждён)).toBe(true);
  });

  it("статус OAuth не теряется", () => {
    expect(профилиДляБилдера(облако).профили.map((p) => p.connected)).toEqual([true, true, false]);
  });
});

describe("мелочи, на которых список врёт незаметно", () => {
  it("профиль без имени показывается идентификатором, а не пустотой", () => {
    const без = профилиДляБилдера([{ ...ряд("uuid-1", true), profile_name: "" }]);
    expect(без.профили[0].name).toBe("uuid-1");
  });

  it("пустой вход не выдумывает строк и не объявляет подтверждение", () => {
    expect(профилиДляБилдера([])).toEqual({ профили: [], подтверждениеЕсть: false });
  });
});
