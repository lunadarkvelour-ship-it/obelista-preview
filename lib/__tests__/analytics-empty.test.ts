/* Пустые состояния листа аналитики.
 *
 * Существует потому, что прод стал чистым листом: у каждого юзера панель
 * начинается с нуля, и пустое состояние — не редкий случай, а ПЕРВОЕ, что
 * человек видит. До 14.08 полностью пустой срез не попадал ни в одну ветку и
 * рисовался таблицей с шапкой и нулём строк, без единого слова, а на всё
 * остальное лист отвечал «No data».
 *
 * Ловушка, ради которой тест написан именно так: ветка «таблица» обязана
 * пережить перезапрос. Если поставить `pending` первым условием, лист на каждой
 * смене диапазона будет мигать «Loading…» поверх уже показанных строк —
 * поведение, которое тестом не видно, а глазом видно сразу.
 */
import { describe, it, expect } from "vitest";
import { emptyKind, type EmptyInput } from "@/lib/analytics-empty";

/** Живой лист с данными: три строки, колонки включены, ответ пришёл. */
const живой: EmptyInput = { board: true, rows: 3, pending: false, error: false, columns: 5 };

describe("какое пустое состояние показать", () => {
  it("есть строки и колонки — таблица, а не заглушка", () => {
    expect(emptyKind(живой)).toBe("table");
  });

  it("чистая панель: ответ пришёл, строк ноль — объяснение, а не пустая таблица", () => {
    expect(emptyKind({ ...живой, rows: 0 })).toBe("empty-range");
  });

  it("пустой срез объясняется, даже когда все колонки выключены", () => {
    expect(emptyKind({ ...живой, rows: 0, columns: 0 })).toBe("empty-range");
  });

  it("строки есть, колонки все выключены — это не «нет данных»", () => {
    expect(emptyKind({ ...живой, columns: 0 })).toBe("all-columns-off");
  });

  it("срез ещё не запрашивали", () => {
    expect(emptyKind({ board: false, rows: 0, pending: false, error: false, columns: 5 }))
      .toBe("not-requested");
  });

  it("первый заход: ответа нет, запрос в пути", () => {
    expect(emptyKind({ board: false, rows: 0, pending: true, error: false, columns: 5 }))
      .toBe("loading");
  });

  it("перезапрос НЕ гасит уже показанную таблицу", () => {
    expect(emptyKind({ ...живой, pending: true })).toBe("table");
  });

  it("но пустой срез объясняется И ВО ВРЕМЯ перезапроса", () => {
    /* Ровно тот случай, из-за которого условие `!pending` снято. Лист зовёт
       себя по таймеру раз в минуту: пока условие стояло, на чистой панели
       человек раз в минуту получал голую шапку таблицы вместо объяснения —
       ту самую картинку, ради которой всё и делалось.

       Правило «таблица переживает перезапрос» верно только когда есть чему
       переживать. При нуле строк переживать нечего, мигать нечем. */
    expect(emptyKind({ ...живой, rows: 0, pending: true })).toBe("empty-range");
  });

  it("ошибку показывает своя плашка — второй раз про неё не говорим", () => {
    expect(emptyKind({ board: false, rows: 0, pending: false, error: true, columns: 0 }))
      .toBe("error");
  });

  it("пустой срез объясняется и при ошибке НЕ показывается: сперва причина", () => {
    // Ответ с нулём строк важнее плашки ошибки только когда ответ реально был.
    expect(emptyKind({ board: true, rows: 0, pending: false, error: true, columns: 5 }))
      .toBe("empty-range");
  });
});
