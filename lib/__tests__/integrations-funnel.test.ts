/* Ключ приёма воронки: три состояния, маска и инструкция (#120).
 *
 * ПОЧЕМУ ТРИ СОСТОЯНИЯ, А НЕ ДВА. «Подключено» без единого события — враньё
 * того же сорта, что мы вычищаем вторые сутки: ключ выдан, данных нет, человек
 * считает, что всё работает. Третий случай злее: события шли и прекратились. По
 * одному факту «ключ есть» он неотличим от первого, а лечится другим — там
 * сломалась выгрузка на стороне CRM, а не подключение здесь.
 *
 * ЗДЕСЬ ЖЕ СТОРОЖ НА ГЛАВНОЕ ПРАВИЛО КЛЮЧА: он не появляется в разметке, пока
 * его не показали, и не попадает в адрес запроса никогда.
 */
import { describe, it, expect } from "vitest";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { readFileSync } from "node:fs";
import path from "node:path";
import {
  ТИШИНА_ЧАСОВ, маска, примерЗапроса, состояниеПриёма,
} from "@/lib/integrations-funnel";
import { FunnelKeyBlock } from "@/components/sections/integrations/FunnelKeyBlock";
import { ALL_VENDORS } from "@/lib/integrations-registry";

const NOW = Date.parse("2026-08-15T12:00:00Z");
const назад = (ч: number) => new Date(NOW - ч * 3_600_000).toISOString();

describe("состояние приёма различает три разные беды", () => {
  it("ключа нет — это не поломка, а «ещё не заводили»", () => {
    const s = состояниеПриёма(null, NOW);
    expect(s.код).toBe("нет ключа");
    expect(s.тон).toBe("notice");
  });

  it("ключ есть, событий не было НИ ОДНОГО — это НЕ «подключено»", () => {
    /* Самая дорогая ошибка этой карточки: написать «connected» по факту
       выданного ключа. Ключ — это возможность прислать, а не доказательство,
       что другая сторона до нас дотягивается. */
    const s = состояниеПриёма({ key: "fnl_x", created_at: назад(50), last_event_at: null }, NOW);
    expect(s.код).toBe("ждёт первого");
    expect(s.заголовок).toMatch(/nothing has arrived yet/i);
    /* И сказано, почему это не «подключено»: отметку ставят только после
       того, как день ЛЁГ, а не когда кто-то постучался. */
    expect(s.пояснение).toMatch(/only after a day is actually stored/i);
  });

  it("события идут — единственное состояние, которое значит «работает»", () => {
    const s = состояниеПриёма({ key: "fnl_x", created_at: назад(100), last_event_at: назад(3) }, NOW);
    expect(s.код).toBe("идут");
    expect(s.тон).toBe("calm");
  });

  it("приходили и перестали — отдельное состояние, и лечится оно у CRM", () => {
    /* Порог суточный с запасом: выгрузка воронки дневная, и пять минут тишины
       здесь не значат ничего, а трое суток значат слишком поздно. */
    const s = состояниеПриёма(
      { key: "fnl_x", created_at: назад(300), last_event_at: назад(ТИШИНА_ЧАСОВ + 2),
        rows_today: 0 }, NOW,
    );
    expect(s.код).toBe("прекратились");
    expect(s.тон).toBe("alarm");
    /* И сказано, где чинить: не здесь. */
    expect(s.пояснение).toMatch(/sending side/i);
  });

  it("строки за сегодня держат приём живым, даже если отметка состарилась", () => {
    /* День закрывают утром: к вечеру отметка успевает состариться, а приём жив.
       Правило назвал автор ручки, и записано оно здесь, а не пересказано в
       разметке. */
    expect(состояниеПриёма(
      { key: "fnl_x", last_event_at: назад(ТИШИНА_ЧАСОВ + 5), rows_today: 12 }, NOW,
    ).код).toBe("идут");
  });

  it("ключа нет — и это первое состояние, даже если что-то когда-то приходило", () => {
    expect(состояниеПриёма({ key: null, last_event_at: назад(2) }, NOW).код).toBe("нет ключа");
  });

  it("граница тишины не превращает свежий приём в мёртвый", () => {
    expect(состояниеПриёма({ key: "fnl_x", created_at: назад(99), last_event_at: назад(ТИШИНА_ЧАСОВ - 1) }, NOW).код)
      .toBe("идут");
  });

  it("часы сервера впереди наших — это не новость про воронку", () => {
    /* Отрицательный возраст считаем нулём, а не «неизвестно»: расхождение часов
       не имеет отношения к тому, идут события или нет. */
    expect(состояниеПриёма({ key: "fnl_x", created_at: назад(5), last_event_at: назад(-1) }, NOW).код)
      .toBe("идут");
  });
});

describe("ключ показывается как пароль, а не как текст", () => {
  it("маска оставляет края и прячет середину", () => {
    expect(маска("fnl_9f3ac1b27d4e")).toBe("fnl_••••••7d4e");
    /* Число точек ПОСТОЯННОЕ, а не равно длине спрятанного: иначе маска сама
       рассказывает, какой длины ключ. */
    expect(маска("fnl_короткий")).toMatch(/^.{4}•{6}.{4}$/);
  });

  it("короткий ключ прячется целиком, а не выдаёт себя длиной краёв", () => {
    expect(маска("abcd")).toBe("••••");
  });

  it("пусто остаётся пустым: маска не выдумывает точки из ничего", () => {
    expect(маска(null)).toBe("");
  });

  it("в примере запроса стоит ПЛЕЙСХОЛДЕР, а не настоящий ключ", () => {
    /* Пример копируют в чат и в тикет целиком. Подставить туда живой ключ
       значит разослать его вместе с вопросом «почему не работает». */
    const пример = примерЗапроса("https://app.example.com/api/analytics");
    expect(пример).toContain("Authorization: Bearer <your key>");
    expect(пример).toContain("/ingest_funnel");
    /* Форма тела — из движка (`core/funnel_intake.принять`), а не из головы. */
    expect(пример).toContain('"day"');
    expect(пример).toContain('"payloads"');
  });
});

describe("блок ключа рисуется и не проговаривается", () => {
  /* Серверный рендер эффектов не выполняет: ответа ручки нет, ключа нет — и
     блок обязан быть целым и честным именно в этом состоянии. */
  const html = renderToStaticMarkup(createElement(FunnelKeyBlock));

  it("сказано, что ключ НАШ, а у CRM его нет вовсе", () => {
    /* Иначе человек уходит искать несуществующий ключ своей CRM. Проверено
       живьём соседним воркером: Bearer, X-Api-Key и Api-Key отвергнуты все три,
       вход отдаёт 404 — работает только кука в браузере. */
    expect(html).toMatch(/does not have a key at all/i);
    expect(html).toMatch(/your own browser session/i);
  });

  it("до ответа сервера ключа на экране нет — ни целиком, ни маской", () => {
    expect(html).toContain("—");
    expect(html).not.toMatch(/Bearer\s+[A-Za-z0-9_-]{8,}/);
  });

  it("инструкция «куда вставить» стоит рядом с ключом", () => {
    expect(html).toContain("/ingest_funnel");
    expect(html).toMatch(/Authorization header, never in the address/i);
  });
});

describe("ключ живёт внутри карточки своего подключения, а не рядом", () => {
  it("ровно один вендор объявляет, что ключ выдаём мы", () => {
    /* Два места про одно подключение — тот самый разъезд, при котором человек
       видит две карточки об одном и не понимает, какая настоящая. */
    expect(ALL_VENDORS.filter((v) => v.issuesKey)).toHaveLength(1);
  });

  it("карточка по-прежнему не знает ни одного имени вендора", () => {
    /* Правило иссуса #126: блок ключа подключён ПРИЗНАКОМ вендора, а не
       условием по его имени. Рядом уже есть тест на имена; здесь — на то, что
       новый блок не завёл исключения. */
    const код = readFileSync(
      path.resolve(__dirname, "..", "..", "components/sections/integrations/VendorCard.tsx"),
      "utf8",
    );
    expect(код).toContain("vendor.issuesKey");
    for (const v of ALL_VENDORS) expect(код).not.toContain(v.name);
  });
});
