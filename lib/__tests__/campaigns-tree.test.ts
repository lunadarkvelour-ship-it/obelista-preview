/* Дерево трёх уровней и результат записи в Мету (#125).
 *
 * Два места, где лист умеет соврать молча:
 *  • сирота — строка, чей родитель в ответе не пришёл. Спрятать её нельзя (по
 *    ней идут деньги), подшить к чужому родителю — тем более;
 *  • оптимистичная запись. «Выключаю» и «выключено» — разные слова, и вторым
 *    нельзя отвечать до ответа Меты.
 */
import { describe, expect, it } from "vitest";
import {
  КЛЮЧ_БЕЗ_РОДИТЕЛЯ, КЛЮЧ_КАБА, СОСТОЯНИЯ_ОБЪЕКТА, applyWrite, buildTree, counts,
  flatten, картаБюджетов, ключиРаскрытия, неДоставляется, отклонения,
  плоскийЛист, поКабинетам, размерВетки, срезДерева, строкиФутера, суммаСпенда,
  счётСостояний, writeWords, type Раскрытие,
} from "@/lib/campaigns-tree";
import { cpc, cpm, ctr, type CampaignRow, type Level } from "@/lib/campaigns";
import { итоги } from "@/lib/campaigns-columns";

function row(over: Partial<CampaignRow> & Pick<CampaignRow, "fb_id" | "level">): CampaignRow {
  return {
    parent_id: null,
    act_id: "act_1",
    name: over.fb_id,
    status: "ACTIVE",
    checked_at: "2026-08-15T11:58:00Z",
    owner: "k1f9qbcs",
    ...over,
  };
}

const НАБОР: CampaignRow[] = [
  row({ fb_id: "c1", level: "campaign", name: "кампания 1" }),
  row({ fb_id: "s1", level: "adset", parent_id: "c1", name: "адсет 1" }),
  row({ fb_id: "a1", level: "ad", parent_id: "s1", name: "объявление 1" }),
  row({ fb_id: "a2", level: "ad", parent_id: "s1", name: "объявление 2" }),
];

describe("buildTree", () => {
  it("три уровня складываются в дерево", () => {
    const [c] = buildTree(НАБОР);
    expect(c.row.fb_id).toBe("c1");
    expect(c.children.map((n) => n.row.fb_id)).toEqual(["s1"]);
    expect(c.children[0].children.map((n) => n.row.fb_id)).toEqual(["a1", "a2"]);
  });

  it("сирота поднимается наверх, а не подшивается к первому попавшемуся", () => {
    const roots = buildTree([...НАБОР, row({ fb_id: "a9", level: "ad", parent_id: "нет-такого" })]);
    expect(roots.map((n) => n.row.fb_id)).toEqual(["c1", "a9"]);
  });

  it("уровень решает порядок раньше имени: сирота не встаёт между кампаниями", () => {
    const roots = buildTree([
      row({ fb_id: "a9", level: "ad", parent_id: null, name: "aaa" }),
      row({ fb_id: "c1", level: "campaign", name: "zzz" }),
    ]);
    expect(roots.map((n) => n.row.level)).toEqual(["campaign", "ad"]);
  });

  it("строка, назначенная родителем самой себе, не зацикливает обход", () => {
    const roots = buildTree([row({ fb_id: "c1", level: "campaign", parent_id: "c1" })]);
    expect(roots).toHaveLength(1);
    expect(roots[0].children).toHaveLength(0);
  });
});

describe("flatten", () => {
  it("свёрнутая ветка в список не попадает", () => {
    expect(flatten(buildTree(НАБОР), new Set()).map((f) => f.node.row.fb_id)).toEqual(["c1"]);
  });

  it("раскрытие идёт по уровням, а не всё разом", () => {
    const roots = buildTree(НАБОР);
    expect(flatten(roots, new Set(["c1"])).map((f) => f.node.row.fb_id)).toEqual(["c1", "s1"]);
    expect(flatten(roots, new Set(["c1", "s1"])).map((f) => f.node.row.fb_id))
      .toEqual(["c1", "s1", "a1", "a2"]);
  });

  it("глубина растёт вместе с уровнем — по ней рисуется отступ", () => {
    const f = flatten(buildTree(НАБОР), new Set(["c1", "s1"]));
    expect(f.map((x) => x.depth)).toEqual([0, 1, 2, 2]);
    expect(f[0].hasKids).toBe(true);
    expect(f[2].hasKids).toBe(false);
  });
});

describe("counts", () => {
  it("считает состав кабинета, а не то, что раскрыто", () => {
    expect(counts(НАБОР)).toEqual({ campaign: 1, adset: 1, ad: 2 });
  });
});

describe("результат записи", () => {
  it("статус берётся ИЗ ОТВЕТА Меты, а не из того, что просили", () => {
    const out = applyWrite(НАБОР, {
      fb_id: "c1", status: "PAUSED", effective_status: "PAUSED",
      applied_at: "2026-08-15T12:00:00Z",
    });
    expect(out.find((r) => r.fb_id === "c1")).toMatchObject({
      status: "PAUSED", checked_at: "2026-08-15T12:00:00Z",
    });
    // Соседей не трогаем.
    expect(out.find((r) => r.fb_id === "s1")!.status).toBe("ACTIVE");
  });

  it("ответ без id ничего не меняет", () => {
    expect(applyWrite(НАБОР, { ok: true })).toBe(НАБОР);
  });

  it("Мета вернула не то, что просили — говорим об этом, а не рисуем успех", () => {
    expect(writeWords("PAUSED", { fb_id: "c1", status: "ACTIVE" }))
      .toContain("reports ACTIVE, not PAUSED");
    expect(writeWords("PAUSED", { fb_id: "c1", status: "PAUSED" })).toContain("Done");
    expect(writeWords("PAUSED", { fb_id: "c1" })).toContain("did not say the new state");
  });
});

/* ── СРЕЗ ВНУТРИ ДЕРЕВА, ЭТАЖИ КАБИНЕТОВ И СУММА СПЕНДА (#125, глубина) ───────
 *
 * На парке владельца открытый набор кабинетов — сотни строк, и вопрос у него не
 * «покажи все», а «что крутится», «что стоит» и «почему включено, а не идёт».
 * Здесь проверяется то, на чём такой срез врёт молча: рассыпает дерево, выдаёт
 * контекст за находку, складывает одни и те же деньги трижды.
 */
const R = (p: Partial<CampaignRow> & { fb_id: string; level: Level }): CampaignRow =>
  ({ parent_id: null, act_id: "act_1", name: "", status: "ACTIVE", ...p } as CampaignRow);

describe("срез внутри дерева", () => {
  const дерево: CampaignRow[] = [
    R({ fb_id: "c1", level: "campaign", name: "hiu--7aug--BD--bangla", status: "ACTIVE",
        effective_status: "ACTIVE", spend: 1873 }),
    R({ fb_id: "s1", level: "adset", parent_id: "c1", name: "set A", status: "PAUSED",
        effective_status: "PAUSED", spend: 900 }),
    R({ fb_id: "a1", level: "ad", parent_id: "s1", name: "creo ЖЁЛТЫЙ", status: "ACTIVE",
        effective_status: "ADSET_PAUSED", spend: 900 }),
    R({ fb_id: "c2", level: "campaign", name: "spx--12aug--DZ", status: "PAUSED",
        effective_status: "PAUSED", spend: 0 }),
  ];

  it("поиск оставляет предков совпавшей строки, иначе дерево рассыпается", () => {
    /* Объявление без своей кампании висит в воздухе, и человек не видит, ЧЕМ
       оно выключено — а это и есть ответ, за которым он пришёл. */
    const s = срезДерева(дерево, { запрос: "ЖЁЛТЫЙ", состояние: "все", безСпендаСкрыт: false });
    expect(s.rows.map((r) => r.fb_id)).toEqual(["c1", "s1", "a1"]);
    /* Но найденной считается ровно одна строка: предки показаны для контекста,
       и выдавать их за находку нельзя. */
    expect([...s.совпало]).toEqual(["a1"]);
  });

  it("«не доставляется» — это РАСХОЖДЕНИЕ, а не список значений Меты", () => {
    /* Мета заводит новые причины недоставки без предупреждения; зашитый список
       назавтра молча перестанет их ловить. Расхождение же означает ровно то,
       что человек спрашивает: «я включил, а оно не идёт». */
    expect(неДоставляется(дерево[2])).toBe(true);
    expect(неДоставляется(дерево[0])).toBe(false);
    expect([...срезДерева(дерево, { запрос: "", состояние: "не доставляется", безСпендаСкрыт: false }).совпало])
      .toEqual(["a1"]);
  });

  it("у кампаний и адсетов недоставку показывает ЧИСЛО ЖИВЫХ ОБЪЯВЛЕНИЙ", () => {
    /* Живой ответ сборщика: `effective_status` у кампаний и адсетов null у ВСЕХ
       (13 кампаний и 54 адсетов на проверенном кабинете). Если полагаться
       только на расхождение статусов, главная кнопка листа работала бы на
       одних объявлениях — то есть не работала бы. Второй факт о доставке —
       сколько объявлений под строкой реально идёт, и ноль при включённом
       статусе и есть «включено, а не идёт». */
    const кампания = R({ fb_id: "cX", level: "campaign", status: "ACTIVE",
                         effective_status: null, active_ads: 0 });
    expect(неДоставляется(кампания)).toBe(true);
    expect(неДоставляется({ ...кампания, active_ads: 3 })).toBe(false);
  });

  it("«не считали» — НЕ ноль: строка без active_ads в недоставку не попадает", () => {
    /* Записать её туда значит утверждать непроверенное: про эту строку мы не
       знаем ничего, а не знаем, что она стоит. */
    expect(неДоставляется(R({ fb_id: "cY", level: "campaign", status: "ACTIVE",
                             effective_status: null }))).toBe(false);
  });

  it("выключенная кампания без живых объявлений недоставкой НЕ считается", () => {
    /* «Не доставляется» — это про включённое. У выключенного нулевая доставка
       не новость, а следствие, и мешать их значит утопить настоящие находки. */
    expect(неДоставляется(R({ fb_id: "cZ", level: "campaign", status: "PAUSED",
                             effective_status: null, active_ads: 0 }))).toBe(false);
  });

  it("«крутится» не считает крутящимся то, что выключено сверху", () => {
    expect([...срезДерева(дерево, { запрос: "", состояние: "крутится", безСпендаСкрыт: false }).совпало])
      .toEqual(["c1"]);
  });

  it("счётчики на кнопках совпадают с тем, что покажет фильтр", () => {
    /* Счёт по СОВПАДЕНИЯМ, а не по показанному: иначе он включал бы предков,
       добавленных ради контекста, и расходился бы с самим фильтром. */
    const счёт = счётСостояний(дерево);
    for (const с of СОСТОЯНИЯ_ОБЪЕКТА) {
      expect(счёт[с], с).toBe(срезДерева(дерево, { запрос: "", состояние: с, безСпендаСкрыт: false }).совпало.size);
    }
    expect(счёт["все"]).toBe(дерево.length);
  });

  it("битая цепочка родителей не зацикливает срез", () => {
    /* Объект, назначенный родителем сам себе, приедет из чужой базы, а не из
       нашей фантазии, и он не имеет права подвесить лист. */
    const кольцо = [R({ fb_id: "x", level: "adset", parent_id: "x", name: "сам себе" })];
    expect(срезДерева(кольцо, { запрос: "сам", состояние: "все", безСпендаСкрыт: false }).rows).toHaveLength(1);
  });
});

