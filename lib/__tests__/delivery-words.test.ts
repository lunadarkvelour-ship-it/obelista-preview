/* Слова о доставке: проверяем не «есть ли перевод», а способы соврать (#155).
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ. Владелец не понял бейджей `derived` и `by parent`. Обе фразы
 * — НАШИ внутренние: первая это имя поля `status_source`, вторая наш пересказ.
 * Ни одной из них нет ни у Меты, ни в Ads Manager, так что узнать их было
 * неоткуда. Поправить такое легко и так же легко поправить наполовину, поэтому
 * проверяются здесь четыре разных болезни, каждая тише предыдущей:
 *
 *  1. СЛОВАРЬ ОТСТАЛ ОТ КОДА. Значения `effective_status` перечислены в
 *     нескольких местах продукта, и список, переписанный сюда руками, знал бы
 *     ровно то, что кто-то вспомнил в день написания. Поэтому набор ВЫВОДИТСЯ
 *     из настоящих файлов — из движка и из панели, — а тест требует, чтобы
 *     словарь покрывал их все. Заведут в движке новое значение — покраснеет
 *     здесь, а не у владельца на экране.
 *  2. ПОЛОВИНА ОТВЕТА. Человек спрашивает четыре разные вещи (идёт или нет,
 *     почему, как это зовёт Мета, дело в объекте или сверху). Бейдж, отвечающий
 *     на три из четырёх, выглядит исправным.
 *  3. РЕБЁНОК, ВЫПЛЕСНУТЫЙ С ВОДОЙ. «Родитель выключен» — законная причина и
 *     факт от Меты: объявление в выключенном адсете остаётся `ADSET_PAUSED`
 *     ПОСЛЕ записи, проверено на живом проде 15.08. Убрать её вместе с
 *     непонятным словом значило бы стереть ответ на вопрос «почему не идёт».
 *  4. ТИХОЕ «ВСЁ ХОРОШО». Худший исход — назвать доставкой то, что не
 *     доставляется: единственный ответ, который человек не пойдёт проверять.
 *
 * ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ — ДАННЫМИ, А НЕ ЛОМАНИЕМ ИСХОДНИКА. Строки ниже взяты
 * не из головы: это формы, которые правда лежат в базе владельца (счёт снят до
 * правки, он в шапке `lib/delivery-words.ts`). В том числе те три, на которых
 * ошибиться проще всего: `PAUSED` + `WITH_ISSUES` (201 строка — выключено И с
 * проблемой, это два факта), кампания без единого поля о доставке (1050 из 1050
 * — «не знаем», а не «выключено») и объявление, до которого сбор не дошёл (2189
 * из 4048, больше половины парка).
 */
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { CampRow } from "@/components/views/CampaignsView";
import { колонки, CAMP_DEFAULT_VISIBLE } from "@/lib/campaigns-columns";
import { подготовить } from "@/lib/campaigns-funnel";
import {
  СЛОВАРЬ_МЕТЫ, СЛОВО_УРОВНЯ, гдеПричина, доставка, кодСловами, откудаСостояние,
  type Вердикт,
} from "@/lib/delivery-words";
import { неДоставляется } from "@/lib/campaigns-tree";
import type { CampaignRow, Level } from "@/lib/campaigns";

const КОРЕНЬ = path.resolve(__dirname, "..", "..", "..");
const читать = (...ч: string[]) => readFileSync(path.join(КОРЕНЬ, ...ч), "utf8");

const УРОВНИ: Level[] = ["campaign", "adset", "ad"];

/** Строка листа. Умышленно без значений по умолчанию у `status`,
 *  `effective_status` и `active_ads`: именно их отсутствие и есть самое частое
 *  состояние живой базы, и подставить туда «нормальное» значит проверять свою
 *  картину мира вместо продукта. */
const строка = (p: Partial<CampaignRow> & { level: Level }): CampaignRow => ({
  fb_id: "1", parent_id: null, act_id: "act_1", name: "MB3 · 04", status: null, ...p,
});

/* ── 1. Словарь не отстаёт от кода ──────────────────────────────────────── */

describe("словарь покрывает все значения Меты, какие продукт уже знает", () => {
  /** Значения `effective_status`, ВЫВЕДЕННЫЕ из настоящих файлов.
   *
   *  Три источника, потому что знание про эти коды в продукте живёт в трёх
   *  местах и разъезжается именно между ними: движок выводит по ним состояние
   *  родителя, отчёт по ним фильтрует запрос к Мете, панель их рисует. Список,
   *  переписанный сюда четвёртой копией, разъехался бы со всеми тремя. */
  function изКода(): Set<string> {
    const коды = new Set<string>();

    /* Движок: чем объявление отвечает про КАЖДЫЙ уровень над собой. Срез по
       якорям, а не весь файл: в файле полно других прописных слов. Начало
       блока проверяется отдельно — переименуют словарь, `indexOf` вернёт -1,
       срез станет всем файлом и тест начнёт находить что угодно. */
    const движок = читать("core", "campaigns.py");
    const от = движок.indexOf("О_КАМПАНИИ = {");
    const до = движок.indexOf("class Отказ", от);
    expect(от).toBeGreaterThan(0);
    expect(до).toBeGreaterThan(от);
    for (const m of движок.slice(от, до).matchAll(/"([A-Z][A-Z_]{2,})"/g)) коды.add(m[1]);

    /* Отчёт по отклонённым: чем он спрашивает у Меты. Эти коды приходят от неё
       живьём, а значит обязаны иметь человеческое имя. */
    const отчёт = читать("core", "stats.py");
    for (const m of отчёт.matchAll(/"effective_status":\s*'\[([^\]]+)\]'/g)) {
      for (const s of m[1].matchAll(/"([A-Z][A-Z_]{2,})"/g)) коды.add(s[1]);
    }

    /* Панель: что она уже умеет подписывать в дереве. Тот самый закрытый
       список, который этот модуль и заменяет, — но пока он жив, разойтись с
       ним нельзя: одна и та же строка получила бы два разных имени. */
    const аналитика = читать("panel", "lib", "analytics.ts");
    const н = аналитика.indexOf("export const STATUS_LABEL");
    const к = аналитика.indexOf("};", н);
    expect(н).toBeGreaterThan(0);
    expect(к).toBeGreaterThan(н);
    for (const m of аналитика.slice(н, к).matchAll(/^\s*([A-Z][A-Z_]{2,}):/gm)) коды.add(m[1]);

    return коды;
  }

  const коды = изКода();

  it("вывод правда что-то нашёл, а не прошёл вхолостую", () => {
    /* Без этой проверки любая правка якорей делала бы весь блок зелёным
       навсегда: пустое множество покрывается любым словарём. Порог не «больше
       нуля», а по числу мест — источников три, и каждый обязан дать своё. */
    expect(коды.size).toBeGreaterThanOrEqual(8);
    /* И ровно тот код, из-за которого писался иссус, обязан быть в выводе:
       если разъедется он, вхолостую пройдёт именно та проверка, ради которой
       всё это здесь. */
    expect(коды.has("ADSET_PAUSED")).toBe(true);
  });

  it("каждому коду из кода продукта есть человеческое имя", () => {
    const без = [...коды].filter((к) => !(к in СЛОВАРЬ_МЕТЫ));
    expect(без).toEqual([]);
  });

  it("сами имена — не пересказ кода Меты обратно", () => {
    /* Подпись `adset paused` для `ADSET_PAUSED` была бы работой, сделанной
       вхолостую: человек ровно этого и не понял. Требуем, чтобы подпись
       отличалась от машинного слова хотя бы у тех, где машинное слово не
       является английской фразой само по себе. */
    for (const [код, з] of Object.entries(СЛОВАРЬ_МЕТЫ)) {
      expect(з.подпись.length).toBeGreaterThan(0);
      if (код.includes("_")) expect(з.подпись).not.toBe(кодСловами(код));
    }
  });
});

/* ── 2. Ответ целиком, а не на три вопроса из четырёх ───────────────────── */

describe("на все четыре вопроса есть ответ, и он не пустой", () => {
  /* Набор строк ВЫВОДИТСЯ из словаря, а не перечисляется: заведут завтра
     тринадцатый код — он проверится сам. Перечисленный руками список знает
     только то, что кто-то вспомнил. */
  const все = Object.keys(СЛОВАРЬ_МЕТЫ).flatMap((код) =>
    УРОВНИ.map((level) => ({ код, level,
                             r: строка({ level, status: "ACTIVE", effective_status: код }) })));

  it("каждый код на каждом уровне даёт подпись, фразу, слово Меты и место причины", () => {
    expect(все.length).toBeGreaterThanOrEqual(30);
    for (const { код, level, r } of все) {
      const д = доставка(r);
      expect(д.подпись, код).not.toBe("");
      /* Фраза — предложение, а не ярлык: она отвечает на «почему» и на «что
         делать», и в одно слово это не помещается. */
      expect(д.почему.length, код).toBeGreaterThan(40);
      expect(д.код, код).toBe(код);
      expect(д.словами, код).toBe(кодСловами(код));
      expect(д.известен, код).toBe(true);
      /* Место причины обязано превращаться во ФРАЗУ, а не в термин: ключ
         типа (`self`, `adset`) на экране был бы вторым `derived`. */
      const где = гдеПричина(д.причина, level);
      expect(где, код).not.toContain("_");
      expect(где.split(" ").length, код).toBeGreaterThan(2);
    }
  });

  it("слово Меты сохранено дословно — по нему человек и сверяется", () => {
    /* Единственный мостик между нашим экраном и Ads Manager. Потеряв его, мы
       заменим один непонятный ярлык другим, только своим. */
    const д = доставка(строка({ level: "ad", status: "ACTIVE",
                                effective_status: "ADSET_PAUSED" }));
    expect(д.код).toBe("ADSET_PAUSED");
    expect(д.словами).toBe("adset paused");
  });

  it("наших внутренних слов на экране не остаётся вовсе", () => {
    /* Проверяем ВЕСЬ вывод модуля разом, а не два бейджа: заменить `derived` и
       оставить `status_source` в подсказке — это ровно тот же дефект, только
       на строку ниже. */
    const наши = ["derived", "by parent", "status_source", "effective_status",
                  "active_ads"];
    const весь = [
      ...все.map(({ r }) => доставка(r)),
      доставка(строка({ level: "campaign", status: "ACTIVE", active_ads: 0 })),
      доставка(строка({ level: "campaign", status: "PAUSED" })),
      доставка(строка({ level: "ad" })),
    ].flatMap((д) => [д.подпись, д.почему]);
    const источники = [
      откудаСостояние(строка({ level: "campaign", status: "PAUSED",
                               status_source: "derived" })),
      откудаСостояние(строка({ level: "adset", status_source: "unknown" })),
    ].flatMap((о) => (о ? [о.подпись, о.почему] : []));

    expect(источники.length).toBe(4);
    for (const текст of [...весь, ...источники]) {
      for (const слово of наши) {
        expect(текст.toLowerCase(), текст).not.toContain(слово);
      }
    }
  });
});

/* ── 3. Родитель на месте: причину не убрали, а назвали ─────────────────── */

describe("«выключен родитель» осталось причиной, и теперь понятно какой", () => {
  it("объявление в выключенном адсете: не идёт, виноват адсет, тушить не здесь", () => {
    /* 317 таких строк в живой базе. Факт от Меты ПОСЛЕ записи, а не наше
       намерение: включить это объявление можно, Мета ответит двухсоткой, и
       состояние останется тем же. Фраза обязана сказать это прямо — иначе
       человек будет жать выключатель и считать, что сломана панель. */
    const д = доставка(строка({ level: "ad", status: "ACTIVE",
                                effective_status: "ADSET_PAUSED" }));
    expect(д.вердикт).toBe("not delivering");
    expect(д.причина).toBe("adset");
    expect(д.подпись).toBe("its ad set is off");
    expect(гдеПричина(д.причина, "ad")).toBe("in the ad set above it");
    expect(д.почему).toContain("ad set");
    expect(д.почему.toLowerCase()).toContain("switch the ad set on");
  });

  it("объявление в выключенной кампании называет КАМПАНИЮ, а не «родителя»", () => {
    /* 147 строк. Разница между адсетом и кампанией — это разные места, куда
       человек пойдёт нажимать; «parent» не называет ни одного из них. */
    const д = доставка(строка({ level: "ad", status: "ACTIVE",
                                effective_status: "CAMPAIGN_PAUSED" }));
    expect(д.причина).toBe("campaign");
    expect(д.подпись).toBe("its campaign is off");
    expect(д.почему).not.toContain("ad set");
  });

  it("тот же код на своём уровне — это про себя, а не про кого-то сверху", () => {
    /* Над кампанией нет ничего, и «выключено что-то сверху» на её строке было
       бы прямой ложью. Один код, два уровня — две разные новости. */
    expect(доставка(строка({ level: "campaign", status: "ACTIVE",
                             effective_status: "CAMPAIGN_PAUSED" })).причина).toBe("self");
    expect(доставка(строка({ level: "adset", status: "ACTIVE",
                             effective_status: "ADSET_PAUSED" })).причина).toBe("self");
    /* А `CAMPAIGN_PAUSED` у адсета — по-прежнему про родителя. */
    expect(доставка(строка({ level: "adset", status: "ACTIVE",
                             effective_status: "CAMPAIGN_PAUSED" })).причина).toBe("campaign");
  });

  it("«derived» стало фразой про то, ОТКУДА состояние, и факт сохранён", () => {
    /* Сам факт важный и остаётся: состояние кампании выведено из её объявлений,
       потому что собственного `status` у неё в базе нет (у всех 1050). Меняется
       только слово — и добавляется то, чего в бейдже не было: что переключатель
       при этом работает нормально. */
    const о = откудаСостояние(строка({ level: "campaign", status: "PAUSED",
                                       status_source: "derived" }));
    expect(о).not.toBeNull();
    expect(о!.подпись).toBe("read from its ads");
    expect(о!.почему).toContain("its ads");
    expect(о!.почему.toLowerCase()).toContain("switching still writes to meta");
  });

  it("состояние снято у Меты напрямую — говорить нечего, бейджа нет", () => {
    expect(откудаСостояние(строка({ level: "ad", status: "ACTIVE",
                                    status_source: "live" }))).toBeNull();
  });
});

/* ── 4. Отрицательный контроль: данными ─────────────────────────────────── */

describe("тихо назвать доставкой то, что не идёт, модуль не может", () => {
  it("НЕЗНАКОМЫЙ код Меты не выдаётся за понятый и не выдаётся за доставку", () => {
    /* Мета заводит значения молча. Послабление «чего не знаем — то пропускаем»
       превратило бы новое состояние в зелёную строку, и узнать об этом было бы
       неоткуда. Требуем обратного: вердикт не «идёт», слово Меты на экране,
       и прямо сказано, что объяснения у нас нет. */
    const д = доставка(строка({ level: "ad", status: "ACTIVE",
                                effective_status: "SOME_NEW_META_STATE" }));
    expect(д.вердикт).toBe("not delivering");
    expect(д.известен).toBe(false);
    expect(д.подпись).toBe("some new meta state");
    expect(д.почему).toContain("some new meta state");
    expect(д.почему.toLowerCase()).toContain("no plain-language explanation");
  });

  it("выключено И с проблемой — это ДВА факта, и второй не прячется", () => {
    /* 201 строка в живой базе: `status = PAUSED`, а Мета говорит `WITH_ISSUES`.
       Показать только «off» значило бы спрятать то, что вылезет ровно в ту
       секунду, когда человек нажмёт «включить». */
    const д = доставка(строка({ level: "ad", status: "PAUSED",
                                effective_status: "WITH_ISSUES" }));
    expect(д.вердикт).toBe("off");
    expect(д.код).toBe("WITH_ISSUES");
    expect(д.почему.toLowerCase()).toContain("switched back on");
    /* И то же самое с отклонением — таких 25. */
    expect(доставка(строка({ level: "ad", status: "PAUSED",
                             effective_status: "DISAPPROVED" })).почему.toLowerCase())
      .toContain("switched back on");
  });

  it("кампания без слова Меты и без живых объявлений — «не идёт», и причина ниже", () => {
    /* Единственный факт о доставке на верхних уровнях: `effective_status` там
       не проставлен НИ У ОДНОЙ строки (1050 кампаний, 3855 адсетов). Ноль
       живых объявлений при включённом переключателе и есть ответ на «включил, а
       не крутится», и причина у него не сверху и не в самой строке. */
    const д = доставка(строка({ level: "campaign", status: "ACTIVE", active_ads: 0 }));
    expect(д.вердикт).toBe("not delivering");
    expect(д.причина).toBe("below");
    expect(гдеПричина(д.причина, "campaign")).toBe("in what sits under this campaign");
    expect(д.код).toBeNull();
  });

  it("ноль живых и «не считали» — РАЗНЫЕ ответы, а не одинаковые", () => {
    /* `undefined` это не ноль. Записать несобранную кампанию в «не
        доставляется» значит утверждать непроверенное — и послать человека
        чинить исправное. */
    const д = доставка(строка({ level: "campaign", status: "ACTIVE" }));
    expect(д.вердикт).toBe("unknown");
    expect(д.подпись).toBe("not collected yet");
  });

  it("до строки не дошёл сбор — «не знаем», и это НЕ «выключено»", () => {
    /* 2189 объявлений из 4048, больше половины парка. «Off» здесь позвал бы
       включать то, что, возможно, и так работает. */
    const д = доставка(строка({ level: "ad" }));
    expect(д.вердикт).toBe("unknown");
    expect(д.вердикт).not.toBe("off");
    expect(д.почему.toLowerCase()).toContain("not");
  });

  it("выключено нами, и Мета молчит — это полный ответ, а не «не знаем»", () => {
    const д = доставка(строка({ level: "adset", status: "PAUSED" }));
    expect(д.вердикт).toBe("off");
    expect(д.подпись).toBe("off");
  });

  it("включено и объявления идут — «идёт», и число не потеряно", () => {
    const д = доставка(строка({ level: "campaign", status: "ACTIVE", active_ads: 3 }));
    expect(д.вердикт).toBe("delivering");
    expect(д.почему).toContain("3 ad(s)");
  });
});

/* ── 5. Две стороны одного фильтра обязаны сходиться ────────────────────── */

describe("вердикт и фильтр «not delivering» не разъезжаются", () => {
  /* Слова этого модуля видны РОВНО В ТОМ фильтре, который считает
     `неДоставляется` (`lib/campaigns-tree`). Файлы разные, правит их разный
     народ, и разъедутся они не в определении, а спустя правку в одном из двух.
     Разъезд при этом тихий: строка либо попадёт в фильтр с подписью «идёт»,
     либо получит объяснение, почему не идёт, и не попадёт туда вовсе.

     Набор строк ВЫВОДИТСЯ перебором, а не перечисляется: коды берутся из
     словаря, к ним добавляется незнакомый Мете и отсутствие кода вовсе. */
  const коды: (string | null)[] = [...Object.keys(СЛОВАРЬ_МЕТЫ), "SOME_NEW_META_STATE", null];
  const переключатели = ["ACTIVE", "PAUSED", null];
  const счёты: (number | undefined)[] = [undefined, 0, 3];

  const строки = коды.flatMap((код) =>
    переключатели.flatMap((status) =>
      счёты.flatMap((active_ads) =>
        УРОВНИ.map((level) =>
          строка({ level, status, effective_status: код, active_ads })))));

  it("перебор правда собрался", () => {
    expect(строки.length).toBe(коды.length * 3 * 3 * 3);
    expect(строки.length).toBeGreaterThanOrEqual(300);
  });

  it("ни одна строка не названа доставкой там, где фильтр считает её сломанной", () => {
    /* Самое опасное направление: зелёная подпись на строке, стоящей в списке
       «не доставляется». Такому человек верит и проверять не идёт. */
    const врут = строки.filter((r) => доставка(r).вердикт === "delivering" && неДоставляется(r));
    expect(врут).toEqual([]);
  });

  it("«не доставляется» у включённой строки означает, что она в этом фильтре и есть", () => {
    /* Обратное направление, и оно тоже дефект: объяснение, почему не идёт,
       написанное для строки, которую в списке «не доставляется» человек не
       увидит никогда. */
    const мимо = строки.filter(
      (r) => (r.status || "").toUpperCase() === "ACTIVE"
        && доставка(r).вердикт === "not delivering" && !неДоставляется(r));
    expect(мимо).toEqual([]);
  });

  it("у каждой строки перебора вердикт из четырёх и непустая подпись", () => {
    const можно: Вердикт[] = ["delivering", "off", "not delivering", "unknown"];
    for (const r of строки) {
      const д = доставка(r);
      expect(можно).toContain(д.вердикт);
      expect(д.подпись).not.toBe("");
      expect(д.почему).not.toBe("");
      /* И уровень назван человеческим словом, а не ключом типа. */
      if (r.level === "adset") expect(СЛОВО_УРОВНЯ[r.level]).toBe("ad set");
    }
  });
});

/* ── СЛОВА ДОЕХАЛИ ДО ЭКРАНА ───────────────────────────────────────────────
 *
 * ЗАЧЕМ ЭТОТ БЛОК И ПОЧЕМУ ОН ЗДЕСЬ САМЫЙ ВАЖНЫЙ. Всё, что выше, проверяет
 * МОДУЛЬ, и всё это было зелёным ровно тогда, когда владелец видел на проде
 * «by parent» 61 раз на одном экране, а на строках 18-часовой давности —
 * слипшееся «activederived». Модуль был написан, покрыт тестами и НЕ ВЫЗВАН
 * НИ ОТКУДА: единственным его читателем был этот же файл.
 *
 * Это ровно та порода, что уже стоила нам вердикта о сборе: компонент работал
 * и стоял не везде. Проверка «функция возвращает правильную строку» на неё
 * слепа by design — она не знает, дошла ли строка до разметки.
 *
 * Поэтому здесь рисуется НАСТОЯЩАЯ строка листа (`CampRow` от голых пропсов,
 * как в смотрелке) и проверяется HTML: наших слов в нём нет, человеческие есть,
 * слово Меты не потеряно. Тест переживёт и переименование модуля, и вынос
 * бейджа в отдельный компонент — он смотрит на экран, а не на устройство.
 */
describe("человеческие слова видны в разметке строки, а не только в модуле", () => {
  const КОЛОНКИ = { метрики: колонки(CAMP_DEFAULT_VISIBLE), ctx: подготовить(null) };

  /** Одна строка листа в статическом HTML — так же, как её собирает смотрелка. */
  const html = (r: CampaignRow): string =>
    renderToStaticMarkup(createElement(CampRow, {
      item: { node: { row: r, children: [] }, depth: 0, hasKids: false, open: false },
      now: Date.parse("2026-08-15T12:00:00Z"),
      pending: {},
      колонки: КОЛОНКИ,
      onToggle: () => {},
      onSwitch: () => {},
    }));

  it("объявление в выключенном адсете НЕ говорит «by parent»", () => {
    /* 317 таких строк на живой базе — из них и набирается 61 бейдж на экране. */
    const h = html(строка({ level: "ad", status: "ACTIVE",
                            effective_status: "ADSET_PAUSED", owner: "k1f9qbcs" }));
    expect(h).not.toContain("by parent");
    expect(h).toContain("its ad set is off");
    /* И слово Меты не потеряно: по нему человек сверяется с Ads Manager. */
    expect(h).toContain("adset paused");
    /* А куда идти — сказано прямо, иначе бейдж только сообщает о наличии беды. */
    expect(h).toContain("Switch the ad set on instead");
  });

  it("объявление в выключенной кампании называет кампанию, а не «родителя»", () => {
    const h = html(строка({ level: "ad", status: "ACTIVE",
                            effective_status: "CAMPAIGN_PAUSED", owner: "k1f9qbcs" }));
    expect(h).not.toContain("by parent");
    expect(h).toContain("its campaign is off");
  });

  it("выведенное состояние НЕ говорит «derived»", () => {
    /* Второе слово из жалобы владельца. На проде оно склеивалось с подписью
       статуса в «activederived» — то есть человек видел даже не термин, а
       мусор. */
    const h = html(строка({ level: "campaign", status: "ACTIVE",
                            status_source: "derived", active_ads: 2,
                            owner: "k1f9qbcs" }));
    expect(h).not.toContain("derived");
    expect(h).toContain("read from its ads");
  });

  it("отклонённое объявление говорит словами, а не машинным кодом", () => {
    const h = html(строка({ level: "ad", status: "ACTIVE",
                            effective_status: "DISAPPROVED", owner: "k1f9qbcs" }));
    expect(h).toContain("rejected by Meta");
    expect(h).toContain("disapproved");
  });

  it("исправная строка бейджей НЕ получает — охват не расширился", () => {
    /* Отрицательный контроль, и он тут обязателен. Пометить лишнее дороже, чем
       промолчать: бейдж на каждой второй строке перестают читать вместе с теми,
       что про дело. Иссус был про СЛОВА, а не про то, где показывать. */
    const h = html(строка({ level: "ad", status: "ACTIVE",
                            effective_status: "ACTIVE", owner: "k1f9qbcs" }));
    for (const слово of ["its ad set is off", "its campaign is off",
                         "rejected by Meta", "read from its ads", "by parent", "derived"]) {
      expect(h, слово).not.toContain(слово);
    }
  });

  it("вьюха не собирает эти фразы сама — они приходят из модуля", () => {
    /* Иначе завтра рядом появится второй набор слов, и разъедутся они молча:
       у бейджа и подсказки один смысл, но разные авторы. */
    const вьюха = readFileSync(
      path.resolve(__dirname, "..", "..", "components", "views", "CampaignsView.tsx"), "utf8");
    const код = вьюха.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
    expect(код).toContain("доставка(r)");
    expect(код).toContain("откудаСостояние(r)");
    expect(код).toContain("подсказка(");
    /* И ни одного из прежних слов в самом коде разметки. */
    expect(код).not.toContain("by parent");
    expect(код).not.toContain("derived,");
    expect(код).not.toMatch(/>\s*derived\s*</);
  });
});
