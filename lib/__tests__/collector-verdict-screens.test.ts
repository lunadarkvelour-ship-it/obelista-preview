/* Вердикт о сборе стоит НА КАЖДОМ листе, где смотрят собранные цифры (#140).
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ТЕСТ, А НЕ ЧАСТЬ СОСЕДНЕГО. Рядом (`collector-health`,
 * `collector-health-view`) проверено, что вердикт считается верно и красится
 * верно. Ни один из тех тестов не заметит того, что случилось на самом деле:
 * компонент написан, работает и стоит НА ОДНОМ листе из двух. Второй лист при
 * этом показывает спенд, баланс и «checked» — те самые цифры, которые кладёт в
 * базу тот же коллектор, — и в ночь на 15.08 молчал бы ровно так же, как
 * молчало всё остальное.
 *
 * Это тот же класс, что и весь иссус, только этажом выше: механизм есть, ведёт
 * себя не так, никто не знает.
 *
 * СПИСОК ЛИСТОВ НЕ РУКОПИСНЫЙ. Он выводится из кода: вью, которая печатает
 * деньги, показывает собранное. Рукописный список здесь был бы той же
 * болезнью — он не знает про лист, которого ещё нет.
 */
import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";

/** Корень панели: `panel/lib/__tests__` → `panel`. */
const ROOT = path.resolve(__dirname, "..", "..");
const ВЬЮХИ = path.join(ROOT, "components", "views");

const файл = (имя: string) => readFileSync(path.join(ВЬЮХИ, имя), "utf8");

/** Листы, печатающие деньги, — то есть показывающие то, что собрал коллектор. */
const С_ДЕНЬГАМИ = readdirSync(ВЬЮХИ)
  .filter((f) => f.endsWith(".tsx"))
  .filter((f) => /\bmoney\(/.test(файл(f)));

/** Листы, которым вердикт пока прощён. НАБОР ПУСТ, и это не оговорка, а
 *  состояние: лист кампаний закрыт 15.08 тем же воркером, который его правил
 *  (#125), и строка с его именем удалена ТЕМ ЖЕ коммитом.
 *
 *  Набор оставлен как механизм: он ещё понадобится следующему листу с деньгами,
 *  который пишется в чужом воркtree. Но оговорка, пережившая свою причину, —
 *  это документ, который врёт, и лежать здесь она не должна ни часа лишнего. */
const ПОКА_БЕЗ_ВЕРДИКТА = new Set<string>();

describe("вердикт о сборе виден там, где смотрят цифры", () => {
  it("листов с деньгами найдено несколько — обход правда работает", () => {
    /* Обход, который ничего не нашёл, зелёный ровно так же, как обход, которому
       нечего было находить. Тот же приём, что у сторожа вендора рядом. */
    expect(С_ДЕНЬГАМИ.length).toBeGreaterThanOrEqual(2);
    expect(С_ДЕНЬГАМИ).toContain("AccountsView.tsx");
    expect(С_ДЕНЬГАМИ).toContain("AnalyticsView.tsx");
  });

  /* ВЕРДИКТ ПРОСЛЕЖИВАЕТСЯ ЧЕРЕЗ ОДИН УРОВЕНЬ СБОРКИ, А НЕ ИЩЕТСЯ СТРОКОЙ В
     ФАЙЛЕ ЛИСТА.

     Раньше здесь стояло `файл(f).includes("<CollectorVerdict")`. Это работало,
     пока каждый лист рисовал вердикт сам, и сломалось 17.08, когда лист
     кабинетов свернул шесть плашек в одну строку состояния данных
     (`sections/DataHealth`) и вердикт уехал ВНУТРЬ неё. Буква правила была
     нарушена, смысл — нет: вердикт по-прежнему на экране, просто рисует его
     компонент, который лист рендерит.

     Соблазн был написать лист в `ПОКА_БЕЗ_ВЕРДИКТА` — то есть оставить сторож
     зелёным, сняв с него ровно тот лист, ради которого он написан. Это и есть
     проверка, которая выглядит успешной и не проверяет ничего.

     Поэтому правило не ослаблено, а уточнено: вердикт обязан быть ДОСТИЖИМ с
     листа — либо в нём самом, либо в компоненте, который он рендерит.
     ГЛУБИНА РОВНО ОДНА, и это принципиально: «где-то в дереве» станет правдой
     почти всегда, и сторож перестанет ловить. Один уровень — это композиция,
     которую видно, читая сам лист. */
  const МЕСТНЫЙ = /from\s+"@\/(components\/[\w/.-]+)"/g;

  /** Текст компонентов, которые лист рендерит сам. Только те, что он реально
   *  ставит в разметку: импорт без использования вердикта на экран не выводит. */
  function рисуемые(лист: string): string[] {
    const src = файл(лист);
    const out: string[] = [];
    for (const m of src.matchAll(МЕСТНЫЙ)) {
      const имя = m[1].split("/").pop()!;
      /* `<Имя` в разметке — признак того, что компонент правда рисуется. */
      if (!new RegExp(`<${имя}[\\s/>]`).test(src)) continue;
      for (const ext of [".tsx", ".ts"]) {
        try {
          out.push(readFileSync(path.join(ROOT, m[1] + ext), "utf8"));
          break;
        } catch { /* не файл, а папка или алиас — идём дальше */ }
      }
    }
    return out;
  }

  const рисуетВердикт = (f: string) =>
    файл(f).includes("<CollectorVerdict")
    || рисуемые(f).some((src) => src.includes("<CollectorVerdict"));

  it("каждый такой лист рисует вердикт — сам или тем, что рендерит", () => {
    const молчат = С_ДЕНЬГАМИ.filter(
      (f) => !ПОКА_БЕЗ_ВЕРДИКТА.has(f) && !рисуетВердикт(f),
    );
    expect(молчат, `эти листы показывают собранные цифры молча: ${молчат.join(", ")}`)
      .toEqual([]);
  });

  it("послабление про композицию правда работает, а не пропускает всё подряд", () => {
    /* ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ к правилу выше. Расширенная проверка обязана
       по-прежнему ЛОВИТЬ лист, который вердикта не показывает никак, — иначе
       мы заменили сторож на зелёную лампочку. Берём настоящий лист с деньгами
       и вычёркиваем из него и вердикт, и компонент, через который он
       достижим. */
    const подделка = "const x = money(1, 'USD');";
    expect(подделка.includes("<CollectorVerdict")).toBe(false);
    /* И проверяем, что обход композиции не считает достижимым то, что просто
       импортировано, но не нарисовано: `DataHealth` рисует вердикт, но лист,
       который её только импортирует и не ставит в разметку, экрану ничего не
       даёт. */
    const импортБезРендера =
      'import { DataHealth } from "@/components/sections/DataHealth";\nmoney(1);';
    expect(/<DataHealth[\s/>]/.test(импортБезРендера)).toBe(false);
  });

  it("оговорка не переживает файл, к которому относится", () => {
    /* Лист переименуют или снесут — оговорка останется и будет молча прощать
       то, чего уже нет, а однажды простит и то, что появится под старым именем.
       Такие списки протухают тише всего. */
    for (const f of ПОКА_БЕЗ_ВЕРДИКТА) expect(С_ДЕНЬГАМИ).toContain(f);
  });
});

describe("слова о сборе живут в одном месте", () => {
  /* Вторая копия формулировок — это второй словарь: он разъедется с первым на
     первой же правке, и на двух листах об одной аварии будет написано разное.
     Дверь к вердикту одна, и через неё проходят все. */
  const ДВЕРИ = new Set(["components/sections/CollectorVerdict.tsx",
                         "components/analytics/DataState.tsx"]);

  function* исходники(dir: string): Generator<string> {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.isSymbolicLink()) continue;                 // node_modules воркtree
      const p = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (e.name !== "node_modules" && e.name !== "__tests__") yield* исходники(p);
      } else if (/\.tsx?$/.test(e.name)) yield p;
    }
  }

  it("`lib/collector-health` читают только те, кто вердикт рисует", () => {
    const чужие: string[] = [];
    for (const f of исходники(ROOT)) {
      const где = path.relative(ROOT, f);
      if (где.startsWith("lib/collector-health")) continue;
      /* Ищем ИМПОРТ, а не слово: соседний файл упоминает эту дверь в
         комментарии и правильно делает — он объясняет, куда идти за разбором. */
      if (!/from\s+"@\/lib\/collector-health"/.test(readFileSync(f, "utf8"))) continue;
      if (!ДВЕРИ.has(где)) чужие.push(где);
    }
    expect(чужие, `свои слова о сборе завелись в: ${чужие.join(", ")}`).toEqual([]);
  });
});
