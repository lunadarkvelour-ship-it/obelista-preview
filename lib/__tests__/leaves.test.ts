/* Каждый пункт меню ведёт на существующий лист, и наоборот.
 *
 *  Зачем этот тест. Пункты меню и сами листы делались разными PR, и файл меню
 *  на время был занят одним из них — поэтому листы приземлялись в `main` без
 *  входа мышью. Обратная ошибка опаснее: пункт на невлитый лист даёт ссылку в
 *  никуда, и это не «мелкая недоделка», а панель, которая врёт про то, что у
 *  неё есть.
 *
 *  Проверяем по файловой системе, а не по списку в голове: список в голове —
 *  ровно то, что уже разошлось.
 */
import { existsSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { LEAVES } from "@/components/shell/leaves";

const APP = path.resolve(__dirname, "../../app");

describe("меню и листы не расходятся", () => {
  it("у каждого пункта меню есть страница", () => {
    for (const l of LEAVES) {
      const page = path.join(APP, l.href.replace(/^\//, ""), "page.tsx");
      expect(existsSync(page), `${l.href} → ${page}`).toBe(true);
    }
  });

  it("адреса начинаются со слеша и не повторяются", () => {
    const hrefs = LEAVES.map((l) => l.href);
    for (const h of hrefs) expect(h.startsWith("/")).toBe(true);
    expect(new Set(hrefs).size).toBe(hrefs.length);
  });

  it("у каждого пункта есть подпись и подсказка", () => {
    // Подсказка — не украшение: по ней человек понимает, чем лист отличается
    // от соседнего, не открывая его.
    for (const l of LEAVES) {
      expect(l.label.trim().length).toBeGreaterThan(0);
      expect(l.hint.trim().length).toBeGreaterThan(0);
    }
  });

  it("шаги пути залива в меню НЕ попадают", () => {
    // Решение, записанное в шапке `leaves.ts`: в навигацию идут самостоятельные
    // места, а не шаги одного пути. Войти в середину процесса, где ещё нечего
    // настраивать, разрешать нельзя.
    const hrefs = LEAVES.map((l) => l.href);
    for (const step of ["/upload", "/preview", "/launch"]) {
      expect(hrefs).not.toContain(step);
    }
  });

  it("снесённый лист «Agencies» не достижим ни меню, ни адресом", () => {
    // Прямое требование владельца 14.08.2026 — лист убран целиком.
    //
    // Проверок ДВЕ, и вторая важнее первой: в Next маршрут существует, пока
    // существует каталог, поэтому «пункта в меню нет» ещё не значит «страницы
    // нет». Зеркальную ошибку — лист есть, пункта нет — этот файл уже ловил
    // на /rules, только там она была недоделкой, а здесь была бы возвратом
    // снесённого. Возврат копипастой строки LEAVES ловится тоже: страницы под
    // неё больше нет, а пункт в никуда запрещает первый тест этого файла.
    expect(LEAVES.map((l) => l.href)).not.toContain("/agencies");
    expect(existsSync(path.join(APP, "agencies"))).toBe(false);
  });

  it("автоправила — пункт меню, не только прямой адрес", () => {
    // Лист /rules приземлился в main без входа мышью (#52): leaves.ts был
    // занят другой работой. Прошлая версия этого файла проверяла только
    // «меню → лист», и удаление строки /rules из LEAVES её не роняло —
    // тест проходил и с забытым пунктом. Прямое утверждение не даёт
    // повториться: у автоправил обязан быть вход, а не только прямой адрес.
    const hrefs = LEAVES.map((l) => l.href);
    expect(hrefs).toContain("/rules");
  });
});
