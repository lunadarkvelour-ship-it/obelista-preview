/**
 * Спарклайн подневного спенда: ряд из лидерборда → геометрия картинки.
 *
 * Ряд считает движок (`core/leaderboard.py`, функция `_spark`) и кладёт в
 * строку полями `days` и `days_bucket_days`. Здесь только пересчёт в точки —
 * рисование живёт в компоненте, ровно как у тепловой шкалы в `heat.ts`.
 *
 * Пикселей здесь нет ни одного, и это не мелочь: картинка растягивается по
 * ячейке (`preserveAspectRatio="none"`), а ширину колонки юзер тянет ползунком
 * и меняет на узком экране. Своя ширина у ряда означала бы обрезанный хвост —
 * тот самый конец, ради которого на спарклайн и смотрят.
 */

/** Точка ряда как её отдаёт демон. `date` — ПЕРВЫЙ день корзины. */
export interface SparkPoint {
  date: string;
  spend: number;
}

/* Система координат картинки. Числа условные — см. шапку. */
export const VB_W = 100;
export const VB_H = 24;

/* Поле сверху и снизу. Линия имеет толщину, и точка на самом пике без запаса
   обрезалась бы по краю картинки ровно наполовину — пик читался бы как полка. */
const PAD = 1.5;

/** Куда идёт ряд. Считается по наклону, а не по «последняя точка выше первой»:
 *  один выброс в хвосте не должен объявлять тренд. */
export type Trend = "up" | "down" | "flat";

export interface Spark {
  /** `points` для <polyline> — сама форма. */
  line: string;
  /** `d` для <path>: та же форма, замкнутая по нулю. Заливка нужна потому, что
   *  волосяная линия под цифрой в строке таблицы не читается: глаз ловит пятно,
   *  а не однопиксельный след. */
  area: string;
  /** Дней в одной точке. Больше единицы — окно длинное и схлопнуто корзинами;
   *  это надо сказать юзеру, иначе он прочтёт точку как день. */
  bucket: number;
  /** Пик ряда В СПЕНДЕ ЗА ДЕНЬ (не сумма корзины) — подпись к подсказке. */
  peak: number;
  /** Y нулевой линии в системе координат картинки. Компонент рисует по ней
   *  волосяную базу: без неё горка висит в воздухе, и «просело до нуля» не
   *  отличается от «просело вдвое». */
  base: number;
  /** Направление ряда — им красится линия. */
  trend: Trend;
  /** Ряд нарисован по ОБЩЕЙ шкале среза, а не по своему максимуму. Нужно
   *  подсказке: на общей шкале низкая горка значит «мало тратит», а на своей
   *  значила бы только «ровно». Две разные фразы. */
  shared: boolean;
}

/** Дата → номер дня. UTC, потому что сравниваются только даты между собой:
 *  местная полночь утащила бы разницу на ±1 день в зависимости от зоны. */
function day(iso: string): number | null {
  const t = Date.parse(iso + "T00:00:00Z");
  return Number.isFinite(t) ? Math.round(t / 86_400_000) : null;
}

/** Сколько дней покрывает каждая корзина.
 *
 *  Считается по соседним датам, а НЕ берётся равным `bucket` — и это главное,
 *  что здесь есть. Последняя корзина окна почти всегда короче: окно редко
 *  делится на размер корзины нацело, и движок отдаёт хвост как есть. Сумма за
 *  один день против сумм за три рисует обрыв в пол на ровном месте — спарклайн
 *  соврал бы именно там, куда смотрят в первую очередь.
 */
function spans(points: SparkPoint[], bucket: number, until: string): number[] {
  const days = points.map((p) => day(p.date));
  const end = day(until);
  return days.map((d, i) => {
    const next = i + 1 < days.length ? days[i + 1] : end === null ? null : end + 1;
    if (d === null || next === null) return bucket;
    // Кривая дата в ряду не должна давать деление на ноль или отрицательную
    // длину: непрочитанная корзина считается полной, а не пустой.
    return Math.min(bucket, Math.max(1, next - d));
  });
}

function isNum(v: unknown): v is number {
  return typeof v === "number" && Number.isFinite(v);
}

const round = (v: number) => Math.round(v * 100) / 100;

/**
 * Ряд → точки картинки. `null` значит «рисовать нечего», и это не ошибка.
 *
 * @param until последний день окна — из ответа демона, для длины хвоста.
 * @param scaleTop общий потолок шкалы на весь срез. Без него каждая строка
 *   нормируется в саму себя, и крео на $600 рисует ровно такую же горку, что
 *   крео на $70: форма врёт о масштабе, а столбец из таких горок не сравнить
 *   между собой вообще никак. С общим потолком высота значит деньги.
 */
export function makeSpark(
  points: SparkPoint[] | null | undefined,
  bucketDays: number | null | undefined,
  until: string,
  scaleTop?: number | null,
): Spark | null {
  const bucket = isNum(bucketDays) && bucketDays >= 1 ? Math.floor(bucketDays) : 1;
  const pts = (points ?? []).filter((p) => p && isNum(p.spend));

  /* Одна точка — это не ряд. Растянутая на всю ячейку полоска прочиталась бы
     как «всё окно ровно столько», хотя окно длиной в сутки и сравнивать не с
     чем. Пусто честнее. Пустой ряд (непривязанная воронка — там спенд не ноль,
     а неизвестен) сюда же. */
  if (pts.length < 2) return null;

  const len = spans(pts, bucket, until);
  /* Спенд В ДЕНЬ, а не сумма корзины: только так точки сравнимы между собой,
     когда корзины разной длины. При bucket = 1 это те же исходные числа. */
  const vals = pts.map((p, i) => p.spend / len[i]);

  const top = Math.max(...vals);
  /* Пол — ноль, а не минимум ряда. Спенд это величина, у которой ноль на своём
     месте: шкала от минимума превратила бы разницу в доллар между тремя днями
     в размах во всю высоту, и ровный расход выглядел бы качелями.
     Минус в дневном приросте бывает (Мета пересчитывает задним числом) — тогда
     пол уезжает под ноль, иначе провал ушёл бы за край картинки. */
  const floor = Math.min(0, ...vals);
  // Ряд из одних нулей: масштабировать не по чему, а линия по полу читалась бы
  // как «крутилось и не тратило».
  if (top <= floor) return null;

  /* Потолок шкалы. Общий, если срез его дал и он не ниже собственного пика
     строки: занизить потолок значит обрезать горку по краю картинки. */
  const shared = isNum(scaleTop) && scaleTop > floor && scaleTop >= top;
  const ceil = shared ? (scaleTop as number) : top;

  const dx = VB_W / (pts.length - 1);
  const y = (v: number) => round(PAD + (VB_H - 2 * PAD) * (1 - (v - floor) / (ceil - floor)));
  const xs = pts.map((_, i) => round(i * dx));
  const ys = vals.map(y);
  const base = y(0);

  return {
    line: xs.map((x, i) => `${x},${ys[i]}`).join(" "),
    area:
      `M${xs[0]},${base} ` +
      xs.map((x, i) => `L${x},${ys[i]}`).join(" ") +
      ` L${xs[xs.length - 1]},${base} Z`,
    bucket,
    peak: top,
    base,
    trend: trendOf(vals),
    shared,
  };
}

/** Направление ряда: медиана первой половины против медианы второй.
 *
 *  Не «последняя точка против первой» и не наименьшие квадраты. Обе эти меры
 *  ловятся на один хвостовой выброс, а он тут обычное дело: Мета досчитывает
 *  день задним числом, и последняя точка регулярно подскакивает. Замерено на
 *  ряде [100, 98, 96, 94, 92, 130] — по наименьшим квадратам он объявляется
 *  растущим, хотя пять дней подряд падал.
 *
 *  Медианы половин к такому выбросу равнодушны и при этом объясняются одной
 *  фразой: «во второй половине окна тратили больше, чем в первой».
 *
 *  Порог 8% от среднего уровня. Ниже — дневная рябь, и красить такую строку в
 *  «разгоняется» значит выдавать шум за сигнал. По этому цвету собираются
 *  тушить.
 */
function trendOf(vals: number[]): Trend {
  const n = vals.length;
  const avg = vals.reduce((a, b) => a + b, 0) / n;
  if (!(avg > 0)) return "flat";

  const half = Math.floor(n / 2);
  if (half < 1) return "flat";
  // При нечётной длине середина не идёт ни в одну половину: она принадлежит
  // обеим одинаково и только размывает разницу.
  const движение = (median(vals.slice(n - half)) - median(vals.slice(0, half))) / avg;
  if (движение > 0.08) return "up";
  if (движение < -0.08) return "down";
  return "flat";
}

function median(xs: number[]): number {
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

/** Общий потолок шкалы на срез: максимум СУТОЧНОГО расхода среди всех рядов.
 *
 *  Считается по тем же правилам, что и внутри `makeSpark` (сумма корзины делится
 *  на её реальную длину), иначе общая шкала разъедется с собственной. */
export function sparkCeiling(
  rows: Array<{ days?: SparkPoint[] | null; days_bucket_days?: number | null }>,
  until: string,
): number | null {
  let top = 0;
  for (const r of rows) {
    const pts = (r.days ?? []).filter((p) => p && isNum(p.spend));
    if (pts.length < 2) continue;
    const bucket =
      isNum(r.days_bucket_days) && r.days_bucket_days >= 1 ? Math.floor(r.days_bucket_days) : 1;
    const len = spans(pts, bucket, until);
    for (let i = 0; i < pts.length; i++) top = Math.max(top, pts[i].spend / len[i]);
  }
  return top > 0 ? top : null;
}
