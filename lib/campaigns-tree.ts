/* Плоские строки трёх уровней → дерево, и состояние незавершённых записей.
 *
 * ПОЧЕМУ ДЕРЕВО СОБИРАЕТСЯ ЗДЕСЬ, А НЕ В КОМПОНЕНТЕ. Оно нужно двум разным
 * вещам: разметке и ответу на вопрос «что сейчас в работе». Собранное внутри
 * компонента, оно пересобиралось бы на каждое нажатие и увозило бы с собой
 * состояние отправки — то есть спиннер прыгал бы на соседнюю строку, стоило
 * прийти свежему ответу базы. Дерево — данные, а не разметка.
 *
 * ЗАПИСЬ ОПТИМИСТИЧНА, НО НЕ ЛЖИВА. Нажали «выключить» — строка немедленно
 * показывает «выключаю», а НЕ «выключено»: между нажатием и ответом Меты живёт
 * секунда-другая, и нарисовать в ней конечное состояние значит соврать про
 * чужую рекламу. Ответ пришёл — берём статус ИЗ НЕГО. Ответ не пришёл — строка
 * возвращается к тому, что в базе, и рядом встаёт текст ошибки как есть.
 */
import type { CampaignRow, Level, WriteResult } from "./campaigns";

export interface CampNode {
  row: CampaignRow;
  children: CampNode[];
}

/** Сирота — строка, чей родитель в ответе не пришёл.
 *
 *  Так бывает честно: кампанию завели не мы, объявление залито мимо движка,
 *  обзор дошёл до объявления и не дошёл до адсета. Прятать такую строку нельзя
 *  — по ней идут деньги, — но и врать про родителя тоже. Поэтому сироты
 *  поднимаются на верхний уровень своим уровнем, а не подшиваются к первому
 *  попавшемуся. */
export function buildTree(rows: CampaignRow[]): CampNode[] {
  const byId = new Map<string, CampNode>();
  for (const r of rows) byId.set(r.fb_id, { row: r, children: [] });

  const roots: CampNode[] = [];
  for (const n of byId.values()) {
    const p = n.row.parent_id ? byId.get(n.row.parent_id) : undefined;
    if (p && p !== n) p.children.push(n);
    else roots.push(n);
  }

  const порядок: Record<Level, number> = { campaign: 0, adset: 1, ad: 2 };
  const sort = (ns: CampNode[]) => {
    /* Сначала уровень, потом имя. Уровень первым нужен ровно ради сирот: без
       него объявление-сирота встало бы между кампаниями по алфавиту, и дерево
       перестало бы читаться как дерево. */
    ns.sort(
      (a, b) =>
        порядок[a.row.level] - порядок[b.row.level] ||
        a.row.name.localeCompare(b.row.name) ||
        a.row.fb_id.localeCompare(b.row.fb_id),
    );
    for (const n of ns) sort(n.children);
  };
  sort(roots);
  return roots;
}

/** Плоский список для отрисовки: только раскрытые ветки. */
export interface FlatCamp {
  node: CampNode;
  depth: number;
  hasKids: boolean;
  open: boolean;
}

export function flatten(roots: CampNode[], open: Set<string>): FlatCamp[] {
  const out: FlatCamp[] = [];
  const walk = (ns: CampNode[], depth: number) => {
    for (const n of ns) {
      const hasKids = n.children.length > 0;
      const isOpen = open.has(n.row.fb_id);
      out.push({ node: n, depth, hasKids, open: isOpen });
      if (hasKids && isOpen) walk(n.children, depth + 1);
    }
  };
  walk(roots, 0);
  return out;
}

/** Сколько строк каждого уровня — для подписи «3 campaigns · 12 ad sets · 40 ads».
 *  Считается по ВСЕМ строкам, а не по видимым: это состав кабинета, а не то,
 *  что сейчас раскрыто. */
export function counts(rows: CampaignRow[]): Record<Level, number> {
  const out: Record<Level, number> = { campaign: 0, adset: 0, ad: 0 };
  for (const r of rows) out[r.level] += 1;
  return out;
}

/* ── СРЕЗ ВНУТРИ ДЕРЕВА ───────────────────────────────────────────────────── */

/* На парке владельца открытый набор кабинетов — это сотни строк, и вопрос у
 * него не «покажи все», а «что крутится», «что стоит» и «почему не идёт». Ровно
 * три состояния, и третье — главное: объект включён, а доставки нет.
 *
 * ПОЧЕМУ ПРЕДКИ СОВПАВШЕЙ СТРОКИ ОСТАЮТСЯ. Дерево без родителя перестаёт быть
 * деревом: объявление без своей кампании висит в воздухе, и человек не видит,
 * ЧЕМ оно выключено — а это и есть ответ, за которым он пришёл. Поэтому предки
 * остаются, но помечаются как контекст (`совпало` их не содержит), и вьюха
 * рисует их приглушённо: строка, показанная для контекста, не должна читаться
 * как найденная. */
export type СостояниеОбъекта = "все" | "крутится" | "на паузе" | "не доставляется";

export const СОСТОЯНИЯ_ОБЪЕКТА: СостояниеОбъекта[] =
  ["все", "крутится", "на паузе", "не доставляется"];

export interface СрезДерева {
  запрос: string;
  состояние: СостояниеОбъекта;
  /** ГЛАЗ: спрятать строки, у которых спенд НЕ НАЙДЕН.
   *
   *  Просьба владельца дословно: «кнопка, которая прячет строки без найденного
   *  спенда», по умолчанию видно ВСЁ. И тут же его условие, из-за которого
   *  кнопка не удобство: «спенд обязан находиться абсолютно весь, если залив
   *  шёл через скилл Обелисты». То есть много спрятанного — это сигнал о НАШЕМ
   *  дефекте, а не о тишине в рекламе, и поэтому число спрятанного обязано
   *  стоять рядом с кнопкой (`скрытоБезСпенда`).
   *
   *  «Не найден» — это `null`, и ноль сюда НЕ попадает: ноль значит «крутилось
   *  и не потратило», и прятать его под тем же глазом значило бы смешать факт с
   *  незнанием — ровно то, от чего лист защищается везде. */
  безСпендаСкрыт: boolean;
}

export const ПУСТОЙ_СРЕЗ_ДЕРЕВА: СрезДерева =
  { запрос: "", состояние: "все", безСпендаСкрыт: false };

/** Доставки нет, хотя объект включён.
 *
 *  Считается по РАСХОЖДЕНИЮ `status` и `effective_status`, а не по списку
 *  значений: Мета заводит новые причины недоставки без предупреждения
 *  (`CAMPAIGN_PAUSED`, `ADSET_PAUSED`, `WITH_ISSUES`, `PENDING_REVIEW`…), и
 *  зашитый список назавтра молча перестанет их ловить. Расхождение же означает
 *  ровно то, что человек и спрашивает: «я включил, а оно не идёт». */
export function неДоставляется(r: CampaignRow): boolean {
  const s = (r.status || "").toUpperCase();
  if (s !== "ACTIVE") return false;
  const e = (r.effective_status || "").toUpperCase();
  if (e) return e !== "ACTIVE";
  /* ЭТОГО ПОЛЯ У КАМПАНИЙ И АДСЕТОВ НЕТ ВОВСЕ — сборщик его им не проставляет,
     и на живом кабинете `null` у всех 13 кампаний и 54 адсетов. Молчать здесь
     значило бы, что главная кнопка листа («включено, а не идёт») работает
     только на объявлениях — то есть не работает.
     Второй ФАКТ о доставке у нас есть: сколько объявлений под строкой реально
     доставляется. Ноль при включённом статусе и есть «включено, а не идёт», и
     это не догадка, а счёт сборщика по `effective_status` детей.
     `undefined` при этом НЕ ноль: про такую строку мы не знаем ничего, и
     записать её в «не доставляется» значит утверждать непроверенное. */
  return r.active_ads === 0;
}

function поСостояниюОбъекта(r: CampaignRow, с: СостояниеОбъекта): boolean {
  const s = (r.status || "").toUpperCase();
  switch (с) {
    case "крутится":
      /* Именно «включён И доставляется». Кабинет, где кампания выключена сверху,
         в «крутится» не попадает: там ничего не крутится, что бы ни говорил
         собственный статус объявления. */
      return s === "ACTIVE" && !неДоставляется(r);
    case "на паузе":
      return s === "PAUSED";
    case "не доставляется":
      return неДоставляется(r);
    default:
      return true;
  }
}

function подходитСтрока(r: CampaignRow, needle: string): boolean {
  if (!needle) return true;
  return (r.name || "").toLowerCase().includes(needle)
    || r.fb_id.toLowerCase().includes(needle);
}

export interface РезультатСреза {
  /** Совпавшие строки ПЛЮС их предки — иначе дерево рассыпается. */
  rows: CampaignRow[];
  /** Сколько строк спрятал ГЛАЗ. Считается всегда — и когда глаз выключен
   *  тоже: иначе человек не узнает, что прятать есть что, пока не нажмёт.
   *  Это число — не удобство, а замер нашей же дырки в сборе спенда. */
  скрытоБезСпенда: number;
  /** Кто совпал на самом деле. Предки, добавленные ради контекста, сюда не
   *  входят: строка, показанная для контекста, не должна читаться как найденная. */
  совпало: Set<string>;
}

export function срезДерева(rows: CampaignRow[], s: СрезДерева): РезультатСреза {
  const needle = s.запрос.trim().toLowerCase();
  /* Сколько строк спрятал бы глаз — считается ВСЕГДА, по тем строкам, которые
     прошли остальной срез. Иначе кнопка молчит о том, что прячет. */
  const безСпенда = (r: CampaignRow) => r.spend == null;
  const скрытоБезСпенда = rows.filter(
    (r) => подходитСтрока(r, needle) && поСостояниюОбъекта(r, s.состояние) && безСпенда(r),
  ).length;

  if (!needle && s.состояние === "все" && !s.безСпендаСкрыт) {
    return { rows, совпало: new Set(rows.map((r) => r.fb_id)), скрытоБезСпенда };
  }
  const поId = new Map(rows.map((r) => [r.fb_id, r]));
  const совпало = new Set<string>();
  const оставить = new Set<string>();
  for (const r of rows) {
    if (!подходитСтрока(r, needle) || !поСостояниюОбъекта(r, s.состояние)) continue;
    if (s.безСпендаСкрыт && безСпенда(r)) continue;
    совпало.add(r.fb_id);
    /* Вверх по родителям. Со сторожем: битая цепочка (объект, назначенный
       родителем сам себе) не имеет права зациклить отрисовку листа. */
    let текущий: CampaignRow | undefined = r;
    const виделиЗдесь = new Set<string>();
    while (текущий && !виделиЗдесь.has(текущий.fb_id)) {
      виделиЗдесь.add(текущий.fb_id);
      оставить.add(текущий.fb_id);
      текущий = текущий.parent_id ? поId.get(текущий.parent_id) : undefined;
    }
  }
  return { rows: rows.filter((r) => оставить.has(r.fb_id)), совпало, скрытоБезСпенда };
}

/** Сколько строк в каждом состоянии — цена фильтра видна ДО нажатия.
 *  Считается по совпадению, а не по показанному: иначе счётчик учитывал бы
 *  предков, добавленных ради контекста, и расходился бы с самим фильтром. */
export function счётСостояний(rows: CampaignRow[]): Record<СостояниеОбъекта, number> {
  const out = Object.fromEntries(
    СОСТОЯНИЯ_ОБЪЕКТА.map((с) => [с, 0]),
  ) as Record<СостояниеОбъекта, number>;
  for (const r of rows) {
    for (const с of СОСТОЯНИЯ_ОБЪЕКТА) if (поСостояниюОбъекта(r, с)) out[с] += 1;
  }
  return out;
}

/* ── КАБИНЕТ — ВЕРХНИЙ ЭТАЖ ДЕРЕВА, А НЕ ЗАГОЛОВОК НАД НИМ ─────────────────── */

/* Владелец 15.08, глядя на лист: «всё должно быть деревом, это базовая логика
 * этого интерфейса». Верхний уровень — рекламный КАБИНЕТ, и он сворачивается:
 * при 268 кабинетах лист без этого не листается, а фильтр All превращает его в
 * кашу. Ниже — строго Ad Account → Campaign → Ad Set → Ad.
 *
 * ОТСЮДА ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: строк вне дерева не бывает. Раньше
 * сирота (строка, чей родитель в ответе не пришёл) вставала верхним уровнем
 * РЯДОМ с кампаниями — объявление и кампания на одной линии, и человек не
 * понимал, к чему относится вторая. Прятать сироту по-прежнему нельзя (по ней
 * идут деньги), подшивать к чужому родителю — тем более. Поэтому она уезжает в
 * СВОЮ ветку под кабинетом, названную словами: ветка раскрывается, её размер
 * виден заранее, и она честно говорит, чего мы про эти строки не знаем. */
export interface ГруппаКаба {
  act_id: string;
  /** Кампании кабинета — единственный законный первый этаж под ним. */
  roots: CampNode[];
  /** Адсеты и объявления, чьего родителя в ответе НЕТ. Своей веткой, а не
   *  вперемешку с кампаниями: строка непонятного уровня рядом с кампанией и
   *  есть то, на что жаловался владелец. */
  безРодителя: CampNode[];
  /** Состав ЭТОГО кабинета: сколько кампаний, адсетов, объявлений в срезе. */
  счёт: Record<Level, number>;
  /** ЧТО СКЛАДЫВАТЬ — решается здесь, СКОЛЬКО получилось — считает каталог
   *  колонок (`итоги()` в `lib/campaigns-columns.ts`).
   *
   *  Разделение не косметическое, и его прямым текстом просил автор каталога:
   *  спенд объявления входит в спенд адсета, а тот — в спенд кампании, поэтому
   *  выбор уровня обязан быть ОДИН на продукт и живёт здесь (`суммаСпенда`).
   *  Само же сложение умеет и каталог — и если складывать в обоих местах, то
   *  однажды поправят одну половину, и футер разойдётся сам с собой. Поэтому
   *  наружу отдаются СТРОКИ ВЫБРАННОГО УРОВНЯ, а не наши суммы по ним. */
  уровеньСпенда: Level | null;
  строкиУровня: CampaignRow[];
  currency: string | null;
  /** Спенд кабинета — ТОЛЬКО ДЛЯ ПОРЯДКА этажей (где деньги, тот выше).
   *  Берётся у того же `суммаСпенда`, что выбирает уровень; на экран идёт
   *  число из `итоги()`, чтобы в таблице и в порядке не оказалось двух разных
   *  правил округления и пропуска. `null` — не собран вовсе, и это не ноль. */
  spend: number | null;
  /** Самый СТАРЫЙ штамп в кабинете: подпись обещает возраст всего показанного. */
  собрано: string | null;
}

/** Строки → этажи кабинетов, каждый со своим деревом.
 *
 *  Порядок кабинетов — по спенду за сегодня, где он есть, и по имени там, где
 *  его нет: человек открывает лист, чтобы посмотреть, где деньги. Кабинет без
 *  спенда встаёт ниже нулевого — ноль это факт, а пусто значит «не знаем». */
export function поКабинетам(rows: CampaignRow[]): ГруппаКаба[] {
  const карта = new Map<string, CampaignRow[]>();
  for (const r of rows) {
    if (!r?.act_id) continue;
    const сюда = карта.get(r.act_id);
    if (сюда) сюда.push(r);
    else карта.set(r.act_id, [r]);
  }
  const out: ГруппаКаба[] = [];
  for (const [act_id, свои] of карта) {
    const итог = суммаСпенда(свои);
    /* Верхний уровень дерева кабинета — только кампании. Всё остальное, что
       осталось без родителя, уходит в свою ветку (см. комментарий выше). */
    const верх = buildTree(свои);
    out.push({
      act_id,
      roots: верх.filter((n) => n.row.level === "campaign"),
      безРодителя: верх.filter((n) => n.row.level !== "campaign"),
      счёт: counts(свои),
      уровеньСпенда: итог.level,
      строкиУровня: свои.filter((r) => r.level === итог.level),
      currency: свои.find((r) => r.currency)?.currency || null,
      spend: итог.units,
      собрано: свои
        .map((r) => r.checked_at || "")
        .filter(Boolean)
        .sort()[0] || null,
    });
  }
  return out.sort((a, b) => {
    const x = a.spend === null ? -1 : a.spend;
    const y = b.spend === null ? -1 : b.spend;
    return y - x || a.act_id.localeCompare(b.act_id);
  });
}

/** Сколько строк в поддеревьях — размер ветки, видимый ДО её раскрытия. */
export function размерВетки(ns: CampNode[]): number {
  let n = 0;
  for (const x of ns) n += 1 + размерВетки(x.children);
  return n;
}

/* ── ЧТО РАСКРЫТО: УМОЛЧАНИЕ СЧИТАЕТСЯ, ОТКЛОНЕНИЯ ХРАНЯТСЯ ───────────────── */

/* Хранить «что открыто» списком открытого нельзя, и это не вкусовщина. Строки
 * приезжают ЗАПРОСОМ, то есть позже первого рендера: список, заполненный в тот
 * момент, когда дерева ещё нет, останется пустым — единственный кабинет не
 * раскроется, и человек увидит одну строку вместо своего дерева. Поэтому
 * умолчание ВЫЧИСЛЯЕТСЯ от того, что сейчас на экране, а в состоянии живут
 * только отклонения от него: «здесь человек сказал наоборот».
 *
 * Умолчания ровно два, и оба про то, чтобы не показать пустой экран:
 *  • кабинет один — он раскрыт: прятать единственное дерево не за чем;
 *  • срез активен — раскрыто всё: иначе счётчик обещает N совпадений, а под
 *    свёрнутыми кабинетами не видно ни одного, и фильтр выглядит сломанным. */
export type ВидСтроки = "кабинет" | "объект" | "без родителя";

export interface Раскрытие {
  /** Ключи, где человек сказал НЕ то, что по умолчанию. */
  иначе: Set<string>;
  подФильтром: boolean;
  одинКабинет: boolean;
}

export const КЛЮЧ_КАБА = (act_id: string) => `acct:${act_id}`;
/** Ключ ветки сирот. С префиксом, а не голым `act_id`: ключи кабинета, ветки и
 *  строки живут в ОДНОМ наборе отклонений, и совпадение означало бы, что
 *  сворачивание кабинета молча сворачивает что-то ещё. */
export const КЛЮЧ_БЕЗ_РОДИТЕЛЯ = (act_id: string) => `orphans:${act_id}`;

export function поУмолчаниюОткрыт(вид: ВидСтроки, р: Раскрытие): boolean {
  if (вид === "кабинет") return р.одинКабинет || р.подФильтром;
  return р.подФильтром;
}

export function открыт(ключ: string, вид: ВидСтроки, р: Раскрытие): boolean {
  const по = поУмолчаниюОткрыт(вид, р);
  return р.иначе.has(ключ) ? !по : по;
}

/** Строка листа. Три вида намеренно одним списком: колонки обязаны совпадать у
 *  кабинета и у кампании, а разложенные по разным таблицам они разъезжаются. */
export type СтрокаЛиста =
  | { вид: "кабинет"; ключ: string; группа: ГруппаКаба; hasKids: boolean; open: boolean }
  | {
      вид: "без родителя"; ключ: string; act_id: string; depth: number;
      сколько: number; open: boolean;
    }
  | { вид: "объект"; ключ: string; item: FlatCamp };

/** Этажи кабинетов → плоский список строк для отрисовки.
 *
 *  Глубина считается ОТ КАБИНЕТА: кабинет 0, кампания 1, адсет 2, объявление 3.
 *  Отступ рисуется по ней, и ветка сирот стоит на глубине кампании — она
 *  такой же этаж под кабинетом, а не строка неизвестно откуда. */
export function плоскийЛист(этажи: ГруппаКаба[], р: Раскрытие): СтрокаЛиста[] {
  const out: СтрокаЛиста[] = [];
  const ветка = (ns: CampNode[], depth: number) => {
    for (const n of ns) {
      const hasKids = n.children.length > 0;
      const о = открыт(n.row.fb_id, "объект", р);
      out.push({
        вид: "объект", ключ: n.row.fb_id,
        item: { node: n, depth, hasKids, open: о },
      });
      if (hasKids && о) ветка(n.children, depth + 1);
    }
  };

  for (const г of этажи) {
    const ключ = КЛЮЧ_КАБА(г.act_id);
    const детей = г.roots.length + (г.безРодителя.length ? 1 : 0);
    const о = открыт(ключ, "кабинет", р);
    out.push({ вид: "кабинет", ключ, группа: г, hasKids: детей > 0, open: о });
    if (!о || !детей) continue;
    ветка(г.roots, 1);
    if (г.безРодителя.length) {
      const кл = КЛЮЧ_БЕЗ_РОДИТЕЛЯ(г.act_id);
      const оо = открыт(кл, "без родителя", р);
      out.push({
        вид: "без родителя", ключ: кл, act_id: г.act_id, depth: 1,
        сколько: размерВетки(г.безРодителя), open: оо,
      });
      if (оо) ветка(г.безРодителя, 2);
    }
  }
  return out;
}

/** Все ключи, которые вообще раскрываются, вместе с их видом.
 *
 *  Выводится ИЗ ДЕРЕВА, а не перечисляется руками: «раскрыть всё», собранное по
 *  списку, молча не раскроет ветку, которую заведут завтра, — и будет выглядеть
 *  сработавшим. */
export function ключиРаскрытия(этажи: ГруппаКаба[]): Array<{ ключ: string; вид: ВидСтроки }> {
  const out: Array<{ ключ: string; вид: ВидСтроки }> = [];
  const ветка = (ns: CampNode[]) => {
    for (const n of ns) {
      if (n.children.length) {
        out.push({ ключ: n.row.fb_id, вид: "объект" });
        ветка(n.children);
      }
    }
  };
  for (const г of этажи) {
    if (г.roots.length || г.безРодителя.length) {
      out.push({ ключ: КЛЮЧ_КАБА(г.act_id), вид: "кабинет" });
    }
    ветка(г.roots);
    if (г.безРодителя.length) {
      out.push({ ключ: КЛЮЧ_БЕЗ_РОДИТЕЛЯ(г.act_id), вид: "без родителя" });
      ветка(г.безРодителя);
    }
  }
  return out;
}

/** Набор отклонений, при котором раскрыто ВСЁ (`хотим = true`) или ничего.
 *  Считается от умолчания, а не вместо него: иначе «свернуть всё» под активным
 *  фильтром не свернуло бы ничего. */
export function отклонения(этажи: ГруппаКаба[], р: Раскрытие, хотим: boolean): Set<string> {
  const out = new Set<string>();
  for (const { ключ, вид } of ключиРаскрытия(этажи)) {
    if (поУмолчаниюОткрыт(вид, р) !== хотим) out.add(ключ);
  }
  return out;
}

/* ── ФУТЕР-ТОТАЛ: СТРОКИ ТЕКУЩЕЙ ВЫБОРКИ, А НЕ ВТОРАЯ АРИФМЕТИКА ──────────── */

/** Строки, по которым считается тотал внизу таблицы.
 *
 *  ЗДЕСЬ НЕТ НИ ОДНОГО СЛОЖЕНИЯ, и это главное свойство функции. Числа футера
 *  считает каталог колонок (`итоги()`), одной формулой на метрику — той же, что
 *  печатает строку. Наше дело — отдать ему ПРАВИЛЬНЫЙ НАБОР СТРОК.
 *
 *  Набор — объединение строк ВЫБРАННОГО УРОВНЯ КАЖДОГО кабинета, а не «самый
 *  верхний уровень всей выборки». Разница — тихий потолок: у одного каба в
 *  ответе кампании, у другого только адсеты; общий «верхний» получается
 *  `campaign`, и деньги второго молча выпадают из тотала. Ошибки нет, число
 *  есть, оно меньше правды. */
export function строкиФутера(этажи: ГруппаКаба[]): CampaignRow[] {
  const out: CampaignRow[] = [];
  for (const г of этажи) out.push(...г.строкиУровня);
  return out;
}

/* ── РАМКА ТАБЛИЦЫ: ТО, ЧТО ВЫКЛЮЧИТЬ НЕЛЬЗЯ НИКОГДА ─────────────────────────
 *
 * Здесь живут ЧЕТЫРЕ колонки, и это не «каталог колонок» — каталог метрик у
 * листа один и лежит в `lib/campaigns-columns.ts` (#159), а ступени воронки
 * приезжают ответом (`lib/campaigns-funnel.ts`). Граница между ними проведена
 * по вопросу «что человек имеет право выключить»:
 *
 *   • МЕТРИКИ (spend, показы, клики, CTR…) — выключаемы: их восемь, и восемь
 *     колонок сразу и есть та перегрузка, ради которой выбор колонок заведён;
 *   • РАМКА (имя, статус, штамп свежести, кнопка) — НЕ выключаема. Это не
 *     метрики, а УСЛОВИЯ ДОВЕРИЯ К СТРОКЕ: без имени строка не опознаётся, без
 *     статуса непонятно, что тушить, без возраста цифра не значит ничего (лист
 *     читает слепок базы, а не Мету), а без кнопки строка перестаёт быть
 *     управлением и становится отчётом. Спрятать их одним нажатием — значит
 *     потерять условие доверия, не заметив.
 *
 * Внутри рамки договорённость держится тем же механизмом, что и раньше: ширина
 * объявлена ОДНОЙ строкой на колонку, шапка и все три вида строк берут её
 * отсюда и метят ячейку `data-col`, а тест сверяет последовательность меток в
 * ОТРИСОВАННОМ выводе шапки и строк. Порядок на экране: имя → метрики →
 * воронка → статус → возраст → кнопка. */
export type КлючКолонки = "name" | "status" | "age" | "action";

export interface КолонкаЛиста {
  ключ: КлючКолонки;
  /** Что стоит в шапке. Пусто — колонка без заголовка (кнопка действия). */
  подпись: string;
  /** Ширина В ПИКСЕЛЯХ, а не классом Tailwind, и это правило того же каталога
   *  метрик (#159) — здесь оно куплено ещё дороже.
   *
   *  ПЕРВАЯ ПРИЧИНА — ЧИСЛО МОЖНО СЛОЖИТЬ. Таблица обязана знать свою полную
   *  ширину, чтобы при нехватке места ПРОКРУЧИВАТЬСЯ, а не сжимать колонки в
   *  ноль. На живом парке владельца сжатие выглядело так: имя кабинета
   *  пропадало целиком, а приписки печатались поверх соседних колонок —
   *  «act_1523320569016244 3 camp$258.22ts · 12 ads» в одной строке.
   *
   *  ВТОРАЯ — КЛАСС ЖИВЁТ ТОЛЬКО ПОСЛЕ СБОРКИ. Tailwind ищет классы
   *  статическим сканированием исходников; всё, что собрано в рантайме, он не
   *  видит вовсе, а всё новое появляется лишь в следующей сборке. Стиль не
   *  зависит ни от того, ни от другого: он приезжает вместе с разметкой. */
  ширина: number | null;
  /** Прижать содержимое вправо. У чисел это не вкус: колонки, выровненные
   *  по-разному, невозможно сравнить взглядом по вертикали. */
  вправо?: boolean;
}

/** Сколько места колонке имени нужно, чтобы имя оставалось ИМЕНЕМ. Меньше —
 *  строка перестаёт опознаваться, а лист существует ради того, чтобы человек
 *  нашёл в нём нужную строку. */
export const МИН_ИМЯ = 220;

export const РАМКА_ЛИСТА: КолонкаЛиста[] = [
  { ключ: "name", подпись: "name", ширина: null },
  /* Статус шире соседей намеренно: рядом со словом стоит бейдж причины
     («by parent», «disapproved», а с #155 — целая фраза вроде «its ad set is
     off»). Уже, и бейдж вылезает на возраст. */
  { ключ: "status", подпись: "status", ширина: 192, вправо: true },
  { ключ: "age", подпись: "age", ширина: 48 },
  { ключ: "action", подпись: "", ширина: 112, вправо: true },
];

export function колонка(ключ: КлючКолонки): КолонкаЛиста {
  const c = РАМКА_ЛИСТА.find((x) => x.ключ === ключ);
  /* Молча вернуть пустую ширину значило бы колонку без ширины — она схлопнется
     и утащит за собой соседние, а выглядеть будет как «немного съехало». */
  if (!c) throw new Error(`колонка «${ключ}» не объявлена в РАМКА_ЛИСТА`);
  return c;
}

/** ПОЛНАЯ ШИРИНА ТАБЛИЦЫ — сумма всех колонок плюс зазоры между ними.
 *
 *  Нужна ровно для того, чтобы таблица прокручивалась по горизонтали, когда
 *  колонок больше, чем места. Альтернатива — сжимать — уже проверена на живом
 *  парке и даёт нечитаемый экран: имя пропадает, приписки налезают на цифры, а
 *  кнопки обрезаются. Прокрутка честнее: ничего не теряется, всё остаётся на
 *  своих местах, и человек сам решает, что смотреть.
 *
 *  `зазор` — тот же `gap-2` (8px), что стоит в разметке строки; передаётся
 *  числом, чтобы это место не гадало о вёрстке. */
export function ширинаТаблицы(метрики: Array<{ width: number }>, зазор = 8): number {
  const рамка = РАМКА_ЛИСТА.reduce((n, c) => n + (c.ширина ?? МИН_ИМЯ), 0);
  const мет = метрики.reduce((n, c) => n + c.width, 0);
  const клеток = РАМКА_ЛИСТА.length + метрики.length;
  /* Шеврон живёт ВНУТРИ колонки имени, поэтому отдельной клетки у него нет. */
  return рамка + мет + Math.max(0, клеток - 1) * зазор;
}

/* ── СПЕНД: СКЛАДЫВАТЬ МОЖНО ТОЛЬКО ОДИН УРОВЕНЬ ──────────────────────────── */

/** Сумма спенда за сегодня по набору строк.
 *
 *  ГЛАВНОЕ ЗДЕСЬ — НЕ СЛОЖИТЬ ОДНИ И ТЕ ЖЕ ДЕНЬГИ ТРИЖДЫ. Спенд объявления
 *  входит в спенд своего адсета, а тот — в спенд кампании: сложив все строки
 *  подряд, мы получили бы тройную сумму и показали бы её как расход дня.
 *  Поэтому складывается РОВНО ОДИН уровень — самый верхний из присутствующих:
 *  есть кампании — по кампаниям, пришли только адсеты — по адсетам.
 *
 *  Уровень возвращается наружу: подпись обязана сказать, по чему сумма, иначе
 *  два разных ответа выглядят одинаково.
 *
 *  `null` значит «спенд не собран ни у одной строки этого уровня» — и это не
 *  ноль. Ноль означал бы «сегодня не потрачено», а это другое утверждение
 *  (#122). */
export interface СуммаСпенда {
  units: number | null;
  level: Level | null;
  /** Строк уровня, у которых спенда нет. Больше нуля — сумма неполная, и
   *  молчать об этом нельзя: неполная сумма выглядит как полная. */
  безСпенда: number;
}

export function суммаСпенда(rows: CampaignRow[]): СуммаСпенда {
  const порядок: Level[] = ["campaign", "adset", "ad"];
  const верхний = порядок.find((l) => rows.some((r) => r.level === l)) || null;
  if (!верхний) return { units: null, level: null, безСпенда: 0 };
  let сумма: number | null = null;
  let безСпенда = 0;
  for (const r of rows) {
    if (r.level !== верхний) continue;
    const v = r.spend;
    if (typeof v === "number" && Number.isFinite(v)) сумма = (сумма ?? 0) + v;
    else безСпенда += 1;
  }
  return { units: сумма, level: верхний, безСпенда };
}

/* ── незавершённые записи ───────────────────────────────────────────────── */

/** Что происходит со строкой прямо сейчас.
 *  `sending` — ушло в Мету, ответа нет; `failed` — Мета отказала, и отказ надо
 *  показать словами. Успех отдельным состоянием НЕ хранится: успех — это новый
 *  статус в самой строке, а лишнее состояние «получилось» пришлось бы гасить
 *  по таймеру и объяснять, почему оно исчезло. */
export interface Pending {
  want: "ACTIVE" | "PAUSED";
  state: "sending" | "failed";
  error?: string;
}

export type PendingMap = Record<string, Pending>;

/** Строки с наложенным результатом записи.
 *
 *  Пока `sending`, статус строки НЕ меняется — меняется только подпись рядом
 *  («pausing…»). Это и есть разница между оптимизмом и враньём: мы обещаем, что
 *  просили, а не что получилось. */
export function applyWrite(rows: CampaignRow[], r: WriteResult): CampaignRow[] {
  if (!r?.fb_id) return rows;
  return rows.map((x) =>
    x.fb_id === r.fb_id
      ? {
          ...x,
          status: r.status ?? x.status,
          effective_status: r.effective_status ?? x.effective_status,
          /* Штамп свежести после записи — момент ЗАПИСИ, а не прошлого обзора.
             Строка только что прочитана из ответа Меты и свежее уже некуда;
             оставить старый штамп значило бы показывать «5h» на цифре, снятой
             секунду назад. */
          checked_at: r.applied_at ?? new Date().toISOString(),
        }
      : x,
  );
}

/** Итог одной записи для человека: что просили, что получилось.
 *  Пустая строка — сказать нечего. */
export function writeWords(want: "ACTIVE" | "PAUSED", r: WriteResult): string {
  const got = (r.status || "").toUpperCase();
  const слово = want === "PAUSED" ? "paused" : "activated";
  if (!got) return `Meta accepted the request, but did not say the new state.`;
  if (got === want) return `Done — ${слово} in Meta.`;
  /* Просили одно, вернулось другое. Это не ошибка панели и не повод молчать:
     чаще всего так выглядит объект, который Мета держит по своей причине. */
  return `Meta accepted the request but reports ${got}, not ${want}.`;
}

/* ── ГДЕ ЖИВЁТ БЮДЖЕТ ЭТОЙ СТРОКИ ─────────────────────────────────────────── */

/* Пустая ячейка бюджета значит РАЗНОЕ, и «не собрано» из четырёх случаев верно
 * ровно в одном. У Меты бюджет живёт ЛИБО на кампании (CBO), ЛИБО на её
 * адсетах (ABO) — никогда на обоих, — а у объявления его не бывает вовсе.
 *
 * Разница для байера прямая: «не собрали» толкает искать поломку у нас, а «он
 * на соседнем уровне» — смотреть туда, где потолок и стоит. Второе — самое
 * полезное из четырёх ответов, и раньше панель не давала его никогда.
 *
 * Отличить «на соседнем уровне» от «правда не собрали» по одной строке нельзя:
 * нужен взгляд на родителя и на детей. Поэтому карта строится на весь ответ
 * разом, а не вычисляется в разметке. */
export type БюджетГде =
  /** Значение есть — рисуем число. */
  | "есть"
  /** Уровень его не имеет по устройству (объявление). Норма, объяснять нечего. */
  | "не бывает"
  /** Потолок стоит на кампании (CBO), а мы адсет. */
  | "на кампании"
  /** Потолок стоит на адсетах (ABO), а мы кампания. */
  | "на адсетах"
  /** Ни здесь, ни у соседей — вот теперь это правда «не собрано». */
  | "не собрано";

function естьБюджет(r: CampaignRow): boolean {
  return (r.daily_budget !== null && r.daily_budget !== undefined)
    || (r.lifetime_budget !== null && r.lifetime_budget !== undefined);
}

export function картаБюджетов(rows: CampaignRow[]): Map<string, БюджетГде> {
  const поId = new Map(rows.map((r) => [r.fb_id, r]));
  /* Дети с бюджетом — одним проходом: перебирать весь ответ на каждую кампанию
     значит квадрат на дереве в четыре сотни строк. */
  const детиСБюджетом = new Set<string>();
  for (const r of rows) {
    if (r.parent_id && естьБюджет(r)) детиСБюджетом.add(r.parent_id);
  }

  const out = new Map<string, БюджетГде>();
  for (const r of rows) {
    if (r.level === "ad") {
      out.set(r.fb_id, "не бывает");
      continue;
    }
    if (естьБюджет(r)) {
      out.set(r.fb_id, "есть");
      continue;
    }
    const родитель = r.parent_id ? поId.get(r.parent_id) : undefined;
    if (r.level === "adset" && родитель && естьБюджет(родитель)) {
      out.set(r.fb_id, "на кампании");
      continue;
    }
    if (r.level === "campaign" && детиСБюджетом.has(r.fb_id)) {
      out.set(r.fb_id, "на адсетах");
      continue;
    }
    /* Родителя в ответе нет вовсе — сказать «он на кампании» нельзя: это было бы
       утверждением о строке, которой мы не видели. Остаётся честное «не
       собрано», и оно тут на своём месте. */
    out.set(r.fb_id, "не собрано");
  }
  return out;
}
