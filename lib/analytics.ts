/* ── формат чисел ──────────────────────────────────────────────────────────
   Прочерк вместо нуля везде, где ноль означал бы «данных нет». Байер читает
   таблицу глазами по колонке, и «0.00» в цене депа — это утверждение, что
   депы бесплатные. */

export const DASH = "—";

/** Строки, которые выглядят как крео, но крео не являются.
 *
 *  `не определён` — спенд на объявлениях, чей крео не опознан.
 *  `связка не найдена` — воронка трекера без объявления в логах вовсе.
 *
 *  Обе обязаны лежать в самом низу при любой сортировке и не разворачиваться:
 *  первое место по цене депа у недостачи читалось бы как «лучший крео — тот,
 *  который мы не опознали». Прятать их нельзя — тогда сумма не сойдётся. */
/* Старые написания оставлены рядом с новыми намеренно: демон и панель
   обновляются порознь, и до перезапуска демона в ответе ещё лежат русские
   метки. Выпади они из списка — эти две строки перестали бы прижиматься к низу
   и всплыли бы на первое место по цене депа. */
export const NOT_A_CREATIVE = [
  "unidentified", "no bundle matched",
  "не определён", "связка не найдена",
];

/** Деньги всегда со знаком валюты: колонка «18.01» рядом с колонкой «10»
 *  читается как ещё одно количество, а это цена депа. Все кабинеты в USD —
 *  проверено на живых данных; появится другая валюта, знак придётся брать из
 *  строки, а не зашивать. */
export function money(v: Maybe): string {
  if (v == null) return DASH;
  return "$" + (v >= 1000 ? v.toFixed(0) : v.toFixed(2));
}

export function num(v: Maybe): string {
  if (v == null) return DASH;
  return v.toLocaleString("en-US");
}

/** Процент с точностью, которая сохраняет разницу.
 *
 *  Шаг округления обязан быть мельче, чем расстояние между решениями. Конверсия
 *  в деп живёт в районе полупроцента: 0.465% и 0.5% отличаются на восьмую часть
 *  результата, а один знак после запятой показывал оба как «0.5%» — две связки
 *  с заметно разной отдачей выглядели одинаково. Поэтому чем меньше величина,
 *  тем больше знаков: до 1% — два, до 10% — один, дальше целое (54.36% и 54%
 *  ведут к одному решению, а лишние знаки в таблице только шумят).
 *
 *  Ровный ноль печатается без хвоста: «0%» — это факт, а «0.00%» выглядит как
 *  измерение с точностью до сотой.
 */
export function pct(v: Maybe): string {
  if (v == null) return DASH;
  const p = v * 100;
  if (p === 0) return "0%";
  const digits = Math.abs(p) < 1 ? 2 : Math.abs(p) < 10 ? 1 : 0;
  return p.toFixed(digits) + "%";
}

/** Дата в формате, который понимает и демон, и <input type="date">. */
export function isoDay(d: Date): string {
  return d.toISOString().slice(0, 10);
}

/* ── возраст спенда ────────────────────────────────────────────────────────
   Ради иссуса #20. Панель за 9 августа показывала $944 при реальных $1516, и
   выглядело это как свежая правда: цифры не отсутствовали и не были обрезаны —
   они ЗАСТЫЛИ. У девяти кабов соца с умершим токеном спенд сняли в первые
   минуты суток, когда там было по доллару, и больше не трогали.

   Шапка при этом писала «спенд 3 мин назад» и была права: круг сбора крутился,
   просто по живым соцам. Возраст последнего круга и возраст ЭТОЙ цифры — разные
   вещи, и путать их означает ровно тот случай, ради которого всё написано. */

/** Порог «сняли задолго до конца суток». Держится в паре с `STALE_GAP_S`
 *  демона (`scripts/analytics_daemon.py`) — там же и объяснение, почему три
 *  часа: между «недобрали хвостик» (2 ч) и «счётчик стоит» (25 ч) на живой базе
 *  не попадает ничего. */
export const STALE_GAP_S = 3 * 3600;

/** Снято раньше, чем сутки начались: токен умер, число осталось лежать. */
export const DEAD_GAP_S = 24 * 3600;

/** `ok` — сказать нечего, `late` — хвост дня не добран, `frozen` — цифру сняли
 *  до начала тех суток, за которые она записана. Разводить их обязательно:
 *  первое лечится следующим кругом сбора, второе — переподключением соца. */
export type StaleLevel = "ok" | "late" | "frozen";

export function staleLevel(gapS: Maybe): StaleLevel {
  if (gapS == null) return "ok";           // незакрытый день или замера не было
  if (gapS >= DEAD_GAP_S) return "frozen";
  return gapS > STALE_GAP_S ? "late" : "ok";
}

/** Сторож нашёл расхождение, о котором стоит говорить.
 *
 *  Записи нет — молчим (сторож ещё не доехал). Запись есть, а разница ноль —
 *  тоже молчим: сторож пишет строку на каждую сверку, а метка нужна только на
 *  несошедшихся. Разница неизвестна, но запись заведена — говорим: сам факт
 *  того, что кабинет попал в список несошедшихся, уже новость. */
export function hasMismatch(c?: AccountCheck | null): boolean {
  if (!c) return false;
  return c.diff == null || Math.abs(c.diff) >= 0.01;
}

/** Момент замера покороче: «в 08:23» за сегодня, «8 авг 23:08» за прошлое.
 *  Абсолютный, а не «14 ч назад»: сравнивать его нужно с концом суток, за
 *  которые записан спенд, а не с текущей минутой. */
export function whenShort(iso: string | null | undefined): string {
  if (!iso) return "";
  const t = new Date(iso);
  if (!Number.isFinite(t.getTime())) return "";
  const hm = t.toLocaleTimeString("en-US", {
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  });
  const now = new Date();
  const sameDay =
    t.getFullYear() === now.getFullYear() &&
    t.getMonth() === now.getMonth() &&
    t.getDate() === now.getDate();
  if (sameDay) return "at " + hm;
  const day = t.toLocaleDateString("en-US", { day: "numeric", month: "short" });
  return day.replace(".", "") + " " + hm;
}

/** Полная фраза для подсказки: когда сняли и чем это грозит цифре рядом.
 *  Пустая строка — сказать нечего (замера не было вовсе).
 *  @param what «кабинету» / «крео» — о чём строка. */
export function staleWhy(
  what: string,
  spendAt: string | null | undefined,
  gapS: Maybe,
  staleSpend: Maybe,
): string {
  const when = whenShort(spendAt);
  if (!when) return "";
  const head = `Spend for ${what} was collected ${when}`;
  const risk =
    staleSpend != null && staleSpend > 0
      ? ` ${money(staleSpend)} is in question — that is a lower bound: only Meta ` +
        `knows how much is missing.`
      : "";
  // Незакрытый день: цифра неполна по определению, и это не повод для тревоги.
  if (gapS == null) return `${head}. The day is still running — the figure will grow.`;
  if (staleLevel(gapS) === "frozen") {
    return (
      `${head} — before the day it is recorded for had even started. This is not ` +
      `the day's total, only what had accrued by the time of the reading: the ad ` +
      `account dropped out of collection, most likely along with its profile.${risk}`
    );
  }
  const h = Math.max(1, Math.round(gapS / 3600));
  return `${head}, ${h} h before the day ended — the tail of the day is not in the figure.${risk}`;
}

