/* Какое пустое состояние показать на листе аналитики.
 *
 * Вынесено из вёрстки не ради красоты, а чтобы это стало проверяемым. До
 * 14.08 развилка жила четырёхэтажной тернаркой внутри `AnalyticsView`, и её
 * не покрывал ни один тест — а стоила она дороже всего именно на пустой
 * панели, то есть в первую минуту знакомства человека с продуктом.
 *
 * Что было не так по факту: у пустоты пять разных причин, а веток было две с
 * половиной. Полностью пустой срез не попадал ни в одну — обе объясняющие
 * ветки требовали, чтобы что-то уже нашлось (`hiddenNoSpend > 0` у одной,
 * `shown.length > 0` у другой), — и человек получал таблицу с шапкой и без
 * единой строки, молча. Пустая таблица без объяснения читается как поломка.
 * Последняя ветка на всё остальное говорила «No data»: два слова, ни причины,
 * ни выхода, и вдобавок неправда, когда строки есть, а колонки выключены.
 *
 * Прод — чистый лист, и у каждого юзера панель начинается с нуля. Значит это
 * не редкий случай, а ПЕРВОЕ, что видит человек.
 */

export type EmptyKind =
  /** Показываем таблицу, пустого состояния нет. */
  | "table"
  /** Запрос в пути. */
  | "loading"
  /** Ошибку показывает своя плашка выше — второй раз не говорим. */
  | "error"
  /** Срез ещё не запрашивали. */
  | "not-requested"
  /** Ответ пришёл, и в нём ноль строк: собирать пока не с чего либо нечего
   *  показать за этот диапазон. */
  | "empty-range"
  /** Строки есть, а все колонки выключены — данные на месте, показать нечем. */
  | "all-columns-off";

export interface EmptyInput {
  /** Ответ демона получен (не `null`). */
  board: boolean;
  /** Сколько строк в срезе ДО фильтров листа. */
  rows: number;
  pending: boolean;
  error: boolean;
  /** Сколько колонок включено. */
  columns: number;
}

/** Порядок веток здесь — это и есть поведение листа, поэтому он один на всех
 *  и живёт в одном месте, а не повторяется в вёрстке. */
export function emptyKind(x: EmptyInput): EmptyKind {
  /* Условия `!pending` здесь НЕТ, и это исправление самого правила, а не
     заплатка. «Таблица переживает перезапрос» верно только когда есть чему
     переживать: при нуле строк переживать нечего, а лист зовёт себя по таймеру
     раз в минуту — значит на чистой панели человек раз в минуту получал бы
     голую шапку таблицы вместо объяснения. Ровно ту картинку, ради которой всё
     и делалось. */
  if (x.board && x.rows === 0) return "empty-range";
  // А вот когда строки есть, перезапрос их не гасит: подменять показанные
  // цифры на «Loading…» значит мигать экраном на каждой смене диапазона.
  if (x.board && x.columns > 0) return "table";
  if (x.error) return "error";
  if (x.pending) return "loading";
  return x.board ? "all-columns-off" : "not-requested";
}
