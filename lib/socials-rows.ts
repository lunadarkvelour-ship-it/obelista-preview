/* Как лист «Профили» делит строки на две группы.
 *
 * Вынесено из вёрстки, потому что иначе это непроверяемо: строки приезжают
 * эффектом, а тестовый рендер эффектов не выполняет — до состояния «ответ
 * пришёл» не добраться. Один символ в условии здесь стоил владельцу рабочего
 * дня, и оставлять такое место без теста нельзя.
 *
 * ЧТО ЗДЕСЬ БЫЛО НЕ ТАК. Правило звучало `!connected && in_antik` и опиралось
 * на рассуждение: соц, которого нет в антидетекте, — «строка ни о чём, нажать
 * нечего». Неверно дважды.
 *
 * По факту: демон кладёт ссылку согласия в КАЖДУЮ строку. Нажать было чем
 * всегда — кнопку просто не рисовали. 14.08 владелец нажал Disconnect, строка
 * исчезла с экрана навсегда, и подключить обратно стало нечем. Движок при этом
 * ничего не терял: `core/fbapp.py:471` снимает токен, а запись соца оставляет
 * со статусом `disconnected`, и там прямо написано, что «был подключён,
 * отключён тогда-то» честнее исчезнувшей строки. Невидимых строк в тот вечер
 * было четыре.
 *
 * По устройству: `in_antik` — свойство файла со снимком локального
 * антидетекта, а не свойство продукта. В облаке локального API нет вовсе,
 * признак ложен у всех, и фильтр отдал бы пустой экран человеку, которому надо
 * начать работу. Состав знает Обелиста, а не файл.
 */

/** Ровно то, что делению нужно знать о строке. Не `Social` целиком: чем меньше
 *  поля, тем очевиднее, что `in_antik` тут больше не участвует. */
export interface РядСоца {
  connected: boolean;
}

/** Что сказать человеку про строку, которой нельзя работать (#163).
 *
 *  ДВЕ РАЗНЫЕ НОВОСТИ, И РАЗНИЦА НЕ В ТОНЕ. «Токен протух» человек чинит сам за
 *  минуту — идёт в диалог согласия. «Вендора нет» он не чинит НИКАК: браузера,
 *  в котором лежала сессия, больше не существует, и предлагать ему нажать
 *  что-нибудь значит врать. Продукт месяц докладывал владельцу «переподключи
 *  два соца», а переподключать было нечего.
 *
 *  Третий случай — «не подтверждён»: профиля нет в списке вендора ПРЯМО СЕЙЧАС.
 *  Это может быть и выключенный антидетект, поэтому здесь не «нельзя», а «мы
 *  его не видим», и ссылку у такой строки не отнимают.
 *
 *  Живёт здесь, а не в вёрстке, по той же причине, что и деление ниже: фразу,
 *  собранную внутри компонента, тестом не достать. */
export function newsOfVendor(row: { vendor_state?: string; profiles?: { vendor?: string }[] }): string {
  if (row.vendor_state === "нет_вендора") {
    const вендоры = [...new Set((row.profiles ?? []).map((p) => p.vendor).filter(Boolean))];
    const чей = вендоры.length ? ` (${вендоры.join(", ")})` : "";
    return `the antidetect browser this profile lived in${чей} is gone — reconnecting cannot help`;
  }
  if (row.vendor_state === "не_подтверждён") {
    return "no antidetect of yours lists this profile right now";
  }
  return "";
}

/** Неполон ли список из-за того, что СПРОСИТЬ БЫЛО НЕКОГО.
 *
 *  Профили живут в антидетекте на машине человека, и когда он молчит, список
 *  тихо становится короче — знаменатель «N из M подключено» уменьшается сам
 *  собой, без единого слова. Человек видит меньше соцев, чем у него есть, и
 *  причину узнать неоткуда: молчание источника выглядит точно так же, как
 *  «профилей стало меньше».
 *
 *  ДВА ФАКТА, А НЕ ОДИН ФЛАГ. `antik_ok` сам по себе в интерфейс не годится: в
 *  облаке он ложен ВСЕГДА (антидетект слушает `127.0.0.1` у оператора, туда
 *  облако не ходит по устройству), и тревога горела бы у каждого и постоянно —
 *  то есть перестала бы читаться. Спрашивать надо вместе с `antik_expected`:
 *  ждали ли мы ответа вообще. В облаке не ждали — и молчание там не новость, а
 *  устройство.
 *
 *  Поля может не быть вовсе (демон постарше) — тогда молчим: выдуманная тревога
 *  хуже отсутствующей. */
export function списокНеполон(
  meta: { antik_ok?: boolean | null; antik_expected?: boolean | null },
): boolean {
  return meta.antik_expected === true && meta.antik_ok === false;
}

export function splitSocials<T extends РядСоца>(rows: T[]): { linked: T[]; rest: T[] } {
  return {
    linked: rows.filter((r) => r.connected),
    /* Никаких условий сверх «не подключён». Всякое добавленное сюда условие
       прячет с экрана строку, которую человек ищет глазами. */
    rest: rows.filter((r) => !r.connected),
  };
}
