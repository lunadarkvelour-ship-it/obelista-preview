/**
 * Итог за сегодня — НЕ ИТОГ, и число обязано сказать это само (#149).
 *
 * ЧТО СЛУЧИЛОСЬ. За 14.08 панель показывала $856.82, настоящий тотал был
 * $1026.59 — занижение 16.5%. Причина в сборщике: день фиксируется на том, что
 * набежало к последнему чтению внутри дня, и после полуночи не перечитывается
 * (`open_days: 25, closed: 0`). Чинит это движок.
 *
 * ПОЧЕМУ ПАНЕЛИ ВСЁ РАВНО ЕСТЬ ЧТО ДЕЛАТЬ. Лист УЖЕ честно писал в поповере
 * «часть спенда протухла, настоящая цифра выше» — и крупно показывал неверное
 * число. Это половина решения: признались и всё равно соврали. Человек читает
 * крупное, а не поповер, и решение принимает по крупному.
 *
 * ГЛАВНОЕ ЗДЕСЬ — ОДНА МЫСЛЬ, И ОНА НЕ ТРЕБУЕТ НИ ОДНОГО НОВОГО ПОЛЯ:
 * СЕГОДНЯШНИЙ ДЕНЬ НЕ ЗАКРЫТ ПО ОПРЕДЕЛЕНИЮ. Пока он идёт, деньги ещё
 * набегают, и любое число за окно, включающее сегодня, — это «столько уже», а
 * не «столько всего». Это верно и до починки движка, и после неё, и не зависит
 * от того, какими полями движок начнёт отмечать закрытые дни.
 *
 * ПРОШЛЫЙ ДЕНЬ ТОЖЕ БЫВАЕТ НЕПОЛНЫМ, и с 15.08 панель это видит. Движок стал
 * ставить `account_day.closed_at` только по чтению ПОСЛЕ конца суток в
 * таймзоне кабинета — раньше отметка стояла и на застывших числах, ровно как
 * на том 14.08. Теперь `closed_at` значит «можно верить», а `NULL` — «может
 * вырасти», и метка на прошлом дне обеспечена механически, а не догадкой.
 *
 * Признаком, а не датой «закрыто по такое-то число»: кабинеты в разных гео, и
 * одна дата на весь лист обязана соврать в одну из сторон (разбор — у
 * `openDays` ниже).
 *
 * ПОРОГОВ ЗДЕСЬ НЕТ. Сравниваются две даты, и всё; «сколько именно недобрали»
 * знает только Мета, и никакая оценка этого числа тут не появится.
 *
 *
 * МЕТКА, КОТОРАЯ СТОИТ ВЕЗДЕ, НЕ ЗНАЧИТ НИЧЕГО (правка 15.08)
 *
 * Владелец на живом листе: «в аналитике теперь ВЕЗДЕ пишет spend day not
 * closed, cost so far, везде вот это больше-равно, ДАЖЕ ЕСЛИ выбираешь
 * фильтрацию по 30 дням или за всё время».
 *
 * Он прав, и причина в устройстве: любое окно, кончающееся сегодня, получало
 * метку «today» — а сегодня входит в КАЖДОЕ окно по умолчанию. Формально верно
 * (сегодня и правда не закрыт), практически бесполезно: на тридцати днях вклад
 * незакрытого сегодня в итог мал, а знак нижней границы на такой сумме сбивает
 * сильнее, чем помогает. Метку перестают читать вместе со всеми остальными —
 * ровно то же, что мы весь день чиним у янтарных плашек, висящих всегда.
 *
 * ПОЭТОМУ ЗДЕСЬ ТЕПЕРЬ ДВА РАЗНЫХ ОТВЕТА, а не один:
 *
 *   • СЛОВА — «часть окна не закрыта, и вот сколько дней из скольких». Стоят
 *     всегда, когда это правда: человек имеет право знать состав окна.
 *   • ЗНАК ≥ НА КРУПНОМ ЧИСЛЕ — только когда незакрытое ЗАМЕТНО В СУММЕ. Это
 *     утверждение о ЧИСЛЕ, и делать его из-за одного идущего дня в тридцати
 *     значит обесценить сам знак.
 *
 * ПОРОГ ЗАМЕТНОСТИ В ПАНЕЛИ НЕ ЖИВЁТ. Панель читает то, что движок УЖЕ
 * посчитал: `stale_spend` — деньги, снятые сильно раньше конца суток, по его
 * собственному порогу (`STALE_GAP_S`). Есть такие деньги в окне — знак есть;
 * нет — окно закрыто достаточно, чтобы верить числу. Ни одной константы про
 * «сколько процентов считать заметным» здесь нет и не будет: у движка
 * запрошены доля незакрытого и счёт открытых дней на окно, и когда они
 * приедут, правило переедет на них одной строкой.
 */

export type НеИтогПочему =
  /** Окно включает сегодняшний день — он идёт прямо сейчас. */
  | "today"
  /** Окно упирается в дни, которые сборщик так и не закрыл. */
  | "not-closed";

export interface FinalityInput {
  /** Первый день окна (`board.since`), `YYYY-MM-DD`. Нужен, чтобы сказать «1
   *  день из 30», а не просто «день не закрыт»: «не закрыт один из тридцати» и
   *  «не закрыты все тридцать» — разные новости, и решения по ним разные. */
  since?: string | null;
  /** Последний день окна, как его вернул демон (`board.until`), `YYYY-MM-DD`. */
  until: string;
  /** Сегодня — днём МЕСТНОГО календаря, а не UTC.
   *
   *  Через `toISOString` нельзя: он переводит в UTC, и восточнее Гринвича
   *  «сегодня» превращается во вчера — метка «день ещё идёт» пропала бы ровно
   *  там, где день и правда идёт. Та же причина, что у `ymd` в листе. */
  today: string;
  /** Есть ли в срезе ПРОШЛЫЙ день, который сборщик не закрыл (`account_day.
   *  closed_at IS NULL`) и не дочитал.
   *
   *  ПОЧЕМУ ПРИЗНАКОМ, А НЕ ДАТОЙ «закрыто по такое-то число». Довод движка, и
   *  он решающий: кабинеты живут в разных гео. У UTC+3 сутки 14.08 кончились в
   *  21:00 UTC, у Лос-Анджелеса — в 07:00 UTC пятнадцатого, и в любой момент
   *  между этими часами половина парка за ОДИН И ТОТ ЖЕ день закрыта, а
   *  половина нет. Одна дата на весь лист обязана соврать в одну из сторон:
   *  рано — пометит верные числа неверными, поздно — снимет метку с занижённых.
   *  Признак «есть хоть один незакрытый» такого выбора не требует. */
  openDays?: boolean;
  /** Сколько дней окна НЕ ЗАКРЫТО — числом от сборщика (`window_open_days`).
   *
   *  Пока не приезжает, панель считает по тому, что знает наверняка: сегодня
   *  внутри окна — это один незакрытый день, плюс `openDays` — признак, что
   *  есть и прошлые. Тогда счёт становится «как минимум N», и подпись говорит
   *  именно так, а не выдумывает точное число. */
  openDaysCount?: number | null;
  /** Сколько дней в окне по данным сборщика (`window_days`). Может отличаться
   *  от календарной длины: в окне бывают дни, за которые нет ни одной строки, и
   *  считать их незакрытыми нельзя — их просто нет. */
  windowDaysFromEngine?: number | null;
  /** РЕШЕНИЕ СБОРЩИКА: заметно ли незакрытое в сумме окна. Считается у него
   *  вместе с порогом (`open_spend / window_spend`), панель его не повторяет.
   *  Не приехало — панель обходится без порога вовсе, см. разбор ниже. */
  materialFromEngine?: boolean | null;
  /** По какой день сборщик считает дни ЗАКРЫТЫМИ, если однажды такое поле
   *  всё-таки появится одной датой. Оставлено ради полноты и НЕ является
   *  предпочтительным путём — см. довод про таймзоны выше. */
  closedThrough?: string | null;
}

export interface НеИтог {
  почему: НеИтогПочему;
  /** Подпись под крупным числом вместо «spend». */
  label: string;
  /** Что это значит, под курсор. */
  hint: string;
  /** Ставить ли ≥ на КРУПНОМ числе.
   *
   *  Отдельно от самого факта незакрытости, и в этом вся правка: слова про
   *  состав окна человек имеет право видеть всегда, а утверждение «это нижняя
   *  граница» делается только когда незакрытое ЗАМЕТНО в сумме. */
  граница: boolean;
  /** Состав окна словами: «1 of 30 days», «at least 2 of 30 days». Пусто —
   *  окно однодневное, и говорить про доли нечего. */
  дни: string;
  /** Доля незакрытых дней в окне, 0..1. Наружу — чтобы тест сверял решение с
   *  числом, а не с текстом. */
  доля: number;
}

/** Сколько дней в окне. `null` — границы неизвестны или бессмысленны.
 *
 *  Считается по календарю, а не делением секунд: часовые пояса и переход на
 *  летнее время делают «сутки» неровными, а нам нужен счёт КЛЕТОК календаря. */
export function днейВОкне(since?: string | null, until?: string | null): number | null {
  if (!since || !until) return null;
  const a = Date.parse(`${since}T00:00:00Z`);
  const b = Date.parse(`${until}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b) || b < a) return null;
  return Math.round((b - a) / 86_400_000) + 1;
}

/* ── КТО РЕШАЕТ, ЧТО НЕЗАКРЫТОЕ «ЗАМЕТНО» ─────────────────────────────────── */

/* Разобрано с автором сборщика (#149), и его довод отменил мою первую попытку
 * целиком. Я хотел считать заметность по `stale_spend` — деньгам, снятым сильно
 * раньше конца суток. Это ОТВЕТ НА ДРУГОЙ ВОПРОС: `stale_spend` меряет качество
 * сбора («недобрали хвостик», «токен умер»), а знак ≥ утверждает, что
 * показанное — нижняя граница и правда выше. Причина роста ровно одна:
 * НЕЗАКРЫТЫЙ ДЕНЬ.
 *
 * ПОРОГА В ПАНЕЛИ НЕТ И НЕ БУДЕТ. Правило продукта живёт в одном месте, и это
 * движок: две константы в двух языках расходятся молча — сегодня мы разбирали
 * ровно это на четырёх копиях предиката гео. Сборщик считает долю незакрытого
 * одним запросом по `account_day` (`open_spend / window_spend`) и сам решает,
 * заметна ли она; панель читает решение.
 *
 * ПОКА РЕШЕНИЕ НЕ ПРИЕХАЛО, панель обходится БЕЗ порога, а не заводит свой:
 * знак ставится только там, где незакрытое и есть всё окно целиком —
 * однодневное «сегодня». Это не порог, а тождество: доля равна единице. Во всех
 * остальных окнах остаются слова, и они честны сами по себе.
 *
 * Числа, которыми автор сборщика показал цену ошибки: 30 дней с одним идущим
 * днём — 3%, семь дней — 14%, «сегодня» — 100%. Между «днём из месяца» и «днём
 * из недели» и лежит граница, которую он ставит у себя. И главное его измерение:
 * на копии живой базы за 30 дней открытых дней НОЛЬ и незакрытых денег НОЛЬ —
 * то есть метка не должна стоять нигде, а стояла везде. Это и был дефект,
 * независимый от любого порога. *//** Окончательно ли число за это окно. `null` — да, окончательно.
 *
 *  Пустые даты — это «ответа ещё нет», и тогда мы молчим: нарисовать «не итог»
 *  до первого ответа значит пометить пустой экран. */
export function неИтог(i: FinalityInput): НеИтог | null {
  if (!i.until || !i.today) return null;

  const сегодняВнутри = i.until >= i.today;
  const незакрытыеПрошлые = Boolean(i.openDays) || Boolean(
    i.closedThrough && i.until > i.closedThrough,
  );
  if (!сегодняВнутри && !незакрытыеПрошлые) return null;

  /* Длину окна берём У СБОРЩИКА, когда он её прислал: в окне бывают дни без
     единой строки, и календарь про них ничего не знает. */
  const всего = (typeof i.windowDaysFromEngine === "number" && i.windowDaysFromEngine > 0
    ? i.windowDaysFromEngine
    : днейВОкне(i.since, i.until)) ?? 1;
  /* Точное число берём у сборщика, если оно есть; иначе считаем по тому, что
     знаем наверняка, и говорим «как минимум». Выдумывать счёт нельзя: на нём
     держится решение про знак. */
  const точно = typeof i.openDaysCount === "number" && Number.isFinite(i.openDaysCount)
    ? Math.max(0, Math.min(всего, Math.round(i.openDaysCount)))
    : null;
  const открытых = точно ?? ((сегодняВнутри ? 1 : 0) + (незакрытыеПрошлые ? 1 : 0));
  const доля = всего > 0 ? Math.min(1, открытых / всего) : 1;
  /* Решение — сборщика, когда оно есть. Своего порога панель не заводит:
     единственное, что она берёт на себя без него, — тождество «незакрытое и
     есть всё окно», где доля равна единице и сравнивать не с чем. */
  const граница = typeof i.materialFromEngine === "boolean"
    ? i.materialFromEngine
    : доля >= 1;

  const многодневное = всего > 1;
  const дни = !многодневное
    ? ""
    : `${точно === null && открытых > 1 ? "at least " : ""}${открытых} of ${всего} days`;

  /* Причина называется ОДНА и самая близкая: когда сегодня внутри окна, оно и
     объясняет число сейчас, даже если в окне есть ещё и незакрытые прошлые дни.
     Две причины подряд в одной плашке читаются как «всё сломано». */
  const почему: НеИтогПочему = сегодняВнутри ? "today" : "not-closed";
  const чтоЗначит = граница
    ? "Its share of this window is large enough that the figure is a lower bound: the real "
      + "total is higher."
    : "Its share of this window is small, and the rest of the window is settled — that is "
      + "why the figure is shown as a total, not as a lower bound.";

  return {
    почему,
    /* Подпись «spend so far» — тоже утверждение о числе, поэтому она следует за
       знаком, а не за самим фактом незакрытого дня. */
    label: граница ? (почему === "today" ? "spend so far" : "spend, day not closed") : "spend",
    hint:
      (почему === "today"
        ? многодневное
          ? `Today is still running, so ${дни} in this window is not closed yet. `
          : "Today is still running, so this is what has accrued so far — not the day's total. "
        : `${дни || "A day"} in this window ${открытых > 1 ? "are" : "is"} not closed: the `
          + "total was read before the day ended in the ad account's own time zone. ")
      + чтоЗначит,
    граница,
    дни,
    доля,
  };
}

/** Число как НИЖНЯЯ ГРАНИЦА: «≥ $856.82».
 *
 *  Знак стоит перед числом, а не после, и это не вкус: «$856.82+» читается как
 *  часть суммы и теряется в колонке цифр, а «≥» ломает форму строки и потому
 *  замечается без чтения подписи. Ровно этого и добиваемся — человек смотрит на
 *  крупное, а не на поповер.
 *
 *  «Примерно» (~) было бы враньём в другую сторону: мы не знаем, сколько
 *  недобрали, но знаем ТОЧНО, что не больше показанного. */
export function нижняяГраница(text: string): string {
  return `≥ ${text}`;
}

/* ── ЧТО ПРИСЛАЛ СБОРЩИК ПРО СОСТАВ ОКНА ──────────────────────────────────── */

/** Три числа доски, если они там есть: сколько дней окна не закрыто, сколько
 *  их всего и заметно ли незакрытое в сумме.
 *
 *  ОДНА ДВЕРЬ, И ОНА ТЕРПИТ ОТСУТСТВИЕ. Полей может не быть на этом деплое —
 *  сборщик кладёт их в `/board` отдельной правкой, — и это НЕ ошибка: тогда
 *  правило обходится без порога вовсе. Разбор через `unknown`, а не через
 *  готовый тип, по той же причине, что у `тишина` рядом: половинчатый ответ не
 *  должен превращаться в утверждение.
 *
 *  ИМЕНА С ЯВНОЙ ПРИВЯЗКОЙ К ОКНУ, и это не педантизм автора сборщика. `open_days`
 *  в ответе `/collector` УЖЕ ЗАНЯТО и значит другое: открытые прошедшие дни
 *  арендатора вообще, без всякого окна. Одно слово на два разных числа в двух
 *  ответах разъедется молча, как только третий читатель начнёт читать оба, —
 *  поэтому здесь `window_open_days` и `window_days`.
 *
 *  Каждое поле читается ОДНИМ именем: чтение синонимов не защищает от
 *  рассинхрона, а прячет его. */
export interface СоставОкна {
  openDays: number | null;
  windowDays: number | null;
  /** Решение сборщика «незакрытое заметно в сумме». `null` — не прислал. */
  material: boolean | null;
  /** Доля незакрытого в сумме окна, 0..1. СПРАВКА ДЛЯ ПОДСКАЗКИ, а не
   *  основание: сравнивать её с порогом панель не имеет права — порог живёт в
   *  движке вместе с решением (`material`). */
  share: number | null;
}

export function readOpenDays(board: unknown): СоставОкна {
  const b = (board && typeof board === "object" ? board : {}) as Record<string, unknown>;
  const число = (v: unknown): number | null =>
    typeof v === "number" && Number.isFinite(v) && v >= 0 ? v : null;
  const доля = число(b.stale_share);
  return {
    openDays: число(b.window_open_days),
    windowDays: число(b.window_days),
    material: typeof b.stale_material === "boolean" ? b.stale_material : null,
    share: доля !== null && доля <= 1 ? доля : null,
  };
}
