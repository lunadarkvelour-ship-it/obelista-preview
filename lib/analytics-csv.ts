/* Настроенная таблица аналитики → CSV.
 *
 *  Экспортируется ровно то, что на экране: те же строки, в том же порядке, с
 *  теми же колонками. Поэтому на вход идёт уже разложенный `flat`, который
 *  считает лист (`AnalyticsView` → `CreativeTable rows={flat}`), а не корни
 *  дерева. Своя реализация обхода дала бы второй порядок сортировки и второй
 *  набор фильтров, которые разъехались бы с таблицей на первой же правке — а
 *  человек, выгрузивший файл, об этом бы не узнал.
 *
 *  Следствие, которое надо знать: свёрнутая ветка в файл не попадает. Это не
 *  потеря, а тот же контракт «что вижу, то и выгружаю» — но чтобы выгрузить
 *  кабы, ветку надо сперва развернуть.
 *
 *  НЕСОБРАННОЕ — ПУСТАЯ ЯЧЕЙКА, А НЕ НОЛЬ (#122). Разница не косметическая:
 *  ноль в спенде значит «крутилось и не потратило», пустота — «не собрали, и
 *  сколько там на самом деле, мы не знаем». В Экселе они тоже не одно и то же —
 *  `СРЗНАЧ` пустые пропускает, а нули считает и занижает результат. Поэтому
 *  `null` печатается пустотой ВЕЗДЕ, включая производные: делить не на что —
 *  пусто, а не 0.00. Для состояния кабинета правило зеркальное — там пустота
 *  двусмысленна, и вместо неё едет слово (см. `UNKNOWN_STATE`).
 *
 *  ЧИСЛА СЫРЫЕ, не форматированные. В таблице `money` печатается как «$142.90»,
 *  здесь будет `142.9`: файл открывают в Экселе и считают по нему дальше, а
 *  строка с валютой и разделителями тысяч там становится текстом, который не
 *  суммируется. По той же причине доли остаются долями: `sub_to_ftd` = `0.5`,
 *  а не «50%» — процент из этого делается форматом ячейки, обратно уже нет.
 */
import { derive, type Node } from "./analytics-tree";
import { BY_KEY, type ColKey } from "./analytics-columns";
import { totalCell, totalsOf } from "./analytics-total";
import type { AccountFact } from "./analytics-accounts";

/** Минимум, который нужен от строки таблицы. `Flat` из `CreativeTable`
 *  подходит структурно — тип компонента сюда не тащим, чтобы `lib` не зависела
 *  от разметки. */
export interface CsvRow {
  node: Node;
  depth: number;
}

/** Поля, которые едут перед метриками всегда, независимо от выбранных колонок.
 *
 *  `level` и `depth` вместе, хотя выглядят дублем: `level` говорит, ЧТО это
 *  (крео, каб, кампания), `depth` — под кем оно лежит. В плоском файле без
 *  второго не собрать обратно вложенность, без первого не отфильтровать один
 *  уровень. Оба дешёвые.
 *
 *  `account` и `agency` появились вместе с #132. На экране строка кабинета
 *  подписана ИМЕНЕМ («Hiuhiu_MediaBuyer_3.8_2»), а `name` в файле у неё —
 *  act_id: контракт «что вижу, то и выгружаю» ломался ровно на той строке, ради
 *  которой иссус и заведён. Оба поля приезжают с лесом и потому есть всегда,
 *  когда есть сама строка. */
const HEAD = [
  "level", "depth", "name", "act_id", "account", "agency", "fb_id", "status",
] as const;

/** Слово для состояния, которого НИКТО НЕ СНИМАЛ.
 *
 *  Пустая ячейка тут не годится: у строк крео, кампаний и адсетов состояния не
 *  бывает вовсе, и они в этой колонке пусты законно. Пустой кабинет читался бы
 *  так же — «у этого уровня статуса не бывает», — хотя правда другая: статус у
 *  кабинета есть, просто мы его не спрашивали. Слово отличает второе от первого
 *  (#122), и оно же попадёт в фильтр Экселя отдельным значением. */
export const UNKNOWN_STATE = "unknown";

/** Экранирование по RFC 4180: кавычка удваивается, поле в кавычках — если
 *  внутри разделитель, кавычка или перенос строки.
 *
 *  Имена крео и кабов приходят от людей и от Меты: там встречаются и запятые
 *  («Barnes George 06 08 2026, backup»), и кавычки. Без экранирования такая
 *  строка молча сдвигает все колонки правее себя — и это заметят не сразу, а
 *  на цифрах, которые не сойдутся. */
export function escapeCsv(v: string): string {
  return /[",\n\r]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
}

/** Число в вид, который Эксель прочитает числом.
 *
 *  Деньги до сотых, доли до 1e-4: `spend / sub` даёт хвосты вида
 *  0.30000000000000004, и в файле они выглядят как ложная точность. */
function numCell(v: number | null, kind: string): string {
  if (v == null || !Number.isFinite(v)) return "";
  if (kind === "money") return v.toFixed(2);
  if (kind === "pct") return v.toFixed(4);
  return String(v);
}

function cell(n: Node, key: ColKey): string {
  // `geos` — единственная текстовая метрика: список стран. Разделяем пробелом,
  // как в таблице; запятая внутри поля потребовала бы кавычек на каждой строке.
  if (key === "geos") return escapeCsv(n.geos.join(" "));
  return numCell(derive(n, key), BY_KEY[key]?.kind ?? "int");
}

/** Состояние объекта строки словом Меты.
 *
 *  У объявления это его доставка (`effective_status`), у кабинета — состояние
 *  самого кабинета, сведённое из базы и снапшота (`lib/analytics-accounts`).
 *  Кабинет без ответа получает слово `unknown`, а не пустоту: см. UNKNOWN_STATE.
 *  У крео, кампании и адсета состояния нет — пусто, и это честно. */
function state(n: Node, accounts?: Map<string, AccountFact>): string {
  if (n.kind !== "account") return n.status ?? "";
  return accounts?.get(n.act_id ?? "")?.status ?? UNKNOWN_STATE;
}

export interface CsvOpts {
  /** Что известно о кабинетах — тот же индекс, что рисует таблицу. Без него
   *  состояние кабинета в файле будет `unknown` у всех: это верно (мы правда
   *  ничего не знаем), но бесполезно. */
  accounts?: Map<string, AccountFact>;
  /** Сколько крео среза скрыто фильтром. Едет в строку ИТОГО той же фразой, что
   *  на экране: итог считается по показанным, и файл обязан сказать, что
   *  показано не всё. */
  hidden?: number;
}

/** Строки таблицы → тело CSV. Без BOM: его добавляет тот, кто отдаёт файл,
 *  чтобы тесты сравнивали текст, а не невидимый префикс. */
export function toCsv(rows: CsvRow[], visible: ColKey[], opts: CsvOpts = {}): string {
  const cols = visible.filter((k) => BY_KEY[k]);
  const head = [...HEAD, ...cols.map((k) => BY_KEY[k].title)];

  const lines = [head.map(escapeCsv).join(",")];
  for (const r of rows) {
    const n = r.node;
    lines.push(
      [
        n.kind,
        String(r.depth),
        escapeCsv(n.label ?? ""),
        escapeCsv(n.act_id ?? ""),
        escapeCsv(n.act_name ?? ""),
        escapeCsv(n.agency ?? ""),
        escapeCsv(n.fb_id ?? ""),
        escapeCsv(state(n, opts.accounts)),
        ...cols.map((k) => cell(n, k)),
      ].join(","),
    );
  }

  /* Строка ИТОГО — та же, что стоит под таблицей на экране, и по той же
     причине, по которой она там есть: цену депа НЕЛЬЗЯ получить, усреднив
     колонку. Крео с одним депом за $290 и крео с десятью по $58 дают «среднее»
     $174 при настоящих $139 (`analytics-total.ts`). Человек, открывший файл,
     посчитает именно средним — это первое, что делает Эксель, — и разойдётся с
     панелью в полтора раза на цифре, по которой закрывают связки.

     Считается по строкам КРЕО, как и на экране: кабы и объявления внутри — те
     же деньги ещё раз, и сложить всё подряд значит удвоить итог. */
  const tops = rows.filter((r) => r.node.kind === "creative").map((r) => r.node);
  if (tops.length) {
    const t = totalsOf(tops);
    const hidden = opts.hidden ?? 0;
    lines.push(
      [
        "total",
        "",
        escapeCsv(
          hidden > 0
            ? `${tops.length} of ${tops.length + hidden} creatives`
            : `${tops.length} creative${tops.length === 1 ? "" : "s"}`,
        ),
        "", "", "", "", "",
        ...cols.map((k) => {
          const v = totalCell(t, k);
          // `undefined` — итога в этой колонке не бывает (гео это перечисление).
          return v === undefined ? "" : numCell(v, BY_KEY[k]?.kind ?? "int");
        }),
      ].join(","),
    );
  }

  // Хвостовой перенос: без него последняя строка у части парсеров съедается.
  return lines.join("\n") + "\n";
}

/** Имя файла с периодом среза: выгрузок за разные дни в папке скапливается
 *  много, и «analytics.csv (3)» через день не отличить одну от другой.
 *
 *  Даты сюда обязаны приходить из ОТВЕТА демона (`board.since/until`), а не из
 *  полей ввода на экране: поля уезжают вперёд данных при выборе пресета, при
 *  ручном вводе (дебаунс) и навсегда, если запрос упал. Имя, обещающее период,
 *  которого в файле нет, хуже безымянного — спорить с ним человеку нечем.
 *
 *  Пустая дата не склеивается в «analytics-_.csv»: такое имя выглядит как
 *  настоящее и молча врёт про пустой период. Лучше сказать словами. */
export function csvFilename(since: string, until: string): string {
  if (!since || !until) return "obelista-analytics-unknown-period.csv";
  return `obelista-analytics-${since}_${until}.csv`;
}

/** UTF-8 BOM. Без него Эксель под Windows читает файл в кодировке системы, и
 *  кириллические имена кабов («Каб 1») превращаются в кракозябры. Гугл-таблицы
 *  и Numbers BOM игнорируют, так что вреда от него нет. */
export const BOM = "﻿";
