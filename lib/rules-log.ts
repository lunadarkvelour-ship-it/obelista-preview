/**
 * Журнал авто-действий: что правило сделало, по какой цифре — и как вернуть.
 *
 * ЗАЧЕМ ОН ВООБЩЕ. Прямое слово владельца: правило потушило объект, и человек
 * обязан увидеть ЧТО, КОГДА и ПО КАКОЙ ЦИФРЕ, а вернуть обратно — одним
 * нажатием, не разбираясь в Ads Manager. Иначе автоматика превращается в то, с
 * чем спорят вручную: «кто-то что-то потушил ночью», и полчаса на выяснение.
 *
 * ТРИ ВЕЩИ, КОТОРЫЕ ЗАПИСЬ ОБЯЗАНА НЕСТИ ВМЕСТЕ. Порознь любая из них
 * бесполезна: «потушено в 3:40» не объясняет почему; «CPL был 7.10» не говорит,
 * что с этим сделали; «правило Rome_CPL» не говорит, к какому объекту оно
 * применилось. Поэтому строка собирается целиком одной функцией, а не
 * складывается в разметке из кусочков — в разметке половину однажды забудут.
 *
 * ОТКАТ — ЭТО ДЕЙСТВИЕ, А НЕ ГАЛОЧКА, и оно может не удаться. Мета отвечает не
 * мгновенно и не всегда согласием, поэтому у кнопки ЧЕТЫРЕ состояния, а не два
 * (`RevertState`). Кнопка, которая нажалась и сразу нарисовала «возвращено», —
 * это обещание вместо факта, ровно того сорта, что мы вычищаем по всему
 * продукту: объект остался бы потушенным, а экран говорил бы обратное.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Ни одного правила о том, «когда откат уместен»: запись
 * откатывается, пока сервер не сказал, что она уже откачена. Своей проверки
 * «прошло ли слишком много времени» тут не будет — расписание и сроки знает
 * воркер, а вторая копия правила разъедется с первой молча.
 */

import {
  RULE_ACTION_LABEL,
  RULE_METRIC_LABEL,
  type Rule,
  type RuleAction,
  type RuleMetric,
} from "./rules";

/** Строка журнала. Форма объявлена панелью заранее и согласована как контракт
 *  с движковой половиной (#141): это не деталь экрана, а стык. */
export interface RuleLogEntry {
  id: string;
  ruleId: string;
  at: string;
  action: RuleAction;
  targetId: string;
  metric: RuleMetric;
  value: number;
  /** Откат отправлен, подтверждения ещё нет. Отдельно от `undoneAt` по той же
   *  причине, по которой у тушения есть `pausePending`: «отправлено» и
   *  «сделано» — разные факты, и показывать второе вместо первого значит
   *  сказать человеку, что объект работает, когда он ещё потушен. */
  undoPending?: boolean;
  /** Движок ПЕРЕЧИТАЛ статус и объект правда вернулся. */
  undoneAt?: string;
  /** Почему откат не удался — словами Меты. Форма та же, что у `failureReason`
   *  у тушения: две формы отказа пришлось бы разбирать порознь и однажды
   *  разобрать по-разному. */
  undoError?: string;
  /** МОЖНО ЛИ ОТКАТИТЬ — РЕШАЕТ СЕРВЕР. Панель этого не выводит: чтобы вернуть
   *  объект, надо знать, каким он был ДО нас, и знает это только движок. */
  canUndo?: boolean;
  /** Каким объект был ДО срабатывания. Это и есть то, что откат восстановит. */
  statusBefore?: string;
}

/* ── Слова ────────────────────────────────────────────────────────────────── */

export interface LogLine {
  /** Что сделано и с чем: «Paused ad set 120210…». */
  what: string;
  /** По какой цифре: «CPL was 7.10 over the last 24h». */
  why: string;
  /** Каким правилом. Имя, если оно известно, иначе честный id. */
  by: string;
}

/** Строка журнала словами.
 *
 *  `rule` необязательно: правило могли выключить или переписать, а запись
 *  осталась — она про прошлое. Подставлять «правило удалено» нельзя (удаления
 *  в продукте нет вовсе), а выдумывать имя тем более: показываем id. */
export function logLine(e: RuleLogEntry, rule?: Rule): LogLine {
  return {
    what: `${RULE_ACTION_LABEL[e.action]} ${e.targetId}`,
    why: `${RULE_METRIC_LABEL[e.metric]} was ${e.value}`,
    by: rule?.name || e.ruleId,
  };
}

/* ── Откат ────────────────────────────────────────────────────────────────── */

export type RevertState =
  /** Можно откатить. */
  | "idle"
  /** Отправлено, подтверждения нет. */
  | "sending"
  /** Сервер подтвердил. */
  | "done"
  /** Мета отказала. */
  | "failed";

export function revertState(e: RuleLogEntry): RevertState {
  if (e.undoneAt) return "done";
  if (e.undoPending) return "sending";
  if (e.undoError) return "failed";
  return "idle";
}

/** Подпись кнопки. Берётся из ПРЕЖНЕГО СТАТУСА объекта, а не из действия
 *  правила, и это исправление, а не оттенок.
 *
 *  Откат ВОЗВРАЩАЕТ ПРЕЖНИЙ СТАТУС, а не «включает». Объект мог лежать на
 *  паузе И ДО НАС: человек поставил сам, правило сработало следом. «Turn back
 *  on» в таком случае — не откат, а чужое решение за человека, принятое нашей
 *  кнопкой. Поэтому слово выбирает `statusBefore`.
 *
 *  Прежний статус неизвестен — кнопки нет вовсе (`canRevert`), и подписи тоже
 *  не требуется: вернуть вслепую хуже, чем не вернуть. */
export function revertLabel(s: RevertState, statusBefore?: string): string {
  switch (s) {
    case "idle":
      return (statusBefore || "").toUpperCase() === "ACTIVE" ? "Turn back on" : "Pause again";
    case "sending": return "Sending…";
    case "done": return "Put back";
    case "failed": return "Try again";
  }
}

/** Можно ли нажать.
 *
 *  Первое слово за СЕРВЕРОМ: `canUndo === false` значит, что прежний статус
 *  неизвестен, и кнопки быть не должно вовсе. Панель этого не выводит сама —
 *  чтобы вернуть объект, надо знать, каким он был до нас.
 *
 *  Дальше — отправленный откат повторно не отправляется: два запроса на один
 *  объект дают две записи в Мете и рассинхрон, который потом никто не
 *  разберёт. */
export function canRevert(e: RuleLogEntry): boolean {
  if (e.canUndo === false) return false;
  const s = revertState(e);
  return s === "idle" || s === "failed";
}

/** Показывать ли кнопку вообще. Отдельно от «можно ли нажать»: погашенная
 *  кнопка обещает, что действие существует и когда-нибудь станет доступным, а
 *  при неизвестном прежнем статусе оно не существует. */
export function showRevert(e: RuleLogEntry): boolean {
  return e.canUndo !== false;
}

/** Журнал в том порядке, в каком его читают: свежее сверху.
 *
 *  Сортировка ЗДЕСЬ, а не в разметке и не на сервере: порядок — часть смысла
 *  («что случилось последним»), и он не должен зависеть от того, в каком
 *  порядке ручка отдала строки. При равном времени решает id — иначе два
 *  действия одной секунды меняются местами между перерисовками. */
export function sortLog(list: readonly RuleLogEntry[]): RuleLogEntry[] {
  return [...list].sort((a, b) => (a.at === b.at ? b.id.localeCompare(a.id)
                                                 : b.at.localeCompare(a.at)));
}
