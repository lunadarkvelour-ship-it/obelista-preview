/**
 * Отсев дерева аналитики: поиск по имени + соц, статус, метод, расход.
 *
 * Поиск тут не «подсветка совпадений», а срез: то, что не попало под запрос, из
 * дерева уходит. Уровень совпадения меняет смысл запроса. Имя крео — вопрос
 * «куда это льётся», ответ обязан включать все кабы и объявления под ним. Имя
 * объявления — вопрос «где эта строка», ответ это она сама плюс цепочка
 * родителей: без кабинета над ней строка бесполезна, потушить нечем.
 *
 * Суммы на промежуточных узлах НЕ пересчитываются. Их посчитал buildTree по
 * полному набору объявлений, и это правда о деньгах. Если пересчитывать под
 * фильтр, спрятанный расход исчезнет из итога каба, и байер увидит меньше, чем
 * реально ушло, — фильтр видимости не должен уметь стирать деньги.
 *
 * Про соц отдельно. Он спрашивается у КАБИНЕТА и по списку `socials` — по всем
 * соцам, которые каб видят. Раньше проверка стояла на `owner`, а это другое
 * поле: соц, которым каб можно ТУШИТЬ, то есть один и только с токеном. В
 * выпадашке при этом стояло десять соцев, а совпасть могли три — семь пунктов
 * молча не находили ничего.
 */
import type { Node } from "./analytics-tree";

export interface TreeFilter {
  /** Подстрока имени, регистронезависимо. Пустая — поиск выключен. */
  q: string;
  /** Профили-соцы. Пустой список — выключено (везде ниже так же). */
  socs: string[];
  statuses: string[];
  methods: string[];
  hideNoSpend: boolean;
}

/** Фильтр включён хоть по одному структурному признаку (не по имени).
 *
 *  Отличать это от поиска важно: узел без детей поиск проходит по своему имени,
 *  а структурный фильтр ему пройти НЕЧЕМ — соц и статус живут ниже. Пока
 *  разница не учитывалась, крео без загруженной ветки выживало всегда, и
 *  фильтр по соцу не убирал со списка ни одной строки. Проверено на панели:
 *  19 строк до фильтра, 19 после. */
function structural(f: TreeFilter): boolean {
  /* `hideNoSpend` сюда НЕ входит, в отличие от соца, статуса и метода.
     Разница не в удобстве, а в том, где живёт признак. Соц и статус есть
     только у потомков, и крео с незагруженной веткой доказать соответствие
     нечем. А расход у крео свой, и его судьбу решают ВЫШЕ по потоку — строки
     без спенда отсеиваются из `board.rows` до сборки дерева
     (`AnalyticsView.tsx:527`). Значит крео, дошедшее сюда, расход уже имеет,
     и убивать его за незагруженных детей — прятать то, что сам же фильтр
     оставил. Внутри ветки признак работает как обычно: строка объявления
     проверяется на своём уровне ниже. */
  return f.socs.length > 0 || f.statuses.length > 0 || f.methods.length > 0;
}

export function filterTree(roots: Node[], f: TreeFilter): Node[] {
  const q = f.q.trim().toLowerCase();
  return keep(roots, f, q, false);
}

function keep(nodes: Node[], f: TreeFilter, q: string, inScope: boolean): Node[] {
  const out: Node[] = [];
  for (const n of nodes) {
    const kept = walk(n, f, q, inScope);
    if (kept) out.push(kept);
  }
  return out;
}

/** @param inScope выше по ветке уже нашлось совпадение по q — значит весь этот
 *  поддерев внутри результата поиска и по имени больше не режется. */
function walk(n: Node, f: TreeFilter, q: string, inScope: boolean): Node | null {
  // Соц — свойство кабинета. Спрашиваем по всему списку соцев, которые каб
  // видят, а не по одному «которым тушить»: вопрос фильтра «что льётся на этом
  // соце», а не «чем я это остановлю».
  if (f.socs.length && n.kind === "account") {
    const socs = n.socials?.length ? n.socials : n.owner ? [n.owner] : [];
    if (!socs.some((s) => f.socs.includes(s))) return null;
  }

  // Статус, метод атрибуции и расход есть только у объявлений. На родителях эти
  // поля пустые, и проверка там означала бы «вырезать всё».
  if (n.kind === "ad") {
    if (f.statuses.length && !f.statuses.includes(n.status ?? "")) return null;
    if (f.methods.length && !f.methods.includes(n.method ?? "")) return null;
    if (f.hideNoSpend && n.spend == null) return null;
  }

  const self = q !== "" && n.label.toLowerCase().includes(q);
  const found = q === "" || inScope || self;

  if (!n.children?.length) {
    // Лист. Под структурным фильтром его судьбу решили проверки выше: строка
    // объявления их прошла и остаётся, а крео без единого объявления доказать
    // соответствие нечем — оно уходит. Иначе «крео без спенда» просачивалось
    // бы через любой фильтр по соцу и статусу.
    if (structural(f) && n.kind !== "ad") return null;
    return found ? { ...n, ...(self && { hit: true }) } : null;
  }

  const kids = keep(n.children, f, q, found);
  // Пустая ветка — мусор: разворачивать нечего, а сумма на ней уже ни к чему не
  // относится. Исключение — узел, который сам нашёлся по запросу: он и есть
  // ответ поиска, и убрать его значит «нашёл и потерял».
  if (kids.length === 0 && !self) return null;

  // Копия неглубокая: сам фильтр в узлы не пишет, а geos/socials переживают
  // отсев без изменений — дублировать их незачем.
  // `hit` пишем только когда есть: без запроса поле не должно появляться
  // вовсе — иначе выключенный фильтр перестаёт быть чистой копией дерева.
  return { ...n, children: kids, ...(self && { hit: true }) };
}

/** Узлы, которые надо раскрыть, чтобы найденное было ВИДНО.
 *
 *  Без этого поиск выглядел сломанным: набираешь имя объявления, дерево честно
 *  оставляет одну ветку — и на экране одна свёрнутая строка крео, под которой
 *  ничего нет. Раскрываем ровно дорогу до совпадений: сам совпавший узел не
 *  разворачиваем, иначе поиск по «--» вываливал бы весь лес.
 */
export function pathsToHits(roots: Node[]): string[] {
  const out: string[] = [];
  const walkPath = (ns: Node[]) => {
    for (const n of ns) {
      if (n.hit) continue; // сам ответ — дальше не раскрываем
      if (n.children?.length) {
        out.push(n.id);
        walkPath(n.children);
      }
    }
  };
  walkPath(roots);
  return out;
}
