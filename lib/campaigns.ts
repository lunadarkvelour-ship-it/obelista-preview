/* Лист «Кампании»: контракт с демоном и всё, что можно посчитать без разметки.
 *
 * УСТРОЙСТВО ЗАДАНО ВЛАДЕЛЬЦЕМ И ОНО ПРО БЮДЖЕТ ВЫЗОВОВ (#125):
 * читаем из СВОЕЙ базы со штампом свежести, пишем в Мету СРАЗУ.
 *
 * Почему так, а не «спросить Graph при открытии листа». Лимит Меты считается на
 * ПРИЛОЖЕНИЕ, а не на кабинет: ~60 вызовов на пятиминутку на всё сразу
 * (`CLAUDE.md`, PROJECT_HISTORY §5). Лист, который ходит в Graph по требованию,
 * ест тот же бюджет, что фоновый сбор спенда, — и первым же открытием душит его.
 * Поэтому чтение идёт в базу (там уже лежат `campaign`, `adset`, `ad`, которые
 * пишет тот же обзор, что снимает спенд), а в Мету уходит ровно одно действие
 * на одно нажатие человека.
 *
 * Отсюда же обязанность показывать ШТАМП СВЕЖЕСТИ у каждой строки. Данные из
 * базы по определению отстают, и лист, который об этом молчит, врёт увереннее,
 * чем лист, который отстал: человек нажимает «выключить» на кампании, которую
 * выключили десять минут назад с телефона, и не понимает, почему ничего не
 * поменялось. Возраст строки — не украшение, а условие, при котором ей можно
 * верить.
 *
 *
 * ЧТО В БЭКЕНДЕ ЕСТЬ (чтение схемы и ручек демона, 16.08)
 *
 *   • `GET /campaigns` СУЩЕСТВУЕТ и читается из базы, а не из Graph — этот
 *     файл её и зовёт (`лист()` ниже). Запись «ручки нет вовсе» стояла здесь
 *     до 16.08 и врала на весь файл: она пережила собственную реализацию, а
 *     рядом с ней жил вызов той самой ручки. Из-за неё же на листе Rules
 *     месяц не было пикера — «нечему перечислить кампании»;
 *   • ручка записи ЕСТЬ: `POST /campaign_status`. Прежняя строка «ручки записи
 *     нет: `manage` живёт MCP-тулом» тоже протухла, и её тоже опровергал
 *     вызов ниже в этом файле;
 *   • `/tree` остаётся тем, чем была: ходит в Graph токеном соца на каждый
 *     вызов, и потому здесь по-прежнему не используется;
 *   • БЮДЖЕТЫ В СХЕМЕ ЕСТЬ — колонки и шаг миграции 9 завёл движок
 *     (иначе на живой базе они не появились бы никогда: `CREATE TABLE IF NOT
 *     EXISTS` существующую таблицу не трогает). Пустыми они будут ровно до
 *     первого круга сбора, и это НЕ повод писать «нет данных» насовсем.
 *     Прежняя запись «бюджетов нет в схеме» протухла и звала завести колонку
 *     второй раз — правка по разбору движковой половины.
 *
 * Панель рисует это ЧЕСТНО: нет поля — прочерк и слово «не собрано», а не ноль
 * и не выдуманное число (#122). Ручки нет — лист говорит об этом прямо и не
 * притворяется пустым кабинетом.
 */
