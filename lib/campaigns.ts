import { периодВЗапрос, type PeriodQuery } from "./period";
import { guardSession } from "./session";

export type Level = "campaign" | "adset" | "ad";

/** Как уровень называется НА ЭКРАНЕ. Короткое, потому что стоит в колонке
 *  шириной в три символа перед именем объекта: полное «campaign» в неё не
 *  влезает и налезает на имя — «campaigRU · smart · 08». Найдено глазами на
 *  снимке, тестами не ловится вовсе: узел есть, текст в нём верный, а видно
 *  кашу.
 *
 *  Живёт здесь, а не в разметке, потому что читателей у него теперь двое:
 *  дерево кампаний и строка воронки без объекта. Второй словарь тех же трёх
 *  слов разъехался бы с первым молча — и разъехался бы именно шириной. */
export const LEVEL_LABEL: Record<Level, string> = {
  campaign: "camp",
  adset: "ad set",
  ad: "ad",
};

/** Строка одного из трёх уровней, как её отдаёт демон ИЗ БАЗЫ.
 *
 *  Одна форма на все три уровня намеренно. Разные типы на кампанию, адсет и
 *  объявление означали бы три ветки кода в каждом обходе, три компоновщика и
 *  три места, где забыли штамп свежести. Уровень — это поле, а не тип. */
export interface CampaignRow {
  fb_id: string;
  level: Level;
  /** Родитель: у адсета — кампания, у объявления — адсет. У кампании `null`. */
  parent_id: string | null;
  act_id: string;
  name: string;
  /** Что человек ПРОСИЛ: ACTIVE / PAUSED / ARCHIVED. */
  status: string | null;
  /** Что происходит НА САМОМ ДЕЛЕ: объявление в активном адсете выключенной
   *  кампании доставляется как `CAMPAIGN_PAUSED`. Разница и есть ответ на
   *  «почему не крутится», поэтому оба поля рядом. */
  effective_status?: string | null;
  /** Бюджеты в МИНОРНЫХ единицах валюты кабинета, как их отдаёт Мета и как их
   *  хранит база (правило проекта: REAL в схеме запрещён, делит на сто тот, кто
   *  рисует). 2000 = 20 долларов.
   *
   *  `NULL` ЧАЩЕ ВСЕГО ЗНАЧИТ «ПОТОЛКА ЗДЕСЬ НЕТ», А НЕ «НЕ СОБРАЛИ». У Меты
   *  бюджет живёт ЛИБО на кампании (CBO), ЛИБО на её адсетах (ABO) — никогда
   *  на обоих, а у объявления его не бывает вовсе: оно тратит бюджет адсета.
   *  То есть пустая половина — НОРМАЛЬНОЕ состояние, и подписывать её «не
   *  собрано» значит посылать человека чинить исправный сбор. Как это
   *  различается на экране — `CampaignsView`, ячейка бюджета.
   *
   *  Ноль — это НЕ пустота: у Меты он значит «ограничения нет», а «$0.00»
   *  читается ровно наоборот. Разные утверждения получают разные слова.
   *
   *  «Не собрано» остаётся ровно на один случай: про объект не знаем ничего
   *  (`status_source: "unknown"`) — тогда пусто и здесь ничего не утверждает. */
  daily_budget?: number | null;
  lifetime_budget?: number | null;
  currency?: string | null;
  /** Когда эту строку последний раз трогал сбор (`updated_at` в базе).
   *  `null` — не знаем; строка тогда честно помечается «возраст неизвестен». */
  checked_at?: string | null;
  /** Соц с токеном, которым объект можно выключить. `null` — выключить нечем,
   *  и кнопка обязана быть выключена С ОБЪЯСНЕНИЕМ, а не молча. */
  owner?: string | null;
  /** ОТКУДА ВЗЯТ `status`, и это поле не про аккуратность, а про доверие.
   *
   *  Замер сборщика 15.08 на копии прода: `status` у ВСЕХ 979 кампаний и 3784
   *  адсетов — `NULL`. Причина не «протухло», а «писателя у этих таблиц в коде
   *  не было никогда»: строки приехали переносом с мака 14.08 (у всех один
   *  `updated_at`) и с тех пор не менялись. Живой оказалась только `ad`.
   *
   *  Пока сбор не обошёл парк, состояние родителя ВЫВОДИТСЯ из доставки его
   *  объявлений (`CAMPAIGN_PAUSED`/`ADSET_PAUSED` — это сама Мета говорит про
   *  родителя). Вывод — не факт, и панель обязана их различать:
   *
   *  • `live` — снято у Меты, это состояние объекта;
   *  • `derived` — выведено из детей; показывается с пометкой, потому что
   *    человек по нему решает, что тушить;
   *  • `unknown` — не знаем; тогда `status` пуст и кнопка выключена.
   *
   *  Поля нет в ответе — считаем `live`: старый сборщик врать не начинал,
   *  он просто не знал про это различие. */
  status_source?: "live" | "derived" | "unknown" | null;
  /** Сколько объявлений под этой строкой ДОСТАВЛЯЕТСЯ прямо сейчас.
   *
   *  Считает сборщик по `effective_status = ACTIVE`, а НЕ по `status`:
   *  включённое объявление в выключенном адсете живым не считается. Разница
   *  тут и есть весь смысл поля — «включено» и «идёт» на живом парке
   *  расходятся сильно.
   *
   *  Есть на всех трёх уровнях. Ноль при включённом статусе — это ответ на
   *  «почему не крутится», и на кампаниях с адсетами он ЕДИНСТВЕННЫЙ: их
   *  `effective_status` сборщик не проставляет вовсе (проверено на живом
   *  кабинете: у 13 кампаний и 54 адсетов он `null`).
   *
   *  Поля нет — значит НЕ ЗНАЕМ, и это не ноль: ноль означает «ни одно не
   *  доставляется», а отсутствие — «не считали». */
  active_ads?: number | null;
  /** Расход ЗА ВЫБРАННЫЙ ПЕРИОД, МИНОРНЫМИ ЕДИНИЦАМИ ВАЛЮТЫ СТРОКИ, целым.
   *
   *  ИМЯ БЕЗ «today» — НЕ КОСМЕТИКА (#154). Поле называлось `spend_today` и
   *  значило сегодняшний день; с появлением выбора периода оно значит окно,
   *  которое выбрал человек. Оставить старое имя было бы ровно тем дефектом,
   *  на котором мы уже стояли: `registration_open` пережил смысл, панель читала
   *  поле ПО ИМЕНИ, а предупреждение автора лежало в докстроке, которую панель
   *  не читает. Переименование ломает сборку у всех читателей сразу — это и
   *  нужно: молча пустая (или молча не та) колонка хуже красного билда.
   *
   *  Единицы названы прямо, потому что пример в иссусе #125 их путает: бюджеты
   *  в той же строке целые минорные (`7000`), а спенд был написан долларами с
   *  копейками (`18.73`). Двух форматов денег в одной строке быть не может —
   *  это прямая дорога показать сумму в сто раз не ту, и заметить будет некому.
   *  Панель делит на сто РОВНО ОДНИМ местом (`budget`). Сквозной сторож на всю
   *  цепочку — `tests/test_spend_units_end_to_end.py`.
   *
   *  `null` — за это окно у нас нет ни одной строки расхода. Это НЕ ноль: ноль
   *  означает «крутилось и не потратило». */
  spend?: number | null;
  /** Показы за тот же период. `null` — строк за окно нет вовсе. */
  impressions?: number | null;
  /** Клики за тот же период (`clicks` Меты — все клики, не только по ссылке). */
  clicks?: number | null;
  /** Клики ПО ССЫЛКЕ (`inline_link_clicks`). Отдельно от `clicks` намеренно:
   *  тот считает и реакции, и разворот текста, и клик по имени страницы, из-за
   *  чего CTR по нему завышен втрое. Байер меряет этим. */
  link_clicks?: number | null;
  /** Охват — УНИКАЛЬНЫЕ ЛЮДИ, и потому он есть НЕ ВЕЗДЕ.
   *
   *  Число приходит только у объявления и только когда окно — одни сутки: это
   *  ровно та строка, которую посчитала Мета. У родителя и на длинном окне
   *  `null`, и это НЕ «не собрали»: сумма охватов за семь дней считает одного
   *  человека семь раз, а сумма по объявлениям адсета — дважды того, кто видел
   *  оба. Дедупликацию делает Мета и только для того окна, о котором её
   *  спросили; внутри дня разбивки не существует.
   *
   *  Прочерк без объяснения тут читается как пробел в сборе, поэтому у него
   *  есть слова — `почемуНетОхвата()`. Выдуманный охват хуже пустого. */
  reach?: number | null;
  /** РЕЗУЛЬТАТЫ — событие, под которое оптимизируется адсет, за это окно.
   *
   *  Не «какое-то действие покрупнее». В одном живом ответе Меты 15.08 рядом
   *  лежали `offsite_conversion.fb_pixel_lead` = 9 (настоящий результат) и
   *  `post_engagement` = 4479. Взять второе значит показать цену результата в
   *  ПЯТЬСОТ РАЗ ниже настоящей — то есть не ошибку на экране, а повод залить
   *  больше денег. Тип события выбирает `core/results.py` по цели адсета.
   *
   *  `null` — «мы не знаем, что здесь считать результатом» (цель незнакомая или
   *  конверсия без события). Это НЕ ноль: ноль значит «событие настроено и не
   *  случилось». Первое лечится сбором и пикселем, второе — крео и ставкой. */
  results?: number | null;
  /** ЧЕМ измерен результат: `offsite_conversion.fb_pixel_lead`, `link_click`…
   *
   *  Число без него — величина без единицы измерения: девять лидов и девять
   *  покупок выглядят одинаково и стоят разного. Приезжает из строки расхода, а
   *  не с адсета: цель меняют на ходу, и вчерашние лиды не должны задним числом
   *  превращаться в покупки. */
  result_type?: string | null;
  /** Под этой строкой цели РАЗНЫЕ, и сумма была бы числом без смысла.
   *
   *  Третье состояние рядом с числом и пустотой. Девять лидов плюс две покупки
   *  — это не одиннадцать чего-то, особенно когда рядом встаёт цена результата.
   *  Адсеты с разными целями под одной кампанией — обычное дело. */
  results_mixed?: boolean | null;
}

/** Период, за который посчитан ответ — РАЗРЕШЁННЫЙ ДЕМОНОМ, а не тот, что
 *  набрала панель.
 *
 *  Панель присылает ЛИБО имя пресета, ЛИБО пару дат, а «какое сегодня число»
 *  считает только демон (`core/period.py`): браузер живёт в поясе своего
 *  человека, а продукт — в своём (сейчас UTC+3). Два счётчика «сегодня»
 *  разъехались бы в первую же ночь на границе суток. Поэтому даты, по которым
 *  реально сделана выборка, приезжают ОТВЕТОМ и ими же подписывается экран. */
export interface Period {
  /** Имя пресета, если период задан им, а не парой дат. */
  preset?: string | null;
  since: string;
  until: string;
  /** Пояс продукта: сейчас `UTC+3` из `core/period.py`, завтра — из Settings. */
  tz: string;
  offset_minutes?: number | null;
  /** Сколько дней в окне. */
  days: number;
  /** Какое сегодня число В ПОЯСЕ ПРОДУКТА. Календарь подсвечивает по нему, а
   *  не по часам браузера. */
  today: string;
  /** За сколько дней окна у ЭТОГО кабинета есть хоть одна строка расхода.
   *
   *  Это факт, а не оценка полноты: сбор заводит строки только там, где деньги
   *  были — `insights` пустых дней не отдаёт вовсе. День без строк значит либо
   *  «не крутились», либо «не собрали», и различить их этим числом нельзя.
   *  Оно отвечает на другой вопрос: «сумма собрана из скольких дней». */
  days_with_data?: number | null;
  /** Самый ранний день, который вообще хранится. За его пределами пусто не
   *  потому, что деньги потеряли, а потому что так настроено хранение. */
  stored_from?: string | null;
  /** Пояс САМОГО КАБИНЕТА и совпадают ли его сутки с нашими.
   *
   *  Мета режет дни по часам кабинета (`insights` с `time_increment=1`), и
   *  переложить их в наши границы нечем — внутри дня разбивки не существует.
   *  Там, где пояса расходятся, «данные ровно за ваши сутки» — неправда, и
   *  экран обязан это сказать. `null` в `same_day_boundary` — пояс кабинета
   *  неизвестен (на живом парке таких больше половины), и это не «совпадает». */
  account_tz?: string | null;
  account_offset_minutes?: number | null;
  same_day_boundary?: boolean | null;
}

export interface CampaignsResponse {
  ok?: boolean;
  rows?: CampaignRow[] | null;
  /** Когда демон собрал ОТВЕТ. Не то же, что возраст строк: строки снимались
   *  каждая в своё время, и это видно в `checked_at`. */
  generated_at?: string | null;
  /** За какой период посчитаны цифры — датами. Необязательное только для
   *  совместимости со старым деплоем демона: без него экран обязан говорить
   *  «период неизвестен», а не подписывать цифры выбранными кнопками. */
  period?: Period | null;
}

/** Ответ ручки записи. Она ходит в Мету СИНХРОННО и возвращает то, что Мета
 *  сказала: панель не гадает по кодам, а показывает результат.
 *
 *  `status` — состояние ПОСЛЕ записи, прочитанное из ответа Меты, а не то, что
 *  мы просили. Разница важна: `POST` может пройти, а объект остаться
 *  `WITH_ISSUES`, и нарисовать зелёное по факту «двухсотки» значит соврать. */
export interface WriteResult {
  ok?: boolean;
  fb_id?: string;
  status?: string | null;
  effective_status?: string | null;
  /** Когда изменение доехало. Штамп свежести строки после записи равен ему. */
  applied_at?: string | null;
  error?: string | null;
}

async function call<T>(
  path: string,
  params: Record<string, string | null> = {},
  init?: RequestInit,
): Promise<T> {
  const url = new URL(API_BASE + path);
  for (const [k, v] of Object.entries(params)) if (v) url.searchParams.set(k, v);
  const r = await fetch(url.toString(), { cache: "no-store", ...init });
  /* До разбора тела: 401 — это «сессия кончилась», и тело тут ни при чём.
     Разбор один на всю панель (`lib/session`), чтобы не заводить ветку на лист. */
  guardSession(r);
  const data = await r.json().catch(() => ({}));
  /* «Ручки нет» отделяем от всего остального ОТДЕЛЬНЫМ типом ошибки: её может
     ещё не быть на этом деплое, и это не поломка, а «бэкенд не доехал».
     Проверено на живом проде 15.08: демон отвечает на незнакомый путь НЕ 404, а
     `400 {"ok": false, "error": "нет такого пути: /campaigns"}`. Ловить один
     только 404 значило показать человеку красную плашку с нашей внутренней
     фразой по-русски в английском интерфейсе — вместо честного «эта ручка ещё
     не выкачена». Ловим оба признака: код и текст. */
  const текст = String(data?.error ?? "");
  if (r.status === 404 || текст.includes("нет такого пути")) throw new NoHandle(path);
  if (!r.ok || data?.ok === false) {
    throw new Error(текст || `API ${r.status}`);
  }
  return data as T;
}

/** Ручки нет на этом деплое. Отдельный класс, потому что лечение другое: не
 *  «повторить», а «дождаться выката демона». */
export class NoHandle extends Error {
  constructor(public path: string) {
    super(`the collector on this deploy has no ${path} handle yet`);
    this.name = "NoHandle";
  }
}

