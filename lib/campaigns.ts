/* ── свежесть строки ────────────────────────────────────────────────────── */

/** `fresh` — строке можно верить, `stale` — уже стоит перепроверить,
 *  `cold` — сбор эту строку давно не трогал, `unknown` — штампа нет вовсе. */
export type Freshness = "fresh" | "stale" | "cold" | "unknown";

/** Час — граница доверия. Не пять минут (такт спенда) и не сутки.
 *
 *  Состояние объектов снимается не тем же тактом, что деньги: спенд идёт по
 *  «горячим» кабинетам каждые пять минут, а статусы — обзором заметно реже,
 *  потому что бюджет вызовов один на всё. Час — это про то, успел ли обзор
 *  пройти хотя бы раз с прошлого взгляда; всё, что моложе, для решения
 *  «тушить или нет» одинаково свежо. */
export const FRESH_MAX_S = 3600;
/** Сутки — граница между «отстало» и «сбор сюда не доходит». За сутки обзор
 *  обязан обойти весь парк даже на самом скупом бюджете; не обошёл — это уже
 *  новость про сбор, а не про строку. */
export const COLD_MAX_S = 24 * 3600;

export function freshness(iso?: string | null, now: number = Date.now()): Freshness {
  if (!iso) return "unknown";
  const t = new Date(iso).getTime();
  if (!Number.isFinite(t)) return "unknown";
  /* Время из БУДУЩЕГО считаем свежим, а не ломаемся. Часы демона и браузера
     расходятся на минуты, и отрицательный возраст — обычное дело; называть
     его «неизвестно» значит пугать человека расхождением часов. */
  const age = Math.max(0, (now - t) / 1000);
  if (age <= FRESH_MAX_S) return "fresh";
  if (age <= COLD_MAX_S) return "stale";
  return "cold";
}

/** Возраст словами, короткий: «2m», «5h», «3d». Пусто — штампа нет.
 *
 *  Короткий намеренно: он стоит в каждой строке дерева, и «14 hours ago» в
 *  сотне строк съедает колонку имени, ради которой дерево и открывают. */
export function ageShort(iso?: string | null, now: number = Date.now()): string {
  if (!iso) return "";
  const t = new Date(iso).getTime();
  if (!Number.isFinite(t)) return "";
  const s = Math.max(0, Math.round((now - t) / 1000));
  if (s < 60) return `${s}s`;
  if (s < 3600) return `${Math.round(s / 60)}m`;
  if (s < 24 * 3600) return `${Math.round(s / 3600)}h`;
  return `${Math.round(s / (24 * 3600))}d`;
}

/** Фраза для подсказки: чему верить в этой строке и почему.
 *
 *  Отдельно от `ageShort`, потому что короткое «5h» отвечает «когда», а
 *  человеку нужно «и что это значит». Молчать нельзя ровно в том случае, когда
 *  штампа нет: строка без возраста выглядит такой же свежей, как остальные. */
export function freshWhy(iso?: string | null, now: number = Date.now()): string {
  const f = freshness(iso, now);
  if (f === "unknown") {
    return "The collector has not stamped this row: we do not know how old it is. " +
      "Not the same as “just collected”.";
  }
  const age = ageShort(iso, now);
  if (f === "fresh") return `Read from our database, collected ${age} ago.`;
  if (f === "stale") {
    return `Read from our database, collected ${age} ago — it may already have ` +
      `been changed in Meta since.`;
  }
  return `Read from our database, collected ${age} ago. The collector has not ` +
    `reached this ad account for over a day — treat the state as a guess.`;
}

/* ── состояния и переходы ───────────────────────────────────────────────── */

/** Что сделает кнопка на этой строке. `null` — делать нечего.
 *
 *  От `status`, а не от `effective_status`, и это принципиально. У объявления в
 *  выключенной кампании доставка `CAMPAIGN_PAUSED`, но само оно `ACTIVE`, и
 *  кнопка «включить» на нём не сделает НИЧЕГО: Мета примет запрос, вернёт
 *  двухсотку, объявление останется невидимым. Кнопку показываем по тому полю,
 *  которое этой кнопкой и меняется. */
export function nextStatus(row: CampaignRow): "ACTIVE" | "PAUSED" | null {
  const s = (row.status || "").toUpperCase();
  if (s === "ACTIVE") return "PAUSED";
  if (s === "PAUSED") return "ACTIVE";
  /* ARCHIVED и DELETED переключать нечем: Мета обратно их не отдаёт. Пустой
     статус — тоже не повод: не зная, что там сейчас, писать туда нельзя. */
  return null;
}

/** Объект выключен НЕ САМ, а сверху. Строка обязана это сказать: иначе
 *  «выключить» на ней выглядит доступным действием, которое ничего не меняет. */
export function pausedByParent(row: CampaignRow): boolean {
  const e = (row.effective_status || "").toUpperCase();
  return e === "CAMPAIGN_PAUSED" || e === "ADSET_PAUSED";
}

/** Почему кнопка недоступна — словами, или пусто, если доступна.
 *  Выключенная кнопка без объяснения читается как поломка панели. */
export function whyBlocked(row: CampaignRow): string {
  if (!row.owner) {
    return "No connected profile can reach this ad account, so nothing can be " +
      "sent to Meta for it.";
  }
  if (!row.status) return "We do not know the current state, so we will not write over it.";
  if (!nextStatus(row)) return `${row.status} cannot be switched back from the panel.`;
  return "";
}

/* ── ЧТО ГОВОРИТ ЭКРАН ЦЕЛИКОМ: ЧЕТЫРЕ РАЗНЫХ НОВОСТИ, А НЕ ОДНА ПУСТОТА ───
 *
 * Пустой лист умеет означать ЧЕТЫРЕ разные вещи, и лечатся они по-разному:
 *
 *  • `no-backend` — ручки на этом деплое нет. Чинится выкатом демона, и до него
 *    человеку делать нечего. Показать вместо этого пустую таблицу значит
 *    сказать «у тебя ничего нет» — утверждение, которого мы не проверяли.
 *  • `empty` — ручка ответила, строк ноль. Это факт про кабинет, а не про нас.
 *  • `stale` — строки есть, но самый старый ответ уже не свежий (или штампа
 *    нет вовсе). Цифры показывать надо, а вот молчать об их возрасте нельзя:
 *    человек по ним тушит чужую рекламу.
 *  • `ok` — строки есть и они свежие.
 *
 * ВЕРДИКТ ОДИН И СЧИТАЕТСЯ ЗДЕСЬ, а не тремя тернарниками в разметке. Разметка
 * уже умела различать первые два, но различала их СВОИМ условием на каждый
 * блок; третьего не было вовсе — возраст стоял серой строчкой рядом с цифрами
 * и вердиктом не был. Пока правило живёт в разметке, следующая правка добавляет
 * четвёртый тернарник, и два из них начинают спорить.
 *
 * ПОРОГ СВЕЖЕСТИ БЕРЁТСЯ У `freshness()`, А НЕ ЗАВОДИТСЯ СВОЙ. План этой работы
 * предлагал отдельные 30 минут — это был бы ВТОРОЙ ответ на вопрос «когда
 * строке уже нельзя верить», рядом с существующим `FRESH_MAX_S`. Два порога
 * разъедутся молча: поправят один, а экран и строка начнут говорить разное про
 * одни и те же данные (ровно та порода, из-за которой в этом репозитории
 * договорённости держат механизмом). Порог здесь один и он общий. */
export type ЭкранКампаний = "no-backend" | "empty" | "stale" | "ok";

export interface ВходЭкрана {
  /** Ручка `/campaigns` на этом деплое ответила (а не «нет такого пути»). */
  handleOk: boolean;
  /** Строки, которые приехали. Форма не важна — важно, сколько их. */
  rows?: unknown[] | null;
  /** Когда демон собрал ОТВЕТ — самый СТАРЫЙ из показанных. Именно старый:
   *  подпись обещает возраст всего показанного. */
  fetchedAt?: string | null;
  now?: number;
}

export function campaignsSurfaceState(в: ВходЭкрана): ЭкранКампаний {
  /* Порядок веток — от того, что перекрывает остальное. Без ручки строк не
     бывает по определению, и назвать это «пусто» значило бы обвинить кабинет
     в нашей невыкаченности. */
  if (!в.handleOk) return "no-backend";
  if (!в.rows?.length) return "empty";
  return freshness(в.fetchedAt, в.now ?? Date.now()) === "fresh" ? "ok" : "stale";
}

/** Вердикт словами — продуктовыми, не нашими. Пусто у `ok`: экран, который
 *  сообщает «всё в порядке», отнимает место у того, что важно.
 *
 *  `stale` объясняется ДВУМЯ разными фразами, и это не косметика: «собрано три
 *  часа назад» и «штампа нет вовсе» — разные новости, и вторая хуже. Обе живут
 *  в `freshWhy`, второго словаря здесь не заводим. */
export function campaignsSurfaceWhy(
  state: ЭкранКампаний,
  fetchedAt?: string | null,
  now: number = Date.now(),
): string {
  switch (state) {
    case "no-backend":
      return "The collector on this deploy cannot serve this page yet: nothing was read, "
        + "so this is not an empty ad account.";
    case "empty":
      return "The collector has nothing stored for this selection yet. Empty, not zero — "
        + "we are not claiming there is no advertising here.";
    case "stale":
      /* Со штампом — общая фраза о возрасте (`freshWhy`), второго словаря
         возраста в панели нет. БЕЗ штампа — своя, потому что подлежащее другое:
         не строка, а весь ответ, и сказать «эта строка» про экран значило бы
         отправить человека искать несуществующую строку. */
      return fetchedAt
        ? freshWhy(fetchedAt, now)
        : "The collector did not stamp this answer, so we do not know how old these "
          + "numbers are. Not the same as “just collected”.";
    default:
      return "";
  }
}

/* ── МОЖНО ЛИ ТРОГАТЬ СТРОКУ: ОДИН ОТВЕТ НА ВСЕ КНОПКИ ───────────────────── */

export interface ActionState {
  enabled: boolean;
  /** Почему нельзя — законченной фразой. У доступного действия пусто.
   *  Выключенная кнопка без объяснения читается как поломка панели. */
  reason: string;
}

export interface ОпцииДействия {
  /** Вердикт экрана (`campaignsSurfaceState`). Без ручки писать некуда. */
  surface?: ЭкранКампаний;
  /** Строка показана РАДИ КОНТЕКСТА: под фильтр она не подошла, её вытащил
   *  наверх совпавший потомок. Действие на ней человек не выбирал. */
  контекст?: boolean;
  now?: number;
}

/** Доступна ли кнопка действия на этой строке и почему нет.
 *
 *  ОДНА ФУНКЦИЯ НА ВСЕ ПРИЧИНЫ. Причин уже четыре (нет владельца, нечего
 *  переключать, ручки нет, строка старше суток), и разметка выбирала из них
 *  только первые две — остальные две выглядели бы доступной кнопкой, которая
 *  ничего не сделает.
 *
 *  ПОЧЕМУ «ПРОСТО НЕСВЕЖО» НЕ ГАСИТ КНОПКУ, А «СТАРШЕ СУТОК» ГАСИТ. План
 *  предлагал гасить всё, что экран назвал `stale`. Проверено счётом на самом
 *  устройстве листа: вердикт экрана считается по САМОМУ СТАРОМУ ответу из всех
 *  открытых кабинетов, а открыть их можно до 25 (`МАКС_КАБОВ`) — то есть один
 *  отставший кабинет погасил бы кнопки на всех остальных, включая только что
 *  собранные строки. Это ровно та порода защиты, что запрещает больше, чем
 *  должна, а мы её здесь уже проходили дорого.
 *
 *  Поэтому смотрим на возраст САМОЙ СТРОКИ (у каждой он свой — правило №2
 *  устройства листа) и гасим на `cold`: сбор не доходил до неё больше суток,
 *  её состояние — догадка, и писать поверх догадки нельзя. Отрицательный
 *  контроль в тесте: строка без владельца остаётся заблокированной и на
 *  свежем экране, то есть послабление не проглотило настоящую причину. */
export function rowActionState(
  row: CampaignRow,
  опции: ОпцииДействия = {},
): ActionState {
  const нет = (reason: string): ActionState => ({ enabled: false, reason });

  if (опции.surface === "no-backend") {
    return нет("The collector on this deploy cannot send changes to Meta yet.");
  }
  /* Причины самой строки — у `whyBlocked`: она же печатается в подсказке
     прочерка, и второй список причин рядом разъехался бы с ней. */
  const своя = whyBlocked(row);
  if (своя) return нет(своя);
  if (опции.контекст) {
    return нет("Shown for context only: this row does not match the filter. "
      + "Clear the filter to change it.");
  }
  if (freshness(row.checked_at, опции.now ?? Date.now()) === "cold") {
    return нет("The collector has not read this row for over a day, so its state is a "
      + "guess — we will not write over a guess.");
  }
  return { enabled: true, reason: "" };
}

/* ── деньги ─────────────────────────────────────────────────────────────── */

/** Валюты, у которых минимальная единица И ЕСТЬ единица. Тот же короткий
 *  список и та же причина, что в `lib/cloud-accounts.ts`: ошибка в сто раз
 *  видна глазом, а полный несопровождаемый справочник — нет. */
const ZERO_DECIMAL = new Set(["JPY", "KRW", "VND", "CLP", "ISK", "PYG", "RWF", "UGX",
                              "VUV", "XAF", "XOF", "XPF"]);

/** Минорные единицы → человеческая сумма. `null` остаётся `null`: ноль бюджета
 *  и «бюджет не собран» — разные вещи, и вторая на экране обязана быть словом,
 *  а не цифрой (#122). */
export function budget(minor?: number | null, currency?: string | null): number | null {
  if (minor == null || !Number.isFinite(minor)) return null;
  return minor / (currency && ZERO_DECIMAL.has(currency.toUpperCase()) ? 1 : 100);
}

/* ── производные метрики ────────────────────────────────────────────────────
 *
 * СЧИТАЮТСЯ ИЗ СУММ, А НЕ УСРЕДНЯЮТСЯ ПО СТРОКАМ, и это не придирка. Средний
 * CTR трёх объявлений — не CTR их суммы: объявление с двумя показами и одним
 * кликом даёт 50% и перевешивает соседа с миллионом показов. На дереве, где
 * каждая строка сворачивает своих детей, разница между двумя способами — это
 * разница между цифрой и впечатлением.
 *
 * ЖИВУТ ОДНИМ МЕСТОМ, И ЭТО ДОКАЗАНО ДОРОГО. 15.08 спенд занизился в сто раз
 * ровно потому, что две половины продукта делали одно и то же по-разному, и
 * каждая была внутренне логична. Здесь считает одна функция на метрику; вёрстка
 * (`CampaignsView`) их зовёт, а не повторяет.
 *
 * `null` — «посчитать не из чего», и это НЕ ноль. Ноль CTR значит «показывали и
 * не кликали»; отсутствие показов не значит ничего, и нарисовать там 0% —
 * соврать про рекламу, которая не крутилась. Делить на ноль мы тоже не будем:
 * бесконечность на экране читается как поломка, а не как «кликов не было».
 */

/** Доля кликов от показов, В ДОЛЯХ ЕДИНИЦЫ (0.031 = 3.1%). Проценты делает
 *  вёрстка: два формата одного числа в разных местах — та же болезнь, что два
 *  формата денег. */
export function ctr(row: CampaignRow): number | null {
  const i = row.impressions;
  const c = row.clicks;
  if (i == null || c == null || !Number.isFinite(i) || !Number.isFinite(c)) return null;
  if (i <= 0) return null;
  return c / i;
}

/** Цена клика В МИНОРНЫХ ЕДИНИЦАХ, как и спенд рядом: делит на сто `budget()`,
 *  в одном месте. Отдать отсюда доллары значило бы завести в одной строке два
 *  формата денег — ровно то, на чём мы уже показали сумму в сто раз не ту. */
export function cpc(row: CampaignRow): number | null {
  const s = row.spend;
  const c = row.clicks;
  if (s == null || c == null || !Number.isFinite(s) || !Number.isFinite(c)) return null;
  if (c <= 0) return null;
  return s / c;
}

/** Цена тысячи показов, тоже в минорных единицах. */
export function cpm(row: CampaignRow): number | null {
  const s = row.spend;
  const i = row.impressions;
  if (s == null || i == null || !Number.isFinite(s) || !Number.isFinite(i)) return null;
  if (i <= 0) return null;
  return (s * 1000) / i;
}

/** CTR ПО ССЫЛКЕ — доля ссылочных кликов от показов. Тот CTR, которым меряют.
 *
 *  Рядом с `ctr()` намеренно: это разные числа, и на живом объявлении 15.08 они
 *  расходились почти вдвое (329 кликов против 204 ссылочных на 11054 показах).
 *  Одна функция «просто CTR» заставила бы гадать, который из двух показан. */
export function linkCtr(row: CampaignRow): number | null {
  const i = row.impressions;
  const c = row.link_clicks;
  if (i == null || c == null || !Number.isFinite(i) || !Number.isFinite(c)) return null;
  if (i <= 0) return null;
  return c / i;
}

/** Цена ссылочного клика, в минорных единицах — как спенд рядом. */
export function linkCpc(row: CampaignRow): number | null {
  const s = row.spend;
  const c = row.link_clicks;
  if (s == null || c == null || !Number.isFinite(s) || !Number.isFinite(c)) return null;
  if (c <= 0) return null;
  return s / c;
}

/** ЦЕНА РЕЗУЛЬТАТА, в минорных единицах. Главное число листа для байера.
 *
 *  Считается из СУММ спенда и результатов той же строки, а не усредняется по
 *  детям. И не считается вовсе там, где результаты смешаны: делить деньги на
 *  «девять лидов плюс две покупки» — это цена несуществующей вещи, а решение
 *  тушить или лить принимают именно по ней.
 *
 *  Сверено с Метой на живом кабинете 15.08: спенд 44.69 при девяти лидах даёт
 *  4.9656, у неё в `cost_per_action_type` — 4.965556. */
export function costPerResult(row: CampaignRow): number | null {
  if (row.results_mixed) return null;
  const s = row.spend;
  const r = row.results;
  if (s == null || r == null || !Number.isFinite(s) || !Number.isFinite(r)) return null;
  if (r <= 0) return null;
  return s / r;
}

/* ── КАК ЭТА КОЛОНКА НАЗЫВАЕТСЯ, И ПОЧЕМУ НЕ «LEADS» ─────────────────────────
 *
 * Решение 15.08, принятое ДО столкновения, а не после жалобы. На листе встают
 * рядом две колонки, и обе имеют право называться Leads:
 *
 *   • результат Меты — это лид ПИКСЕЛЯ. Замер 15.08 на живом кабинете:
 *     `offsite_conversion.fb_pixel_lead` = 9 на ОДНОМ ОБЪЯВЛЕНИИ;
 *   • лид владельца — подписчик CRM. Замер того же дня (`core/funnel_join.py`):
 *     16974 подписчика ПО ВСЕМУ ПАРКУ за неделю; на одну кампанию максимум —
 *     1990 (проверено по `funnel_daily`).
 *
 * Числа считают РАЗНЫЕ вещи, оба НАСТОЯЩИЕ, и при сравнении сопоставимого
 * расходятся примерно в двести раз. Одно имя на двоих дало бы человеку два
 * ответа на один вопрос без способа понять, какой из них про его деньги.
 * Поэтому слово «лид» не принадлежит никому: половина от Меты — это `Results`
 * (ровно как в Ads Manager), половина из CRM — `Subs` (слово владельца;
 * проверено по коду — так называется колонка в `lib/analytics-columns.ts`, и
 * это же держит сторож `lib/__tests__/campaigns-funnel.test.ts`).
 *
 * ОБЛАСТЬ ЧИСЛА — ТАКАЯ ЖЕ ЕГО ЧАСТЬ, КАК САМО ЧИСЛО, и это урок правки. Здесь
 * стояло «16974 на ТОЙ ЖЕ кампании» и «разница почти в две тысячи раз».
 * Число настоящее и лежит в коде, но оно ПО ПАРКУ за неделю, а делили его на
 * девять лидов одного объявления — park-wide итог, приклеенный к одной строке,
 * даёт множитель на порядок больше правды. Ошибка была не в цифре, а в том, к
 * чему она относится; заметно это только сверкой с данными, потому что и число,
 * и вывод по отдельности выглядят убедительно.
 *
 * Довод про имена от этого не изменился ни на грамм: разойдись числа хоть в
 * двести раз, хоть в две тысячи — звать их одним словом всё равно нельзя.
 *
 * Та же порода, что спенд в сто раз и `spend_today`, начавший значить неделю:
 * обе стороны правы по отдельности и расходятся в момент встречи. Имя — тоже
 * стык, и разводить его надо заранее.
 */

/** Название события ЧЕЛОВЕЧЕСКИМИ ТЕРМИНАМИ МЕТЫ, а не внутренним значением.
 *
 *  Владелец просил дословно: «человеческими и актуальными Facebook-терминами, а
 *  не внутренними значениями». `offsite_conversion.fb_pixel_lead` — это код, а
 *  не слово; на экране рядом с числом должно стоять «Pixel lead».
 *
 *  Незнакомый тип отдаётся КАК ЕСТЬ, а не превращается в «Other»: сырой код
 *  человек хотя бы загуглит, а «Other» не значит ничего и скрывает, что мы
 *  чего-то не знаем. Слово «Leads» в одиночку здесь не появляется намеренно —
 *  оно занято подписчиками CRM на соседней колонке. */
export function названиеРезультата(type?: string | null): string {
  const t = (type || "").trim();
  if (!t) return "";
  const прямые: Record<string, string> = {
    "link_click": "Link clicks",
    "landing_page_view": "Landing page views",
    "post_engagement": "Post engagement",
    "video_view": "Video views",
    "video_thruplay_watched": "ThruPlays",
    "like": "Page likes",
    "mobile_app_install": "App installs",
    "onsite_conversion.lead_grouped": "On-Facebook leads",
  };
  if (прямые[t]) return прямые[t];
  /* Конверсии пикселя: `offsite_conversion.fb_pixel_lead` → «Pixel lead».
     Имя события берём из самого кода, а не из своего списка, — тогда новое
     событие пикселя читается сразу, а не ждёт правки здесь. */
  const пиксель = t.match(/^offsite_conversion\.fb_pixel_(.+)$/);
  if (пиксель) {
    const слова = пиксель[1].replace(/_/g, " ");
    return "Pixel " + слова;
  }
  return t;
}

/** Почему в этой строке нет результата — словами, или пусто, если он есть.
 *
 *  Причин три, и они лечатся по-разному: смешанные цели (лечится тем, что
 *  человек откроет уровень ниже), неизвестная цель (лечится сбором и
 *  настройкой пикселя) и отсутствие сбора за период. Прочерк без слов
 *  отправляет чинить не то. */
export function почемуНетРезультата(row: CampaignRow): string {
  if (row.results != null && !row.results_mixed) return "";
  if (row.results_mixed) {
    return "Ad sets under this row optimise for different events, so there is no " +
      "single “result” to add up — nine leads plus two purchases is not eleven of " +
      "anything. Open the level below to see each goal on its own.";
  }
  if (row.spend == null) {
    return "Nothing was collected for this row in the selected period.";
  }
  return "We do not know which event counts as the result here: the ad set's " +
    "optimisation goal is missing or is a conversion without a pixel event. Meta " +
    "returns two dozen action types per row and none of them is labelled “result”, " +
    "so we show nothing rather than pick one.";
}

/** Частота: сколько раз один человек видел объявление. Показы делить на охват.
 *
 *  Живёт там же, где охват, и по той же причине: без охвата её не существует.
 *  Считать «частоту адсета» как среднее частот его объявлений нельзя — это
 *  разные знаменатели и разные люди. Сверено с ответом Меты на живом кабинете
 *  15.08: 11054/10472 = 1.0556, у неё в `frequency` — 1.055577. То есть мы
 *  считаем ровно то же, что она, и лишнего поля в базе для этого не нужно. */
export function frequency(row: CampaignRow): number | null {
  const i = row.impressions;
  const r = row.reach;
  if (i == null || r == null || !Number.isFinite(i) || !Number.isFinite(r)) return null;
  if (r <= 0) return null;
  return i / r;
}

/** Почему в этой строке нет охвата — словами, или пусто, если он есть.
 *
 *  Отдельная функция, потому что «не складывается» и «не собрано» — разные
 *  ответы с разным лечением, а на экране оба выглядят прочерком. Первый —
 *  свойство метрики и не чинится ничем; второй чинится сбором. Молчаливый
 *  прочерк отправляет человека чинить исправное. */
export function почемуНетОхвата(row: CampaignRow, period?: Period | null): string {
  if (row.reach != null) return "";
  if (row.level !== "ad") {
    return "Reach counts unique people, so it cannot be added up: someone who saw " +
      "two ads in this ad set is one person, not two. Only Meta can de-duplicate " +
      "that, and only for a range we ask it about separately. Open an ad to see its reach.";
  }
  if (period && period.days > 1) {
    return `Reach is exact for a single day only. Over ${period.days} days the same ` +
      "person is counted once per day, so we do not show a number we would have " +
      "made up. Pick one day to see it.";
  }
  return "No spend rows for this ad in the selected period, so nothing was collected " +
    "to show — not the same as “nobody was reached”.";
}
