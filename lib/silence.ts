/**
 * Тишина в цифрах видна как тишина, а не как ноль — панельная половина #122.
 *
 * ЧТО ЗА ПРОБЛЕМА. Ноль и «мы не смогли собрать» на экране выглядят одинаково,
 * и байер принимает решение по НЕСОБРАННОМУ как по нулевому. По этим же цифрам
 * тушат кампании автоправила (#25). «Депов сегодня не было» и «трекер сегодня
 * не отвечал» — два разных вывода и два разных действия, а на листе они одна
 * строка с нулём.
 *
 * ГДЕ ЖИВЁТ ПРАВДА. В демоне: `core/silence.тишина()` считает, чего в окне мы
 * НЕ СПРАШИВАЛИ, и кладёт это в `/leaderboard`, `/ads` и `/creative/<имя>`.
 * Здесь — только слова и разбор. Признак `молчит` приходит СВОДНЫЙ и
 * пересчитывать его тут нельзя: правило «что считать тишиной» обязано жить в
 * одном месте, иначе две копии на двух языках разъедутся молча.
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ «ЧАСТЬ СПЕНДА ПРОТУХЛА» (#149), которое лист уже
 * показывает. Там мы спросили, но СЛИШКОМ РАНО: день не закрылся, и число
 * занижено — известно, что оно меньше правды. Здесь мы не спрашивали ВОВСЕ:
 * число не занижено, его просто нет, а на экране стоит ноль. Разные причины,
 * разные действия и разные слова; смешать их значит получить одну общую
 * фразу «цифрам не верь», после которой не верят ничему и ничего не чинят.
 *
 * ПОЧЕМУ ОТМЕТКА У ДНЯ И ИСТОЧНИКА, А НЕ У КАЖДОЙ ЦИФРЫ — решение демона, и
 * оно неочевидное. Трекеры пишут строку, только когда СОБЫТИЕ БЫЛО: у
 * объявления без депов строки нет и не будет никогда. Значит «строки нет» на
 * уровне объявления не значит ни «ноль», ни «не собрали», и подпись у каждой
 * цифры была бы враньём в обе стороны. Различить можно этажом выше: собирали ли
 * мы ЭТОТ ДЕНЬ вообще.
 */

import { COLUMNS, type ColKey } from "./analytics-columns";
import { derive, type Node } from "./analytics-tree";

/* ── Блок «тишина» из ответа ──────────────────────────────────────────────── */

/** Один источник: собирали ли мы его в этом окне. */
export interface SilenceSource {
  /** Имя источника, как его зовёт демон (`spend`, `funnel`). */
  key: string;
  собрано_дней: number;
  /** Дни окна, за которые нет ни одной строки. */
  молчат: string[];
  /** Когда этот источник в последний раз что-то приносил. */
  последний_сбор: string | null;
}

export interface Silence {
  дней: number;
  /** Источники СПИСКОМ, а не парой полей `spend`/`funnel`.
   *
   *  Это и есть «список мест, где цифра может оказаться несобранной», и
   *  рукописным он быть не должен: демон заведёт третий источник (второй
   *  трекер, свой сборщик кликов), и пара полей его молча не заметит — экран
   *  скажет «всё собрано», не спросив про него. Поэтому источники ВЫЧИТЫВАЮТСЯ
   *  из ответа по форме, а не берутся по именам. */
  источники: SilenceSource[];
  кабинетов_молчит: number;
  кабинеты_молчат: string[];
  /** Сводный признак демона. Не пересчитывается здесь НИКОГДА. */
  молчит: boolean;
}

function число(v: unknown): number {
  return typeof v === "number" && Number.isFinite(v) ? v : 0;
}

function строки(v: unknown): string[] {
  return Array.isArray(v) ? v.filter((x): x is string => typeof x === "string") : [];
}

/** Похоже ли значение на описание источника. По ФОРМЕ, а не по имени ключа:
 *  имя следующего источника нам сегодня неизвестно, а форма у него будет та же
 *  — так устроен `core/silence.тишина`. */
function источник(key: string, v: unknown): SilenceSource | null {
  if (!v || typeof v !== "object") return null;
  const o = v as Record<string, unknown>;
  if (!Array.isArray(o["молчат"])) return null;
  if (typeof o["собрано_дней"] !== "number") return null;
  return {
    key,
    собрано_дней: число(o["собрано_дней"]),
    молчат: строки(o["молчат"]),
    последний_сбор:
      typeof o["последний_сбор"] === "string" && o["последний_сбор"]
        ? (o["последний_сбор"] as string)
        : null,
  };
}

/** Блок `тишина` из ответа — или `null`, если его там нет.
 *
 *  `null` значит РОВНО «демон старше контракта», а не «всё собрано». Экран на
 *  `null` обязан молчать так же, как молчал до этого поля: показать «данные
 *  полные», не спросив, — то самое враньё, против которого весь иссус. */
export function readSilence(raw: unknown): Silence | null {
  if (!raw || typeof raw !== "object") return null;
  const o = raw as Record<string, unknown>;
  if (typeof o["молчит"] !== "boolean") return null;
  if (typeof o["дней"] !== "number") return null;
  const источники: SilenceSource[] = [];
  for (const [k, v] of Object.entries(o)) {
    const и = источник(k, v);
    if (и) источники.push(и);
  }
  return {
    дней: число(o["дней"]),
    источники,
    кабинетов_молчит: число(o["кабинетов_молчит"]),
    кабинеты_молчат: строки(o["кабинеты_молчат"]),
    молчит: o["молчит"] as boolean,
  };
}

/* ── Слова ────────────────────────────────────────────────────────────────── */

/** Английское имя источника для человека. Незнакомый источник печатается своим
 *  именем, а не прячется: «мы не собрали ЧТО-ТО» бесполезно, а «не собрали
 *  clicks2» человек хотя бы отнесёт куда надо. */
const ИМЯ: Record<string, string> = { spend: "spend", funnel: "funnel" };

/** День без года: «Aug 14». Разбираем СТРОКУ, а не `Date`: `new Date("2026-08-14")`
 *  читается как полночь UTC и в минусовых поясах печатается вчерашним днём —
 *  подпись «не собрано 13 августа» на дыре за 14-е хуже отсутствия подписи. */
const МЕС = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
             "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

export function shortDay(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  if (!m) return iso;
  return `${МЕС[Number(m[2]) - 1] || m[2]} ${Number(m[3])}`;
}

/** Дни списком, с обрывом. Три имени и «and N more»: список из двадцати дат
 *  не читается, а факт «дыра большая» несёт само число. */
function дни(list: string[], сколько = 3): string {
  const имена = list.slice(0, сколько).map(shortDay).join(", ");
  const ещё = list.length - сколько;
  return ещё > 0 ? `${имена} and ${ещё} more` : имена;
}

export interface SilenceNote {
  title: string;
  detail: string;
}

/** Что сказать про окно. `null` — сказать нечего, и молчание здесь честно:
 *  метка «не собрано» на собранном дне дороже пропуска. Она отменяет доверие ко
 *  всем остальным меткам, и тогда байер снова читает нули как нули. */
export function silenceNote(s: Silence | null): SilenceNote | null {
  if (!s || !s.молчит) return null;
  const части: string[] = [];
  for (const и of s.источники) {
    if (!и.молчат.length) continue;
    const имя = ИМЯ[и.key] || и.key;
    части.push(
      `${и.молчат.length} of ${s.дней} day${s.дней === 1 ? "" : "s"} have no ${имя} ` +
      `collected at all (${дни(и.молчат)})`,
    );
  }
  if (s.кабинетов_молчит) {
    /* САМЫЙ ОПАСНЫЙ СЛУЧАЙ ИЗ ВСЕХ, и потому он назван последним и прямо:
       кабинет в списке есть, спенд у него ноль, и читается это как «не тратил»,
       а мы к нему просто не ходили. */
    части.push(
      `${s.кабинетов_молчит} ad account${s.кабинетов_молчит === 1 ? " was" : "s were"} ` +
      `not polled once in this window` +
      (s.кабинеты_молчат.length ? ` (${s.кабинеты_молчат.slice(0, 3).join(", ")}` +
        (s.кабинетов_молчит > 3 ? ` and ${s.кабинетов_молчит - 3} more)` : ")") : ""),
    );
  }
  if (!части.length) return null;
  return {
    title: "Part of this window was never collected",
    detail:
      `${части.join(". ")}. A zero on those rows means "not collected", not ` +
      `"nothing happened" — and it is not the same as spend that arrived too early ` +
      `in the day.`,
  };
}

/* ── Цифра, которой не было: воронка ──────────────────────────────────────── */

/** Поля воронки — ИЗ КАТАЛОГА КОЛОНОК, а не списком здесь.
 *
 *  Каталог и есть то место, где объявлено, что такое воронка (`group`).
 *  Переписать его сюда значило бы завести вторую копию: заведут шестую ступень
 *  воронки — она появится в таблице и не появится в этой проверке, и её нули
 *  снова станут неотличимы от незнания. */
export const ВОРОНОЧНЫЕ_ПОЛЯ: ColKey[] = COLUMNS.filter((c) => c.group === "воронка")
  .map((c) => c.key);

/** Пробная строка, на которой задают вопрос «а читает ли эта колонка воронку».
 *
 *  Все величины ненулевые намеренно: на нулях половина колонок честно отдаёт
 *  прочерк (деление на ноль), и вопрос остался бы без ответа именно там, где он
 *  важен. Свойство колонки не должно зависеть от того, какая строка попалась. */
const ПРОБА = {
  id: "проба", kind: "ad", label: "", geos: [],
  spend: 8, clicks: 8, sub: 4, contact: 4, checkout: 4, ftd: 2, rd: 2,
  ads: 1, ads_with_ftd: 1,
} as unknown as Node;

const кэш = new Map<string, boolean>();

/** Читает ли КОЛОНКА цифры воронки. Определяется ОПЫТОМ, а не списком.
 *
 *  Считаем значение на пробной строке как есть и на её копии, где цифры воронки
 *  стёрты. Разошлось — значит колонка воронку читает. Так в проверку сами собой
 *  попадают производные: CPFTD, Sub→FTD, Clicks/FTD и всё, что заведут завтра.
 *  Список зависимостей, написанный руками, отстал бы от `derive` на первой же
 *  новой колонке — а расхождение это тихое, его видно только на числах.
 *
 *  Вопрос задан КОЛОНКЕ, а не паре «колонка + строка», и это важно: на строке с
 *  нулевыми подписками `Sub→FTD` отдаёт прочерк и по значению неотличим от
 *  колонки, воронку не читающей вовсе. Свойство колонки от строки не зависит. */
export function колонкаЧитаетВоронку(key: ColKey): boolean {
  const было = кэш.get(key);
  if (было !== undefined) return было;
  const без = { ...ПРОБА } as Record<string, unknown>;
  for (const поле of ВОРОНОЧНЫЕ_ПОЛЯ) без[поле] = null;
  const ответ = derive(без as unknown as Node, key) !== derive(ПРОБА, key);
  кэш.set(key, ответ);
  return ответ;
}

/** Приезжали ли цифры воронки этой строки хоть раз.
 *
 *  ТРИ ОТВЕТА, а не два, и это здесь главное:
 *    • строка с меткой времени — приезжали, ноль рядом означает ноль;
 *    • `null` — демон сказал «не приезжало НИКОГДА», и ноль рядом означает
 *      «не знаем»;
 *    • `undefined` — поля в ответе нет вовсе (демон старше контракта), и тогда
 *      мы не знаем даже этого. Молчим: пометить весь лист «не собрано» на
 *      старом демоне значит отменить доверие ко всем меткам разом.
 */
export function воронкаНеПриезжала(n: Node): boolean {
  return n.funnel_at === null;
}

/** Надо ли показать ячейку как несобранную, а не как ноль. */
export function ячейкаНеСобрана(n: Node, key: ColKey): boolean {
  return воронкаНеПриезжала(n) && колонкаЧитаетВоронку(key);
}
