/**
 * Тепловая шкала для колонок цены (CPFTD, CPCheck, CPSub…).
 *
 * Задача одна: глядя на столбец, байер должен за полсекунды видеть, где дёшево,
 * а где он переплачивает. Значит нужен не «красивый градиент», а шкала, которая
 * не разваливается на реальных данных среза.
 *
 * Здесь только математика и CSS-строка — рисование ячейки живёт в компоненте.
 */

/** 0 — самое дешёвое (хорошо), 1 — самое дорогое (плохо), null — красить нечем. */
export interface HeatScale {
  at(v: number | null): number | null;
}

/* Обрезка по 10-му и 90-му перцентилю. Причина — форма данных: в любом срезе
   есть выбросы (одно объявление, один деп, $390). На линейной min/max шкале
   такой выброс забирает себе весь верх, и все нормальные строки схлопываются
   в один оттенок — столбец перестаёт что-либо показывать. Перцентильное окно
   отдаёт цвет основной массе, а хвосты просто упираются в 0 и 1. */
const LOW_Q = 0.1;
const HIGH_Q = 0.9;

/* Меньше трёх различимых цен — шкалы нет. Градиент из двух точек не «показывает
   дорого/дёшево», он показывает «одно из двух», и юзер читает это как вывод
   об эффективности там, где выводу неоткуда взяться. Лучше не красить вовсе. */
const MIN_DISTINCT = 3;

/* Потолок насыщенности и пол середины задаёт CSS, а не этот модуль: они обязаны
   различаться по темам. В светлой `--heat-cold` это насыщенный фиолетовый
   #7c3aed, и его 32% над белым дают читаемую пастель; в тёмной это светлый
   #a78bfa, и те же 32% над #171719 дают блок, который перебивает само число.
   Отсюда `var(--heat-max)` и `var(--heat-floor)` — см. globals.css. */
const MAX = "var(--heat-max)";
const FLOOR = "var(--heat-floor)";

/** Шкала-заглушка: на всё отвечает null. Одна на всех — она без состояния. */
const DEAD: HeatScale = { at: () => null };

/* Цена определена только если это конечное положительное число. Ноль и null —
   это «депов не было», а не «бесплатно»: пустив их в выборку, мы прибили бы
   нижнюю границу к нулю и перекрасили половину столбца в зелёный. */
function isPrice(v: number | null | undefined): v is number {
  return typeof v === "number" && Number.isFinite(v) && v > 0;
}

/* Перцентиль с линейной интерполяцией (тот же вариант, что по умолчанию в
   numpy/pandas). Из ходовых определений именно он меньше всех подтягивает
   границу к выбросу на коротких срезах. */
function quantile(sorted: number[], q: number): number {
  const pos = (sorted.length - 1) * q;
  const lo = Math.floor(pos);
  const hi = Math.ceil(pos);
  if (lo === hi) return sorted[lo];
  return sorted[lo] + (sorted[hi] - sorted[lo]) * (pos - lo);
}

/**
 * Строит шкалу по значениям столбца. Чистая: входной массив не мутируется
 * (`filter` отдаёт новый, сортируется уже он) и не запоминается.
 */
export function makeHeatScale(values: Array<number | null>): HeatScale {
  const prices = values.filter(isPrice).sort((a, b) => a - b);
  if (new Set(prices).size < MIN_DISTINCT) return DEAD;

  let lo = quantile(prices, LOW_Q);
  let hi = quantile(prices, HIGH_Q);

  /* Окно схлопнулось в точку: вся середина среза по одной цене. Различимых
     значений при этом три и больше (проверено выше), так что min/max заведомо
     не вырожден — расширяемся до него, вместо деления на ноль. */
  if (hi <= lo) {
    lo = prices[0];
    hi = prices[prices.length - 1];
  }

  const span = hi - lo;

  return {
    at(v) {
      if (!isPrice(v)) return null;
      if (v <= lo) return 0;
      if (v >= hi) return 1;
      return (v - lo) / span;
    },
  };
}

/**
 * CSS-значение для `style.background` ячейки. Пустая строка — не красить.
 *
 * Возвращается именно строка с токенами, а не класс: оттенок непрерывный,
 * классами его пришлось бы нарезать ступенями и дублировать под тёмную тему.
 * Токены уже разные в обеих темах, а color-mix в oklch смешивает по светлоте —
 * поэтому переход идёт ровно, без грязного провала посередине.
 *
 * Токены свои, а не `--success`/`--destructive`: те означают состояние (живое /
 * сломанное) и красят статусы кабов и соцев. Цена — не состояние, дорогое крео
 * ничем не «сломано». Пока цвет был общий, перекрасить шкалу, не тронув
 * статусы, было нельзя.
 *
 * ТРИ стопа, а не два. С двумя оттенок прыгал между холодным и горячим через
 * прозрачную середину, и столбец читался как два набора пятен: непрерывного
 * хода не было ни на одном участке. Теперь цвет считается вложенным color-mix —
 * сначала смешиваются два соседних стопа, потом результат разбавляется до
 * нужной насыщенности. Браузер делает обе операции сам, в oklch.
 *
 * Насыщенность середины — не ноль, а `--heat-floor` от потолка. С нулём
 * основная масса строк оставалась неокрашенной, и «градиент» жил только на
 * хвостах: между «чуть дешевле среднего» и «чуть дороже» глаз не видел ничего.
 */
export function heatTone(t: number | null): string {
  if (t === null || !Number.isFinite(t)) return "";

  const clamped = Math.min(1, Math.max(0, t));

  /* Какие два стопа смешиваем и в какой пропорции. Доля считается внутри
     половины шкалы: на 0.25 это ровно середина между холодным и средним. */
  const холодная = clamped <= 0.5;
  const from = холодная ? "--heat-cold" : "--heat-mid";
  const to = холодная ? "--heat-mid" : "--heat-hot";
  const доля = Math.round((холодная ? clamped / 0.5 : (clamped - 0.5) / 0.5) * 1000) / 10;

  const hue = `color-mix(in oklch, var(${from}), var(${to}) ${доля}%)`;

  /* Насколько ушли от середины: 0 в центре, 1 на краю. Отсюда насыщенность —
     от пола в центре до полного потолка на хвостах. */
  const away = Math.round(Math.abs(clamped - 0.5) * 2 * 1000) / 1000;
  const alpha = `calc(${MAX} * (${FLOOR} + (1 - ${FLOOR}) * ${away}))`;

  return `color-mix(in oklch, ${hue} ${alpha}, transparent)`;
}
