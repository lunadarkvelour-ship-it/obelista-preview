/* Навигация листа «Кампании»: соц → кабинет → кампания → адсет → объявление.
 *
 * ПОЧЕМУ УРОВНЕЙ ПЯТЬ, А НЕ ТРИ. Владелец 15.08: «чтобы было очень похоже на
 * Ads Manager… чтобы можно было многоуровнево заходить на уровень — соц / каб /
 * кампании / адсеты / объявления». Верхних двух уровней в Ads Manager нет
 * вовсе, и это не украшение: у байера десятки кабинетов на ТРЁХ соцах, и первый
 * вопрос дня у него не «какая кампания», а «что вообще происходит у этого
 * соца». Лист, который начинается с выпадающего «choose an ad account…» на 268
 * строк, на этот вопрос не отвечает ничем.
 *
 * ЗДЕСЬ ЛЕЖИТ ТОЛЬКО ТО, ЧТО СЧИТАЕТСЯ БЕЗ РАЗМЕТКИ: где человек находится,
 * какие строки показывать на каждом уровне и как сложить ответы по нескольким
 * кабинетам в одно дерево. Причина та же, что у остальной панели: строки
 * приезжают запросом, а тестовый рендер запросов не делает — внутри компонента
 * это непроверяемо.
 *
 * GRAPH ЗДЕСЬ НЕ ТРОГАЕТСЯ НИ ОДНИМ ВЫЗОВОМ, и это сторожится
 * (`lib/__tests__/campaigns-no-graph.test.ts`, файл добавлен в список). Лимит
 * Меты считается на ПРИЛОЖЕНИЕ — ~60 вызовов на пятиминутку на всё, — и лист,
 * который ходит в Мету по требованию, душит фоновый сбор. Читаем свою базу.
 *
 * ПОЧЕМУ НА ПЕРВОМ УРОВНЕ ТОЛЬКО ПОДКЛЮЧЁННЫЕ СОЦЫ. Лист не смотрит, а
 * УПРАВЛЯЕТ: пауза и включение уходят в Мету токеном соца. Без токена
 * управлять нечем, и показать такой соц значило бы предложить действие,
 * которого не существует. Кабинеты выбывших профилей никуда не делись — они
 * лежат на листе «Кабинеты», где у них своя кнопка охвата.
 */
import { statusLabel } from "./account-status";
import type { UnifiedAccount } from "./cloud-accounts";
import { правилоСоца } from "./cloud-filter";
import type { CampaignRow, CampaignsResponse, Period } from "./campaigns";
import { NoHandle } from "./campaigns";

/* ── где человек находится ────────────────────────────────────────────────── */

export type Шаг = "соцы" | "кабинеты" | "дерево";

/** Место на листе. Одним объектом, а не тремя состояниями рядом: шаг, соц и
 *  набор кабинетов меняются ВМЕСТЕ, и разъехавшись однажды (шаг «дерево» при
 *  пустом наборе), дают пустой экран без объяснения. */
export interface Место {
  /** Выбранный соц. `null` на шаге «кабинеты» значит «все подключённые сразу» —
   *  это и есть «следить за всем своим из одного места». */
  соц: string | null;
  /** Кабинеты, чьи кампании показываем. Несколько намеренно: владелец смотрит
   *  связку из нескольких кабов как одно целое. */
  кабы: string[];
  шаг: Шаг;
}

export const НАЧАЛО: Место = { соц: null, кабы: [], шаг: "соцы" };

/** Ключ «все соцы сразу». Не пустая строка и не `null` в разметке: по этому
 *  ключу рисуется отдельная строка списка, и её надо чем-то отличать. */
export const ВСЕ_СОЦЫ = "__все__";

/* ── уровень 1: соцы ──────────────────────────────────────────────────────── */

/** Строка первого уровня: что у этого соца есть.
 *
 *  ЦИФРЫ ТУТ ТОЛЬКО ТЕ, ЧТО МЫ ПРАВДА ЗНАЕМ. Сколько у соца кампаний и сколько
 *  из них крутится — этот уровень не считает: `GET /campaigns` отдаёт дерево
 *  ОДНОГО кабинета, а у соца их десятки, и число стоило бы десятков вызовов на
 *  раскрытие одной строки. Подставить сюда ноль значило бы сказать «кампаний
 *  нет». Поэтому на уровне соца стоят кабинеты и их состояние — то, что
 *  приезжает из базы одним запросом.
 *
 *  До 16.08 причина была названа неверно: «ручки `/campaigns` в сборщике ещё
 *  нет». Ручка есть (`scripts/analytics_daemon.py`), и этот же модуль её
 *  зовёт — то есть файл спорил сам с собой и звал завести уже написанное. */
export interface СоцСтрока {
  profile: string;
  label: string;
  кабов: number;
  /** Кабинетов со статусом ACTIVE. */
  активных: number;
  /** Забаненных: DISABLED или PENDING_CLOSURE. Считается общим словарём
   *  (`lib/account-status`), а не своим списком рядом.
   *
   *  Стоит на первом уровне рядом с живыми, потому что владелец спрашивает
   *  ровно эту пару: «мне нужно видеть живые кабы и забаненные». Бан — его
   *  деньги, а не техническая подробность. */
  забаненных: number;
  /** Кабинетов, у которых статус ни разу не снимали. Отдельно от забаненных и
   *  от живых: «не знаем» — не то же, что «выключен» (#122). */
  неснятых: number;
}

/** Соцы первого уровня — по ВЛАДЕЛЬЦАМ кабинетов, а не по списку профилей
 *  антидетекта: список профилей отвечает на «что открыто на этой машине», а
 *  лист управления — на «чем я могу управлять».
 *
 *  Порядок: где больше кабинетов, тот выше; при равенстве — по имени, чтобы
 *  порядок не зависел от того, как база сложила выборку. */
export function соцыДляЛиста(rows: UnifiedAccount[]): СоцСтрока[] {
  /* Правило «текущего профиля» — ОДНО на продукт и берётся из `cloud-filter`.
     Своё «есть токен» здесь показало бы владельцу первым уровнем четыре
     профиля прежнего вендора антидетекта: токен у их человека жив, а окна нет
     с самого переезда. Разбор — там же, у `правилоСоца`. */
  const годен = правилоСоца(rows);
  const карта = new Map<string, СоцСтрока>();
  for (const a of rows) {
    for (const o of a.owners) {
      /* Соц без токена и без открытого окна в лист управления не идёт: писать
         в Мету нечем, а окна, чтобы открыть браузер, нет. */
      if (!годен(o)) continue;
      let s = карта.get(o.profile);
      if (!s) {
        s = {
          profile: o.profile, label: o.label || o.profile,
          кабов: 0, активных: 0, забаненных: 0, неснятых: 0,
        };
        карта.set(o.profile, s);
      }
      s.кабов += 1;
      const метка = statusLabel(a.status || undefined);
      if (метка === "active") s.активных += 1;
      if (метка === "disabled") s.забаненных += 1;
      if (метка === "unknown") s.неснятых += 1;
    }
  }
  return [...карта.values()].sort(
    (x, y) => y.кабов - x.кабов || x.label.localeCompare(y.label),
  );
}

/* ── уровень 2: кабинеты ──────────────────────────────────────────────────── */

/** Кабинеты выбранного соца. `null` — все подключённые, без разбора соца.
 *
 *  Фильтр по ВСЕМ владельцам, а не по главному: общий кабинет виден с
 *  нескольких соцев, и прятать его от второго владельца значит терять кабинет
 *  на ровном месте (то же правило, что в `cloud-filter`). */
export function кабинетыСоца(
  rows: UnifiedAccount[],
  соц: string | null,
): UnifiedAccount[] {
  const годен = правилоСоца(rows);
  const свои = соц
    ? rows.filter((a) => a.owners.some((o) => o.profile === соц && годен(o)))
    : rows.filter((a) => a.owners.some(годен));
  /* Порядок — по имени: на этом уровне человек ИЩЕТ кабинет глазами, а не
     сравнивает деньги. Сортировка по спенду увела бы искомое вниз. */
  return свои.slice().sort((a, b) =>
    (a.name || a.act_id).localeCompare(b.name || b.act_id));
}

/* ── «ВЫБРАТЬ ВСЁ АКТИВНОЕ» ───────────────────────────────────────────────── */

/* Владелец, глядя на живой лист: «надо ещё ж сделать кнопку choose all active и
 * открыть всё активное». Цифры с его экрана объясняют, почему это не удобство,
 * а работоспособность: из 72 кабинетов профиля активных ШЕСТЬ, забаненных 63.
 * «Открыть все» на таком наборе даёт дерево, где девять веток из десяти мертвы,
 * — то есть кнопка есть, а пользоваться ею нельзя.
 *
 * ЖИВОЙ — ЭТО ACTIVE У МЕТЫ, и считается общим словарём (`account-status`), а
 * не своим списком рядом. «Не собрано» живым НЕ считается: неизвестное — не
 * утверждение, и молча записать его в активные значит открыть человеку то,
 * про что мы ничего не знаем, под видом работающего.
 */
export function активные(rows: UnifiedAccount[]): UnifiedAccount[] {
  return rows.filter((a) => statusLabel(a.status || undefined) === "active");
}

/** Отметить или снять кабинет. Порядок отметок сохраняется: он же порядок
 *  запросов и, значит, порядок появления деревьев на экране. */
export function переключитьКаб(кабы: string[], id: string): string[] {
  return кабы.includes(id) ? кабы.filter((x) => x !== id) : [...кабы, id];
}

/** Сколько кабинетов открываем за раз. Каждый — отдельный запрос в НАШУ базу
 *  (в Мету не ходит ни один), но сотня запросов одним нажатием это сотня
 *  запросов, а дерево на сотню кабинетов человек всё равно не читает.
 *
 *  Предел ЗАЯВЛЕН, а не применён молча: `ограничить` возвращает и то, что
 *  отброшено, и это число обязано быть на экране. Молчаливое усечение читается
 *  как «вот всё, что есть» — худший вид неполноты. */
export const МАКС_КАБОВ = 25;

export function ограничить(ids: string[], предел = МАКС_КАБОВ): {
  взяли: string[]; отброшено: number;
} {
  return { взяли: ids.slice(0, предел), отброшено: Math.max(0, ids.length - предел) };
}

/* ── уровни 3-5: три уровня дерева, но данных на них может не быть ────────── */

/** Ответ по ОДНОМУ кабинету. Раздельно, а не одной кучей строк: кабинеты
 *  отвечают вразнобой, один может упасть, и «часть приехала» обязано
 *  отличаться от «всё приехало». */
export interface ЗагрузкаКаба {
  act_id: string;
  rows: CampaignRow[];
  generated_at: string | null;
  /** ЗА КАКОЕ ОКНО ПОСЧИТАН ЭТОТ КАБИНЕТ — датами от демона, а не кнопками
   *  панели (#154). Держится ПОКАБИНЕТНО, а не одним полем на весь лист, ровно
   *  по той же причине, что и ошибки: у кабинета свой пояс, и «совпадают ли его
   *  сутки с нашими» — свойство кабинета, а не выборки. Сложив это в одно поле,
   *  мы бы подписали чужой границей все двадцать пять. */
  period: Period | null;
  /** Текст отказа как есть. Мету пересказывать нельзя — лечится по точной. */
  error: string | null;
  /** Ручки нет на этом деплое. Не поломка, а «бэкенд не доехал». */
  noHandle: boolean;
}

/** Спросить несколько кабинетов подряд, не больше `параллельно` за раз.
 *
 *  ПОЧЕМУ НЕ `Promise.all` ЦЕЛИКОМ. Двадцать пять одновременных запросов к
 *  сборщику — это не забота о человеке, а очередь, в которой первый ответ
 *  приходит вместе с последним.
 *
 *  ПОЧЕМУ ОБРЫВ НА `NoHandle`. Ручки либо нет на деплое, либо она есть: это
 *  свойство сервера, а не кабинета. Получив первый такой ответ, остальные
 *  двадцать четыре запроса можно не делать — они принесут то же самое, а
 *  человек всё равно увидит одну плашку. Оборванные кабинеты возвращаются
 *  честно, с тем же `noHandle`, а не пропадают из ответа. */
export async function загрузитьМного(
  ids: string[],
  один: (act_id: string) => Promise<CampaignsResponse>,
  параллельно = 4,
): Promise<ЗагрузкаКаба[]> {
  const out = new Map<string, ЗагрузкаКаба>();
  let ручкиНет = false;

  const пусто = (act_id: string, noHandle: boolean): ЗагрузкаКаба =>
    ({ act_id, rows: [], generated_at: null, period: null, error: null, noHandle });

  for (let i = 0; i < ids.length; i += параллельно) {
    const пачка = ids.slice(i, i + параллельно);
    if (ручкиНет) {
      for (const id of пачка) out.set(id, пусто(id, true));
      continue;
    }
    await Promise.all(пачка.map(async (act_id) => {
      try {
        const r = await один(act_id);
        out.set(act_id, {
          act_id, rows: r.rows ?? [], generated_at: r.generated_at ?? null,
          period: r.period ?? null, error: null, noHandle: false,
        });
      } catch (e) {
        if (e instanceof NoHandle) {
          ручкиНет = true;
          out.set(act_id, пусто(act_id, true));
          return;
        }
        out.set(act_id, {
          act_id, rows: [], generated_at: null, period: null,
          error: e instanceof Error ? e.message : String(e), noHandle: false,
        });
      }
    }));
  }
  /* Порядок ответов — порядок запроса, а не порядок прихода: иначе дерево
     перестраивается под человеком, пока грузится. */
  return ids.map((id) => out.get(id) || пусто(id, false));
}

/** Что показывать над деревом, когда кабинетов несколько. */
export interface Сводка {
  rows: CampaignRow[];
  /** Кабинетов ответило строками. */
  сДанными: number;
  /** Ответило пустотой: в базе по ним ничего нет. Это не ошибка. */
  пустых: number;
  /** Отказов сборщика, с текстами. */
  ошибки: Array<{ act_id: string; error: string }>;
  /** Ручки нет вовсе — тогда говорить про пустые кабинеты бессмысленно. */
  ручкиНет: boolean;
  /** Самый СТАРЫЙ ответ из показанных. Именно старый, а не свежий: подпись над
   *  деревом обещает возраст ВСЕГО показанного, и обещать по самому свежему
   *  значило бы подписать трёхдневные строки минутной давностью. */
  собрано: string | null;
  /** Окно, которым подписан экран, — из ОТВЕТА демона, а не из нажатой кнопки
   *  (#154). Панель не считает даты вовсе: «какое сегодня число» знает один
   *  `core/period.py` в поясе продукта, а браузер живёт в поясе своего человека.
   *  `null` — ответа ещё нет или деплой старый; тогда экран честно говорит, что
   *  период не подтверждён, вместо того чтобы подписать цифры кнопкой. */
  период: Period | null;
  /** СУТКИ КАБИНЕТА НЕ СОВПАДАЮТ С НАШИМИ. Мета режет дни по часам самого
   *  кабинета, и переложить их в наши границы нечем — внутри дня разбивки не
   *  существует. Там, где пояса разошлись, «данные ровно за ваши сутки» —
   *  неправда, и молчать об этом нельзя: цифра есть, подпись есть, а отрезок
   *  другой. Ровно наша порода дефектов, только снаружи. */
  границыДругие: number;
  /** Пояс кабинета неизвестен вовсе — на живом парке таких больше половины.
   *  Считается ОТДЕЛЬНО от расхождения: «не знаем» и «не совпадает» — разные
   *  утверждения, и валить их в одно значит соврать в обе стороны. */
  границыНеизвестны: number;
}

export function свести(ответы: ЗагрузкаКаба[]): Сводка {
  const rows: CampaignRow[] = [];
  const видели = new Set<string>();
  const out: Сводка = {
    rows, сДанными: 0, пустых: 0, ошибки: [], ручкиНет: false, собрано: null,
    период: null, границыДругие: 0, границыНеизвестны: 0,
  };
  for (const о of ответы) {
    if (о.noHandle) out.ручкиНет = true;
    if (о.period) {
      /* Окно берём у первого ответившего: всем кабинетам уходит ОДИН запрос с
         одним периодом, и разные даты здесь означали бы не выбор человека, а
         рассинхрон деплоя. Пояс же и границы суток у каждого свои — они
         считаются ниже поштучно. */
      if (!out.период) out.период = о.period;
      if (о.period.same_day_boundary === false) out.границыДругие += 1;
      else if (о.period.same_day_boundary == null) out.границыНеизвестны += 1;
    }
    if (о.error) out.ошибки.push({ act_id: о.act_id, error: о.error });
    if (о.rows.length) out.сДанными += 1;
    else if (!о.error && !о.noHandle) out.пустых += 1;
    for (const r of о.rows) {
      /* Дубль по `fb_id` возможен, когда один кабинет попал в набор дважды
         (общий каб выбрали с двух соцев). Вторая копия дала бы вторую ветку
         дерева с теми же деньгами. */
      if (!r?.fb_id || видели.has(r.fb_id)) continue;
      видели.add(r.fb_id);
      rows.push(r);
    }
    if (о.generated_at && (!out.собрано || о.generated_at < out.собрано)) {
      out.собрано = о.generated_at;
    }
  }
  return out;
}
