/* Что показать человеку на первой двери продукта: вход или первую регистрацию.
 *
 * Решение отдельной функцией, а не веткой внутри страницы, по той же причине,
 * что и на листе аналитики: страница узнаёт ответ `/auth/me` эффектом, а
 * тестовый рендер эффектов не выполняет — до состояния «сервер ответил» из
 * вёрстки не добраться. Правило без места исполнения не правило, а первый
 * экран продукта — последнее место, где стоит на это надеяться.
 *
 * ОДИН ЗАПРОС НА ДВА РЕШЕНИЯ. Признак приходит и в успешном ответе, и в 401.
 * Экран входа спрашивает `/auth/me`, НЕ будучи вошедшим — это его обычное
 * состояние, — и на свежей установке получает именно отказ. Живи признак только
 * в успехе, панель не узнала бы про свежую установку ровно тогда, когда это
 * единственно и нужно. Отдельной ручки под этот вопрос нет намеренно: два
 * источника одной правды расходятся молча.
 *
 * ПОЛЕ ЗОВЁТСЯ `first_tenant`, И ЭТО ВТОРОЕ ИМЯ, А НЕ ПЕРВОЕ. Раньше здесь
 * читался `registration_open`, и читался ВЕРНО ровно до 15.08: пока окно
 * захлопывалось за первой учёткой, «установка свободна» и «можно
 * зарегистрироваться» были одним вопросом. В тот день владелец открыл
 * регистрацию всем — вопросы разошлись, а имя осталось прежним, и панель
 * прочитала поле ПО ИМЕНИ (иссус #143). Докстроки она не читает: предупреждение
 * в тексте не работает там, где работает имя.
 *
 * Отсюда и местное имя: `свежаяУстановка`, а не `окноОткрыто`. Имя обязано
 * говорить, на какой вопрос отвечает признак, — иначе следующая смена модели
 * входа переживёт его ровно так же.
 *
 * `registration_open` в ответе тоже есть и сегодня всегда `true`. Здесь он не
 * читается СОВСЕМ и подмешивать его в выбор двери нельзя: он про «можно ли
 * завести учётку», а не про «кому что показать первым».
 *
 * ПОЧЕМУ РЕГИСТРАЦИЯ НЕ ОТДЕЛЬНЫМ АДРЕСОМ — довод сменился 15.08, и старый
 * записан здесь же, чтобы никто не восстановил его по памяти.
 *
 * БЫЛО: окно открыто ровно один раз за жизнь установки, и `/register`
 * девяносто девять процентов времени отвечал бы «закрыто навсегда» — дверь,
 * которая почти всегда заперта.
 *
 * СТАЛО: регистрация открыта ВСЕГДА, каждый регистрирующийся получает своё
 * рабочее пространство. Отдельный адрес теперь имел бы смысл — но одна дверь
 * с переключателем всё равно лучше двух: человек, промахнувшийся формой, не
 * уходит со страницы и не теряет введённое, а ссылка на вход из письма
 * приводит туда же, куда ссылка на регистрацию.
 *
 * КТО РЕШАЕТ, ЧТО ПОКАЗАТЬ. Теперь человек, а не сервер. Признак с сервера
 * остался, но отвечает он на другой вопрос — «эта установка совсем свежая»,
 * — и годится ровно на одно: показать первому пришедшему сразу регистрацию,
 * потому что входить ему всё равно нечем.
 */

export type Дверь =
  /** Сессия жива — человека тут держать не за чем, уводим внутрь. */
  | "внутрь"
  /** На установке нет ни одной учётки: этот человек заводит первую и станет админом. */
  | "регистрация"
  /** Обычный вход. */
  | "вход"
  /** Ответа ещё нет. Форму при этом уже показываем — см. ниже. */
  | "ждём";

export interface ВходноеСостояние {
  /** Пришёл ли ответ `/auth/me` хоть какой-нибудь. */
  отвечено: boolean;
  /** Сессия жива. */
  вошёл: boolean;
  /** `first_tenant` из ответа: установка совсем свежая, учёток на ней нет и
   *  следующему достанется первое рабочее пространство. `undefined` — сервер
   *  про это не сказал.
   *
   *  НЕ `registration_open`. Это разные вопросы с 15.08, и подставить сюда
   *  второй значит вернуть иссус #143 тем же способом, каким он завёлся. */
  свежаяУстановка?: boolean;
  /** Что ВЫБРАЛ человек, нажав «нет аккаунта? Sign up» или обратную ссылку.
   *  `undefined` — ещё не выбирал, решаем за него по умолчанию. */
  выбор?: Дверь;
}

export function дверь(s: ВходноеСостояние): Дверь {
  if (!s.отвечено) return "ждём";
  if (s.вошёл) return "внутрь";
  /* ВЫБОР ЧЕЛОВЕКА СИЛЬНЕЕ ЛЮБОГО ПРИЗНАКА С СЕРВЕРА. Он нажал ссылку и ждёт
     другую форму; показать ему прежнюю «потому что сервер считает иначе» —
     это кнопка, которая не работает. */
  if (s.выбор === "регистрация" || s.выбор === "вход") return s.выбор;
  /* Он ещё не выбирал. Свежей установке показываем регистрацию сразу: входить
     первому человеку всё равно нечем. `undefined` читаем как «не свежая» —
     старый сервер поля не присылает вовсе, и ошибка в эту сторону дешевле:
     человек увидит вход, которым и так умеет пользоваться, а до регистрации
     дойдёт ссылкой в одно нажатие. */
  return s.свежаяУстановка === true ? "регистрация" : "вход";
}

/** Что рисовать, пока ответа нет.
 *
 *  Форму ВХОДА, а не пустоту и не крутилку. Человек, пришедший по 401, начинает
 *  печатать сразу, и запертые на время проверки поля съедают первые нажатия.
 *  Промах возможен только на свежей установке — там ответ придёт и сменит форму
 *  на регистрацию, а печатать в тот момент ещё нечего: почты у него нет. */
export function дверьДоОтвета(): Дверь {
  return "вход";
}
