/* Ключ приёма воронки и состояние самого приёма (#120, панельная половина).
 *
 * ЗАЧЕМ ЭТО ЕСТЬ. Вся цепочка воронки бесполезна, пока ключ негде взять:
 * сервер его знает, CRM его ждёт, а человеку скопировать неоткуда. Владелец
 * спросил прямо, почему воронкой никто не занят, и в этом он прав — места, где
 * он возьмёт свой ключ, не было ни у кого.
 *
 * КЛЮЧ — ЭТО ДОСТУП НА ЗАПИСЬ В ЕГО АНАЛИТИКУ, и обращаться с ним надо как с
 * паролем: не в логи, не в адресную строку, не в разметку целиком, пока не
 * нажали «показать». Поэтому здесь два разных поля — маска и сам ключ, — а не
 * одно с обрезкой на отрисовке: обрезка в разметке значит, что целое всё равно
 * лежало в HTML, и любое расширение браузера его видело.
 *
 * ФОРМА ПРИЁМА НЕ ВЫДУМАНА: она прочитана в движке
 * (`core/funnel_intake.проверить`, `scripts/analytics_daemon.py:2319`) —
 * `POST /ingest_funnel`, заголовок `Authorization: Bearer <ключ>`, тело
 * `{payloads, day}`. Ключ едет ЗАГОЛОВКОМ намеренно: тело собирается из ответа
 * CRM, то есть с чужой стороны, а адреса и тела попадают в логи прокси.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Своего словаря состояний CRM, своей проверки ключа и своих
 * попыток «починить» приём. Панель показывает то, что сказал сервер, и
 * различает три ответа, которые человек лечит разным.
 */

/** Ответ ручки ключа. Форма — ДОСЛОВНО от автора #147, панель под неё
 *  подстроилась, а не наоборот: договорённость между двумя местами стоит
 *  ровно столько, сколько стоит имя поля.
 *
 *  `key` приезжает ЦЕЛИКОМ и всегда — отдельного «покажи» у ручки нет. Значит
 *  прятать его до нажатия обязана панель: в разметку идёт маска, сам ключ
 *  живёт в памяти блока и в буфере обмена, куда его кладёт человек. */
export interface FunnelKeyResponse {
  ok?: boolean;
  /** Ключ целиком. Пусто — ключа ещё не выдавали. */
  key?: string | null;
  created_at?: string | null;
  /** Когда перевыпускали в последний раз. Пусто — ни разу. */
  rotated_at?: string | null;
  /** Когда событие ЛЕГЛО. Ставится только после удачного приёма, а не на
   *  каждый стук, — и это главное свойство поля: оно значит «данные дошли», а
   *  не «кто-то постучался». Строить состояние можно только на таком. */
  last_event_at?: string | null;
  /** Сколько строк принято за сегодняшний день сервера. */
  rows_today?: number | null;
  /** Какой день сервер считает сегодняшним. Свой день панель не вычисляет:
   *  часовые пояса браузера и сервера расходятся, и «сегодня» у них разное. */
  today?: string | null;
}

/* ── ТРИ СОСТОЯНИЯ ПРИЁМА, А НЕ ДВА ──────────────────────────────────────── */

/* «Подключено» без единого события — враньё того же сорта, что мы вычищаем
 * вторые сутки: ключ выдан, а данных нет, и человек считает, что всё работает.
 * Ещё хуже третий случай: события шли и прекратились. По одному только факту
 * «ключ есть» он неотличим от первого, а лечится совсем другим — там сломалась
 * выгрузка на стороне CRM, а не подключение.
 */
export type ПриёмКод = "нет ключа" | "ждёт первого" | "идут" | "прекратились";

export interface Приём {
  код: ПриёмКод;
  заголовок: string;
  пояснение: string;
  /** Тон плашки. `alarm` только у прекратившегося приёма: остальные два — не
   *  поломка, а этап. */
  тон: "calm" | "notice" | "alarm";
}

/** Сколько молчания считаем обрывом.
 *
 *  Выгрузка воронки суточная (`{payloads, day}` — день целиком), поэтому пять
 *  минут тишины здесь ничего не значат, а трое суток значат слишком поздно.
 *  Тридцать шесть часов — сутки с запасом на часовой пояс и на то, что
 *  вчерашний день закрывают утром. */
export const ТИШИНА_ЧАСОВ = 36;

function часовНазад(iso: string | null | undefined, now: number): number | null {
  if (!iso) return null;
  const t = new Date(iso).getTime();
  if (!Number.isFinite(t)) return null;
  /* Отрицательный возраст (часы сервера ушли вперёд) считаем нулём, а не
     «неизвестно»: расхождение часов — не новость про приём воронки. */
  return Math.max(0, (now - t) / 3_600_000);
}

/** Правила ровно те, что назвал автор ручки, и записаны они здесь, а не
 *  пересказаны в разметке: место одно, и разойтись ему не с чем. */
export function состояниеПриёма(
  st: FunnelKeyResponse | null | undefined,
  now: number = Date.now(),
): Приём {
  if (!st?.key) {
    return {
      код: "нет ключа",
      заголовок: "No key issued yet",
      пояснение:
        "Nothing can be sent to your funnel until a key exists. Issue one here, then paste "
        + "it into the job that uploads your CRM day.",
      тон: "notice",
    };
  }
  const тишина = часовНазад(st.last_event_at, now);
  const сегодня = typeof st.rows_today === "number" ? st.rows_today : 0;
  if (тишина === null) {
    return {
      код: "ждёт первого",
      заголовок: "Key is ready — nothing has arrived yet",
      пояснение:
        "The key exists, but no day has landed with it. That is not «connected»: the stamp "
        + "is written only after a day is actually stored, so until it appears we have no "
        + "proof the other side can reach us.",
      тон: "notice",
    };
  }
  /* Свежая отметка ИЛИ строки за сегодня. Второе слагаемое не лишнее: день
     закрывают утром, и к вечеру отметка успевает состариться, хотя приём жив. */
  if (тишина <= ТИШИНА_ЧАСОВ || сегодня > 0) {
    return {
      код: "идут",
      заголовок: "Events are arriving",
      пояснение:
        `Last day stored ${тишина < 1 ? "less than an hour" : `${Math.round(тишина)} hours`} `
        + "ago. This is the only state that means the funnel is actually connected.",
      тон: "calm",
    };
  }
  return {
    код: "прекратились",
    заголовок: "Events stopped arriving",
    пояснение:
      `Days used to land and none has for ${Math.round(тишина)} hours. The key is still `
      + "valid, so this is the sending side: the extension, its schedule, or the machine it "
      + "runs on — not the connection here.",
    тон: "alarm",
  };
}

/* ── ПОКАЗ КЛЮЧА ─────────────────────────────────────────────────────────── */

/** Маска на случай, когда сервер её не прислал.
 *
 *  Запасной ход, а не основной путь: маску считает сервер, потому что маска,
 *  собранная в браузере, требует целого ключа в браузере — то есть ровно того,
 *  чего мы избегаем. Но если ключ уже показан по нажатию, скрыть его обратно
 *  надо чем-то, и вот этим. */
export function маска(key: string | null | undefined): string {
  const k = (key || "").trim();
  if (!k) return "";
  if (k.length <= 8) return "•".repeat(k.length);
  return `${k.slice(0, 4)}${"•".repeat(6)}${k.slice(-4)}`;
}

/* ── ИНСТРУКЦИЯ ──────────────────────────────────────────────────────────── */

/** Куда вставить ключ, чтобы события пошли.
 *
 *  Форма списана с движка, а не придумана: `core/funnel_intake.проверить`
 *  сверяет ровно `Authorization: Bearer <ключ>`, а `принять` ждёт `payloads`
 *  списком и `day` строкой `YYYY-MM-DD` (иначе отказ `bad_day`). Пример
 *  показывает ОБА обязательных поля и ни одного лишнего: лишнее в примере
 *  повторяют, а потом ищут, почему сервер ругается.
 *
 *  Ключ в примере — плейсхолдер, и подставлять в него настоящий нельзя:
 *  человек скопирует команду в чат или в тикет вместе с ключом. */
export function примерЗапроса(base: string): string {
  const адрес = `${base.replace(/\/$/, "")}/ingest_funnel`;
  return [
    `curl -X POST ${адрес} \\`,
    `  -H "Authorization: Bearer <your key>" \\`,
    `  -H "content-type: application/json" \\`,
    `  -d '{"day":"2026-08-15","payloads":[ ... one day of CRM rows ... ]}'`,
  ].join("\n");
}

