/* Одно место, где панель узнаёт, что сессия кончилась.
 *
 * ЗАЧЕМ ОДНО. Гейт отвечает `401` не только на входные пути, а на ЛЮБОЙ запрос к
 * `/api/analytics/*` — то есть на лидерборд, на дерево объявлений, на состав
 * кабинетов, на всё. Если каждый лист разбирается с этим сам, разберутся не все:
 * девять веток «а вдруг 401» пишутся в разное время разными руками, и одна из них
 * обязательно останется незакрытой. А незакрытая выглядит как ПУСТАЯ ТАБЛИЦА —
 * неотличимо от «сбор не работает». Человек уходит чинить сбор, который цел.
 *
 * Ровно это мы чинили весь день 14.08 в других местах, и владелец три раза сказал
 * одно и то же: панель не должна врать. Пустой лист вместо «сессия кончилась» —
 * враньё того же сорта, просто в новом месте.
 *
 * ПОЧЕМУ НЕ ВСЯКИЙ 401 — НАШ. До блока Е панель стоит за basic auth Caddy, и он
 * отвечает тем же кодом. Разница видна в заголовке: у него `WWW-Authenticate:
 * Basic`, и разбирается с ним САМ БРАУЗЕР — он покажет своё окно ввода. Увести
 * человека на наш экран входа в этот момент значит увести его от единственного
 * места, где он может ответить. Заголовок читается: запрос к аналитике идёт на тот
 * же домен, что панель (`deploy/Caddyfile`), а на своём origin доступны все
 * заголовки ответа.
 *
 * Проверка живёт отдельной чистой функцией, потому что её надо испытать тестом, а
 * переход — нет: `window.location` в тесте не подделать без выдуманного окружения,
 * и такой тест проверял бы мок, а не поведение.
 */

/** Куда уводим. Один экран, и путь тут — единственный экземпляр строки. */
export const LOGIN_PATH = "/login";

/** Ответ означает «наша сессия кончилась»?
 *
 *  `401` от basic auth сюда не входит — см. шапку файла. */
export function isSessionExpired(r: { status: number; headers: Headers }): boolean {
  if (r.status !== 401) return false;
  const вызов = (r.headers.get("www-authenticate") || "").trim().toLowerCase();
  return !вызов.startsWith("basic");
}

/** Адрес входа с возвратом туда, где человека прервали.
 *
 *  Возврат хранится параметром, а не в памяти модуля: переход перезагружает
 *  страницу, и любая память о том, «куда он шёл», этого не переживёт.
 *
 *  Разбор общий с тем, что читает параметр на самом экране входа (`safeNext`):
 *  одно правило на запись и на чтение, иначе они разъедутся ровно тогда, когда
 *  кто-то поправит одно из двух.
 *
 *  Возвращаем ТОЛЬКО путь внутри панели. Хвост приходит из адресной строки, то
 *  есть снаружи; отдать его в редирект как есть — открытый редирект, дыра из
 *  учебника: `?next=https://чужой.сайт` увёл бы человека, только что введшего
 *  пароль, на чужую страницу с нашим логотипом. */
export function safeNext(raw: string | null | undefined): string {
  const from = raw || "/";
  /* Только путь внутри панели. `//чужой.сайт` тоже отбрасывается: браузер читает
     его как адрес с тем же протоколом, то есть это полноценный уход наружу,
     хотя выглядит как путь. */
  const свой = from.startsWith("/") && !from.startsWith("//") ? from : "/";
  /* Вход как место возврата — это круг: вошёл и снова на форму входа. */
  if (свой === LOGIN_PATH || свой.startsWith(LOGIN_PATH + "?")) return "/";
  return свой;
}

export function loginHref(from: string): string {
  const свой = safeNext(from);
  if (свой === "/" && (from === LOGIN_PATH || from.startsWith(LOGIN_PATH + "?"))) {
    /* Пришли с самого входа — второй раз параметр не навешиваем. */
    return LOGIN_PATH;
  }
  return `${LOGIN_PATH}?next=${encodeURIComponent(свой)}`;
}

/** Ошибка, которую бросает страж. Отдельный тип, чтобы лист мог отличить «сессия
 *  кончилась» от «демон ответил ерундой» и не показывать красную плашку поверх
 *  уже начавшегося перехода. */
export class SessionExpired extends Error {
  constructor() {
    super("session expired");
    this.name = "SessionExpired";
  }
}

/** Страж: зовётся на КАЖДЫЙ ответ демона, до разбора тела.
 *
 *  Уводит на вход и бросает — бросает намеренно: без этого вызывающий продолжит
 *  разбирать тело 401-го ответа и покажет что-нибудь бессмысленное в те доли
 *  секунды, пока браузер уходит на другую страницу. */
export function guardSession(r: { status: number; headers: Headers }): void {
  if (!isSessionExpired(r)) return;
  if (typeof window !== "undefined") {
    const сейчас = window.location.pathname + window.location.search;
    /* Уже на входе — никуда не идём. Иначе 401 от самого экрана входа
       закольцевал бы переходы, и вкладка мигала бы, пока её не закроют. */
    if (window.location.pathname !== LOGIN_PATH) {
      window.location.assign(loginHref(сейчас));
    }
  }
  throw new SessionExpired();
}
