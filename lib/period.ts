/* Период — КОНТЕКСТ РАЗДЕЛА, а не фильтр одного листа (#154, пункт 5).
 *
 * Владелец 15.08 просил зазор под будущую связку: Creative Analytics → выбранная
 * дата → выбранные крео → «Open Campaigns» → те же объекты за ТУ ЖЕ дату. Саму
 * связку сейчас не делаем, но дату надо строить так, чтобы она пережила переход
 * между разделами. Локальное состояние компонента этого не переживает никогда:
 * ушёл на другой лист — и период начался заново, а человек уверен, что смотрит
 * то же окно.
 *
 * Поэтому период живёт В АДРЕСЕ СТРАНИЦЫ (`?period=last_7d` или
 * `?since=…&until=…`). Адрес переживает переход, перезагрузку и пересылку
 * ссылки коллеге — то есть ровно те три случая, в которых состояние компонента
 * теряется молча.
 *
 * ЗДЕСЬ НЕТ АРИФМЕТИКИ ДАТ, И ЭТО ГЛАВНОЕ СВОЙСТВО ФАЙЛА. «Какое сегодня
 * число» считает ровно одно место на весь продукт — `core/period.py` в поясе
 * продукта (сейчас UTC+3). Панель присылает ИМЯ пресета, а даты получает
 * ОТВЕТОМ и ими же подписывает экран. Посчитай она «последние 7 дней» сама —
 * у продукта стало бы два «сегодня»: браузер живёт в поясе своего человека, и
 * байер из Тбилиси увидел бы неделю, сдвинутую на день, без единой ошибки на
 * экране. Это тот самый разъезд договорённости, который не краснеет.
 *
 * Единственное, что здесь продублировано, — ИМЕНА пресетов и пояс по умолчанию.
 * Оба сверяются с настоящим исходником движка, а не с памятью автора. Сверку
 * делает ПИТОНОВСКАЯ половина — `tests/test_period.py`: она читает ЭТОТ файл и
 * требует, чтобы `ПРЕСЕТЫ` совпали с `core/period.ПОРЯДОК`, а `TZ_ПО_УМОЛЧАНИЮ`
 * — с `core/period.ПОЯС_ПО_УМОЛЧАНИЮ`.
 *
 * АДРЕС ЗДЕСЬ ВАЖЕН, И РАНЬШЕ ОН БЫЛ НЕВЕРЕН. Стояло «`lib/__tests__/period.ts`
 * читает `core/period.py`» — этот тест `core/period.py` не открывает вовсе, он
 * проверяет только то, что копия пояса в файле одна. Проверено подломом 15.08:
 * заводим в движке пресет `last_90d` и меняем пояс на `UTC+4` — панельный
 * прогон остаётся ЗЕЛЁНЫМ (код 0), питоновский краснеет обоими тестами и
 * называет разошедшееся значение.
 *
 * Разница не косметическая. Обещание в комментарии — такая же проверка, только
 * её никто не запускает: тот, кто пойдёт по неверному адресу, увидит зелёное и
 * решит, что механизма нет; а тот, кто соберётся переписать `tests/test_period.py`,
 * решит, что сверка продублирована в панели, и снесёт единственную настоящую.
 */

import type { Period } from "./campaigns";

/** Как период уходит в запрос: ЛИБО пресет, ЛИБО пара дат. Оба сразу — это
 *  один вопрос, заданный дважды, и демон отвечает на них отказом, а не
 *  догадкой (`core/period.окно`). */
export interface PeriodQuery {
  preset?: string | null;
  since?: string | null;
  until?: string | null;
  /** Пояс. Сегодня не задаётся ниоткуда — демон берёт свой; поле есть, чтобы
   *  Settings → Timezone стал строкой в запросе, а не новым расчётом. */
  tz?: string | null;
}

/** Пояс продукта по умолчанию. Копия `ПОЯС_ПО_УМОЛЧАНИЮ` из `core/period.py`;
 *  сверяется с настоящим файлом в `tests/test_period.py`
 *  (`test_пояс_по_умолчанию_совпадает_с_панелью`). Нужен ровно до первого ответа демона —
 *  дальше пояс приезжает в `period.tz` и показывается оттуда. */
export const TZ_ПО_УМОЛЧАНИЮ = "UTC+3";

/** Кнопки периода. Порядок — порядок на экране; `id` обязан совпадать с
 *  `ПОРЯДОК` в `core/period.py`, и это проверяет `tests/test_period.py`
 *  (`test_набор_совпадает_с_панелью`) — он читает этот файл и сравнивает списки.
 *
 *  Подписи короткие и БЕЗ обещания границ: что именно значит «7 days», человек
 *  читает не по кнопке, а по датам рядом — их отдаёт демон. Кнопка, которая
 *  сама объясняет период словами, начинает врать в тот день, когда пресет
 *  поменяет смысл на бэкенде. */
export const ПРЕСЕТЫ: Array<{ id: string; label: string }> = [
  { id: "today", label: "Today" },
  { id: "yesterday", label: "Yesterday" },
  { id: "last_7d", label: "7 days" },
  { id: "last_14d", label: "14 days" },
  { id: "last_30d", label: "30 days" },
  { id: "this_month", label: "This month" },
];

/** Период по умолчанию: сегодня. Не «последние 30 дней» — байер открывает лист,
 *  чтобы увидеть, что происходит СЕЙЧАС, и месячная сумма на этот вопрос не
 *  отвечает. */
export const НАЧАЛЬНЫЙ: PeriodQuery = { preset: "today" };

/* ── запрос ──────────────────────────────────────────────────────────────── */

/** Период → параметры ручки. Пустое остаётся пустым: `call()` не кладёт в
 *  адрес пустые значения, и «period=» без имени демон принял бы за «не задан». */
export function периодВЗапрос(п?: PeriodQuery | null): Record<string, string | null> {
  if (!п) return {};
  /* Пресет ПОБЕЖДАЕТ пару дат, а не досылается вместе с ней. Иначе состояние
     «нажал кнопку, а в полях остались прошлые даты» уехало бы в запрос целиком
     и получило отказ — при том, что человек сделал понятное движение. */
  if (п.preset) return { period: п.preset, tz: п.tz ?? null };
  return { since: п.since ?? null, until: п.until ?? null, tz: п.tz ?? null };
}

/* ── период листа, который считает деньги ПОПЕРЁК ПАРКА ───────────────────── */

/** То же окно, что у листа кампаний, плюс ответ про сутки НАБОРА кабинетов.
 *
 *  Зачем отдельная форма. У листа кампаний кабинет один, и вопрос «совпадают ли
 *  границы суток» имеет ответ про него (`account_tz`, `same_day_boundary`).
 *  Creative Analytics складывает деньги поперёк парка: в одной сумме лежат
 *  кабинеты с разными поясами, и «пояс кабинета» перестаёт существовать как
 *  единственное число. Поэтому здесь приезжает СОСТАВ — и вердикт по нему.
 *
 *  Поля необязательные: демон постарше их не пришлёт, и лист обязан работать,
 *  а не решать за него, что всё совпало. */
export interface PeriodПарка extends Period {
  /** Сколько кабинетов положили деньги в это окно. Не весь парк: кабинет без
   *  единой строки расхода в окне в сумме не участвует. */
  accounts?: number | null;
  accounts_same?: number | null;
  accounts_diff?: number | null;
  accounts_unknown?: number | null;
}

/** Что сказать про сутки, когда кабинетов много.
 *
 *  Отдельно от `оСутках` в `PeriodPicker` — там фраза про ОДИН кабинет («this ad
 *  account runs on…»), и на листе парка она была бы неправдой формы, а не
 *  только смысла. Три состояния и три текста, и ни одно из них не молчание:
 *  молчание про границы суток читается как подтверждение совпадения.
 *
 *  Пусто — только когда в окне нет ни одного кабинета с деньгами: утверждать
 *  тогда нечего, и оговорка на пустом экране была бы шумом. */
export function оСуткахПарка(p?: PeriodПарка | null): string {
  if (!p) return "";
  const всего = p.accounts ?? 0;
  if (!всего) return "";
  const общее =
    `Meta cuts daily spend by each ad account's own clock, not by ${p.tz}, and ` +
    `there is no finer breakdown to convert.`;

  if (p.same_day_boundary === true) {
    return `Day boundaries match: all ${всего} ad account(s) with spend in ` +
      `${p.since}…${p.until} run on the same offset as ${p.tz}.`;
  }
  if (p.same_day_boundary === false) {
    const чужих = p.accounts_diff ?? 0;
    return `${чужих} of ${всего} ad account(s) with spend in ${p.since}…${p.until} ` +
      `run on a different offset than ${p.tz}, so this total is summed across days ` +
      `that start and end at different moments. ${общее}`;
  }
  const немых = p.accounts_unknown ?? 0;
  return `We do not know the timezone of ${немых} of ${всего} ad account(s) with ` +
    `spend in ${p.since}…${p.until}, so we cannot say whether their day boundaries ` +
    `match ${p.tz}. ${общее}`;
}

/* ── контекст между разделами ────────────────────────────────────────────── */

/** Период из адреса страницы. Неизвестное игнорируем молча: адрес приходит
 *  снаружи (ссылка от коллеги, старая закладка), и падать на чужом параметре
 *  лист не должен. Проверять значения будет демон — он один и знает, какие
 *  пресеты есть сегодня. */
export function изURL(search: string | URLSearchParams): PeriodQuery {
  const p = typeof search === "string" ? new URLSearchParams(search) : search;
  const preset = (p.get("period") || "").trim();
  const since = (p.get("since") || "").trim();
  const until = (p.get("until") || "").trim();
  const tz = (p.get("tz") || "").trim();
  const общее = tz ? { tz } : {};
  if (preset) return { preset, ...общее };
  if (since || until) return { since: since || until, until: until || since, ...общее };
  return { ...НАЧАЛЬНЫЙ, ...общее };
}

/** Период → параметры адреса. Тот же набор имён, что уходит в ручку, и это
 *  намеренно: ссылка, скопированная из адресной строки, обязана открыть тот же
 *  экран, а не «похожий». */
export function вURL(п: PeriodQuery): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(периодВЗапрос(п))) if (v) out[k] = v;
  return out;
}

/** Тот ли это период. Нужен, чтобы не перезапрашивать лист на каждый рендер:
 *  объекты в React новые каждый раз, а период — нет. */
export function тотЖе(a?: PeriodQuery | null, b?: PeriodQuery | null): boolean {
  const s = (п?: PeriodQuery | null) => JSON.stringify(периодВЗапрос(п));
  return s(a) === s(b);
}

/** Просьба, за которую УЖЕ ушёл запрос. */
export interface Запрошено {
  период: PeriodQuery;
  geo: string | null;
}

/**
 * Нужен ли новый запрос. Сравниваем просьбу с ПРОШЛОЙ ПРОСЬБОЙ — никогда с
 * ответом.
 *
 * ПОЧЕМУ ЭТО НЕ ПРИДИРКА, А ПОЧИНКА ШТОРМА ЗАПРОСОВ (#167). Лист сравнивал
 * выбранный период с периодом ИЗ ОТВЕТА. Просьба и ответ тут по устройству
 * разные: панель просит `{preset: "today"}` и пояс НЕ НАЗЫВАЕТ, а движок
 * отвечает тем же пресетом и УЖЕ РАЗРЕШЁННЫМ поясом (`tz: "UTC+3"`). Строки
 * не совпадают никогда, поэтому «уже посчитано ровно это» не срабатывало ни
 * разу: приходил ответ, эффект видел расхождение и просил снова.
 *
 * Замер на живом проде: 99 запросов лидерборда за 60 секунд с ОДНОЙ открытой
 * вкладки, около двух в секунду. Побочно этим же выключены все кнопки дат и
 * «обновить»: они гаснут на время загрузки, а загрузка не кончалась. То есть
 * владелец не мог сменить период вовсе — и это выглядело как «кнопка не
 * нажимается», а не как «лист долбит сервер».
 *
 * Сравнение с прошлой просьбой замкнуться не может в принципе: ответ в него не
 * входит, а просьба меняется только рукой человека.
 */
export function нуженЗапрос(было: Запрошено | null, период: PeriodQuery,
                            geo: string | null): boolean {
  if (!было) return true;
  return !тотЖе(было.период, период) || (было.geo ?? null) !== (geo ?? null);
}
