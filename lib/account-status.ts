/* Статус кабинета → одна из четырёх корзин. ЕДИНСТВЕННОЕ место, где это решается.
 *
 *  Почему модуль отдельный, а не «в health-bits, где было». Классификация нужна
 *  двум разным мирам: разметке (точка статуса, чип) и сборке спеки залива
 *  (`groups.ts`). `health-bits.tsx` — клиентский компонент с React и иконками;
 *  тащить его в `lib`, откуда строится спека и откуда генерится контрактная
 *  фикстура для питоновских тестов, — значит тянуть разметку в место, где её
 *  быть не должно. Поэтому здесь чистая часть, а `statusMeta` в `health-bits`
 *  остаётся её лицом: тон и иконка там, подпись отсюда. Имя и сигнатура
 *  `statusMeta` не менялись — на неё уже есть импорт из `business-rows.ts`.
 *
 *  Зеркало `core/tabs.py:179` (`_SNAP_DEAD = {"DISABLED", "PENDING_CLOSURE"}`).
 *  Расходиться им нельзя: движок и панель обязаны считать мёртвым одно и то же.
 *
 *  Цена расхождения уже заплачена. Отклонённый PR завёл СВОЙ список из одного
 *  `DISABLED` рядом с тремя существующими — и `PENDING_CLOSURE` проходил в залив
 *  как живой. Отсюда правило: новых списков не заводить, добавлять статус сюда.
 */

/** Корзины, которыми думает и панель, и человек.
 *
 *  `review` отдельно от `dead` намеренно: кабинет на проверке не мёртв — его
 *  могут вернуть, — но и обещать по нему залив нельзя. Слить его с `dead`
 *  значило бы запретить работу по догадке, слить с `active` — промолчать. */
export type StatusLabel = "active" | "disabled" | "billing" | "review" | "unknown";

/** Мёртвые НАВСЕГДА. Владелец 13.08.2026: «разбана кабинета никогда не бывает».
 *  У Меты это в один конец, как и пауза: выключить даёт, включить обратно нет. */
const DEAD = new Set(["DISABLED", "PENDING_CLOSURE"]);

/** Счёт не оплачен. НЕ бан: лечится оплатой, залив держать из-за него нельзя. */
const BILLING = new Set(["UNSETTLED", "IN_GRACE_PERIOD"]);

/** Мета смотрит сама. Исход неизвестен, поэтому и не бан, и не «всё хорошо». */
const REVIEW = new Set(["PENDING_RISK_REVIEW", "PENDING_APPEAL", "TEMP_UNAVAILABLE"]);

export function statusLabel(status?: string): StatusLabel {
  if (!status) return "unknown";
  if (status === "ACTIVE") return "active";
  if (DEAD.has(status)) return "disabled";
  if (BILLING.has(status)) return "billing";
  if (REVIEW.has(status)) return "review";
  /* Статус, которого мы не знаем, — «unknown», а НЕ «мёртвый». Мета заводит
     новые значения без предупреждения, и молча записать такой каб в баны
     значит запретить залив по незнанию. Обратная ошибка (счесть живым) стоит
     одной осечки на одном кабе; эта — остановки работы. */
  return "unknown";
}

/** Каб, который в залив не пойдёт никогда. Единственная причина блокировки. */
export function isDeadStatus(status?: string): boolean {
  return statusLabel(status) === "disabled";
}

/** Каб под проверкой Меты: не блокирует, но человек обязан о нём знать. */
export function isReviewStatus(status?: string): boolean {
  return statusLabel(status) === "review";
}
