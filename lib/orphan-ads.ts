/* Объявления без кампании — индикатор, которого не было (#164).
 *
 * ЗАЧЕМ. Дыра, из-за которой 422 объявления остались без кампании, прожила
 * МЕСЯЦ и нашлась случайно (#152). Импортёр считал это число и выбрасывал:
 * лечение доходило и стиралось следующим же импортом, число не двигалось, и
 * увидеть это было негде. Индикатор существует ровно затем, чтобы следующая
 * такая дыра нашлась за день, а не за месяц.
 *
 * ПОЭТОМУ ЗДЕСЬ ДВИЖЕНИЕ, А НЕ ЧИСЛО. Одна цифра на экране не отличает
 * «чинится» от «стоит на месте» — а стояние на месте и было симптомом.
 * Показываем три состояния: сколько сейчас, сколько было до последнего
 * изменения, и как давно оно не менялось.
 *
 * Порогов здесь нет ни одного — ни «неделя это много», ни «сто это авария».
 * Причина та же, что в `lib/collector-health.ts`: две копии правила на двух
 * языках разъезжаются молча. Панель показывает факт и его возраст, а решение
 * принимает человек.
 */

/** Что отдаёт `/collector` про сирот. `null` в любом поле — «не считали», и это
 *  НЕ ноль: ноль значит «посчитали, сирот нет». */
export interface OrphanAds {
  /** Сколько объявлений без кампании сейчас. `null` — импорт ещё не считал. */
  сейчас: number | null;
  /** Сколько было ДО последнего изменения. `null` — число не менялось ни разу
   *  на нашей памяти, и сравнивать не с чем. */
  было: number | null;
  /** Сколько секунд число стоит на месте. `null` — момент не записан (демон
   *  старше индикатора либо значение ещё ни разу не менялось). */
  стоит_с: number | null;
}

const число = (v: unknown): number | null =>
  typeof v === "number" && Number.isFinite(v) ? v : null;

/** Прочитать блок из ответа `/collector`. Отсутствие полей — не поломка:
 *  демон на маке обновляется рестартом Claude Desktop и может быть старше
 *  панели. Тогда `сейчас === null`, и экран честно молчит. */
export function readOrphanAds(raw: unknown): OrphanAds {
  const o = (raw && typeof raw === "object" ? raw : {}) as Record<string, unknown>;
  return {
    сейчас: число(o["ads_no_campaign"]),
    было: число(o["ads_no_campaign_prev"]),
    стоит_с: число(o["ads_no_campaign_since_s"]),
  };
}

/** Показывать ли строку вообще.
 *
 *  Молчим в двух случаях: сирот нет (ноль — хорошая новость, и место на экране
 *  она занимать не должна) и число не приехало вовсе. Второе — именно молчание,
 *  а не «всё хорошо»: сказать «сирот нет», ничего не посчитав, значит соврать
 *  ровно тем способом, из-за которого дыру не замечали месяц. */
export function показыватьСирот(o: OrphanAds): boolean {
  return o.сейчас != null && o.сейчас > 0;
}

/** Возраст числа словами. Короткий: строка стоит над цифрами на каждом листе. */
function возраст(сек: number): string {
  if (сек < 3600) return `${Math.max(1, Math.round(сек / 60))}m`;
  if (сек < 24 * 3600) return `${Math.round(сек / 3600)}h`;
  return `${Math.round(сек / (24 * 3600))}d`;
}

/** Строка для экрана: сколько сирот, куда движется число и как давно стоит.
 *
 *  Движение — половина смысла. «422 ads without a campaign» читается как
 *  состояние, а «422, was 500» — как процесс, и только вторая форма отвечает на
 *  вопрос «чинится ли». Когда сравнивать не с чем, так и сказано. */
export function строкаСирот(o: OrphanAds): string {
  if (!показыватьСирот(o)) return "";
  const части = [`${o.сейчас} ads have no campaign`];
  if (o.было != null && o.было !== o.сейчас) {
    части.push(o.было > (o.сейчас as number)
      ? `down from ${o.было}`
      : `up from ${o.было}`);
  }
  if (o.стоит_с != null) {
    части.push(o.было == null
      ? `unchanged for ${возраст(o.стоит_с)}`
      : `for ${возраст(o.стоит_с)}`);
  }
  return части.join(" · ");
}

/** Что это значит и что с этим делать — для подсказки.
 *
 *  Отдельно от короткой строки: та отвечает «сколько», а человеку нужно «и
 *  почему мне не всё равно». Без объяснения индикатор читается как ещё одна
 *  цифра диагностики, мимо которой и прошли в прошлый раз. */
export function смыслСирот(o: OrphanAds): string {
  if (!показыватьСирот(o)) return "";
  const хвост = o.стоит_с != null && o.было == null
    ? " The number has not moved since we started watching it — that is the " +
      "symptom to look at, not the number itself: a fix that lands and gets " +
      "overwritten looks exactly like this."
    : "";
  return (
    "These ads are in the tree but belong to no campaign, so any breakdown by " +
    "campaign silently leaves them out. Last time this went unnoticed for a " +
    "month: 422 ads, and the count never moved because the fix kept being " +
    "overwritten by the next import." + хвост
  );
}
