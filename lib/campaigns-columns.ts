/** Включить колонку, не ломая ручную перестановку.
 *
 *  Порядок принадлежит человеку. Пересобирать список из каталога при каждом
 *  включении значит стирать перестановку одним нажатием в выборе колонок,
 *  поэтому новая встаёт на своё место по каталогу ОТНОСИТЕЛЬНО уже показанных,
 *  а взаимный порядок остальных не трогается вовсе. */
export function сПоказом(visible: CampColKey[], key: CampColKey): CampColKey[] {
  if (visible.includes(key)) return visible;
  const ранг = (k: CampColKey) => CAMP_COLUMNS.findIndex((c) => c.key === k);
  const куда = visible.findIndex((k) => ранг(k) > ранг(key));
  const out = visible.slice();
  out.splice(куда < 0 ? out.length : куда, 0, key);
  return out;
}

export function безПоказа(visible: CampColKey[], key: CampColKey): CampColKey[] {
  return visible.includes(key) ? visible.filter((k) => k !== key) : visible;
}

/** Переставить колонку на позицию `куда`. Вынесено из разметки, чтобы
 *  перестановку проверял тест, а не только рука в браузере. */
export function переставить(
  visible: CampColKey[], key: CampColKey, куда: number,
): CampColKey[] {
  const откуда = visible.indexOf(key);
  if (откуда < 0 || куда < 0 || куда >= visible.length || откуда === куда) return visible;
  const out = visible.slice();
  out.splice(куда, 0, out.splice(откуда, 1)[0]);
  return out;
}

/** Колонки к отрисовке: определения в том порядке, в каком их показывать.
 *
 *  Именно это и есть «список колонок, который дерево возьмёт и нарисует».
 *  Неизвестный ключ выбрасывается молча — он мог приехать из сохранённого
 *  набора прошлой версии, и падать из-за него незачем. */
export function колонки(visible: CampColKey[]): CampColDef[] {
  return visible.map((k) => CAMP_BY_KEY[k]).filter(Boolean);
}

