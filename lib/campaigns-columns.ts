/* Какие метрики показывать в колонках дерева «Кампании» (#159).
 *
 * Владелец 15.08: «аналог настройки колонок Ads Manager, аккуратно и красиво,
 * без перегрузки интерфейса», выбор переживает перезаход в раздел.
 *
 * ЭТОТ МОДУЛЬ — ЕДИНСТВЕННЫЙ ИСТОЧНИК ПРАВДЫ О КОЛОНКАХ, и это не красивые
 * слова, а причина, по которой он устроен именно так. Колонку рисуют ТРИ
 * разных места — шапка таблицы, строка и футер-тотал (#153), — и если каждое
 * знает про метрику само, то ширина в шапке разъезжается со строкой, а футер
 * усредняет CTR вместо того, чтобы пересчитать его от суммы. Гит такого не
 * покажет: файлы разные, каждый по себе выглядит правильным.
 *
 * Поэтому наружу отдаётся не список ключей, а всё, чем колонка рисуется:
 *
 *   `CAMP_COLUMNS`   — каталог: подпись, расшифровка, группа, ШИРИНА В
 *                      ПИКСЕЛЯХ, правило итога;
 *   `ячейка()`       — что напечатать в клетке строки и что сказать в
 *                      подсказке (включая «не собрано» вместо нуля);
 *   `итоги()`        — тотал по колонке, посчитанный ПРАВИЛЬНО;
 *   `ТОН_КЛАСС`      — покраска, чтобы «тревожный ноль» красился одинаково
 *                      в строке и в тотале.
 *
 * Дерево берёт видимые колонки, идёт по ним слева направо и красит. Своего
 * `switch` по ключу метрики у него нет вовсе — а значит, и разъезжаться нечему.
 *
 *
 * ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО
 *
 * Имя объекта, статус, штамп свежести и кнопка действия В КАТАЛОГ НЕ ВХОДЯТ и
 * выключателя не получают. Это не метрики, а условия, при которых строке можно
 * верить и с ней можно что-то сделать: лист управляет чужими деньгами, читает
 * их из НАШЕЙ базы со штампом возраста, и человек, спрятавший возраст, получит
 * лист, который врёт тем увереннее, чем сильнее отстал (`campaigns.ts`,
 * `freshWhy`). Выбор колонок — про то, ЧТО МЕРИТЬ, а не про то, чему верить.
 *
 *
 * ЕДИНИЦЫ НАЗВАНЫ ЗДЕСЬ ОДИН РАЗ И ЖЁСТКО
 *
 * Деньги — ЦЕЛЫЕ МИНОРНЫЕ единицы валюты строки, как в `CampaignRow` и как их
 * отдаёт Мета: 7000 = $70.00. Делит на сто ровно одно место (`budget()` из
 * `campaigns.ts`), и это не вкус: в иссусе #125 пример уже путал минорные
 * бюджеты с долларовым спендом в одной строке, а ошибка в сто раз замечается
 * только глазами. CTR — ДОЛЯ, не проценты: 0.0123 = 1.23%, потому что `pct()`
 * умножает на сто сам. Прислать сюда 1.23 значит нарисовать 123%.
 */
