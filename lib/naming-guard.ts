/**
 * Одно правило: имя объявления обязано кончаться на [CREO_NAME].
 *
 * Почему это отдельный модуль, а не строчка в валидации. Шаблон попадает в
 * спеку четырьмя разными путями, и каждый из них — своя дыра:
 *   1. дефолт новой формы            lib/seed.ts
 *   2. дефолт при импорте спеки      lib/spec-to-state.ts
 *   3. форма, сохранённая в браузере lib/store.ts (перекрывает дефолт)
 *   4. пресет юзера с областью «нейминг»  lib/store.ts: applyUserPreset
 * Починить только первый — значит починить ровно один сценарий: чистый
 * браузер и новая группа. У того, кто уже работал с панелью, всё осталось бы
 * по-старому, и он бы об этом не узнал.
 *
 * Цена нарушения известна точно. Атрибуция режет имя объявления по `--` и
 * берёт ПОСЛЕДНИЙ кусок (core/attrib.py:241-244). Если там не имя крео,
 * объявление не привязывается ни к одному крео, и его расход навсегда оседает
 * в «не опознан»: имя уже ушло в Мету, переименовывать нечего. 08.08 шаблон
 * `ad--[ACT_LAST4]--[RAND5]` стоил четырнадцати объявлений и $193.
 */

const MACRO = "[CREO_NAME]";
/** Разделитель, по которому режет атрибуция (core/attrib.py:241-244). */
const SEP = "--";

/** Шаблон уже безопасен: макрос стоит в самом хвосте. */
export function hasCreoName(tpl: string): boolean {
  return (tpl || "").trim().endsWith(MACRO);
}

/**
 * Дописать имя крео в хвост, если его там нет.
 *
 * Дописываем, а не отказываем: отказ ломает работу из-за одного макроса и
 * ничего не спасает — человек уберёт проверку и зальёт. Дописывание делает
 * ровно то, ради чего проверка нужна.
 *
 * Макрос в СЕРЕДИНЕ шаблона переносим в конец: хвоста он не даёт, ошибка при
 * этом выглядит как исправный шаблон и глазами не ловится. Пустые звенья после
 * выемки схлопываем — иначе `ad--[CREO_NAME]--[RAND5]` дал бы `ad----[RAND5]`.
 */
export function ensureCreoName(tpl: string): string {
  const t = (tpl || "").trim();
  if (!t) return "ad" + SEP + MACRO;
  if (t.endsWith(MACRO)) return t;
  const parts = t.split(SEP).map((p) => p.trim()).filter((p) => p && p !== MACRO);
  parts.push(MACRO);
  return parts.join(SEP);
}
