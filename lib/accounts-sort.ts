/* Порядок строк листа «Кабинеты»: нажатие по заголовку колонки.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ПАРОЙ СТРЕЛОК В РАЗМЕТКЕ. Сортировка выглядит
 * украшением ровно до первой колонки с деньгами. На этом парке в одной колонке
 * встречаются доллары и донги, а рядом — кабинеты, у которых спенда нет ВОВСЕ,
 * и это два разных «нуля». Наивное `a - b` тут не ошибается заметно: оно ставит
 * вьетнамский кабинет на пару тысяч долларов первой строкой, и выглядит это как
 * «вот где деньги». Такое видно только глазами и только если знать, куда
 * смотреть, — поэтому правило живёт в тестируемом месте, а не в `onClick`.
 *
 * ГЛАВНОЕ ПРАВИЛО, ОДНО НА ВСЕ КОЛОНКИ: НЕЗНАНИЕ ТОНЕТ ВСЕГДА.
 *
 * Обычная сортировка переворачивает список целиком, вместе с пустыми клетками.
 * Тогда по возрастанию первыми встают строки, про которые мы не знаем ничего, —
 * и человек читает верх списка как ответ на свой вопрос («вот кабинеты с самым
 * маленьким спендом»), хотя это ответ «вот кабинеты, которые мы не спрашивали».
 * Поэтому направление меняет порядок ТОЛЬКО среди известных значений, а «не
 * знаем» остаётся внизу в обе стороны. Ноль при этом не «не знаем»: ноль —
 * факт, он сортируется как число (правило всей панели, `cloud-accounts.DASH`).
 *
 * СПЕНД НЕ СРАВНИВАЕТСЯ ЗДЕСЬ ВООБЩЕ. Он уходит в `cloud-accounts.bySpendIn`,
 * где это уже решено и проверено: чужая валюта в конец (курса у нас нет и мы
 * его не выдумываем), отсутствие спенда ниже нуля. Второй компаратор рядом
 * разошёлся бы с первым молча — файлы разные, гит не покажет.
 */

import { bySpendIn, type UnifiedAccount } from "./cloud-accounts";

/** По какой колонке и в какую сторону. `id` — тот же, что у колонки таблицы:
 *  два разных набора идентификаторов разъехались бы на первой же правке. */
export interface Ряд {
  id: string;
  /** `true` — по убыванию. Деньги человек смотрит сверху вниз, поэтому у
   *  спенда это и есть начальное состояние. */
  desc: boolean;
}

/** Начальный порядок листа — по спенду вниз. Тот же, что был до появления
 *  сортировки (`flatAccounts`), чтобы лист не переставился сам собой у того,
 *  кто на заголовки не нажимал. */
export const РЯД: Ряд = { id: "spend", desc: true };

/** Значение колонки для сравнения. `null` значит «не знаем» — такая строка
 *  утонет независимо от направления.
 *
 *  Ноль, пустая строка и `false` — НЕ `null`: это факты, и они сортируются. */
type Ключ = string | number | null;

function имя(a: UnifiedAccount): Ключ {
  /* Имени нет — Мета его не отдала. На экране это «no name from Meta», то есть
     прямо названное незнание, и вести себя оно обязано так же. */
  return a.name || null;
}

function соц(a: UnifiedAccount): Ключ {
  /* Сравниваем по ТОМУ ЖЕ, что показано в клетке: по имени профиля, а не по
     его id. Иначе колонка, где написано «MeDuA6aeP», сортируется по «2fcc2d23»
     — порядок верный по своему основанию и необъяснимый на экране. */
  const показан = a.profile || a.owners[0]?.profile || null;
  if (!показан) return null;
  const главный = a.owners.find((o) => o.profile === показан);
  return (главный?.label || показан).toLowerCase();
}

function оплата(a: UnifiedAccount): Ключ {
  /* Три состояния, и они упорядочены по тому, насколько всё плохо: карта есть →
     карты нет → не спрашивали. «Не спрашивали» — это `null`, и оно тонет.
     Утверждение «карты нет» делаем только про кабинет, состояние которого
     снимали: то же правило, что в фильтре и в сводной строке. */
  if (a.funding_type || a.funding_display_string) return 1;
  if (a.status_checked_at) return 0;
  return null;
}

function пиксели(a: UnifiedAccount): Ключ {
  /* Пиксели собираются ТОЛЬКО с машины оператора. У кабинета из базы их нет в
     самих данных, и посчитать это нулём значит утверждать «пикселей нет» про
     то, чего никто не смотрел. Ровно та же развилка, что рисует прочерк в
     клетке. */
  if (!a.pixels.length && !a.inSnapshot) return null;
  return a.pixels.length;
}

/** Колонка → чем её сравнивать. Колонки, которой здесь нет, сортировка не
 *  предлагает вовсе: заголовок без компаратора — это кнопка, которая ничего не
 *  делает, и нажав её дважды, человек перестаёт верить остальным. */
const КЛЮЧИ: Record<string, (a: UnifiedAccount) => Ключ> = {
  cab: имя,
  soc: соц,
  pay: оплата,
  pixel: пиксели,
};

/** Можно ли сортировать по этой колонке. Читается разметкой, чтобы стрелка
 *  появлялась ровно там, где нажатие что-то меняет. */
export function сортируется(id: string): boolean {
  return id === "spend" || id in КЛЮЧИ;
}

/** Компаратор для текущего порядка.
 *
 *  `currency` — основная валюта листа, та же, которой считаются суммы. Нужна
 *  только спенду и передаётся сюда, а не вычисляется здесь: посчитать её второй
 *  раз значит получить строки, упорядоченные по одному основанию и посчитанные
 *  по другому. */
export function сравнение(ряд: Ряд, currency: string) {
  if (ряд.id === "spend") {
    const вниз = bySpendIn(currency);
    if (ряд.desc) return вниз;
    /* Вверх — это НЕ развёрнутый `вниз`. Разворот утащил бы наверх и чужую
       валюту, и кабинеты без спенда, то есть ровно то, что `bySpendIn`
       намеренно опускает вниз. Поэтому переворачиваем только сравнение сумм, а
       «чужая валюта» и «спенда нет» остаются внизу. */
    return (a: UnifiedAccount, b: UnifiedAccount): number => {
      const свой = (x: UnifiedAccount) => ((x.currency || currency) === currency ? 0 : 1);
      const sa = свой(a);
      const sb = свой(b);
      if (sa !== sb) return sa - sb;
      const есть = (x: UnifiedAccount) => (typeof x.amount_spent === "number" ? 0 : 1);
      const ea = есть(a);
      const eb = есть(b);
      if (ea !== eb) return ea - eb;
      if (ea === 1) return a.act_id.localeCompare(b.act_id);
      const d = (a.amount_spent as number) - (b.amount_spent as number);
      return d !== 0 ? d : a.act_id.localeCompare(b.act_id);
    };
  }

  const ключ = КЛЮЧИ[ряд.id];
  /* Колонки без компаратора не переставляют список вовсе. Молча вернуть 0 —
     единственный честный ответ: выдумать порядок значит показать человеку
     перестановку, которой он не просил и объяснить которую нечем. */
  if (!ключ) return () => 0;

  return (a: UnifiedAccount, b: UnifiedAccount): number => {
    const x = ключ(a);
    const y = ключ(b);
    /* Незнание тонет в ОБЕ стороны — см. шапку файла. */
    if (x === null && y === null) return a.act_id.localeCompare(b.act_id);
    if (x === null) return 1;
    if (y === null) return -1;
    const d = typeof x === "number" && typeof y === "number"
      ? x - y
      : String(x).localeCompare(String(y));
    /* Одинаковые значения разводим по `act_id`: без этого порядок строк с
       равным ключом зависит от того, в каком порядке они приехали, и лист
       перетасовывается сам при каждом обновлении данных. */
    if (d === 0) return a.act_id.localeCompare(b.act_id);
    return ряд.desc ? -d : d;
  };
}

/** Отсортированный список. Копия, а не сортировка на месте: входной массив
 *  приходит из `useMemo` соседа, и перетасовать его значит менять чужое
 *  состояние под ним. */
export function поРяду(
  rows: UnifiedAccount[],
  ряд: Ряд,
  currency: string,
): UnifiedAccount[] {
  return rows.slice().sort(сравнение(ряд, currency));
}
