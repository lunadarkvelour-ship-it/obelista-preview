/* Срез листа кабинетов: поиск, фильтр по состоянию, по БМ и по соцу — и ОХВАТ,
 * то есть какой парк лист вообще показывает (см. раздел «охват» ниже).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Ровно то же место, что и на листе аналитики: строки
 * приезжают запросом, а тестовый рендер запросов не делает — внутри компонента
 * фильтр непроверяем. А фильтр на листе, где 261 строка, это не украшение: без
 * него лист нечитаем, и владелец сказал об этом прямо.
 *
 * ПОЧЕМУ ЗДЕСЬ ПОЯВИЛСЯ ФИЛЬТР ПО СОЦУ. Раньше его тут не было, и это было
 * записано как граница: ручка `/accounts` соца не отдаёт, а придумать его на
 * фронте значит сделать фильтр, который врёт молча. Граница снята не догадкой —
 * с иссусом #121 лист стал ОДИН, а его строка (`UnifiedAccount`) сводит базу и
 * снапшот до разметки и несёт `owners`. Там, где соцев не знает никто (облако),
 * список владельцев пуст, и фильтр по соцу честно не показывает ничего — вместо
 * того чтобы показать всё и назвать это совпадением.
 *
 * ПОИСК ЖИВЁТ НЕ ЗДЕСЬ, а в `acc-query`: он разбирает и одиночный запрос, и
 * ВСТАВЛЕННЫЙ СПИСОК из двадцати кабинетов, и это разбор с своими граблями
 * (имя сверяется целиком, иначе список из десяти молча захватывает одиннадцатый).
 * Второй такой разбор рядом разошёлся бы с первым на первой же правке.
 */

