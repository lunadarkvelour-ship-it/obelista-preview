/* ЧТО БЫЛО. Состояний было десять, и они отвечали на разные вопросы вперемешку:
 * четыре про статус Меты, три про устройство парка («общие», «соц подключён»,
 * «без пикселя»), одно про залив («можно лить») и одно общее ведро («мёртвые»).
 * Ряд из десяти кнопок висел над таблицей, а ВЫШЕ него стояла плитка, печатавшая
 * ТЕ ЖЕ ЧЕТЫРЕ ЧИСЛА нечитаемо-нажимаемым способом. На живом проде это выглядело
 * так: плитка «109 · 39 active · 70 banned · 0 billing · 0 not collected», под
 * ней чипы «all 109 · active 39 · banned 70 · ready to upload 39».
 *
 * ЧТО СТАЛО. Одно выпадающее меню, и его пункты — РОВНО корзины `StatusLabel`.
 * Владелец назвал их сам: «активные кабы, забаненные кабы, биллинг / ансетлд».
 *
 * ПОЧЕМУ СПИСОК ВЫВОДИТСЯ, А НЕ ПЕРЕЧИСЛЯЕТСЯ. Перечисленный руками список не
 * знает про корзину, которой сегодня пусто: `review` не показывался нигде, и
 * первый же кабинет на проверке Меты исчезал бы с экрана молча. Здесь пункты
 * строятся из `СОСТОЯНИЕ_КОРЗИНЫ`, а он объявлен `Record<StatusLabel, …>` —
 * то есть новая корзина не скомпилируется, пока ей не дадут пункт. Это то же
 * покрытие, которое держала плитка (#166, «сумма частей равна целому»), только
 * теперь оно живёт в типе, а не в тесте над разметкой.
 *
 * ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ И ПОЧЕМУ:
 *   • «можно лить» — снято по прямым словам владельца («чип только раздражает»).
 *     Само ПРАВИЛО никуда не делось: `можноЛить` по-прежнему гасит чекбокс, и
 *     это единственное место, где годность к заливу решается.
 *   • «мёртвые» — общее ведро из бана, неоплаты и проверки. Три разные новости с
 *     тремя разными лечениями; теперь у каждой свой пункт, и ведро не нужно.
 *   • «без пикселя», «общие», «соц подключён» — отвечают на «почему данные
 *     такие», а не «что мне делать». Ушли с экрана вместе с рядом «more».
 *
 * «БЕЗ КАРТЫ» ОСТАЛОСЬ, НО НЕ В ЭТОМ МЕНЮ: это не статус Меты, и подмешать его
 * к корзинам значило бы сломать ровно то покрытие, ради которого меню и собрано
 * (73 «без карты» на парке владельца пересекаются и с активными, и с баном).
 * Оно живёт числом в сводной строке, и число это нажимается. */

export type Состояние =
  | "все"
  /** Мета отвечает ACTIVE. */
  | "живые"
  /** Бан: DISABLED или PENDING_CLOSURE. Разбана у Меты не бывает.
   *
   *  Слово ВЛАДЕЛЬЦА — «забаненные», не «disabled»: на экране это обязано
   *  читаться как потеря, а не как состояние настройки. */
  | "забаненные"
  /** Счёт не оплачен: UNSETTLED или IN_GRACE_PERIOD. НЕ бан — лечится оплатой. */
  | "биллинг"
  /** Мета смотрит сама. Не бан и не «всё хорошо». */
  | "на проверке"
  /** Статус ни разу не снимали: про такой кабинет не утверждаем ничего. */
  | "не собрано"
  /** Способ оплаты не привязан — доставки не будет, каким бы ни был статус. */
  | "без карты";

/** Корзина статуса → пункт меню. ЕДИНСТВЕННОЕ место этой связи.
 *
 *  `Record<StatusLabel, …>` здесь несёт всю нагрузку: заведут в
 *  `account-status.ts` новую корзину — этот файл перестанет компилироваться,
 *  пока ей не дадут пункт. Список, который нельзя забыть дополнить. */
export const СОСТОЯНИЕ_КОРЗИНЫ: Record<StatusLabel, Состояние> = {
  active: "живые",
  disabled: "забаненные",
  billing: "биллинг",
  review: "на проверке",
  unknown: "не собрано",
};

/** Пункты выпадающего меню, по порядку. Выводятся, а не пишутся: см. выше. */
export const СОСТОЯНИЯ_МЕНЮ: Состояние[] = [
  "все", ...(Object.keys(СОСТОЯНИЕ_КОРЗИНЫ) as StatusLabel[])
    .map((к) => СОСТОЯНИЕ_КОРЗИНЫ[к]),
];

/** Всё, по чему лист умеет резать: меню плюс «без карты», которое живёт
 *  нажимаемым числом в сводной строке, а не пунктом меню. */
export const СОСТОЯНИЯ: Состояние[] = [...СОСТОЯНИЯ_МЕНЮ, "без карты"];

export interface Срез {
  запрос: string;
  состояние: Состояние;
  /** id соца в антидетекте. Пусто — все. */
  профиль: string;
}

export const ПУСТОЙ_СРЕЗ: Срез = { запрос: "", состояние: "все", профиль: "" };

/** Поиск идёт по имени, `act_id`, имени БМ и по соцам кабинета.
 *
 *  По id — потому что человек приносит его из Ads Manager и из чата; по БМ —
 *  потому что «покажи всё из этого БМ» это первый вопрос на парке в 261 строку;
 *  по соцу — потому что «где этот каб» спрашивают не реже.
 *
 *  Поиск по соцу идёт по ВСЕМ владельцам, а не по главному: главный выбран
 *  годностью к заливу, и прятать каб от того, кто ищет его по второму соцу,
 *  значит потерять кабинет на ровном месте. */
function подходит(a: UnifiedAccount, q: ReturnType<typeof parseAccQuery>): boolean {
  if (!q.needle) return true;
  const acc = { id: a.act_id, name: a.name || undefined };
  const соцы = a.owners.length ? a.owners : [{ profile: "", label: "" }];
  if (соцы.some((o) => matchAcc(q, acc, o.profile, o.label || o.profile))) return true;
  /* БМ ищется только одиночным запросом. Во вставленном списке сверяют кабинеты
     поимённо, и имя БМ, случайно совпавшее со строкой списка, притащило бы в
     отметку весь его состав. */
  return !q.list && (a.bm_name || "").toLowerCase().includes(q.needle);
}

/** Корзина статуса этой строки. ОДИН словарь на продукт (`lib/account-status`),
 *  и обращение к нему здесь ровно одно.
 *
 *  Своего списка статусов рядом не заводим ни под каким предлогом: отклонённый
 *  PR однажды завёл здесь собственный набор из одного `DISABLED`, и
 *  `PENDING_CLOSURE` проходил как живой. */
function корзина(a: UnifiedAccount): StatusLabel {
  return statusLabel(a.status || undefined);
}

function поСостоянию(a: UnifiedAccount, с: Состояние): boolean {
  /* «Без карты» — не статус Меты, поэтому и не корзина: оно пересекается и с
     активными, и с баном. Утверждение делаем только про кабинет, состояние
     которого снимали: у неопрошенного пустое поле значит «не знаем», а не
     «карты нет». Тот же разбор, что в сводной строке. */
  if (с === "без карты") {
    return Boolean(a.status_checked_at) && !a.funding_type && !a.funding_display_string;
  }
  if (с === "все") return true;
  /* Остальные пункты — ровно корзины, и сверяются одним сравнением. Развилка
     на case-ветку с собственным условием («не ACTIVE и статус известен» и
     подобные) — это и есть второй словарь: он расходится с первым молча. */
  return СОСТОЯНИЕ_КОРЗИНЫ[корзина(a)] === с;
}

/* ── ОХВАТ: РАБОТА НА СЕГОДНЯ ПРОТИВ ИСТОРИИ ПАРКА ────────────────────────── */

/* Владелец, посмотрев прод 15.08: «в листе аккаунтов тянет всё непонятно
 * откуда, а надо чтобы тянуло с того, что подключено в socials». Лист показывал
 * 268 кабинетов при ТРЁХ подключённых профилях: 130 из них видны только с
 * профилей, которые давно выбыли, и работать с ними сегодня нельзя ничем.
 *
 * Выбросить их нельзя — это история парка, по ней сверяют старые заливы и
 * спенд, — но и держать первым экраном нельзя тем более: лист, где две трети
 * строк недоступны, читается как «у меня 268 кабинетов», и это неправда про
 * сегодняшний день.
 *
 * Поэтому охват — не фильтр, а ВСЕЛЕННАЯ листа: он выбирается отдельной
 * кнопкой, стоит перед фильтрами и виден числом. Всё, что лист считает
 * (плитка, счётчики состояний, «x of y»), считается ВНУТРИ охвата: сводка,
 * которая спорит с показанным списком, хуже отсутствующей.
 */

/** У кабинета есть соц С ТОКЕНОМ. Слабое условие: этим же правилом считается
 *  кнопка «profile connected», и оно на обе одно. Для охвата его НЕ ХВАТАЕТ,
 *  см. разбор ниже. */
export function подключён(a: UnifiedAccount): boolean {
  return a.owners.some((o) => o.oauth);
}

export type Охват = "подключённые" | "все";

/* ── ОДНОГО ТОКЕНА МАЛО, И ЭТО РАЗОБРАНО НА ЖИВОМ ПРОДЕ ───────────────────── */

/* Первая редакция охвата резала парк по одному `oauth`. На прод она выехала и
 * не изменила НИЧЕГО: владелец по-прежнему видел 269 кабинетов. Дело не в
 * выкате — правка в собранном чанке лежит (`page-7aec4ba7893d9cfc.js` содержит
 * и «whole park», и «more filters», проверено запросом к проду).
 *
 * Дело в том, ЧТО значит `oauth` у соца базы. Демон считает его не по
 * совпадению профиля со строкой в `token`, а ЧЕРЕЗ ЧЕЛОВЕКА
 * (`analytics_daemon._соцы_профилей`): профиль → его соц (`social_profile`) →
 * есть ли у соца живой токен. Так сделано намеренно и правильно — ключ токена
 * не переезжает на новый профиль, — но следствие такое: ПРЕЖНИЕ, давно
 * выбывшие профили того же человека тоже получают `oauth = true`. У владельца
 * после переезда между вендорами антидетекта это ровно его случай, и потому
 * «подключённым» оказался весь парк до единого кабинета.
 *
 * Владелец дословно: «мне нужно ВИДЕТЬ ЖИВЫЕ КАБЫ И ЗАБАНЕННЫЕ С ТЕКУЩИХ
 * ПОДКЛЮЧЕННЫХ ПО OAUTH ПРОФИЛЕЙ». «Текущих» — это и есть недостающая
 * половина: не «у человека когда-то был токен», а «этот профиль открыт ПРЯМО
 * СЕЙЧАС». Второй признак у нас уже есть отдельным полем (`in_antidetect` →
 * `present`), и вместе они дают ровно те три профиля, которые он видит в
 * `/socials`.
 *
 * ЗАПАСНОЙ ХОД. Если окна не подтвердил НИКТО (мостик с машины ещё не ходил —
 * на свежей учётке так и есть), строгое правило спрятало бы лист целиком.
 * Тогда работает слабое: показать лишнее лучше, чем показать пустоту вместо
 * парка. Тот же приём и та же причина, что в `lib/antik-profiles`: берём
 * лучший ДОСТУПНЫЙ признак, а не единственный. */

/** Правило охвата, посчитанное ПО ВСЕМУ ПАРКУ разом.
 *
 *  Функцией от парка, а не предикатом на строку: строгость зависит от того,
 *  подтвердил ли окна хоть кто-нибудь, и решать это на каждой строке заново
 *  значит получить разный ответ для разных строк одного листа. */
export function правилоСоца(rows: UnifiedAccount[]): (o: UnifiedOwner) => boolean {
  const строго = rows.some((a) => a.owners.some((o) => o.oauth && o.present === true));
  return (o) => o.oauth === true && (!строго || o.present === true);
}

/** То же правило, поднятое на кабинет: он в охвате, если такой соц у него есть.
 *
 *  Оба правила — одно определение и один вызов: лист кабинетов и лист кампаний
 *  обязаны считать «текущий профиль» одинаково, иначе на одном экране соц есть,
 *  а на другом его нет, и объяснить это будет нечем. */
export function правилоОхвата(rows: UnifiedAccount[]): (a: UnifiedAccount) => boolean {
  const годен = правилоСоца(rows);
  return (a) => a.owners.some(годен);
}

/** Куда кабинет попадает по своим соцам. Четыре доли, и лечатся они разным:
 *
 *  • `текущий` — виден с профиля, у которого есть и токен, и открытое окно.
 *    Это работа на сегодня.
 *  • `токен без окна` — соц подключён, но именно это окно в антидетекте не
 *    открыто. Чинится за минуту в антидетекте, и потому НЕ то же самое, что
 *    выбывший профиль.
 *  • `отключённый` — соцы известны, токена нет ни у одного. История парка.
 *  • `неизвестно` — соцев не знает никто. Это «мы не проверяли», а не «их
 *    нет»: связи приезжают мостиком с машины, и до первого моста их нет ни у
 *    кого. Свалить их к выбывшим значит утверждать непроверенное. */
export type Принадлежность =
  | "текущий" | "токен без окна" | "отключённый" | "неизвестно";

export function принадлежность(a: UnifiedAccount): Принадлежность {
  if (a.owners.some((o) => o.oauth && o.present === true)) return "текущий";
  if (подключён(a)) return "токен без окна";
  return a.owners.length ? "отключённый" : "неизвестно";
}

/** Строки охвата. «Все» — это правда все, включая те, у кого соцев не знает
 *  никто: охват выключают именно затем, чтобы увидеть весь парк. */
export function вОхвате(rows: UnifiedAccount[], охват: Охват): UnifiedAccount[] {
  if (охват === "все") return rows;
  const годен = правилоОхвата(rows);
  return rows.filter(годен);
}

export interface СчётОхвата {
  /** Что показывается по умолчанию. Считается ТЕМ ЖЕ правилом, что и фильтр:
   *  кнопка, обещающая одно число, и лист, показывающий другое, — это способ
   *  перестать верить обоим. */
  подключённые: number;
  токенБезОкна: number;
  отключённые: number;
  неизвестные: number;
  всего: number;
  /** Сколько строк спрятано охватом. Отдельным полем, чтобы подпись у кнопки
   *  не складывала числа сама и не разошлась с фильтром. */
  скрытые: number;
}

/** Сколько кабинетов в каждой доле парка — чтобы человек видел цену
 *  переключателя ДО нажатия и знал, что спрятанное не пропало. */
export function счётОхвата(rows: UnifiedAccount[]): СчётОхвата {
  const годен = правилоОхвата(rows);
  const out: СчётОхвата = {
    подключённые: 0, токенБезОкна: 0, отключённые: 0, неизвестные: 0,
    всего: rows.length, скрытые: 0,
  };
  for (const a of rows) {
    if (годен(a)) {
      out.подключённые += 1;
      continue;
    }
    const к = принадлежность(a);
    if (к === "отключённый") out.отключённые += 1;
    else if (к === "неизвестно") out.неизвестные += 1;
    else out.токенБезОкна += 1;
  }
  out.скрытые = out.всего - out.подключённые;
  return out;
}

export function срез(rows: UnifiedAccount[], s: Срез): UnifiedAccount[] {
  /* Запрос разбирается ОДИН раз на срез, а не на каждую строку парка: при 216
     кабинетах и вставке на два десятка значений это разница между «мгновенно» и
     заметной задержкой на каждом нажатии. */
  const q = parseAccQuery(s.запрос);
  return rows.filter(
    (a) =>
      подходит(a, q)
      && поСостоянию(a, s.состояние)
      && (!s.профиль || a.owners.some((o) => o.profile === s.профиль)),
  );
}

/* Списка БМ здесь больше нет: Business Manager ушёл с листа целиком — колонка,
   выпадашка, группировка и переключатель вида (решение владельца 17.08). Имя
   БМ при этом НЕ выброшено из данных и остаётся находимым: `подходит` выше
   по-прежнему сверяет с ним одиночный запрос, и строка показывает его в
   подсказке. Разница в том, что оно больше не занимает экран и не заводит
   собственного измерения. */

/** Соцы для выпадающего списка — по ВЛАДЕЛЬЦАМ, а не по главному соцу: иначе
 *  соц, который всюду проиграл выбор главного, пропал бы из фильтра вместе со
 *  своими кабинетами.
 *
 *  В СПИСОК ИДУТ ТОЛЬКО ТЕКУЩИЕ ПРОФИЛИ — те же, что человек видит в
 *  `/socials`. Владелец, посмотрев прод: «тут добавлены все профили, которые я
 *  удалял, архивировал — нахуй не надо». И он прав не только про удобство:
 *  связи `account_owner` копятся вечно и мёртвыми не помечаются, поэтому у
 *  кабинета в списке владельцев лежит вся его история — на живой базе до пяти
 *  профилей при одном рабочем. Выпадашка из истории предлагает фильтровать по
 *  тому, чем нельзя работать, а выбранный мёртвый профиль отдаёт пустой лист,
 *  и человек считает, что сломана панель.
 *
 *  Правило то же самое, что у охвата (`правилоСоца`), и вызывается тем же
 *  вызовом: список фильтра и содержимое листа обязаны отвечать на один вопрос
 *  одинаково. Удалённые и архивные профили в антидетекте не открыты, значит и
 *  сюда не попадают — отдельного признака «архивный» для этого не нужно. */
export function профилиСписок(rows: UnifiedAccount[]): Array<{ id: string; label: string }> {
  const годен = правилоСоца(rows);
  const seen = new Map<string, string>();
  for (const a of rows) {
    for (const o of a.owners) {
      if (годен(o) && !seen.has(o.profile)) seen.set(o.profile, o.label || o.profile);
    }
  }
  return [...seen].map(([id, label]) => ({ id, label }));
}

/** Сколько строк в каждом состоянии — чтобы человек видел цену фильтра до
 *  нажатия, а не после. */
export function счётПоСостояниям(rows: UnifiedAccount[]): Record<Состояние, number> {
  const out = Object.fromEntries(СОСТОЯНИЯ.map((с) => [с, 0])) as Record<Состояние, number>;
  out["все"] = rows.length;
  for (const a of rows) {
    for (const с of СОСТОЯНИЯ) {
      if (с !== "все" && поСостоянию(a, с)) out[с] += 1;
    }
  }
  return out;
}
